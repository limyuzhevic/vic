# Create example scripts
create_example_scripts() {
    echo -e "${YELLOW}Creating example scripts...${NC}"
    
    # Create a simple example C++ program
    cat > examples/hello.cpp << 'EOF'
#include <nlm/Brain.hpp>
#include <iostream>

int main() {
    std::cout << "=== NLM Hello World ===" << std::endl;
    std::cout << "Neural Learning Machine - Simple Example" << std::endl;
    std::cout << "" << std::endl;
    
    // Create a simple configuration
    auto config = std::make_shared<nlm::Config>();
    config->set("neuron_count", 100);
    config->set("region_count", 1);
    config->set("random_seed", 42);
    
    // Create and initialize brain
    nlm::Brain brain(config);
    if (!brain.initialize()) {
        std::cerr << "Failed to initialize brain!" << std::endl;
        return 1;
    }
    
    std::cout << "Brain initialized successfully!" << std::endl;
    std::cout << "Neurons: " << brain.getTotalNeuronCount() << std::endl;
    std::cout << "Regions: " << brain.getRegionCount() << std::endl;
    std::cout << "Synaptogenesis: " << (brain.getStructuralPlasticity() ? "Enabled" : "Disabled") << std::endl;
    std::cout << "" << std::endl;
    
    // Run a few steps
    std::cout << "Running simulation steps..." << std::endl;
    for (nlm::SimulationStep step = 0; step < 10; ++step) {
        brain.step(step);
        std::cout << "Step " << step << ": " << brain.getTotalSpikeCount() << " spikes" << std::endl;
    }
    
    std::cout << "" << std::endl;
    std::cout << "=== Example Complete ===" << std::endl;
    std::cout << "NLM is working correctly with integrated brain systems!" << std::endl;
    
    return 0;
}
EOF
    
    # Create a Python example
    cat > examples/hello.py << 'EOF'
#!/usr/bin/env python3
"""
NLM Python Example

Simple Python example demonstrating NLM integration with the experiment framework.
"""

import sys
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

def main():
    print("=== NLM Python Example ===")
    print("NLM Neural Learning Machine - Python Integration")
    print()
    
    # Check if NLM modules are available
    try:
        # Import NLM components
        from nlm import Brain, Experiment, ExperimentRunner
        from nlm.core import Config
        
        print("✓ NLM Python modules imported successfully")
        
        # Create a simple configuration
        config = Config()
        config.set("neuron_count", 100)
        config.set("region_count", 1)
        config.set("random_seed", 42)
        
        print("✓ Configuration created")
        
        # Create and initialize brain
        brain = Brain(config)
        if brain.initialize():
            print("✓ Brain initialized successfully")
            print(f"  - Neurons: {brain.getTotalNeuronCount()}")
            print(f"  - Regions: {brain.getRegionCount()}")
        else:
            print("✗ Failed to initialize brain")
            return 1
        
        # Create experiment framework
        runner = ExperimentRunner()
        experiment = runner.createExperiment("Hello World Example")
        
        print("✓ Experiment framework initialized")
        
        # Run a simple simulation
        print("\nRunning simulation...")
        for step in range(5):
            brain.step(step)
            experiment.recordStep(
                step,
                brain.getTotalNeuronCount(),
                brain.getTotalSynapseCount(),
                brain.getFiringNeuronCount(),
                brain.getAverageFiringRate()
            )
            print(f"  Step {step}: {brain.getTotalSpikeCount()} spikes")
        
        print("\n✓ Simulation completed successfully")
        
        # Save results
        runner.saveResults("hello_world_example.csv")
        print("✓ Results saved to hello_world_example.csv")
        
        print("\n=== Python Example Complete ===")
        print("NLM Python integration is working correctly!")
        
        return 0
        
    except ImportError as e:
        print(f"✗ Failed to import NLM modules: {e}")
        print("Make sure the NLM Python bindings are properly installed.")
        return 1
    except Exception as e:
        print(f"✗ Error: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
EOF
    
    # Make the Python script executable
    chmod +x examples/hello.py
    
    echo -e "${GREEN}✓ Example scripts created${NC}"
}

