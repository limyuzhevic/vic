## Troubleshooting

### Build Errors

If you encounter build errors:

1. **CMake not found**
   - Install CMake: `sudo apt-get install cmake` (Ubuntu/Debian)
   - Install CMake: `brew install cmake` (macOS)
   - Install CMake: `choco install cmake` (Windows)

2. **Compiler not found**
   - Install C++ compiler: `sudo apt-get install g++` (Ubuntu/Debian)
   - Install C++ compiler: `brew install gcc` (macOS)
   - Install C++ compiler: `choco install mingw` (Windows)

3. **Python dependencies not found**
   - Install pip dependencies: `pip3 install -r requirements.txt`

### Runtime Errors

If you encounter runtime errors:

1. **Brain initialization failed**
   - Check configuration file for valid parameters
   - Verify all required systems are initialized
   - Check system resources (memory, CPU)

2. **Experiment framework issues**
   - Verify experiment files exist and are readable
   - Check for proper experiment setup
   - Verify save/load functionality

### Common Issues

- **Memory usage too high**: Reduce neuron count or region count
- **Simulation too slow**: Use parallel processing or optimize parameters
- **Integration not working**: Check brain loop integration points
- **Tests failing**: Update test expectations or fix implementation

