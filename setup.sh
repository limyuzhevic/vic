#!/usr/bin/env bash
# NLM Environment Setup Script

# This script sets up the development environment for NLM projects
# Run this script after cloning the repository to install dependencies

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Print banner
print_banner() {
    echo -e "${GREEN}================================================${NC}"
    echo -e "${GREEN}NLM - Neural Learning Machine Setup Script${NC}"
    echo -e "${GREEN}================================================${NC}"
    echo ""
}

# Check if we're in the right directory
check_directory() {
    if [ ! -f "README.md" ]; then
        echo -e "${RED}ERROR: README.md not found. Are you in the NLM project root?${NC}"
        exit 1
    fi
    
    if [ ! -f "CMakeLists.txt" ]; then
        echo -e "${RED}ERROR: CMakeLists.txt not found. Are you in the NLM project root?${NC}"
        exit 1
    fi
    
    echo -e "${GREEN}✓ Found NLM project structure${NC}"
}

# Install system dependencies
deploy_system_deps() {
    echo -e "${YELLOW}Deploying system dependencies...${NC}"
    
    # Check for CMake
    if ! command -v cmake &> /dev/null; then
        echo -e "${RED}CMake not found. Please install CMake (version 3.16 or higher)${NC}"
        if [[ "$OSTYPE" == "linux-gnu"* ]]; then
            echo "On Ubuntu/Debian: sudo apt-get install cmake"
            echo "On CentOS/RHEL: sudo yum install cmake"
        elif [[ "$OSTYPE" == "darwin"* ]]; then
            echo "On macOS: brew install cmake"
        fi
        exit 1
    fi
    
    # Check for C++ compiler
    if ! command -v g++ &> /dev/null && ! command -v clang++ &> /dev/null; then
        echo -e "${RED}C++ compiler not found. Please install a C++ compiler${NC}"
        if [[ "$OSTYPE" == "linux-gnu"* ]]; then
            echo "On Ubuntu/Debian: sudo apt-get install g++"
            echo "On CentOS/RHEL: sudo yum install gcc-c++"
        elif [[ "$OSTYPE" == "darwin"* ]]; then
            echo "On macOS: xcode-select --install"
        fi
        exit 1
    fi
    
    # Check Python
    if ! command -v python3 &> /dev/null; then
        echo -e "${RED}Python3 not found. Please install Python3${NC}"
        if [[ "$OSTYPE" == "linux-gnu"* ]]; then
            echo "On Ubuntu/Debian: sudo apt-get install python3 python3-pip"
            echo "On CentOS/RHEL: sudo yum install python3 python3-pip"
        elif [[ "$OSTYPE" == "darwin"* ]]; then
            echo "On macOS: brew install python3"
        fi
        exit 1
    fi
    
    echo -e "${GREEN}✓ System dependencies check passed${NC}"
}

# Create project structure
create_project_structure() {
    echo -e "${YELLOW}Creating project structure...${NC}"
    
    # Create directories
    mkdir -p build
    mkdir -p docs/examples
    mkdir -p examples
    mkdir -p configs
    mkdir -p data
    
    echo -e "${GREEN}✓ Project structure created${NC}"
}

# Build the project
build_project() {
    echo -e "${YELLOW}Building NLM project...${NC}"
    
    if [ ! -d "build" ]; then
        echo -e "${RED}Build directory not found. Creating...${NC}"
        mkdir -p build
    fi
    
    cd build
    
    # Configure with CMake
    echo "Configuring with CMake..."
    cmake .. -DCMAKE_BUILD_TYPE=Release
    
    if [ $? -ne 0 ]; then
        echo -e "${RED}CMake configuration failed${NC}"
        exit 1
    fi
    
    # Build
    echo "Building with make..."
    make -j4
    
    if [ $? -ne 0 ]; then
        echo -e "${RED}Build failed${NC}"
        exit 1
    fi
    
    cd ..
    
    echo -e "${GREEN}✓ Project built successfully${NC}"
}

# Install Python dependencies
install_python_deps() {
    echo -e "${YELLOW}Installing Python dependencies...${NC}"
    
    # Check if requirements.txt exists
    if [ -f "requirements.txt" ]; then
        echo "Installing Python dependencies from requirements.txt..."
        pip3 install -r requirements.txt
        
        if [ $? -ne 0 ]; then
            echo -e "${YELLOW}Warning: Some Python dependencies failed to install${NC}"
            echo "You can install them manually with: pip3 install -r requirements.txt"
        fi
    else
        echo -e "${YELLOW}requirements.txt not found. Skipping Python dependencies.${NC}"
    fi
}

