#!/usr/bin/env python3
"""
NLM Configuration File Generator

This script creates configuration files for NLM (Neural Learning Machine) simulations.
The configuration files are simple key=value format files that can be used with
NLM's command-line interface.

Example usage:
    python generate_config.py --output my_config.cfg
    python generate_config.py --neurons 1000 --steps 5000 --demo=PHASE6
"""

import argparse
import sys
from pathlib import Path

def generate_config_file(output_path, neurons, steps, demo_mode, verbose=False):
    """Generate a configuration file with the specified parameters."""
    
    config_content = f"""# NLM Configuration File
# Generated by NLM Config Generator
# Version: 1.0

# Basic configuration
random_seed = 42
simulation_timestep = 0.001
neuron_count = {neurons}
region_count = 1
connection_probability = 0.15f

# Phase 2 neural computation parameters
stdp_ltp_weight = 0.02f
stdp_ltd_weight = 0.015f
stdp_tau = 20.0f

# Structural plasticity parameters
synaptogenesis_rate = 0.0001f
pruning_rate = 0.00001f

# Demo mode settings
# demo_mode = {PHASE2|PHASE6|BENCHMARK|CUSTOM}
demo_mode = {demo_mode}

# Simulation settings
max_steps = {steps}
enable_learning = true
enable_memory = true
enable_neuromodulation = true
enable_development = true

# Output and checkpoint settings
output_file = simulation_results.txt
checkpoint_path = ./checkpoints/simulation_checkpoint.bin
enable_checkpointing = true
enable_replay = true

# Logging and verbosity
log_level = {"INFO" if verbose else "WARN"}
verbose_mode = {str(verbose).lower()}

# Advanced settings
# (Uncomment and modify as needed)
# learning_rate = 0.01f
# novelty_threshold = 0.5f
# curiosity_strength = 0.8f
# development_stage = "adult"

# Memory system settings
# working_memory_capacity = {neurons // 10}
# episodic_memory_max_episodes = 1000
# associative_memory_strength = 0.5f

# Neuromodulation settings
# dopamine_baseline = 0.1f
# curiosity_baseline = 0.2f
# novelty_threshold = 0.3f
"""
    
    with open(output_path, 'w') as f:
        f.write(config_content)
    
    print(f"Configuration file generated: {output_path}")
    print(f"  - Neurons: {neurons}")
    print(f"  - Steps: {steps}")
    print(f"  - Demo mode: {demo_mode}")
    print(f"  - Verbose: {verbose}")

def create_example_configs():
    """Create example configuration files for different use cases."""
    
    examples = {
        "demo_phase2": {
            "neurons": 500,
            "steps": 2000,
            "demo_mode": "PHASE2",
            "verbose": False
        },
        "demo_phase6": {
            "neurons": 1000,
            "steps": 5000,
            "demo_mode": "PHASE6",
            "verbose": True
        },
        "benchmark": {
            "neurons": 100,
            "steps": 1000,
            "demo_mode": "BENCHMARK",
            "verbose": False
        },
        "custom_learning": {
            "neurons": 2000,
            "steps": 10000,
            "demo_mode": "CUSTOM",
            "verbose": True
        }
    }
    
    for name, config in examples.items():
        output_path = f"configs/{name}.cfg"
        Path("configs").mkdir(exist_ok=True)
        generate_config_file(output_path, **config)
    
    print("\nExample configuration files created in configs/ directory:")
    for name in examples.keys():
        print(f"  - {name}.cfg")

def main():
    parser = argparse.ArgumentParser(
        description="NLM Configuration File Generator",
        formatter_class=argparse.RawDescriptionHelpFormatter
    )
    
    parser.add_argument(
        "--output", "-o",
        help="Output configuration file path",
        default="generated_config.cfg"
    )
    
    parser.add_argument(
        "--neurons", "-n",
        type=int,
        default=500,
        help="Number of neurons (default: 500)"
    )
    
    parser.add_argument(
        "--steps", "-s",
        type=int,
        default=2000,
        help="Number of simulation steps (default: 2000)"
    )
    
    parser.add_argument(
        "--demo",
        choices=["PHASE2", "PHASE6", "BENCHMARK", "CUSTOM"],
        default="PHASE2",
        help="Demo mode (default: PHASE2)"
    )
    
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Enable verbose output"
    )
    
    parser.add_argument(
        "--examples",
        action="store_true",
        help="Create example configuration files"
    )
    
    args = parser.parse_args()
    
    if args.examples:
        create_example_configs()
        return
    
    generate_config_file(args.output, args.neurons, args.steps, args.demo, args.verbose)

if __name__ == "__main__":
    main()
