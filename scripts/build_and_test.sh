#!/bin/bash

# NLM Build and Test Script
# This script builds and tests the enhanced NLM system

set -e

echo "=== NLM Enhanced System Build and Test ==="

echo "1. Building NLM Core Library..."
cd /workspace/app
mkdir -p build
cd build
cmake .. -DCMAKE_BUILD_TYPE=Release
make -j4

echo "2. Building Python Bindings..."
cd /workspace/app/python
python -m pip install -e .

cd /workspace/app

echo "3. Running Basic Configuration Tests..."
./build/nlm --help 2>&1 | head -20

echo "4. Creating Configuration Files..."
mkdir -p configs
mkdir -p experiments

# Create default config file
cat > configs/default.cfg << 'EOF'
# Default NLM Configuration
# Generated by enhanced configuration system

# Core neural parameters
neuron_count = 500
region_count = 1
connection_probability = 0.15
simulation_timestep = 0.001
random_seed = 42

# Plasticity parameters
stdp_ltp_weight = 0.02
stdp_ltd_weight = 0.015
stdp_tau = 20.0
synaptogenesis_rate = 0.0001
pruning_rate = 0.00001

# Development parameters
enable_development = true
development_rate = 0.001
EOF

# Create experiment config file
cat > configs/experiment.cfg << 'EOF'
# Experiment Configuration
# Enhanced configuration for NLM experiments

# Experiment settings
experiment_mode = "all_tests"
verbose_output = true
performance_monitoring = true
log_level = "info"

# Output settings
output_file = "experiment_results.txt"
results_format = "text"
save_intermediate_results = true

# Monitoring settings
monitoring_enabled = true
monitoring_interval = 1.0
monitoring_file = "experiment_monitor.log"

# Plugin settings
plugin_system_enabled = true
plugin_path = "plugins"
max_plugins = 10
EOF

echo "5. Testing Enhanced Command Line Interface..."
./build/nlm test1 --config configs/default.cfg 2>&1 | head -30

echo "6. Testing Experiment Framework..."
cat > /tmp/test_demo.cpp << 'EOF'
#include "experiments/NLMSystemDemo.cpp"

int main() {
    NLMSystemDemo demo;
    demo.run();
    return 0;
}
EOF

echo "7. Running Enhanced Demo..."
./build/nlm --demo 2>&1 | head -50

echo "8. Creating Demonstration Reports..."
mkdir -p reports

# Generate configuration summary
cat > reports/config_summary.txt << 'EOF'
