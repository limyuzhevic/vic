#!/usr/bin/env python3
"""
Configuration documentation generator for NLM.

This script generates human-readable documentation from NLM configuration schemas.
"""

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Dict, List, Any
import yaml

class ConfigDocsGenerator:
    """Generate documentation from configuration schemas."""
    
    def __init__(self):
        self.templates = {
            "markdown": {
                "header": "# Configuration Schema Documentation",
                "field_format": "## {key}\n\n{type}\n\n{description}\n\n- Required: {required}",
                "constraints": "\n**Constraints:**\n{constraints}",
                "footer": "\n---\nGenerated by NLM Configuration Documentation Generator"
            },
            "html": {
                "header": "<h1>Configuration Schema Documentation</h1>",
                "field_format": "<h2>{key}</h2>\n<p><strong>Type:</strong> {type}</p>\n<p>{description}</p>",
                "constraints": "<h4>Constraints:</h4><ul>{constraints}</ul>",
                "footer": "<hr>Generated by NLM Configuration Documentation Generator"
            }
        }
    
    def load_schema(self, schema_path: str) -> Dict:
        """Load a schema from a file."""
        if not os.path.exists(schema_path):
            raise FileNotFoundError(f"Schema file not found: {schema_path}")
        
        with open(schema_path, 'r') as f:
            if schema_path.endswith('.json'):
                return json.load(f)
            elif schema_path.endswith(('.yaml', '.yml')):
                return yaml.safe_load(f)
            else:
                raise ValueError(f"Unsupported schema format: {schema_path}")
    
    def generate_docs(self, schema: Dict, output_format: str = "markdown") -> str:
        """Generate documentation from a schema."""
        if output_format not in self.templates:
            raise ValueError(f"Unsupported output format: {output_format}")
        
        template = self.templates[output_format]
        docs = template["header"]
        docs += "\n\nSchema Version: " + schema.get("version", "1.0.0")
        if "filename" in schema:
            docs += f"\nSource: {schema['filename']}"
        
        docs += "\n\n## Fields\n"
        
        for field in schema.get("fields", []):
            field_docs = template["field_format"].format(
                key=field["key"],
                type=field["type"],
                description=field.get("description", ""),
                required="Yes" if field.get("required", False) else "No"
            )
            
            # Add constraints
            constraints = []
            if "min" in field and field["min"] is not None:
                constraints.append(f"Minimum: {field['min']}")
            if "max" in field and field["max"] is not None:
                constraints.append(f"Maximum: {field['max']}")
            if "allowed_values" in field and field["allowed_values"]:
                constraints.append(f"Allowed values: {', '.join(field['allowed_values'])}")
            
            if constraints:
                if output_format == "markdown":
                    constraints_str = "\n".join(f"  - {c}" for c in constraints)
                else:  # HTML
                    constraints_str = "\n".join(f"    <li>{c}</li>" for c in constraints)
                
                field_docs += template["constraints"].format(constraints=constraints_str)
            
            docs += field_docs + "\n\n"
        
        docs += template["footer"]
        return docs
    
    def save_docs(self, docs: str, output_path: str):
        """Save documentation to a file."""
        with open(output_path, 'w') as f:
            f.write(docs)


def generate_docs_command(args):
    """Command line handler for documentation generation."""
    generator = ConfigDocsGenerator()
    
    try:
        schema = generator.load_schema(args.schema)
        docs = generator.generate_docs(schema, args.format)
        
        if args.output.endswith('.html'):
            # Add HTML boilerplate
            docs = f"<!DOCTYPE html>\n<html>\n<head><title>Configuration Documentation</title></head>\n<body>\n{docs}\n</body>\n</html>"
        
        generator.save_docs(docs, args.output)
        print(f"Documentation generated successfully: {args.output}")
        return 0
        
    except Exception as e:
        print(f"Error: {e}")
        return 1


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="NLM Configuration Documentation Generator",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s generate-docs --schema phase1_schema.json --output docs.md
  %(prog)s generate-docs --schema phase1_schema.json --output docs.html --format html
        """
    )
    
    parser.add_argument('--schema', required=True, help='Path to schema file')
    parser.add_argument('--output', required=True, help='Path to output documentation file')
    parser.add_argument('--format', choices=['markdown', 'html'], default='markdown',
                       help='Output format (default: markdown)')
    
    parser.set_defaults(func=generate_docs_command)
    
    args = parser.parse_args()
    
    if not hasattr(args, 'func'):
        parser.print_help()
        return 1
    
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
