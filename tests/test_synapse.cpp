void testSynapsePlasticityFlagManagement() {
    nlm::Synapse synapse(nlm::SynapseId(1), nlm::NeuronId(1), nlm::NeuronId(2));
    
    // Test mutable plasticity flags reference
    auto& flags = synapse.getPlasticityFlags();
    flags.hebbian = true;
    flags.stdp = false;
    flags.reward_modulated = true;
    
    assert(synapse.getPlasticityFlags().hebbian);
    assert(!synapse.getPlasticityFlags().stdp);
    assert(synapse.getPlasticityFlags().reward_modulated);
    
    // Test enablePlasticity method
    synapse.enablePlasticity(false, true, false);
    assert(!synapse.getPlasticityFlags().hebbian);
    assert(synapse.getPlasticityFlags().stdp);
    assert(!synapse.getPlasticityFlags().reward_modulated);
    
    std::cout << "    testSynapsePlasticityFlagManagement passed" << std::endl;
}

