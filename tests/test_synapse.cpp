void testSynapseEligibilityTraceDecay() {
    nlm::Synapse synapse(nlm::SynapseId(1), nlm::NeuronId(1), nlm::NeuronId(2));
    
    // Set eligibility trace
    synapse.setEligibilityTrace(1.0f);
    assert(synapse.getEligibilityTrace() == 1.0f);
    
    // Decay multiple times
    synapse.decayEligibilityTrace(0.1f);  // 10% decay
    assert(synapse.getEligibilityTrace() < 1.0f);
    
    synapse.decayEligibilityTrace(0.5f);  // 50% decay
    assert(synapse.getEligibilityTrace() < 0.5f);
    
    // Decay until near zero
    synapse.decayEligibilityTrace(0.99f);  // 99% decay
    assert(std::abs(synapse.getEligibilityTrace()) < 0.001f);
    
    std::cout << "    testSynapseEligibilityTraceDecay passed" << std::endl;
}

void testSynapseSpikeHistoryManagement() {
    nlm::Synapse synapse(nlm::SynapseId(1), nlm::NeuronId(1), nlm::NeuronId(2));
    
    // Record spikes
    synapse.recordPreSpike(0.1f);
    synapse.recordPreSpike(0.2f);
    synapse.recordPreSpike(0.3f);
    synapse.recordPostSpike(0.15f);
    synapse.recordPostSpike(0.25f);
    
    assert(synapse.getPreSpikeHistory().size() == 3);
    assert(synapse.getPostSpikeHistory().size() == 2);
    assert(synapse.getPreSpikeHistory()[0] == 0.1f);
    assert(synapse.getPreSpikeHistory()[2] == 0.3f);
    
    // Clear history
    synapse.clearHistory();
    assert(synapse.getPreSpikeHistory().empty());
    assert(synapse.getPostSpikeHistory().empty());
    
    std::cout << "    testSynapseSpikeHistoryManagement passed" << std::endl;
}

