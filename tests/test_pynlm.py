class TestPynlmSimulation:
    """Test NLM simulation functionality"""
    
    def test_basic_simulation(self):
        """Test a basic simulation"""
        config = pynlm.createDefaultConfig()
        brain = pynlm.createBrain(config)
        brain.initialize()
        
        # Run a few steps
        for i in range(10):
            brain.step(i)
            
        # Check that brain has neurons and synapses
        assert brain.getTotalNeuronCount() > 0
        assert brain.getTotalSynapseCount() > 0
        
    def test_world_simulation(self):
        """Test simulation with world interaction"""
        # Create components
        config = pynlm.createDefaultConfig()
        brain = pynlm.createBrain(config)
        brain.initialize()
        
        world = pynlm.createSimpleWorld()
        world.configure(width=10, height=10, visionWidth=8, visionHeight=8)
        world.reset()
        
        agent = pynlm.createAgentBrain(brain)
        agent.initialize(world)
        
        # Run a simple simulation
        for step in range(20):
            world.update(0.1)
            percept = world.getSensoryPercept()
            agent.processSensoryInput(percept)
            brain.step(step)
            action = agent.decodeMotorCommand()
            world.applyMotorCommand(action, world.getSimulationTime())
            
        # Verify some basic metrics
        assert brain.getTotalSpikeCount() >= 0
        
    def test_agent_subsystems(self):
        """Test agent subsystems"""
        config = pynlm.createDefaultConfig()
        brain = pynlm.createBrain(config)
        brain.initialize()
        
        world = pynlm.createSimpleWorld()
        world.configure(width=20, height=20, visionWidth=8, visionHeight=8)
        world.reset()
        
        agent = pynlm.createAgentBrain(brain)
        agent.initialize(world)
        
        # Enable subsystems
        agent.enableRewardModulation(True)
        agent.enableStructuralPlasticity(True)
        agent.enableDevelopment(True)
        agent.enableCuriosity(True)
        
        # Check that subsystems are enabled
        assert agent.isRewardModulationEnabled()
        assert agent.isStructuralPlasticityEnabled()
        assert agent.isDevelopmentEnabled()
        assert agent.isCuriosityEnabled()
        
        # Run simulation with subsystems
        for step in range(30):
            world.update(0.1)
            agent.processSensoryInput(world.getSensoryPercept())
            brain.step(step)
            action = agent.decodeMotorCommand()
            world.applyMotorCommand(action, world.getSimulationTime())
            
        # Check neuromodulation levels
        assert agent.getCuriosityLevel() >= 0.0
        assert agent.getNoveltyLevel() >= 0.0
        assert agent.getNeuromodulationLevel() >= 0.0
        
    def test_config_file_io(self):
        """Test configuration file I/O"""
        # Create and configure a config
        config1 = pynlm.createDefaultConfig()
        
        # Save to a temporary file
        import tempfile
        with tempfile.NamedTemporaryFile(mode='w', suffix='.cfg', delete=False) as f:
            config_path = f.name
            
        try:
            # Save config
            config1.saveToFile(config_path)
            
            # Load config
            config2 = pynlm.createDefaultConfig()
            loaded = config2.loadFromFile(config_path)
            assert loaded, "Config should load successfully"
            
            # Verify config has keys
            keys = config2.getKeys()
            assert len(keys) > 0, "Config should have keys after loading"
            
        finally:
            # Clean up
            if os.path.exists(config_path):
                os.unlink(config_path)
                
    def test_brain_state_save_load(self):
        """Test brain state save and load"""
        config = pynlm.createDefaultConfig()
        brain1 = pynlm.createBrain(config)
        brain1.initialize()
        
        # Run some simulation steps
        for i in range(10):
            brain1.step(i)
            
        # Save brain state
        import tempfile
        with tempfile.NamedTemporaryFile(suffix='.bin', delete=False) as f:
            brain_path = f.name
            
        try:
            brain1.save(brain_path)
            
            # Create new brain and load state
            config2 = pynlm.createDefaultConfig()
            brain2 = pynlm.createBrain(config2)
            brain2.load(brain_path)
            
            # Verify brain has neurons (loaded)
            assert brain2.getTotalNeuronCount() > 0
            
        finally:
            if os.path.exists(brain_path):
                os.unlink(brain_path)

