void testSchemaManagement() {
    nlm::Config config;
    
    // Create a simple validator
    auto validator = [](const nlm::ConfigValue& val) -> bool {
        if (const std::string* s = std::get_if<std::string>(&val)) {
            return s->size() > 0 && s->size() < 100;
        }
        return false;
    };
    
    // Create a schema
    nlm::ConfigSchema schema;
    schema.name = "test_schema";
    schema.description = "Test schema for validation";
    schema.required = true;
    schema.validator = validator;
    
    // Add schema
    config.addSchema("test_key", schema);
    assert(config.hasSchema("test_key"));
    
    // Test with valid value
    config.set("test_key", std::string("valid_value"), nlm::ConfigSource::Runtime);
    
    // Test with invalid value
    try {
        config.set("test_key", std::string(""), nlm::ConfigSource::Runtime);
        assert(false); // Should have thrown
    } catch (const nlm::ConfigValidationError&) {
        // Expected
    }
    
    // Clean up
    config.removeSchema("test_key");
    assert(!config.hasSchema("test_key"));
    
    std::cout << "    testSchemaManagement passed" << std::endl;
}

void testFormatDetection() {
    // Test extension-based detection
    assert(nlm::Config::detectFileFormat("test.json") == "json");
    assert(nlm::Config::detectFileFormat("test.yaml") == "yaml");
    assert(nlm::Config::detectFileFormat("test.yml") == "yaml");
    assert(nlm::Config::detectFileFormat("test.cfg") == "keyvalue");
    assert(nlm::Config::detectFileFormat("test.unknown") == "unknown");
    
    // Test JSON file detection
    assert(nlm::Config::isJsonFile("test.json"));
    assert(!nlm::Config::isJsonFile("test.yaml"));
    assert(!nlm::Config::isJsonFile("test.cfg"));
    
    // Test YAML file detection
    assert(nlm::Config::isYamlFile("test.yaml"));
    assert(nlm::Config::isYamlFile("test.yml"));
    assert(!nlm::Config::isYamlFile("test.json"));
    
    // Test key=value file detection
    assert(nlm::Config::isKeyValueFile("test.cfg"));
    assert(!nlm::Config::isKeyValueFile("test.json"));
    assert(!nlm::Config::isKeyValueFile("test.yaml"));
    
    std::cout << "    testFormatDetection passed" << std::endl;
}

void testSaveToFile() {
    nlm::Config config;
    
    // Create test values
    config.set("test_int", 42, nlm::ConfigSource::Runtime);
    config.set("test_string", std::string("hello world"), nlm::ConfigSource::Runtime);
    config.set("test_double", 3.14, nlm::ConfigSource::Runtime);
    
    // Save as JSON
    assert(config.saveToFile("test_config.json"));
    
    // Load it back
    nlm::Config config2;
    assert(config2.loadFromFile("test_config.json"));
    
    auto intVal = config2.get<int>("test_int");
    assert(intVal.has_value());
    assert(*intVal == 42);
    
    auto stringVal = config2.get<std::string>("test_string");
    assert(stringVal.has_value());
    assert(*stringVal == "hello world");
    
    auto doubleVal = config2.get<double>("test_double");
    assert(doubleVal.has_value());
    assert(*doubleVal > 3.13 && *doubleVal < 3.15);
    
    // Clean up
    std::remove("test_config.json");
    
    std::cout << "    testSaveToFile passed" << std::endl;
}

