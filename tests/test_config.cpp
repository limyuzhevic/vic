void testJsonFileLoad() {
    nlm::Config config;
    
    // Create a temporary JSON file
    const std::string jsonFile = "test_config.json";
    std::ofstream file(jsonFile);
    file << "{\n";
    file << "    \"test_int\": 42,\n";
    file << "    \"test_double\": 3.14,\n";
    file << "    \"test_string\": \"hello world\",\n";
    file << "    \"test_bool\": true,\n";
    file << "    \"test_array\": [1, 2, 3]\n";
    file << "}\n";
    file.close();
    
    // Load the JSON file
    assert(config.loadFromFile(jsonFile));
    
    // Verify the loaded values
    auto intVal = config.get<int>("test_int");
    assert(intVal.has_value());
    assert(*intVal == 42);
    
    auto doubleVal = config.get<double>("test_double");
    assert(doubleVal.has_value());
    assert(*doubleVal > 3.13 && *doubleVal < 3.15);
    
    auto stringVal = config.get<std::string>("test_string");
    assert(stringVal.has_value());
    assert(*stringVal == "hello world");
    
    auto boolVal = config.get<bool>("test_bool");
    assert(boolVal.has_value());
    assert(*boolVal == true);
    
    // Clean up
    std::remove(jsonFile.c_str());
    
    std::cout << "    testJsonFileLoad passed" << std::endl;
}

