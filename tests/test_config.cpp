// Helper function to create test files
static std::string createTestFile(const std::string& filename, const std::string& content, const std::string& dir = "/tmp/nlm_test_configs") {
    std::filesystem::create_directories(dir);
    std::string filepath = dir + "/" + filename;
    std::ofstream file(filepath);
    if (file.is_open()) {
        file << content;
        file.close();
    }
    return filepath;
}

