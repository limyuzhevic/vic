void testBrainEpisodicMemoryAttentionGating() {
    auto config = std::make_shared<nlm::Config>();
    config->set("neuron_count", static_cast<int64_t>(100), nlm::ConfigSource::Default);
    config->set("region_count", static_cast<int64_t>(1), nlm::ConfigSource::Default);
    
    nlm::Brain brain(config);
    brain.initialize();
    
    // Get initial episode count
    auto* episodicMemory = brain.getEpisodicMemory();
    assert(episodicMemory != nullptr);
    
    size_t initialEpisodes = episodicMemory->getEpisodeCount();
    
    // Run some steps with neural activity
    for (nlm::SimulationStep step = 0; step < 50; ++step) {
        brain.step(step);
    }
    
    // With attention gating, we should have fewer episodes than without
    // because only attended experiences are stored
    size_t afterStepsEpisodes = episodicMemory->getEpisodeCount();
    
    // Should have at least initial + some episodes (due to activity)
    assert(afterStepsEpisodes >= initialEpisodes);
    
    std::cout << "    testBrainEpisodicMemoryAttentionGating passed" << std::endl;
}

