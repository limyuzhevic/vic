void testBrainMoveConstructor() {
    auto config = std::make_shared<nlm::Config>();
    config->set("neuron_count", static_cast<int64_t>(100), nlm::ConfigSource::Default);
    config->set("region_count", static_cast<int64_t>(2), nlm::ConfigSource::Default);
    
    nlm::Brain brain1(config);
    brain1.initialize();
    
    // Capture state before move
    size_t neuronCount1 = brain1.getTotalNeuronCount();
    size_t regionCount1 = brain1.getRegionCount();
    
    // Move construct
    nlm::Brain brain2(std::move(brain1));
    
    // Original should be in valid empty state
    assert(brain1.getTotalNeuronCount() == 0);
    assert(brain1.getRegionCount() == 0);
    
    // Moved-to object should have correct state
    assert(brain2.getTotalNeuronCount() == neuronCount1);
    assert(brain2.getRegionCount() == regionCount1);
    
    // Test move assignment
    nlm::Brain brain3(config);
    brain3.initialize();
    brain3 = std::move(brain2);
    
    assert(brain3.getTotalNeuronCount() == neuronCount1);
    assert(brain3.getRegionCount() == regionCount1);
    
    // brain2 should now be in valid empty state
    assert(brain2.getTotalNeuronCount() == 0);
    
    std::cout << "    testBrainMoveConstructor passed" << std::endl;
}

void testBrainCopyBehavior() {
    auto config = std::make_shared<nlm::Config>();
    config->set("neuron_count", static_cast<int64_t>(50), nlm::ConfigSource::Default);
    config->set("region_count", static_cast<int64_t>(1), nlm::ConfigSource::Default);
    
    // Brain copying is explicitly disabled in the header
    // Verify that copy constructor and assignment operator are deleted
    static_assert(std::is_copy_constructible<nlm::Brain>::value == false, "Brain should be non-copyable");
    static_assert(std::is_copy_assignable<nlm::Brain>::value == false, "Brain should be non-copyable");
    
    // But moving should work
    nlm::Brain brain1(config);
    brain1.initialize();
    
    nlm::Brain brain2(std::move(brain1));
    
    // Original should be in valid empty state
    assert(brain1.getTotalNeuronCount() == 0);
    
    std::cout << "    testBrainCopyBehavior passed" << std::endl;
}

