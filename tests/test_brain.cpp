void testMemorySystemsIntegration() {
    auto config = std::make_shared<nlm::Config>();
    config->set("neuron_count", static_cast<int64_t>(200), nlm::ConfigSource::Default);
    config->set("region_count", static_cast<int64_t>(2), nlm::ConfigSource::Default);
    
    nlm::Brain brain(config);
    assert(brain.initialize());
    
    // Test Working Memory integration
    auto* workingMemory = brain.getWorkingMemory();
    assert(workingMemory != nullptr);
    
    // Test Episodic Memory integration  
    auto* episodicMemory = brain.getEpisodicMemory();
    assert(episodicMemory != nullptr);
    
    // Test Associative Memory integration
    auto* associativeMemory = brain.getAssociativeMemory();
    assert(associativeMemory != nullptr);
    
    // Run steps to trigger memory operations
    for (nlm::SimulationStep step = 0; step < 50; ++step) {
        brain.step(step);
        
        // Inject sensory input to trigger memory
        if (step % 10 == 0) {
            nlm::SensoryInput input;
            std::vector<float> data = {1.0f, 0.5f, -0.3f};
            input.setData(data);
            brain.receiveSensoryInput(input);
        }
    }
    
    // Verify memory traces were created
    assert(workingMemory->getActiveTraces() > 0);
    
    std::cout << "    Memory systems integration PASSED" << std::endl;
}

