void testAgentBrainSensoryProcessing() {
    auto config = std::make_shared<nlm::Config>();
    config->set("neuron_count", static_cast<int64_t>(100), nlm::ConfigSource::Default);
    config->set("region_count", static_cast<int64_t>(1), nlm::ConfigSource::Default);
    
    nlm::Brain brain(config);
    brain.initialize();
    
    nlm::AgentBrain agentBrain(brain);
    
    // Create test sensory percept
    nlm::SensoryPercept percept;
    percept.setVision(std::vector<float>(256, 0.5f)); // Vision input (16x16)
    percept.setTouch(std::vector<float>(8, 0.0f));  // Touch input
    percept.setInternal(std::vector<float>(4, 0.0f)); // Internal signals
    
    // Test sensory processing
    agentBrain.processSensoryInput(percept);
    
    // Check that sensory neurons received input (we can't directly verify without internal access)
    // but at least verify no crash
    assert(agentBrain.getSensoryInputSize() == 268); // 256 + 8 + 4
    
    std::cout << "    testAgentBrainSensoryProcessing passed" << std::endl;
}

