BindingIntegration::BindingIntegration(const std::string& projectRoot) {
    projectRoot_ = projectRoot;
    pythonBindingsDir_ = projectRoot + "/python";
    generatedBindingsDir_ = projectRoot + "/generated_bindings";
    backupDir_ = projectRoot + "/bindings_backup";
    
    stats_.filesCreated = 0;
    stats_.filesModified = 0;
    stats_.bindingsGenerated = 0;
    stats_.conflictsResolved = 0;
}

bool BindingIntegration::initialize() {
    log("Initializing binding integration...");
    
    // Create necessary directories
    if (!ensureDirectory(generatedBindingsDir_)) {
        log("ERROR: Failed to create generated bindings directory");
        return false;
    }
    
    if (!ensureDirectory(backupDir_)) {
        log("ERROR: Failed to create backup directory");
        return false;
    }
    
    // Initialize backup directory with existing bindings if they exist
    std::string existingBindingsPath = pythonBindingsDir_ + "/bindings.cpp";
    if (fs::exists(existingBindingsPath)) {
        if (!backupExistingBindings(existingBindingsPath)) {
            log("WARNING: Failed to backup existing bindings, proceeding anyway");
        }
    }
    
    log("Binding integration initialized successfully");
    return true;
}

