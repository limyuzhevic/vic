std::string BindingIntegration::readExistingBindings(const std::string& path) {
    std::ifstream file(path);
    if (!file.is_open()) {
        log("ERROR: Cannot open existing bindings file: " + path);
        return "";
    }
    
    std::stringstream buffer;
    buffer << file.rdbuf();
    return buffer.str();
}

std::string BindingIntegration::parseExistingBindings(const std::string& source) {
    // Extract the PYBIND11_MODULE section from existing bindings
    // This is a simplified parser - in production, use a proper C++ parser
    
    std::stringstream result;
    size_t startPos = source.find("PYBIND11_MODULE(pynlm, m)");
    
    if (startPos == std::string::npos) {
        return source; // Return original if module not found
    }
    
    // Extract the entire PYBIND11_MODULE block
    size_t braceCount = 0;
    size_t moduleStart = source.find("{", startPos);
    size_t moduleEnd = std::string::npos;
    
    for (size_t i = moduleStart; i < source.length(); ++i) {
        if (source[i] == '{') braceCount++;
        else if (source[i] == '}') {
            braceCount--;
            if (braceCount == 0) {
                moduleEnd = i;
                break;
            }
        }
    }
    
    if (moduleEnd != std::string::npos) {
        result << source.substr(0, moduleStart + 1) << std::endl;
        result << source.substr(moduleStart + 1, moduleEnd - moduleStart - 1) << std::endl;
        result << source.substr(moduleEnd) << std::endl;
    }
    
    return result.str();
}

std::string BindingIntegration::extractBindingsSection(const std::string& source, const std::string& sectionName) {
    // Extract specific sections from bindings code
    // This is a simplified implementation
    
    std::stringstream result;
    size_t startPos = 0;
    
    while ((startPos = source.find(".def(", startPos)) != std::string::npos) {
        size_t endPos = source.find(");", startPos);
        if (endPos != std::string::npos) {
            size_t nextStart = endPos + 1;
            std::string line = source.substr(startPos, endPos - startPos + 1);
            
            // Simple section filtering
            if (sectionName == "core_bindings" && (line.find("Config") != std::string::npos || 
                                                 line.find("Brain") != std::string::npos ||
                                                 line.find("Neuron") != std::string::npos ||
                                                 line.find("Synapse") != std::string::npos)) {
                result << line << "\n";
            } else if (sectionName == "enum_bindings" && (line.find("NeuronType") != std::string::npos || 
                                                          line.find("SynapseType") != std::string::npos)) {
                result << line << "\n";
            } else if (sectionName == "factory_functions" && (line.find("create") != std::string::npos)) {
                result << line << "\n";
            } else if (sectionName == "utility_functions" && (line.find("def ") != std::string::npos && 
                                                              line.find("create") == std::string::npos)) {
                result << line << "\n";
            }
            
            startPos = nextStart;
        }
    }
    
    return result.str();
}

bool BindingIntegration::ensureDirectory(const std::string& path) {
    try {
        fs::create_directories(path);
        return true;
    } catch (const fs::filesystem_error& e) {
        log("ERROR: Failed to create directory " + path + ": " + e.what());
        return false;
    }
}

bool BindingIntegration::writeFile(const std::string& path, const std::string& content) {
    std::ofstream file(path);
    if (!file.is_open()) {
        log("ERROR: Failed to open file for writing: " + path);
        return false;
    }
    
    file << content;
    file.close();
    
    stats_.filesCreated++;
    log("  Written: " + path);
    return true;
}

