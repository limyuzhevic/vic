bool BindingIntegration::integrateWithExistingBindings(const std::string& existingBindingsPath) {
    log("Integrating with existing bindings...");
    log("Source: " + existingBindingsPath);
    
    std::string existingContent = readExistingBindings(existingBindingsPath);
    if (existingContent.empty()) {
        log("ERROR: Failed to read existing bindings");
        return false;
    }
    
    log("Existing bindings parsed: " + std::to_string(existingContent.length()) + " characters");
    
    // Parse existing bindings to extract current API
    std::string parsedBindings = parseExistingBindings(existingContent);
    
    // Create new bindings based on configuration
    BindingConfig config;
    config.bindingLevel = BindingConfig::Level::ADVANCED;
    config.outputDirectory = generatedBindingsDir_;
    config.moduleName = "pynlm";
    config.enableDocumentation = true;
    config.enableErrorHandling = true;
    config.enableTypeConversion = true;
    config.generateConvenienceMethods = true;
    
    // Generate new bindings
    BindingGenerator generator(config);
    if (!generator.generateAllBindings()) {
        log("ERROR: Failed to generate bindings");
        return false;
    }
    
    // Merge with existing
    if (!generateMergedBindings(existingBindingsPath)) {
        log("ERROR: Failed to merge generated bindings with existing");
        return false;
    }
    
    log("Binding integration completed successfully");
    return true;
}

