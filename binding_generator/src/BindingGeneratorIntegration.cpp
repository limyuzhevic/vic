bool BindingIntegration::backupExistingBindings(const std::string& sourcePath) {
    log("Backing up existing bindings...");
    
    std::string backupPath = backupDir_ + "/bindings_backup_" + getCurrentTimestamp() + ".cpp";
    
    if (!copyFile(sourcePath, backupPath)) {
        log("ERROR: Failed to backup existing bindings");
        return false;
    }
    
    log("  Backup created: " + backupPath);
    return true;
}

bool BindingIntegration::copyFile(const std::string& src, const std::string& dst) {
    try {
        fs::copy_file(src, dst, fs::copy_options::overwrite_existing);
        return true;
    } catch (const fs::filesystem_error& e) {
        log("ERROR: Failed to copy file " + src + " to " + dst + ": " + e.what());
        return false;
    }
}

std::string BindingIntegration::getCurrentTimestamp() const {
    auto now = std::chrono::system_clock::now();
    auto time = std::chrono::system_clock::to_time_t(now);
    std::stringstream ss;
    ss << std::put_time(std::localtime(&time), "%Y%m%d_%H%M%S");
    return ss.str();
}

