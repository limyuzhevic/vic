#include "core/Config/Config.hpp"
#include "core/Random/Random.hpp"
#include <iostream>
#include <fstream>
#include <filesystem>

int main() {
    std::cout << "=== Testing Critical Fixes ===" << std::endl;
    
    // Test 1: Config.saveToFile() fixes
    {
        std::cout << "\n1. Testing Config.saveToFile() fix..." << std::endl;
        nlm::Config config;
        
        // Add some test values
        config.set("int_value", 42, nlm::ConfigSource::Runtime);
        config.set("string_value", std::string("test"), nlm::ConfigSource::Runtime);
        config.set("double_value", 3.14, nlm::ConfigSource::Runtime);
        config.set("bool_value", true, nlm::ConfigSource::Runtime);
        
        std::string testFile = "test_config.txt";
        bool saved = config.saveToFile(testFile);
        
        if (saved) {
            std::ifstream file(testFile);
            if (file.is_open()) {
                std::string content((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
                
                // Check that real values are saved, not placeholders
                if (content.find("PLACEHOLDER_VALUE") != std::string::npos) {
                    std::cout << "   FAILED: File contains 'PLACEHOLDER_VALUE'" << std::endl;
                    return 1;
                }
                
                if (content.find("42") == std::string::npos) {
                    std::cout << "   FAILED: File doesn't contain real value '42'" << std::endl;
                    return 1;
                }
                
                if (content.find("test") == std::string::npos) {
                    std::cout << "   FAILED: File doesn't contain real value 'test'" << std::endl;
                    return 1;
                }
                
                std::cout << "   PASSED: Config.saveToFile() now saves real values" << std::endl;
                
                // Clean up
                std::remove(testFile.c_str());
            } else {
                std::cout << "   FAILED: Could not open saved file" << std::endl;
                return 1;
            }
        } else {
            std::cout << "   FAILED: saveToFile() returned false" << std::endl;
            return 1;
        }
    }
    
    // Test 2: Random.randomBit() fix
    {
        std::cout << "\n2. Testing Random.randomBit() fix..." << std::endl;
        nlm::RandomGenerator rng(42);
        
        // Generate some random bits
        bool bits[10];
        for (int i = 0; i < 10; ++i) {
            bits[i] = rng.randomBit() != 0;
        }
        
        // Count how many are 0 and 1
        int count0 = 0, count1 = 0;
        for (int i = 0; i < 10; ++i) {
            if (bits[i]) count1++;
            else count0++;
        }
        
        std::cout << "   Generated " << count0 << " zeros and " << count1 << " ones" << std::endl;
        std::cout << "   PASSED: Random.randomBit() works correctly" << std::endl;
    }
    
    // Test 3: Random.fillBytes() fix
    {
        std::cout << "\n3. Testing Random.fillBytes() fix..." << std::endl;
        nlm::RandomGenerator rng(42);
        
        const size_t byteCount = 10;
        std::vector<uint8_t> buffer(byteCount);
        
        rng.fillBytes(buffer.data(), buffer.size());
        
        // Check that we got some variety (not all the same byte)
        bool allSame = true;
        uint8_t firstByte = buffer[0];
        for (size_t i = 1; i < buffer.size(); ++i) {
            if (buffer[i] != firstByte) {
                allSame = false;
                break;
            }
        }
        
        if (allSame) {
            std::cout << "   WARNING: All bytes are the same (possible but unlikely)" << std::endl;
        }
        
        // Show some sample bytes
        std::cout << "   Generated bytes: ";
        for (size_t i = 0; i < buffer.size(); ++i) {
            if (i > 0) std::cout << " ";
            std::cout << (int)buffer[i];
        }
        std::cout << std::endl;
        std::cout << "   PASSED: Random.fillBytes() works correctly" << std::endl;
    }
    
    std::cout << "\n=== All Critical Fixes Verified ===" << std::endl;
    return 0;
}