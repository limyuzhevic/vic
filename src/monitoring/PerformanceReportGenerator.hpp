#pragma once

#include <vector>
#include <string>
#include <memory>
#include <mutex>
#include <chrono>
#include <unordered_map>
#include <map>

namespace nlm {

// Performance report configuration
struct ReportConfig {
    std::string reportType;           // "executive", "detailed", "technical", "custom"
    std::string title;                // Report title
    std::string description;          // Report description
    std::string dateRange;            // Date range (e.g., "2024-01-01 to 2024-01-31")
    std::string generatedBy;          // Report generated by
    std::string version;              // System version
    bool includeCharts;               // Include charts in report
    bool includeTables;               // Include tables in report
    bool includeAnomalies;            // Include anomalies section
    bool includeTrends;               // Include trends section
    bool includeRecommendations;      // Include recommendations section
    std::string outputPath;           // Path for report output files
    std::vector<std::string> metrics; // Specific metrics to include
    
    ReportConfig()
        : includeCharts(true), includeTables(true), includeAnomalies(true),
          includeTrends(true), includeRecommendations(true) {}
};

// Executive summary
struct ExecutiveSummary {
    std::chrono::system_clock::time_point reportDate;
    double overallPerformanceScore;   // 0.0 to 100.0
    size_t totalMetricsAnalyzed;
    size_t anomalyCount;
    std::string keyFindings;
    std::string recommendations;
    std::string healthStatus;         // "good", "warning", "critical"
    
    ExecutiveSummary() : overallPerformanceScore(0.0), totalMetricsAnalyzed(0),
                        anomalyCount(0), healthStatus("good") {}
};

// Performance trend analysis
struct TrendAnalysis {
    std::string metricName;
    double currentValue;
    double previousValue;
    double trendPercentage;
    std::string trendDirection;  // "increasing", "decreasing", "stable"
    std::chrono::system_clock::time_point analysisDate;
    
    TrendAnalysis(const std::string& name) : metricName(name), currentValue(0.0),
                                             previousValue(0.0), trendPercentage(0.0) {}
};

// Anomaly report
struct AnomalyReport {
    std::string anomalyId;
    std::string metricName;
    std::string anomalyType;        // "spike", "drop", "outlier"
    double anomalousValue;
    double expectedValue;
    double severity;               // 0.0 to 1.0
    std::chrono::system_clock::time_point detectionTime;
    std::string description;
    std::string suggestedAction;
    
    AnomalyReport(const std::string& id) : anomalyId(id), anomalousValue(0.0),
                                          expectedValue(0.0), severity(0.0) {}
};

// Recommendation
struct Recommendation {
    std::string id;
    std::string category;          // "performance", "capacity", "security"
    std::string title;
    std::string description;
    std::string priority;          // "low", "medium", "high", "critical"
    double impactScore;            // 0.0 to 100.0
    std::chrono::system_clock::time_point suggestedDate;
    bool isImplemented;
    std::string implementationNotes;
    
    Recommendation(const std::string& id) : id(id), impactScore(0.0),
                                           isImplemented(false) {}
};

class PerformanceReportGenerator {
public:
    PerformanceReportGenerator(std::shared_ptr<HistoricalMetricsStore> historicalStore,
                               std::shared_ptr<PerformanceAnalyzer> analyzer,
                               const ReportConfig& config = ReportConfig());
    ~PerformanceReportGenerator() = default;
    
    // Generate performance report
    bool generateReport(const std::string& reportName);
    
    // Generate report from metrics data
    bool generateReport(const std::string& reportName,
                       const std::vector<MetricData>& metrics);
    
    // Generate report for time range
    bool generateReport(const std::string& reportName,
                       const std::chrono::system_clock::time_point& start,
                       const std::chrono::system_clock::time_point& end);
    
    // Get generated report data
    std::string getReportData(const std::string& reportName) const;
    
    // Export report to different formats
    std::string exportToJSON(const std::string& reportName) const;
    std::string exportToHTML(const std::string& reportName) const;
    std::string exportToCSV(const std::string& reportName) const;
    
    // Get report metadata
    struct ReportMetadata {
        std::string name;
        std::chrono::system_clock::time_point generatedTime;
        std::string format;           // "JSON", "HTML", "CSV"
        size_t size;                  // File size in bytes
        std::string contentType;
        
        ReportMetadata(const std::string& name) : name(name), size(0) {}
    };
    
    ReportMetadata getReportMetadata(const std::string& reportName) const;
    
    // List available reports
    std::vector<ReportMetadata> listReports() const;
    
    // Configure report generator
    void configure(const ReportConfig& config) { config_ = config; }
    
    // Clean up old reports
    void cleanupOldReports();
    
    // Thread safety
    void lock() { std::lock_guard<std::mutex> lock(mutex_); }
    void unlock() { std::lock_guard<std::mutex> lock(mutex_); }
    
private:
    // Report generation worker
    void generateReportWorker(const std::string& reportName,
                             const std::vector<MetricData>& metrics);
    
    // Generate executive summary
    ExecutiveSummary generateExecutiveSummary(const std::vector<MetricData>& metrics) const;
    
    // Generate trend analysis
    std::vector<TrendAnalysis> generateTrendAnalysis(const std::vector<MetricData>& metrics) const;
    
    // Generate anomaly report
    std::vector<AnomalyReport> generateAnomalyReport(const std::vector<MetricData>& metrics) const;
    
    // Generate recommendations
    std::vector<Recommendation> generateRecommendations(const std::vector<MetricData>& metrics) const;
    
    // Generate HTML report
    std::string generateHTMLReport(const std::string& reportName,
                                  const ExecutiveSummary& executiveSummary,
                                  const std::vector<TrendAnalysis>& trends,
                                  const std::vector<AnomalyReport>& anomalies,
                                  const std::vector<Recommendation>& recommendations) const;
    
    // Generate JSON report
    std::string generateJSONReport(const std::string& reportName,
                                   const ExecutiveSummary& executiveSummary,
                                   const std::vector<TrendAnalysis>& trends,
                                   const std::vector<AnomalyReport>& anomalies,
                                   const std::vector<Recommendation>& recommendations) const;
    
    // Calculate performance score
    double calculatePerformanceScore(const std::vector<MetricData>& metrics) const;
    
    // Determine health status
    std::string determineHealthStatus(double performanceScore, size_t anomalyCount) const;
    
    std::shared_ptr<HistoricalMetricsStore> historicalStore_;
    std::shared_ptr<PerformanceAnalyzer> analyzer_;
    
    // Report configuration
    ReportConfig config_;
    
    // Generated reports
    std::unordered_map<std::string, std::string> reports_;
    
    // Threading
    mutable std::mutex mutex_;
    
    // Report worker threads
    std::unordered_map<std::string, std::thread> reportThreads_;
};

} // namespace nlm
