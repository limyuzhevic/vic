void BaseDemo::initializeLogging(const std::string& logLevel, const std::string& logFile) {
    // Set up logging based on options
    auto logger = std::make_shared<Logger>();
    
    LogLevel level;
    if (logLevel == "DEBUG") level = LogLevel::Debug;
    else if (logLevel == "INFO") level = LogLevel::Info;
    else if (logLevel == "WARN") level = LogLevel::Warning;
    else if (logLevel == "ERROR") level = LogLevel::Error;
    else level = LogLevel::Info;
    
    auto consoleLogger = std::make_shared<ConsoleLogger>(level);
    logger->addLogger(consoleLogger);
    
    if (!logFile.empty()) {
        auto fileLogger = std::make_shared<FileLogger>(logFile, level);
        logger->addLogger(fileLogger);
    }
    
    Logger::setGlobal(logger);
}

void BaseDemo::saveConfiguration(const std::string& filename) {
    // Save current configuration to file
    std::ofstream file(filename);
    if (file.is_open()) {
        file << "# NLM Configuration" << std::endl;
        file << "# Generated by " << __DATE__ << std::endl;
        file << std::endl;
        
        file << "[general]" << std::endl;
        file << "seed = " << options.randomSeed << std::endl;
        file << "timestep = " << options.simulationTimestep << std::endl;
        file << std::endl;
        
        file << "[brain]" << std::endl;
        file << "neurons = " << options.neuronCount << std::endl;
        file << "regions = " << options.regionCount << std::endl;
        file << "conn_prob = " << options.connectionProbability << std::endl;
        file << std::endl;
        
        file.close();
    }
}

bool BaseDemo::loadConfiguration(const std::string& filename) {
    // Load configuration from file
    std::ifstream file(filename);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    while (std::getline(file, line)) {
        // Simple configuration parser
        size_t commentPos = line.find('#');
        if (commentPos != std::string::npos) {
            line = line.substr(0, commentPos);
        }
        
        // Trim whitespace
        size_t firstNonSpace = line.find_first_not_of(" \t\r\n");
        if (firstNonSpace == std::string::npos) continue;
        line = line.substr(firstNonSpace);
        
        size_t lastNonSpace = line.find_last_not_of(" \t\r\n");
        if (lastNonSpace != std::string::npos) {
            line = line.substr(0, lastNonSpace + 1);
        }
        
        if (line.empty()) continue;
        
        // Parse key = value pairs
        size_t equalsPos = line.find('=');
        if (equalsPos != std::string::npos) {
            std::string key = line.substr(0, equalsPos);
            std::string value = line.substr(equalsPos + 1);
            
            // Trim key and value
            size_t keyFirst = key.find_first_not_of(" \t");
            if (keyFirst != std::string::npos) {
                key = key.substr(keyFirst);
                size_t keyLast = key.find_last_not_of(" \t");
                if (keyLast != std::string::npos) {
                    key = key.substr(0, keyLast + 1);
                }
            }
            
            size_t valFirst = value.find_first_not_of(" \t");
            if (valFirst != std::string::npos) {
                value = value.substr(valFirst);
                size_t valLast = value.find_last_not_of(" \t");
                if (valLast != std::string::npos) {
                    value = value.substr(0, valLast + 1);
                }
            }
            
            // Apply configuration based on key
            if (key == "seed") {
                options.randomSeed = std::stol(value);
            } else if (key == "timestep") {
                options.simulationTimestep = std::stod(value);
            } else if (key == "neurons") {
                options.neuronCount = std::stol(value);
            } else if (key == "regions") {
                options.regionCount = std::stol(value);
            } else if (key == "conn_prob") {
                options.connectionProbability = std::stof(value);
            }
        }
    }
    
    file.close();
    return true;
}

