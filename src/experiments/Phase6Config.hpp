#pragma once

/**
 * Phase6Config - Configuration for Phase 6 integration experiment
 * 
 * This configuration struct controls all parameters for the Phase 6
 * final integration experiment that verifies all brain systems are
 * properly connected and functional.
 */

namespace nlm {

/**
 * Configuration for Phase 6 integration experiment
 */
struct Phase6Config {
    uint64_t maxSteps;
    size_t neuronCount;
    size_t regionCount;
    float connectionProbability;
    bool enableCheckpointing;
    bool enableReplay;
    bool enableDevelopment;
    std::string checkpointPath;
    
    Phase6Config()
        : maxSteps(10000)
        , neuronCount(1000)
        , regionCount(1)
        , connectionProbability(0.1f)
        , enableCheckpointing(true)
        , enableReplay(true)
        , enableDevelopment(true)
        , checkpointPath("./checkpoint_test.bin") {}
};

} // namespace nlm
