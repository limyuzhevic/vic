void VisualizationInterface::saveBrainGraph(const Brain& brain, const std::string& filename) {
    NLM_LOG_INFO("Saving brain visualization to: " + filename);
    
    std::ofstream file(filename);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open file for visualization: " + filename);
        return;
    }
    
    file << "# NLM Brain Visualization" << std::endl;
    file << "# Generated by NLM Visualization System" << std::endl;
    file << "# " << brain.getTotalNeuronCount() << " neurons, " << brain.getTotalSynapseCount() << " synapses" << std::endl;
    file << std::endl;
    
    // Write neuron information
    file << "# Neurons:" << std::endl;
    for (const auto& region : brain.getRegions()) {
        file << "# Region " << region->getId().index() << " (" << region->getName() << ")" << std::endl;
        for (const auto& pop : region->getPopulations()) {
            file << "#   Population " << pop->getId().index() << ": " << pop->getNeuronCount() << " neurons" << std::endl;
            for (const auto* neuron : pop->getNeurons()) {
                const auto& state = neuron->getState();
                file << "#     Neuron " << neuron->getId().index() << ": V=" << state.membranePotential 
                     << "mV, threshold=" << state.threshold << "mV, firing=" << (neuron->isFiring() ? "yes" : "no")
                     << ", spike history=" << neuron->getSpikeHistory().size() << std::endl;
            }
        }
    }
    
    file << std::endl;
    
    // Write synapse information
    file << "# Synapses:" << std::endl;
    size_t synapseCount = 0;
    for (const auto& region : brain.getRegions()) {
        for (const auto* syn : region->getSynapses()) {
            file << "# Synapse " << ++synapseCount << ": " 
                 << "source=" << syn->getSourceNeuron().index() << ", dest=" << syn->getDestinationNeuron().index()
                 << ", weight=" << syn->getWeight() << ", type=" << static_cast<int>(syn->getType())
                 << ", plasticity: hebbian=" << syn->getPlasticityFlags().hebbian 
                 << ", stdp=" << syn->getPlasticityFlags().stdp 
                 << ", reward=" << syn->getPlasticityFlags().reward_modulated << std::endl;
        }
    }
    
    file << std::endl;
    
    // Write statistics
    file << "# Statistics:" << std::endl;
    file << "# Total neurons: " << brain.getTotalNeuronCount() << std::endl;
    file << "# Total synapses: " << brain.getTotalSynapseCount() << std::endl;
    file << "# Active neurons: " << brain.getActiveNeuronCount() << std::endl;
    file << "# Firing neurons: " << brain.getFiringNeuronCount() << std::endl;
    file << "# Total spikes: " << brain.getTotalSpikeCount() << std::endl;
    file << "# Average firing rate: " << brain.getAverageFiringRate() << " Hz" << std::endl;
    file << "# E/I ratio: " << brain.getExcitationInhibitionRatio() << std::endl;
    file << "# Developmental stage: " << static_cast<int>(brain.getDevelopmentalStage()) << std::endl;
    
    file.close();
    NLM_LOG_INFO("Brain visualization saved successfully (" + std::to_string(brain.getTotalNeuronCount()) + " neurons, " + std::to_string(brain.getTotalSynapseCount()) + " synapses)");
}

void VisualizationInterface::generateSpikeTrainPlot(const Brain& brain, const std::string& filename) {
    NLM_LOG_INFO("Generating spike train plot to: " + filename);
    
    // Create a simple ASCII plot of spike activity
    std::ofstream file(filename);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open file for spike train plot: " + filename);
        return;
    }
    
    file << "NLM Spike Train Visualization" << std::endl;
    file << "===============================" << std::endl;
    file << "Time (ms)" << std::endl;
    file << "---" << std::endl;
    
    // Get total spike count and estimate plot dimensions
    size_t totalSpikes = brain.getTotalSpikeCount();
    size_t neurons = brain.getTotalNeuronCount();
    
    // Create a simple spike raster plot
    file << "# Neuron spikes (showing first 100 spikes):" << std::endl;
    size_t spikeCount = 0;
    for (const auto& region : brain.getRegions()) {
        for (const auto& pop : region->getPopulations()) {
            for (const auto* neuron : pop->getNeurons()) {
                const auto& spikeHistory = neuron->getSpikeHistory();
                for (size_t i = 0; i < std::min(size_t(10), spikeHistory.size()); ++i) {
                    if (spikeCount >= 100) break;
                    file << "#   Neuron " << neuron->getId().index() << ": " << spikeHistory[i] << " ms" << std::endl;
                    spikeCount++;
                }
            }
        }
    }
    
    file << std::endl;
    file << "# Summary:" << std::endl;
    file << "# Total neurons: " << neurons << std::endl;
    file << "# Total spikes: " << totalSpikes << std::endl;
    if (neurons > 0) {
        file << "# Average spikes per neuron: " << (static_cast<double>(totalSpikes) / neurons) << std::endl;
    }
    
    file.close();
    NLM_LOG_INFO("Spike train plot saved successfully");
}

void VisualizationInterface::createNetworkGraph(const Brain& brain, const std::string& filename) {
    NLM_LOG_INFO("Creating network graph to: " + filename);
    
    // Create a simple adjacency list representation
    std::ofstream file(filename);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open file for network graph: " + filename);
        return;
    }
    
    file << "# NLM Network Graph" << std::endl;
    file << "# Format: source -> target [weight] (type)" << std::endl;
    file << std::endl;
    
    // Collect all connections
    std::vector<std::tuple<uint64_t, uint64_t, float, std::string>> connections;
    
    for (const auto& region : brain.getRegions()) {
        for (const auto* syn : region->getSynapses()) {
            std::string typeStr;
            switch (syn->getType()) {
                case SynapseType::Excitatory: typeStr = "exc"; break;
                case SynapseType::Inhibitory: typeStr = "inh"; break;
                case SynapseType::Modulatory: typeStr = "mod"; break;
                case SynapseType::Electrical: typeStr = "elec"; break;
                case SynapseType::GapJunction: typeStr = "gap"; break;
                default: typeStr = "unk"; break;
            }
            connections.emplace_back(
                syn->getSourceNeuron().index(),
                syn->getDestinationNeuron().index(),
                syn->getWeight(),
                typeStr
            );
        }
    }
    
    // Sort connections for consistent output
    std::sort(connections.begin(), connections.end());
    
    // Write connections
    for (const auto& conn : connections) {
        file << std::get<0>(conn) << " -> " << std::get<1>(conn) 
             << " [" << std::get<2>(conn) << "] (" << std::get<3>(conn) << ")" << std::endl;
    }
    
    file << std::endl;
    file << "# Statistics:" << std::endl;
    file << "# Total nodes (neurons): " << brain.getTotalNeuronCount() << std::endl;
    file << "# Total edges (synapses): " << brain.getTotalSynapseCount() << std::endl;
    
    // Calculate degree distribution
    std::vector<size_t> inDegree(brain.getTotalNeuronCount(), 0);
    std::vector<size_t> outDegree(brain.getTotalNeuronCount(), 0);
    
    for (const auto& conn : connections) {
        inDegree[std::get<1>(conn)]++;
        outDegree[std::get<0>(conn)]++;
    }
    
    file << "# Max in-degree: " << (*std::max_element(inDegree.begin(), inDegree.end())) << std::endl;
    file << "# Max out-degree: " << (*std::max_element(outDegree.begin(), outDegree.end())) << std::endl;
    
    file.close();
    NLM_LOG_INFO("Network graph saved successfully");
}

void VisualizationInterface::generateDebugReport(const Brain& brain, const std::string& filename) {
    NLM_LOG_INFO("Generating debug report to: " + filename);
    
    std::ofstream file(filename);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open file for debug report: " + filename);
        return;
    }
    
    file << "=== NLM Debug Report ===" << std::endl;
    file << "Generated at: " << getCurrentTimestamp() << std::endl;
    file << std::endl;
    
    // Basic system information
    file << "--- System Information ---" << std::endl;
    file << "Build: NLM Phase 2 - Real Neural Computation" << std::endl;
    file << "Total neurons: " << brain.getTotalNeuronCount() << std::endl;
    file << "Total synapses: " << brain.getTotalSynapseCount() << std::endl;
    file << "Number of regions: " << brain.getRegionCount() << std::endl;
    file << "Total spike count: " << brain.getTotalSpikeCount() << std::endl;
    file << std::endl;
    
    // Neural state information
    file << "--- Neural State ---" << std::endl;
    for (const auto& region : brain.getRegions()) {
        file << "Region " << region->getId().index() << " (" << region->getName() << "):" << std::endl;
        file << "  Neuron count: " << region->getTotalNeuronCount() << std::endl;
        file << "  Synapse count: " << region->getSynapseCount() << std::endl;
        file << "  Active neurons: " << region->getActiveNeuronCount() << std::endl;
        file << "  Average synaptic weight: " << region->getAverageSynapticWeight() << std::endl;
    }
    file << std::endl;
    
    // Plasticity information
    file << "--- Plasticity State ---" << std::endl;
    auto* stdp = brain.getSTDP();
    auto* hebbian = brain.getHebbian();
    auto* structural = brain.getStructuralPlasticity();
    
    if (stdp) {
        file << "STDP LTP weight: " << stdp->getLTPWeight() << std::endl;
        file << "STDP LTD weight: " << stdp->getLTDWeight() << std::endl;
    }
    if (hebbian) {
        // Note: Hebbian class doesn't have public getter methods for its state
        file << "Hebbian learning: enabled" << std::endl;
    }
    if (structural) {
        // Note: StructuralPlasticity class doesn't have public getter methods for its state
        file << "Structural plasticity: enabled" << std::endl;
    }
    file << std::endl;
    
    // Neuromodulation state
    file << "--- Neuromodulation ---" << std::endl;
    auto* dopamine = brain.getDopamine();
    auto* curiosity = brain.getCuriosity();
    auto* novelty = brain.getNovelty();
    auto* predictionError = brain.getPredictionErrorSignal();
    
    if (dopamine) {
        file << "Dopamine level: " << dopamine->getLevel() << std::endl;
    }
    if (curiosity) {
        file << "Curiosity level: " << curiosity->getLevel() << std::endl;
    }
    if (novelty) {
        file << "Novelty level: " << novelty->getLevel() << std::endl;
    }
    if (predictionError) {
        file << "Prediction error: " << predictionError->getLevel() << std::endl;
    }
    file << std::endl;
    
    // Memory system status
    file << "--- Memory Systems ---" << std::endl;
    auto* workingMemory = brain.getWorkingMemory();
    auto* episodicMemory = brain.getEpisodicMemory();
    auto* associativeMemory = brain.getAssociativeMemory();
    
    if (workingMemory) {
        file << "Working memory active traces: " << workingMemory->getActiveTraces() << std::endl;
        file << "Working memory capacity: " << workingMemory->getCapacity() << std::endl;
    }
    if (episodicMemory) {
        file << "Episodic memory episodes: " << episodicMemory->getEpisodeCount() << std::endl;
        file << "Episodic memory max episodes: " << episodicMemory->getMaxEpisodes() << std::endl;
    }
    if (associativeMemory) {
        file << "Associative memory patterns: " << associativeMemory->getPatternCount() << std::endl;
    }
    file << std::endl;
    
    // Development state
    file << "--- Development ---" << std::endl;
    file << "Developmental stage: " << static_cast<int>(brain.getDevelopmentalStage()) << std::endl;
    file << "Plasticity modifier: " << (1.0f - brain.getDevelopmentSystem()->getMaturationFactor()) << std::endl;
    file << std::endl;
    
    // Performance metrics
    file << "--- Performance ---" << std::endl;
    file << "Average firing rate: " << brain.getAverageFiringRate() << " Hz" << std::endl;
    file << "E/I ratio: " << brain.getExcitationInhibitionRatio() << std::endl;
    file << "Total spikes per step: " << brain.getFiringNeuronCount() << std::endl;
    file << "Pending spike events: " << brain.getPendingSpikeEventCount() << std::endl;
    file << std::endl;
    
    // Recommendations
    file << "--- Recommendations ---" << std::endl;
    if (brain.getAverageFiringRate() < 0.1f) {
        file << "- Low firing rate detected. Consider increasing input strength or neuron excitability." << std::endl;
    }
    if (brain.getExcitationInhibitionRatio() > 10.0f) {
        file << "- High E/I ratio detected. May indicate insufficient inhibition." << std::endl;
    }
    if (brain.getTotalSynapseCount() == 0) {
        file << "- No synapses detected. Network may be disconnected." << std::endl;
    }
    if (brain.getTotalNeuronCount() < 10) {
        file << "- Very small network. Consider increasing neuron count for meaningful results." << std::endl;
    }
    
    file.close();
    NLM_LOG_INFO("Debug report saved successfully");
}

std::string VisualizationInterface::getCurrentTimestamp() {
    auto now = std::chrono::system_clock::now();
    auto in_time_t = std::chrono::system_clock::to_time_t(now);
    
    std::stringstream ss;
    ss << std::put_time(std::localtime(&in_time_t), "%Y-%m-%d %H:%M:%S");
    return ss.str();
}

