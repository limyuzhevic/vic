bool parseSetArguments(const std::vector<std::string>& args, Config& config) {
    bool success = true;
    
    for (const auto& arg : args) {
        size_t eqPos = arg.find('=');
        if (eqPos == std::string::npos) {
            std::cerr << "Warning: Invalid --set argument format: '" << arg << "'" << std::endl;
            std::cerr << "  Expected format: --set=key=value" << std::endl;
            success = false;
            continue;
        }
        
        std::string key = arg.substr(0, eqPos);
        std::string valueStr = arg.substr(eqPos + 1);
        
        try {
            // Try to determine type from schema and parse accordingly
            const ConfigSchemaEntry* schemaEntry = config.getSchema().getEntry(key);
            if (schemaEntry) {
                ConfigValue parsedValue = config.parseValue(valueStr, schemaEntry->type);
                config.set(key, parsedValue, ConfigSource::CommandLine);
                std::cout << "  Set \"" << key << "\" = " << valueStr << std::endl;
            } else {
                // Unknown key - still try to set it as string
                config.set(key, valueStr, ConfigSource::CommandLine);
                std::cout << "  Set \"" << key << "\" = " << valueStr << " (unknown key)" << std::endl;
            }
        } catch (const ConfigValidationError& e) {
            std::cerr << "Error: Invalid value for key \"" << key << "\": " << e.what() << std::endl;
            success = false;
        } catch (const std::exception& e) {
            std::cerr << "Error: Failed to parse value for key \"" << key << "\": " << e.what() << std::endl;
            success = false;
        }
    }
    
    return success;
}

