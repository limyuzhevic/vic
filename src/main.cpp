// Configuration and setup utilities
class NLMConfigurator {
public:
    static std::shared_ptr<Config> createDefaultConfig() {
        auto config = std::make_shared<Config>();
        
        // Set default values for Phase 2
        config->set("random_seed", static_cast<int64_t>(42), ConfigSource::Default);
        config->set("simulation_timestep", 0.001, ConfigSource::Default);
        config->set("neuron_count", static_cast<int64_t>(500), ConfigSource::Default);
        config->set("region_count", static_cast<int64_t>(1), ConfigSource::Default);
        config->set("connection_probability", 0.15f, ConfigSource::Default);
        
        // STDP parameters
        config->set("stdp_ltp_weight", 0.02f, ConfigSource::Default);
        config->set("stdp_ltd_weight", 0.015f, ConfigSource::Default);
        config->set("stdp_tau", 20.0f, ConfigSource::Default);
        
        // Structural plasticity parameters
        config->set("synaptogenesis_rate", 0.0001f, ConfigSource::Default);
        config->set("pruning_rate", 0.00001f, ConfigSource::Default);
        
        return config;
    }
    
    static bool loadConfigFromFile(std::shared_ptr<Config> config, const std::string& configFile) {
        // Try to load from file if provided
        if (config->loadFromFile(configFile)) {
            NLM_LOG_INFO("Loaded configuration from: " + configFile);
            return true;
        }
        return false;
    }
    
    static void applyCommandLineArgs(std::shared_ptr<Config> config, int argc, char** argv) {
        config->loadFromArgs(argc, argv);
    }
};

// Test execution framework
class NLMSimulationTester {
public:
    struct LearningExperiment {
        std::shared_ptr<Brain> brain;
        uint64_t seed;
        size_t initialSynapseCount;
        std::vector<float> initialWeights;
        std::vector<float> finalWeights;
        std::vector<NeuronId> mostActiveNeurons;
        
        LearningExperiment(std::shared_ptr<Brain> b, uint64_t s) 
            : brain(b), seed(s), initialSynapseCount(0) {}
        
        void recordInitialState() {
            initialSynapseCount = brain->getTotalSynapseCount();
            initialWeights.clear();
            
            // Record initial weights from first region
            if (auto* region = brain->getRegion(RegionId(1))) {
                for (const auto& syn : region->getSynapses()) {
                    initialWeights.push_back(syn->getWeight());
                }
            }
            
            NLM_LOG_INFO("Initial state recorded:");
            NLM_LOG_INFO("  Synapses: " + std::to_string(initialSynapseCount));
            if (!initialWeights.empty()) {
                float sum = std::accumulate(initialWeights.begin(), initialWeights.end(), 0.0f);
                float mean = sum / initialWeights.size();
                NLM_LOG_INFO("  Mean weight: " + std::to_string(mean));
            }
        }
        
        void recordFinalState() {
            finalWeights.clear();
            
            // Record final weights from first region
            if (auto* region = brain->getRegion(RegionId(1))) {
                for (const auto& syn : region->getSynapses()) {
                    finalWeights.push_back(syn->getWeight());
                }
            }
            
            mostActiveNeurons = brain->getSpikeSystem()->getMostActiveNeurons(10);
            
            NLM_LOG_INFO("Final state recorded:");
            NLM_LOG_INFO("  Total spikes: " + std::to_string(brain->getTotalSpikeCount()));
            if (!finalWeights.empty()) {
                float sum = std::accumulate(finalWeights.begin(), finalWeights.end(), 0.0f);
                float mean = sum / finalWeights.size();
                NLM_LOG_INFO("  Mean weight: " + std::to_string(mean));
            }
        }
        
        void computeStatistics() {
            NLM_LOG_INFO("");
            NLM_LOG_INFO("=== Learning Experiment Results ===");
            NLM_LOG_INFO("");
            
            if (initialWeights.empty() || finalWeights.empty()) {
                NLM_LOG_INFO("ERROR: No weights recorded");
                return;
            }
            
            // Compute weight changes
            float initialSum = std::accumulate(initialWeights.begin(), initialWeights.end(), 0.0f);
            float finalSum = std::accumulate(finalWeights.begin(), finalWeights.end(), 0.0f);
            float initialMean = initialSum / initialWeights.size();
            float finalMean = finalSum / finalWeights.size();
            
            NLM_LOG_INFO("Weight Statistics:");
            NLM_LOG_INFO("  Initial mean weight: " + std::to_string(initialMean));
            NLM_LOG_INFO("  Final mean weight: " + std::to_string(finalMean));
            NLM_LOG_INFO("  Change: " + std::to_string(finalMean - initialMean));
            
            // Count synapses that changed significantly
            size_t strengthened = 0;
            size_t weakened = 0;
            size_t unchanged = 0;
            
            size_t minSize = std::min(initialWeights.size(), finalWeights.size());
            for (size_t i = 0; i < minSize; ++i) {
                float delta = finalWeights[i] - initialWeights[i];
                if (delta > 0.01f) ++strengthened;
                else if (delta < -0.01f) ++weakened;
                else ++unchanged;
            }
            
            NLM_LOG_INFO("");
            NLM_LOG_INFO("Synaptic Changes:");
            NLM_LOG_INFO("  Strengthened: " + std::to_string(strengthened));
            NLM_LOG_INFO("  Weakened: " + std::to_string(weakened));
            NLM_LOG_INFO("  Unchanged: " + std::to_string(unchanged));
            
            NLM_LOG_INFO("");
            NLM_LOG_INFO("Spike Activity:");
            NLM_LOG_INFO("  Total spikes: " + std::to_string(brain->getTotalSpikeCount()));
            NLM_LOG_INFO("  Most active neurons recorded: " + std::to_string(mostActiveNeurons.size()));
            
            // Determine if learning occurred
            bool learningOccurred = (std::abs(finalMean - initialMean) > 0.001f) ||
                                    (strengthened > 0 || weakened > 0);
            
            NLM_LOG_INFO("");
            if (learningOccurred) {
                NLM_LOG_INFO("✓ LEARNING DETECTED: Synaptic weights changed through experience");
            } else {
                NLM_LOG_INFO("✗ NO LEARNING: Weights did not change significantly");
            }
        }
    };
    
    static void runBasicConnectivityTest(std::shared_ptr<Brain> brain) {
        NLM_LOG_INFO("");
        NLM_LOG_INFO("=== Test 1: Basic Neural Connectivity ===");
        
        // Inject current into a few neurons and see if spikes propagate
        auto* region = brain->getRegion(RegionId(1));
        if (!region) return;
        
        auto neurons = region->getAllNeurons();
        if (neurons.empty()) {
            NLM_LOG_INFO("  No neurons found!");
            return;
        }
        
        // Get initial spike count
        size_t initialSpikes = brain->getTotalSpikeCount();
        
        // Inject strong current into first 10 neurons
        NLM_LOG_INFO("  Injecting current into 10 neurons...");
        for (size_t i = 0; i < std::min(size_t(10), neurons.size()); ++i) {
            neurons[i]->injectCurrent(50.0f);  // Strong excitatory input
        }
        
        // Run a few steps
        for (SimulationStep step = 0; step < 50; ++step) {
            brain->step(step, step * 0.001);
        }
        
        size_t spikes = brain->getTotalSpikeCount() - initialSpikes;
        NLM_LOG_INFO("  Spikes generated: " + std::to_string(spikes));
        
        if (spikes > 0) {
            NLM_LOG_INFO("  ✓ Spikes propagate through network");
        } else {
            NLM_LOG_INFO("  ! No spikes - checking neuron parameters...");
            for (size_t i = 0; i < std::min(size_t(3), neurons.size()); ++i) {
                NLM_LOG_INFO("    Neuron " + std::to_string(i) + 
                            " V=" + std::to_string(neurons[i]->getMembranePotential()) +
                            " thresh=" + std::to_string(neurons[i]->getThreshold()));
            }
        }
    }
    
    static void runPlasticityExperiment(std::shared_ptr<Brain> brain) {
        NLM_LOG_INFO("");
        NLM_LOG_INFO("=== Test 2: Plasticity Learning Experiment ===");
        
        LearningExperiment experiment(brain, 42);
        
        // Record initial state
        experiment.recordInitialState();
        
        // Enable plasticity on synapses
        if (auto* region = brain->getRegion(RegionId(1))) {
            for (auto& syn : region->getSynapses()) {
                syn->enablePlasticity(true, true, false);  // Enable Hebbian and STDP
            }
        }
        
        // Apply repeated input pattern to stimulate learning
        NLM_LOG_INFO("");
        NLM_LOG_INFO("Applying repeated input patterns (1000 steps)...");
        
        // A pattern, not a seizure: stimulate only the first 20 sensory neurons
        // each step. The old code injected 30.0f into *every* sensory neuron
        // 20 times per step (600.0f), so the whole network fired synchronously
        // and every weight saturated to 1.0 - learning was measurable but not
        // selective at all.
        std::vector<NeuronId> patternNeurons;
        if (auto* region = brain->getRegion(RegionId(1))) {
            for (auto* neuron : region->getAllNeurons()) {
                if (neuron->getType() == NeuronType::Sensory && patternNeurons.size() < 20) {
                    patternNeurons.push_back(neuron->getId());
                }
            }
        }
        for (SimulationStep step = 0; step < 1000; ++step) {
            for (NeuronId id : patternNeurons) {
                brain->injectCurrent(id, 30.0f);
            }
            
            brain->step(step, step * 0.001);
            
            // Log progress every 100 steps
            if (step % 100 == 0) {
                NLM_LOG_INFO("  Step " + std::to_string(step) + 
                            " | Spikes: " + std::to_string(brain->getTotalSpikeCount()) +
                            " | Firing: " + std::to_string(brain->getFiringNeuronCount()));
            }
        }
        
        // Record final state
        experiment.recordFinalState();
        
        // Compute and display statistics
        experiment.computeStatistics();
    }
    
    static void runStdpVerification(std::shared_ptr<Brain> brain) {
        NLM_LOG_INFO("");
        NLM_LOG_INFO("=== Test 3: STDP Verification ===");
        
        auto* region = brain->getRegion(RegionId(1));
        if (!region) return;
        
        // Use one real synapse and its own pre/post neurons. The old test
        // fired neurons[0]/neurons[1] and measured synapses[0..4], which are
        // usually unrelated to that pair, so its result said nothing about STDP.
        auto& synapses = region->getSynapses();
        if (synapses.empty()) {
            NLM_LOG_INFO("  No synapses for STDP test");
            return;
        }
        Synapse* syn = synapses[0].get();
        syn->enablePlasticity(false, true, false);  // STDP only
        float beforeWeight = syn->getWeight();
        NLM_LOG_INFO("  Testing STDP on 1 synapse:");
        NLM_LOG_INFO("    Synapse before: " + std::to_string(beforeWeight) +
                     " (pre=" + std::to_string(syn->getSourceNeuron().index()) +
                     ", post=" + std::to_string(syn->getDestinationNeuron().index()) + ")");
        
        NLM_LOG_INFO("");
        NLM_LOG_INFO("  Creating correlated pre->post activity (potentiation)...");
        
        for (int trial = 0; trial < 50; ++trial) {
            brain->injectCurrent(syn->getSourceNeuron(), 60.0f);
            brain->step(trial * 2, trial * 2 * 0.001);
            brain->injectCurrent(syn->getDestinationNeuron(), 60.0f);
            brain->step(trial * 2 + 1, (trial * 2 + 1) * 0.001);
        }
        
        float delta = syn->getWeight() - beforeWeight;
        NLM_LOG_INFO("  After correlated activity:");
        NLM_LOG_INFO("    Synapse after: " + std::to_string(syn->getWeight()) +
                     " (Δ=" + std::to_string(delta) + ")");
        
        float totalDelta = delta;
        
        NLM_LOG_INFO("");
        if (totalDelta > 0.001f) {
            NLM_LOG_INFO("  ✓ STDP WORKING: Pre-before-post produced potentiation");
        } else if (totalDelta < -0.001f) {
            NLM_LOG_INFO("  ! STDP reversed: Check parameters");
        } else {
            NLM_LOG_INFO("  ! No change: STDP may not be triggering");
        }
    }
};

// User interface and command-line parsing
class NLMUserInterface {
public:
    struct CommandLineOptions {
        std::string configFile = "configs/default.cfg";
        bool verbose = false;
        bool quiet = false;
        std::string outputFile = "";
        int runMode = 0; // 0=normal, 1=benchmark, 2=test_only, 3=help
        std::vector<std::string> extraArgs;
    };
    
    static CommandLineOptions parseCommandLine(int argc, char** argv) {
        CommandLineOptions opts;
        
        for (int i = 1; i < argc; ++i) {
            std::string arg = argv[i];
            
            if (arg == "--help" || arg == "-h") {
                opts.runMode = 3;
            } else if (arg == "--quiet" || arg == "-q") {
                opts.quiet = true;
            } else if (arg == "--verbose" || arg == "-v") {
                opts.verbose = true;
            } else if (arg == "--benchmark" || arg == "--bench") {
                opts.runMode = 1;
            } else if (arg == "--test-only" || arg == "--test") {
                opts.runMode = 2;
            } else if (arg == "--output" || arg == "-o") {
                if (i + 1 < argc) {
                    opts.outputFile = argv[++i];
                }
            } else if (arg.substr(0, 7) == "--config") {
                if (arg.find('=') != std::string::npos) {
                    opts.configFile = arg.substr(arg.find('=') + 1);
                } else if (i + 1 < argc) {
                    opts.configFile = argv[++i];
                }
            } else {
                opts.extraArgs.push_back(arg);
            }
        }
        
        return opts;
    }
    
    static void displayHelp() {
        std::cout << R"(
NLM — 熙然 (Phase 2: Real Neural Computation)

USAGE:
  nlm [options]

OPTIONS:
  -h, --help              Show this help message
  -v, --verbose           Enable verbose output
  -q, --quiet             Quiet mode (minimal output)
  -o, --output FILE       Save output to file
  --config FILE           Load configuration from file (default: configs/default.cfg)
  --benchmark, --bench    Run benchmark tests
  --test-only, --test     Run tests only (no demo)

EXAMPLES:
  nlm                                    # Run default demo
  nlm --verbose                          # Run with verbose output
  nlm --config myconfig.cfg              # Load custom config
  nlm --benchmark                        # Run benchmark suite
  nlm --test-only                        # Run tests only

For more information, visit: https://github.com/nlm-project/nlm

PHASE 2 FEATURES:
  - Real LIF neuron dynamics
  - Event-driven spike propagation with delays
  - STDP and Hebbian plasticity rules
  - Structural plasticity (synaptogenesis/pruning)
  - Learning experiment demonstrating measurable changes
  - Network showing activity-dependent synaptic modification
)" << std::endl;
    }
    
    static void displayVersion() {
        std::cout << "NLM Phase 2.0.0 (熙然) - Neural Learning Machine" << std::endl;
        std::cout << "Experimental artificial developmental brain" << std::endl;
        std::cout << "Real spiking neural computation with plasticity" << std::endl;
    }
};

// Main execution function
int main(int argc, char** argv) {
    // Set up logging
    auto logger = std::make_shared<Logger>();
    auto consoleLogger = std::make_shared<ConsoleLogger>(LogLevel::Info);
    logger->addLogger(consoleLogger);
    Logger::setGlobal(logger);
    
    try {
        // Parse command line options
        auto opts = NLMUserInterface::parseCommandLine(argc, argv);
        
        // Handle special modes
        if (opts.runMode == 3) {
            NLMUserInterface::displayHelp();
            return 0;
        }
        
        if (opts.runMode == 1) {
            NLM_LOG_INFO("=== NLM Benchmark Mode ===");
            // TODO: Add benchmark functionality
            NLM_LOG_INFO("Benchmark mode not yet implemented");
            return 0;
        }
        
        if (opts.runMode == 2) {
            NLM_LOG_INFO("=== NLM Test Mode ===");
            // TODO: Add test-only functionality
            NLM_LOG_INFO("Test mode not yet implemented");
            return 0;
        }
        
        // Normal demo mode
        printBanner();
        
        if (!opts.quiet) {
            std::cout << "Initializing NLM Phase 2 Real Neural Computation...\n" << std::endl;
        }
        
        // Create and configure brain
        auto config = NLMConfigurator::createDefaultConfig();
        NLMConfigurator::loadConfigFromFile(config, opts.configFile);
        NLMConfigurator::applyCommandLineArgs(config, argc, argv);
        
        if (!opts.quiet) {
            NLM_LOG_INFO("=== NLM Phase 2: Real Neural Computation ===");
            NLM_LOG_INFO("Implementing:");
            NLM_LOG_INFO("  - Leaky Integrate-and-Fire (LIF) neuron dynamics");
            NLM_LOG_INFO("  - Event-driven spike propagation with delays");
            NLM_LOG_INFO("  - STDP and Hebbian plasticity rules");
            NLM_LOG_INFO("  - Structural plasticity (synaptogenesis/pruning)");
            NLM_LOG_INFO("");
            
            // Log configuration summary
            NLM_LOG_INFO("Configuration:");
            NLM_LOG_INFO("  random_seed: " + std::to_string(config->getOr<int64_t>("random_seed", 42)));
            NLM_LOG_INFO("  simulation_timestep: " + std::to_string(config->getOr<double>("simulation_timestep", 0.001)) + "s");
            NLM_LOG_INFO("  neuron_count: " + std::to_string(config->getOr<int64_t>("neuron_count", 500)));
            NLM_LOG_INFO("  region_count: " + std::to_string(config->getOr<int64_t>("region_count", 1)));
            NLM_LOG_INFO("  connection_probability: " + std::to_string(config->getOr<float>("connection_probability", 0.15f)));
            NLM_LOG_INFO("");
        }
        
        // Initialize brain
        auto brain = std::make_shared<Brain>(config);
        
        if (!brain->initialize()) {
            NLM_LOG_ERROR("Failed to initialize brain!");
            return 1;
        }
        
        brain->logStatus();
        
        // Run Test 1: Basic connectivity
        NLMSimulationTester::runBasicConnectivityTest(brain);
        
        // Reset brain for plasticity experiment
        brain->reset();
        brain->initialize();
        
        // Run Test 2: Plasticity learning experiment
        NLMSimulationTester::runPlasticityExperiment(brain);
        
        // Reset and run Test 3: STDP verification
        brain->reset();
        brain->initialize();
        NLMSimulationTester::runStdpVerification(brain);
        
        // Final brain status
        NLM_LOG_INFO("");
        NLM_LOG_INFO("=== Final Brain Status ===");
        brain->logStatus();
        
        NLM_LOG_INFO("");
        NLM_LOG_INFO("=== Phase 2 Complete ===");
        NLM_LOG_INFO("");
        NLM_LOG_INFO("Phase 2 Objectives Completed:");
        NLM_LOG_INFO("  ✓ Real LIF neuron dynamics implemented");
        NLM_LOG_INFO("  ✓ Event-driven spike propagation with delays");
        NLM_LOG_INFO("  ✓ STDP plasticity rule");
        NLM_LOG_INFO("  ✓ Hebbian plasticity rule");
        NLM_LOG_INFO("  ✓ Structural plasticity (synaptogenesis/pruning)");
        NLM_LOG_INFO("  ✓ Learning experiment demonstrates measurable changes");
        NLM_LOG_INFO("  ✓ Network shows activity-dependent synaptic modification");
        NLM_LOG_INFO("");
        NLM_LOG_INFO("The NLM brain is now a functioning artificial neural substrate");
        NLM_LOG_INFO("capable of changing its own synaptic connections through experience.");
        NLM_LOG_INFO("");
        
        // Save output if requested
        if (!opts.outputFile.empty()) {
            if (brain->save(opts.outputFile)) {
                NLM_LOG_INFO("Brain state saved to: " + opts.outputFile);
            } else {
                NLM_LOG_ERROR("Failed to save brain state to: " + opts.outputFile);
            }
        }
        
        return 0;
        
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Fatal error: ") + e.what());
        return 1;
    } catch (...) {
        NLM_LOG_ERROR("Unknown fatal error occurred");
        return 1;
    }
}

