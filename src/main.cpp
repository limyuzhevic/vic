// Command line argument parser
class SimpleCLI {
public:
    std::string programName;
    std::map<std::string, std::string> args;
    
    SimpleCLI(const std::string& name) : programName(name) {}
    
    bool parse(int argc, char** argv) {
        for (int i = 1; i < argc; ++i) {
            std::string arg = argv[i];
            
            // Handle --key=value format
            if (arg.substr(0, 2) == "--") {
                size_t pos = arg.find('=');
                if (pos != std::string::npos) {
                    std::string key = arg.substr(2, pos - 2);
                    std::string value = arg.substr(pos + 1);
                    args[key] = value;
                }
            }
            // Handle -key value format
            else if (arg[0] == '-' && i + 1 < argc && argv[i + 1][0] != '-') {
                std::string key = arg.substr(1);
                args[key] = argv[++i];
            }
            // Handle boolean flags
            else if (arg == "--help" || arg == "-h") {
                printHelp();
                return false;
            } else if (arg == "--version" || arg == "-v") {
                printVersion();
                return false;
            }
        }
        return true;
    }
    
    std::string getValue(const std::string& key, const std::string& defaultValue = "") const {
        auto it = args.find(key);
        if (it != args.end()) return it->second;
        return defaultValue;
    }
    
    bool hasValue(const std::string& key) const {
        return args.find(key) != args.end();
    }
    
    void printHelp() const {
        std::cout << "Usage: " << programName << " [options]" << std::endl;
        std::cout << std::endl;
        std::cout << "Options:" << std::endl;
        std::cout << "  --help, -h              Show help message" << std::endl;
        std::cout << "  --version, -v           Show version information" << std::endl;
        std::cout << "  --config=<file>         Load configuration from file (JSON or key=value)" << std::endl;
        std::cout << "  --experiment=<name>     Specify experiment to run" << std::endl;
        std::cout << "  --epochs=<num>          Number of epochs" << std::endl;
        std::cout << "  --steps=<num>           Number of steps per epoch" << std::endl;
        std::cout << "  --seed=<num>            Random seed" << std::endl;
        std::cout << "  --neurons=<num>         Number of neurons" << std::endl;
        std::cout << "  --verbose, -V           Enable verbose output" << std::endl;
        std::cout << std::endl;
        std::cout << "Available experiments:" << std::endl;
        std::cout << "  phase3_demo             Phase 3: World interaction demo" << std::endl;
        std::cout << "  phase4_demo             Phase 4: Advanced learning demo" << std::endl;
        std::cout << "  phase5_demo             Phase 5: Full agent demo" << std::endl;
        std::cout << "  phase6_demo             Phase 6: Integrated brain demo" << std::endl;
        std::cout << "  phase6_text_demo        Phase 6: Text-based demo" << std::endl;
        std::cout << std::endl;
        std::cout << "Example:" << std::endl;
        std::cout << "  " << programName << " --experiment=phase3_demo --epochs=5 --steps=200" << std::endl;
    }
    
    void printVersion() const {
        std::cout << programName << " version 0.1.0 - Phase 2: Real Neural Computation" << std::endl;
    }
};

