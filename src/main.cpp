// Command line argument parsing
struct CLIArgs {
    std::string mode = "basic";
    std::string configFile = "configs/default.cfg";
    uint64_t neuronCount = 500;
    uint64_t regionCount = 1;
    uint64_t maxSteps = 1000;
    float connectionProbability = 0.1f;
    bool enableSTDP = true;
    bool enableHebbian = true;
    bool enableStructuralPlasticity = true;
    bool enableDevelopment = true;
    bool verbose = false;
    std::string outputFile = "";
    bool help = false;
};

CLIArgs parseArguments(int argc, char** argv) {
    CLIArgs args;
    
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        if (arg == "--mode" && i + 1 < argc) {
            args.mode = argv[++i];
        } else if (arg == "--config" && i + 1 < argc) {
            args.configFile = argv[++i];
        } else if (arg == "--neurons" && i + 1 < argc) {
            args.neuronCount = std::stoull(argv[++i]);
        } else if (arg == "--regions" && i + 1 < argc) {
            args.regionCount = std::stoull(argv[++i]);
        } else if (arg == "--steps" && i + 1 < argc) {
            args.maxSteps = std::stoull(argv[++i]);
        } else if (arg == "--connection-prob" && i + 1 < argc) {
            args.connectionProbability = std::stof(argv[++i]);
        } else if (arg == "--no-stdp") {
            args.enableSTDP = false;
        } else if (arg == "--no-hebbian") {
            args.enableHebbian = false;
        } else if (arg == "--no-structural") {
            args.enableStructuralPlasticity = false;
        } else if (arg == "--no-development") {
            args.enableDevelopment = false;
        } else if (arg == "--verbose" || arg == "-v") {
            args.verbose = true;
        } else if (arg == "--output" && i + 1 < argc) {
            args.outputFile = argv[++i];
        } else if (arg == "--help" || arg == "-h") {
            args.help = true;
        }
    }
    
    return args;
}

