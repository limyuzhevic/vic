class LearningExperiment {
public:
    struct Results {
        size_t initialSynapseCount = 0;
        std::vector<float> initialWeights;
        std::vector<float> finalWeights;
        std::vector<NeuronId> mostActiveNeurons;
        size_t totalSpikes = 0;
        bool learningOccurred = false;
        float initialMeanWeight = 0.0f;
        float finalMeanWeight = 0.0f;
        float weightChange = 0.0f;
        size_t strengthened = 0;
        size_t weakened = 0;
        size_t unchanged = 0;
    };
    
    LearningExperiment(std::shared_ptr<Brain> brain, uint64_t seed) 
        : brain(brain), seed(seed) {}
    
    Results runExperiment() {
        Results results;
        
        // Record initial state
        recordState(results, true);
        
        // Run learning simulation
        runPlasticityLearning(results);
        
        // Record final state
        recordState(results, false);
        
        // Calculate statistics
        calculateStatistics(results);
        
        return results;
    }
    
    void runPlasticityLearning(Results& results) {
        NLM_LOG_INFO("");
        NLM_LOG_INFO("=== Running Plasticity Learning Experiment ===");
        NLM_LOG_INFO("Seed: " + std::to_string(seed));
        
        // Enable plasticity on synapses
        if (auto* region = brain->getRegion(RegionId(1))) {
            for (auto& syn : region->getSynapses()) {
                syn->enablePlasticity(true, true, false);  // Enable Hebbian and STDP
            }
        }
        
        // Apply repeated input pattern to stimulate learning
        NLM_LOG_INFO("");
        NLM_LOG_INFO("Applying repeated input patterns (1000 steps)...");
        
        for (SimulationStep step = 0; step < 1000; ++step) {
            // Create input pattern - inject current into sensory neurons
            for (size_t i = 0; i < 20 && i < brain->getTotalNeuronCount() / 4; ++i) {
                brain->injectCurrentToNeurons(NeuronType::Sensory, 30.0f);
            }
            
            brain->step(step, step * 0.001);
            
            // Log progress every 100 steps
            if (step % 100 == 0) {
                NLM_LOG_INFO("  Step " + std::to_string(step) + 
                            " | Spikes: " + std::to_string(brain->getTotalSpikeCount()) +
                            " | Firing: " + std::to_string(brain->getFiringNeuronCount()));
            }
        }
    }
    
    void printExperimentResults(const Results& results) {
        NLM_LOG_INFO("");
        NLM_LOG_INFO("=== Learning Experiment Results ===");
        NLM_LOG_INFO("");
        
        if (results.initialWeights.empty() || results.finalWeights.empty()) {
            NLM_LOG_ERROR("ERROR: No weights recorded");
            return;
        }
        
        // Compute weight changes
        float initialSum = std::accumulate(results.initialWeights.begin(), results.initialWeights.end(), 0.0f);
        float finalSum = std::accumulate(results.finalWeights.begin(), results.finalWeights.end(), 0.0f);
        float initialMean = initialSum / results.initialWeights.size();
        float finalMean = finalSum / results.finalWeights.size();
        
        NLM_LOG_INFO("Weight Statistics:");
        NLM_LOG_INFO("  Initial mean weight: " + std::to_string(initialMean));
        NLM_LOG_INFO("  Final mean weight: " + std::to_string(finalMean));
        NLM_LOG_INFO("  Change: " + std::to_string(finalMean - initialMean));
        
        // Count synapses that changed significantly
        size_t strengthened = 0;
        size_t weakened = 0;
        size_t unchanged = 0;
        
        size_t minSize = std::min(results.initialWeights.size(), results.finalWeights.size());
        for (size_t i = 0; i < minSize; ++i) {
            float delta = results.finalWeights[i] - results.initialWeights[i];
            if (delta > 0.01f) ++strengthened;
            else if (delta < -0.01f) ++weakened;
            else ++unchanged;
        }
        
        NLM_LOG_INFO("");
        NLM_LOG_INFO("Synaptic Changes:");
        NLM_LOG_INFO("  Strengthened: " + std::to_string(strengthened));
        NLM_LOG_INFO("  Weakened: " + std::to_string(weakened));
        NLM_LOG_INFO("  Unchanged: " + std::to_string(unchanged));
        
        NLM_LOG_INFO("");
        NLM_LOG_INFO("Spike Activity:");
        NLM_LOG_INFO("  Total spikes: " + std::to_string(results.totalSpikes));
        NLM_LOG_INFO("  Most active neurons recorded: " + std::to_string(results.mostActiveNeurons.size()));
        
        // Determine if learning occurred
        bool learningOccurred = (std::abs(finalMean - initialMean) > 0.001f) ||
                                (strengthened > 0 || weakened > 0);
        
        NLM_LOG_INFO("");
        if (learningOccurred) {
            NLM_LOG_INFO("✓ LEARNING DETECTED: Synaptic weights changed through experience");
        } else {
            NLM_LOG_INFO("✗ NO LEARNING: Weights did not change significantly");
        }
    }
    
private:
    std::shared_ptr<Brain> brain;
    uint64_t seed;
    
    void recordState(Results& results, bool isInitial) {
        auto& weights = isInitial ? results.initialWeights : results.finalWeights;
        auto& spikeCount = results.totalSpikes;
        
        weights.clear();
        spikeCount = brain->getTotalSpikeCount();
        
        // Record weights from first region
        if (auto* region = brain->getRegion(RegionId(1))) {
            for (const auto& syn : region->getSynapses()) {
                weights.push_back(syn->getWeight());
            }
        }
        
        if (isInitial) {
            results.initialSynapseCount = brain->getTotalSynapseCount();
            NLM_LOG_INFO("Initial state recorded:");
        } else {
            results.mostActiveNeurons = brain->getSpikeSystem()->getMostActiveNeurons(10);
            NLM_LOG_INFO("Final state recorded:");
        }
        
        NLM_LOG_INFO("  Synapses: " + std::to_string(results.initialSynapseCount));
        NLM_LOG_INFO("  Total spikes: " + std::to_string(spikeCount));
        
        if (!weights.empty()) {
            float sum = std::accumulate(weights.begin(), weights.end(), 0.0f);
            float mean = sum / weights.size();
            NLM_LOG_INFO("  Mean weight: " + std::to_string(mean));
            
            if (isInitial) {
                results.initialMeanWeight = mean;
            } else {
                results.finalMeanWeight = mean;
                results.weightChange = mean - results.initialMeanWeight;
            }
        }
    }
    
    void calculateStatistics(Results& results) {
        if (results.initialWeights.empty() || results.finalWeights.empty()) {
            return;
        }
        
        size_t minSize = std::min(results.initialWeights.size(), results.finalWeights.size());
        for (size_t i = 0; i < minSize; ++i) {
            float delta = results.finalWeights[i] - results.initialWeights[i];
            if (delta > 0.01f) ++results.strengthened;
            else if (delta < -0.01f) ++results.weakened;
            else ++results.unchanged;
        }
        
        results.learningOccurred = (std::abs(results.weightChange) > 0.001f) ||
                                   (results.strengthened > 0 || results.weakened > 0);
    }
};

void runBasicConnectivityTest(std::shared_ptr<Brain> brain) {
    NLM_LOG_INFO("");
    NLM_LOG_INFO("=== Test 1: Basic Neural Connectivity ===");
    
    // Inject current into a few neurons and see if spikes propagate
    auto* region = brain->getRegion(RegionId(1));
    if (!region) return;
    
    auto neurons = region->getAllNeurons();
    if (neurons.empty()) {
        NLM_LOG_INFO("  No neurons found!");
        return;
    }
    
    // Get initial spike count
    size_t initialSpikes = brain->getTotalSpikeCount();
    
    // Inject strong current into first 10 neurons
    NLM_LOG_INFO("  Injecting current into 10 neurons...");
    for (size_t i = 0; i < std::min(size_t(10), neurons.size()); ++i) {
        neurons[i]->injectCurrent(50.0f);  // Strong excitatory input
    }
    
    // Run a few steps
    for (SimulationStep step = 0; step < 50; ++step) {
        brain->step(step, step * 0.001);
    }
    
    size_t spikes = brain->getTotalSpikeCount() - initialSpikes;
    NLM_LOG_INFO("  Spikes generated: " + std::to_string(spikes));
    
    if (spikes > 0) {
        NLM_LOG_INFO("  ✓ Spikes propagate through network");
    } else {
        NLM_LOG_INFO("  ! No spikes - checking neuron parameters...");
        for (size_t i = 0; i < std::min(size_t(3), neurons.size()); ++i) {
            NLM_LOG_INFO("    Neuron " + std::to_string(i) + 
                        " V=" + std::to_string(neurons[i]->getMembranePotential()) +
                        " thresh=" + std::to_string(neurons[i]->getThreshold()));
        }
    }
}

