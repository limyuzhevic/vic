// Configuration constants with reasonable defaults
const size_t DEFAULT_NEURON_COUNT = 500;
const size_t DEFAULT_REGION_COUNT = 1;
const float DEFAULT_CONNECTION_PROBABILITY = 0.15f;
const float DEFAULT_STDP_LTP_WEIGHT = 0.02f;
const float DEFAULT_STDP_LTD_WEIGHT = 0.015f;
const float DEFAULT_STDP_TAU = 20.0f;
const float DEFAULT_SYNAPTOGENESIS_RATE = 0.0001f;
const float DEFAULT_PRUNING_RATE = 0.00001f;
const float DEFAULT_SIMULATION_TIMESTEP = 0.001f;

// Command-line arguments structure
struct CommandLineArgs {
    std::string configFile = "configs/default.cfg";
    bool runTests = true;
    bool enableDebug = false;
    SimulationStep maxSteps = 1000;
    NeuronCount neuronCount = DEFAULT_NEURON_COUNT;
    bool verbose = true;
};

// Parse command line arguments
CommandLineArgs parseCommandLineArgs(int argc, char** argv) {
    CommandLineArgs args;
    
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        if (arg == "--help" || arg == "-h") {
            std::cout << "NLM Usage: " << argv[0] << " [options]" << std::endl;
            std::cout << "Options:" << std::endl;
            std::cout << "  --help, -h              Show this help message" << std::endl;
            std::cout << "  --config <file>          Configuration file (default: configs/default.cfg)" << std::endl;
            std::cout << "  --steps <n>             Maximum simulation steps (default: 1000)" << std::endl;
            std::cout << "  --neurons <n>           Neuron count (default: 500)" << std::endl;
            std::cout << "  --quiet, -q             Quiet mode (no logging)" << std::endl;
            std::cout << "  --no-tests              Skip running tests" << std::endl;
            std::cout << "  --debug                 Enable debug logging" << std::endl;
            std::cout << std::endl;
            std::cout << "Examples:" << std::endl;
            std::cout << "  " << argv[0] << " --config myconfig.cfg" << std::endl;
            std::cout << "  " << argv[0] << " --steps 5000 --quiet" << std::endl;
            exit(0);
        }
        
        if (arg.substr(0, 7) == "--config") {
            if (arg.find('=') != std::string::npos) {
                args.configFile = arg.substr(arg.find('=') + 1);
            } else if (i + 1 < argc) {
                args.configFile = argv[++i];
            }
        } else if (arg.substr(0, 8) == "--steps=") {
            args.maxSteps = std::stoul(arg.substr(8));
        } else if (arg.substr(0, 10) == "--neurons=") {
            args.neuronCount = std::stoull(arg.substr(10));
        } else if (arg == "--quiet" || arg == "-q") {
            args.verbose = false;
        } else if (arg == "--no-tests") {
            args.runTests = false;
        } else if (arg == "--debug") {
            args.enableDebug = true;
        }
    }
    
    return args;
}

// Configuration helper functions
void configureBrainWithDefaults(std::shared_ptr<Config> config, const CommandLineArgs& args) {
    config->set("random_seed", static_cast<int64_t>(42), ConfigSource::Default);
    config->set("simulation_timestep", DEFAULT_SIMULATION_TIMESTEP, ConfigSource::Default);
    config->set("neuron_count", static_cast<int64_t>(args.neuronCount), ConfigSource::Default);
    config->set("region_count", static_cast<int64_t>(DEFAULT_REGION_COUNT), ConfigSource::Default);
    config->set("connection_probability", DEFAULT_CONNECTION_PROBABILITY, ConfigSource::Default);
    
    // STDP parameters
    config->set("stdp_ltp_weight", DEFAULT_STDP_LTP_WEIGHT, ConfigSource::Default);
    config->set("stdp_ltd_weight", DEFAULT_STDP_LTD_WEIGHT, ConfigSource::Default);
    config->set("stdp_tau", DEFAULT_STDP_TAU, ConfigSource::Default);
    
    // Structural plasticity parameters
    config->set("synaptogenesis_rate", DEFAULT_SYNAPTOGENESIS_RATE, ConfigSource::Default);
    config->set("pruning_rate", DEFAULT_PRUNING_RATE, ConfigSource::Default);
}

void setupLogging(bool verbose, bool debug) {
    auto logger = std::make_shared<Logger>();
    LogLevel logLevel = debug ? LogLevel::Debug : (verbose ? LogLevel::Info : LogLevel::Warning);
    auto consoleLogger = std::make_shared<ConsoleLogger>(logLevel);
    logger->addLogger(consoleLogger);
    Logger::setGlobal(logger);
}

