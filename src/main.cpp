bool parseArguments(int argc, char** argv, std::string& configFile, bool& verbose, bool& help) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        if (arg == "--help" || arg == "-h") {
            help = true;
        } else if (arg == "--verbose" || arg == "-v") {
            verbose = true;
        } else if (arg.find("--config=") == 0) {
            configFile = arg.substr(9); // strlen("--config=")
        } else if (arg.find("--config") == 0) {
            if (i + 1 < argc && argv[i + 1][0] != '-') {
                configFile = argv[++i];
            } else {
                NLM_LOG_WARNING("Missing config file path after --config");
                return false;
            }
        } else if (arg.find("-") == 0 && arg.length() > 1 && !std::isalpha(arg[1])) {
            // Unknown flag
            NLM_LOG_WARNING("Unknown argument: " + arg);
            return false;
        }
    }
    return true;
}

