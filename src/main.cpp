std::string formatDuration(double seconds) {
    if (seconds < 60) {
        return std::to_string(seconds) + "s";
    } else if (seconds < 3600) {
        return std::to_string(seconds / 60) + "min";
    } else {
        return std::to_string(seconds / 3600) + "h " + std::to_string((seconds / 60) % 60) + "min";
    }
}

void validateConfiguration(std::shared_ptr<Config> config) {
    // Validate configuration parameters
    auto neuronCount = config->getOr<int64_t>("neuron_count", 500);
    auto regionCount = config->getOr<int64_t>("region_count", 1);
    auto timestep = config->getOr<double>("simulation_timestep", 0.001);
    
    if (neuronCount <= 0) {
        NLM_LOG_WARNING("Neuron count should be positive, using default (500)");
        config->set("neuron_count", static_cast<int64_t>(500), ConfigSource::Default);
    }
    
    if (regionCount <= 0) {
        NLM_LOG_WARNING("Region count should be positive, using default (1)");
        config->set("region_count", static_cast<int64_t>(1), ConfigSource::Default);
    }
    
    if (timestep <= 0) {
        NLM_LOG_WARNING("Timestep should be positive, using default (0.001)");
        config->set("simulation_timestep", 0.001, ConfigSource::Default);
    }
}