bool ConfigurationManager::parseCommandLineArgs(int argc, char** argv, 
                                        std::string& configFile,
                                        std::map<std::string, std::string>& extraArgs) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        if (arg == "--help" || arg == "-h") {
            displayHelp();
            return false; // Signal to exit
        }
        else if (arg.substr(0, 7) == "--config") {
            if (arg.find('=') != std::string::npos) {
                configFile = arg.substr(arg.find('=') + 1);
            } else if (i + 1 < argc) {
                configFile = argv[++i];
            }
        }
        else if (arg.find('=') != std::string::npos) {
            // Handle --key=value format
            size_t pos = arg.find('=');
            std::string key = arg.substr(0, pos);
            std::string value = arg.substr(pos + 1);
            extraArgs[key] = value;
        }
        else {
            // Handle standalone flags
            if (arg == "--verbose" || arg == "-v") {
                extraArgs["verbose"] = "true";
            } else if (arg == "--quick-run") {
                extraArgs["quick_run"] = "true";
            } else {
                NLM_LOG_WARNING("Unknown option: " + arg);
            }
        }
    }
    return true;
}

