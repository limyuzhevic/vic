// Enhanced Progress Monitor
class ProgressMonitor {
public:
    static void showProgress(const std::string& message, int current, int total, int width = 50) {
        double progress = static_cast<double>(current) / total;
        int pos = static_cast<int>(progress * width);
        
        std::cout << "\r["; 
        for (int i = 0; i < width; ++i) {
            if (i < pos) std::cout << "=";
            else if (i == pos) std::cout << ">";
            else std::cout << " ";
        }
        std::cout << "] " << std::fixed << std::setprecision(1) << (progress * 100.0) << "% " << message;
        
        if (current >= total) {
            std::cout << std::endl;
        }
    }
    
    static void showSessionInfo(const std::string& sessionName, const std::chrono::system_clock::time_point& startTime) {
        auto now = std::chrono::system_clock::now();
        auto duration = std::chrono::duration_cast<std::chrono::seconds>(now - startTime);
        
        std::cout << "\n=== Session Information ===" << std::endl;
        std::cout << "Session: " << sessionName << std::endl;
        std::cout << "Start time: " << std::put_time(std::localtime(&std::chrono::system_clock::to_time_t(startTime)), "%Y-%m-%d %H:%M:%S") << std::endl;
        std::cout << "Duration: " << duration.count() << " seconds" << std::endl;
        std::cout << "============================" << std::endl;
    }
};

