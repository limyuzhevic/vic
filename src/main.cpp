void runBenchmark(std::shared_ptr<Brain> brain, int maxSteps) {
    NLM_LOG_INFO("");
    NLM_LOG_INFO("=== Performance Benchmark ===");
    
    auto startTime = std::chrono::high_resolution_clock::now();
    
    // Warm-up run
    brain->reset();
    brain->initialize();
    
    size_t warmUpSteps = std::min(maxSteps / 10, 1000UL);
    for (SimulationStep step = 0; step < warmUpSteps; ++step) {
        brain->step(step, step * 0.001);
    }
    
    // Benchmark run
    size_t benchmarkSteps = std::min(maxSteps, 1000UL);
    size_t spikes = 0;
    size_t neurons = 0;
    
    for (SimulationStep step = 0; step < benchmarkSteps; ++step) {
        brain->step(step, step * 0.001);
        spikes += brain->getTotalSpikeCount();
        neurons = brain->getTotalNeuronCount();
    }
    
    auto endTime = std::chrono::high_resolution_clock::now();
    auto duration = std::chrono::duration_cast<std::chrono::milliseconds>(endTime - startTime);
    
    NLM_LOG_INFO("Benchmark Results:");
    NLM_LOG_INFO("  Steps executed: " + std::to_string(benchmarkSteps));
    NLM_LOG_INFO("  Total time: " + std::to_string(duration.count()) + " ms");
    NLM_LOG_INFO("  Average step rate: " + std::to_string(benchmarkSteps * 1000.0 / duration.count()) + " steps/sec");
    NLM_LOG_INFO("  Total spikes generated: " + std::to_string(spikes));
    NLM_LOG_INFO("  Spikes per step: " + std::to_string(spikes / (benchmarkSteps > 0 ? benchmarkSteps : 1)));
    NLM_LOG_INFO("  Neurons in simulation: " + std::to_string(neurons));
    
    // Calculate efficiency
    if (duration.count() > 0) {
        float efficiency = benchmarkSteps * 1000.0f / duration.count();
        NLM_LOG_INFO("  Simulation efficiency: " + std::to_string(efficiency) + " steps/sec");
    }
    
    NLM_LOG_INFO("=== Benchmark Complete ===");
}

