// Inline checksum implementations
uint64_t CheckpointSystem::ChecksumCalculator::crc64Internal(const void* data, size_t size) {
    // Simple implementation using std::hash
    uint64_t result = 0xFFFFFFFFFFFFFFFFULL;
    const uint8_t* bytes = static_cast<const uint8_t*>(data);
    
    for (size_t i = 0; i < size; ++i) {
        result = (result >> 8) ^ table[(result ^ bytes[i]) & 0xFF];
    }
    
    return result ^ 0xFFFFFFFFFFFFFFFFULL;
}

uint32_t CheckpointSystem::ChecksumCalculator::crc32Internal(const void* data, size_t size) {
    uint32_t crc = 0xFFFFFFFF;
    const uint8_t* bytes = static_cast<const uint8_t*>(data);
    
    for (size_t i = 0; i < size; ++i) {
        crc ^= bytes[i];
        for (int j = 0; j < 8; ++j) {
            crc = (crc >> 1) ^ (0xEDB88320 & -(crc & 1));
        }
    }
    
    return ~crc;
}

uint64_t CheckpointSystem::ChecksumCalculator::fletcher64Internal(const uint64_t* data, size_t count) {
    uint64_t sum1 = 0, sum2 = 0;
    for (size_t i = 0; i < count; ++i) {
        sum1 = (sum1 + data[i]) % 0xFFFFFFFFFFFFFFFF;
        sum2 = (sum2 + sum1) % 0xFFFFFFFFFFFFFFFF;
    }
    return (sum2 << 32) | sum1;
}

