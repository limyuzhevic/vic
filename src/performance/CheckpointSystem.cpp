bool CheckpointSystem::CheckpointReader::open(const std::string& filepath) {
    close();
    filepath_ = filepath;
    
    stream_.open(filepath, std::ios::binary | std::ios::in);
    if (!stream_.is_open()) {
        error_ = "Failed to open checkpoint file: " + filepath;
        return false;
    }
    
    // Read header
    stream_.read(reinterpret_cast<char*>(&header_), sizeof(CheckpointHeader));
    if (!stream_.good()) {
        error_ = "Failed to read checkpoint header";
        close();
        return false;
    }
    
    if (!header_.validate()) {
        error_ = "Invalid checkpoint file format";
        close();
        return false;
    }
    
    // Read section headers
    uint64_t sectionCount = (header_.totalSize - sizeof(CheckpointHeader)) / sizeof(SectionHeader);
    sections_.resize(sectionCount);
    
    stream_.seekg(sizeof(CheckpointHeader));
    for (auto& section : sections_) {
        stream_.read(reinterpret_cast<char*>(&section), sizeof(SectionHeader));
        if (!stream_.good()) {
            error_ = "Failed to read section headers";
            close();
            return false;
        }
    }
    
    streamPos_ = stream_.tellg();
    return true;
}

