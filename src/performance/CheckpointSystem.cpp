bool CheckpointSystem::CheckpointReader::validate() const {
    // Simple validation - check if file is not corrupted
    if (!stream_.is_open()) {
        error_ = "Checkpoint file is not open";
        return false;
    }
    
    // Try to read and validate header
    std::streampos currentPos = stream_.tellg();
    stream_.seekg(0);
    
    CheckpointHeader testHeader;
    stream_.read(reinterpret_cast<char*>(&testHeader), sizeof(CheckpointHeader));
    if (!stream_.good()) {
        error_ = "Cannot read checkpoint header";
        return false;
    }
    
    stream_.seekg(currentPos);
    
    return header_.validate();
}

double CheckpointSystem::CheckpointReader::getProgress() const {
    if (sections_.empty()) return 0.0;
    
    uint64_t totalSize = 0;
    for (const auto& section : sections_) {
        totalSize += section.size;
    }
    
    if (totalSize == 0) return 1.0;
    
    uint64_t currentSize = 0;
    for (const auto& section : sections_) {
        if (section.offset <= streamPos_ && streamPos_ < section.offset + section.size) {
            currentSize += (streamPos_ - section.offset);
        } else if (section.offset > streamPos_) {
            currentSize += section.size;
        }
    }
    
    return static_cast<double>(currentSize) / static_cast<double>(totalSize);
}

