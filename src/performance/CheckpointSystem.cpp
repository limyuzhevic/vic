bool CheckpointSystem::CheckpointManager::saveImmediately(const std::string& name) {
    std::string filename = checkpointDir_ + "/";
    if (!name.empty()) {
        filename += name;
    } else {
        filename += "checkpoint_" + std::to_string(lastSaveStep_) + ".bin";
    }
    
    // Create checkpoint
    CheckpointWriter writer;
    
    if (!writer.create(filename, compress_ ? CompressionLevel::Balanced : CompressionLevel::None)) {
        return false;
    }
    
    // Set metadata (simplified - in real implementation would get from brain)
    writer.setMetadata(0, 0, 0, lastSaveStep_, currentTime);
    
    // Write data (if providers are set)
    if (neuronProvider_) {
        NeuronCheckpointData neuronData;
        if (!neuronProvider_(neuronData)) {
            writer.abort();
            return false;
        }
        if (!writer.writeNeurons(neuronData)) {
            writer.abort();
            return false;
        }
    }
    
    if (synapseProvider_) {
        SynapseCheckpointData synapseData;
        if (!synapseProvider_(synapseData)) {
            writer.abort();
            return false;
        }
        if (!writer.writeSynapses(synapseData)) {
            writer.abort();
            return false;
        }
    }
    
    if (!writer.finalize()) {
        return false;
    }
    
    lastCheckpointPath_ = filename;
    return true;
}

