// Advanced configuration management for power users
class AdvancedConfigManager {
public:
    AdvancedConfigManager(std::shared_ptr<Config> config) : config(config) {}
    
    // Load configuration from multiple sources with priority
    bool loadConfiguration(const std::vector<std::string>& configFiles, 
                          const std::string& environmentPrefix = "NLM_") {
        bool allSuccess = true;
        
        // Load from files (in priority order)
        for (const auto& filepath : configFiles) {
            if (!config->loadFromFile(filepath)) {
                NLM_LOG_WARNING("Failed to load configuration from: " + filepath);
                allSuccess = false;
            } else {
                NLM_LOG_INFO("Loaded configuration from: " + filepath);
            }
        }
        
        // Load from environment variables
        config->loadFromEnvironment(environmentPrefix);
        
        return allSuccess;
    }
    
    // Export configuration with different formats and options
    bool exportConfiguration(const std::string& outputFile, 
                            const std::string& format = "json",
                            bool includeDefaults = false,
                            bool includeSecrets = false) {
        Config::Format saveFormat;
        if (format == "json") saveFormat = Config::Format::JSON;
        else if (format == "yaml") saveFormat = Config::Format::YAML;
        else if (format == "simple") saveFormat = Config::Format::SIMPLE;
        else {
            NLM_LOG_ERROR("Unsupported format: " + format);
            return false;
        }
        
        return config->saveToFile(outputFile, saveFormat);
    }
    
    // Create configuration template
    bool createConfigTemplate(const std::string& templateFile, 
                             const std::string& description = "NLM Configuration Template") {
        std::ofstream file(templateFile);
        if (!file.is_open()) {
            NLM_LOG_ERROR("Cannot create template file: " + templateFile);
            return false;
        }
        
        file << "# " << description << "\n";
        file << "# Generated by NLM Advanced Configuration Manager\n";
        file << "# Customize this template for your specific use case\n\n";
        
        // Write sample configuration
        file << "# Core neural parameters\n";
        file << "neuron_count = 1000\n";
        file << "region_count = 1\n";
        file << "simulation_timestep = 0.001\n\n";
        
        file << "# Plasticity parameters\n";
        file << "stdp_ltp_weight = 0.02\n";
        file << "stdp_ltd_weight = 0.015\n";
        file << "stdp_tau = 20.0\n";
        file << "synaptogenesis_rate = 0.0001\n";
        file << "pruning_rate = 0.00001\n\n";
        
        file << "# Memory and performance\n";
        file << "working_memory_capacity = 100\n";
        file << "episodic_memory_max_episodes = 1000\n\n";
        
        file << "# Development parameters\n";
        file << "developmental_stage = 1\n";
        file << "plasticity_modifier = 1.0\n\n";
        
        file << "# Advanced neuromodulation\n";
        file << "enable_curiosity = true\n";
        file << "enable_novelty = true\n";
        file << "enable_dopamine = true\n\n";
        
        file << "# Checkpoint and replay\n";
        file << "enable_checkpointing = true\n";
        file << "checkpoint_dir = ./checkpoints\n";
        file << "enable_replay = true\n";
        file << "replay_interval = 100\n";
        file << "consolidation_interval = 1000\n";
        
        file.close();
        NLM_LOG_INFO("Created configuration template: " + templateFile);
        return true;
    }
    
    // Validate configuration against constraints
    std::vector<std::string> validateConfiguration(const std::string& constraintsFile = "") {
        std::vector<std::string> errors;
        
        // Basic validation
        if (!config->has("neuron_count")) {
            errors.push_back("Missing required parameter: neuron_count");
        } else {
            auto neuronCount = config->get<int64_t>("neuron_count");
            if (neuronCount.has_value() && (*neuronCount <= 0)) {
                errors.push_back("Invalid neuron_count: must be positive");
            }
        }
        
        if (!config->has("simulation_timestep")) {
            errors.push_back("Missing required parameter: simulation_timestep");
        } else {
            auto timestep = config->get<double>("simulation_timestep");
            if (timestep.has_value() && (*timestep <= 0.0)) {
                errors.push_back("Invalid simulation_timestep: must be positive");
            }
        }
        
        // Check for incompatible combinations
        if (config->get<bool>("enable_curiosity").value_or(false) &&
            config->get<bool>("enable_novelty").value_or(false)) {
            // Both enabled - that's fine, but log warning
            NLM_LOG_WARNING("Both curiosity and novelty are enabled - may cause exploration conflicts");
        }
        
        // Load constraint file if provided
        if (!constraintsFile.empty()) {
            // Parse constraint file and apply additional validation
            // This is a simplified implementation
        }
        
        if (errors.empty()) {
            NLM_LOG_INFO("Configuration validation passed");
        } else {
            NLM_LOG_ERROR("Configuration validation failed with " + 
                         std::to_string(errors.size()) + " errors");
            for (const auto& error : errors) {
                NLM_LOG_ERROR("  - " + error);
            }
        }
        
        return errors;
    }
    
private:
    std::shared_ptr<Config> config;
};

// Performance monitoring and statistics
class PerformanceMonitor {
public:
    PerformanceMonitor(std::shared_ptr<Brain> brain) : brain(brain) {}
    
    // Get comprehensive performance statistics
    std::string getPerformanceReport() const {
        std::ostringstream report;
        
        report << "=== NLM Performance Report ===" << std::endl;
        report << std::endl;
        
        // Brain statistics
        report << "Brain Statistics:" << std::endl;
        report << "  Total neurons: " << brain->getTotalNeuronCount() << std::endl;
        report << "  Total synapses: " << brain->getTotalSynapseCount() << std::endl;
        report << "  Active neurons: " << brain->getActiveNeuronCount() << std::endl;
        report << "  Firing neurons (this step): " << brain->getFiringNeuronCount() << std::endl;
        report << "  Total spikes: " << brain->getTotalSpikeCount() << std::endl;
        report << "  Pending spike events: " << brain->getPendingSpikeEventCount() << std::endl;
        report << "  Average firing rate: " << brain->getAverageFiringRate() << std::endl;
        report << "  E/I ratio: " << brain->getExcitationInhibitionRatio() << std::endl;
        report << std::endl;
        
        // Memory statistics
        auto* workingMemory = brain->getWorkingMemory();
        if (workingMemory) {
            report << "Memory Systems:" << std::endl;
            report << "  Working memory traces: " << workingMemory->getActiveTraces() << std::endl;
        }
        
        auto* episodicMemory = brain->getEpisodicMemory();
        if (episodicMemory) {
            report << "  Episodic memory episodes: " << episodicMemory->getEpisodeCount() << std::endl;
        }
        
        // Neuromodulation statistics
        auto* dopamine = brain->getDopamine();
        if (dopamine) {
            report << "Neuromodulation:" << std::endl;
            report << "  Dopamine level: " << dopamine->getLevel() << std::endl;
        }
        
        auto* curiosity = brain->getCuriosity();
        if (curiosity) {
            report << "  Curiosity level: " << curiosity->getLevel() << std::endl;
        }
        
        return report.str();
    }
    
    // Get detailed performance metrics
    std::map<std::string, double> getPerformanceMetrics() const {
        std::map<std::string, double> metrics;
        
        metrics["total_neurons"] = static_cast<double>(brain->getTotalNeuronCount());
        metrics["total_synapses"] = static_cast<double>(brain->getTotalSynapseCount());
        metrics["active_neurons"] = static_cast<double>(brain->getActiveNeuronCount());
        metrics["firing_neurons"] = static_cast<double>(brain->getFiringNeuronCount());
        metrics["total_spikes"] = static_cast<double>(brain->getTotalSpikeCount());
        metrics["pending_events"] = static_cast<double>(brain->getPendingSpikeEventCount());
        metrics["avg_firing_rate"] = brain->getAverageFiringRate();
        metrics["e_i_ratio"] = brain->getExcitationInhibitionRatio();
        
        return metrics;
    }
    
    // Check if performance is within acceptable limits
    bool isPerformanceAcceptable(double maxMemoryUsage = 1000.0, 
                                 double maxFiringRate = 1000.0) const {
        auto metrics = getPerformanceMetrics();
        
        return metrics["firing_neurons"] <= maxFiringRate &&
               metrics["total_synapses"] <= maxMemoryUsage;
    }
    
private:
    std::shared_ptr<Brain> brain;
};

