bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

void Config::loadFromEnvironment(const std::string& prefix) {
    // Load environment variables that start with the given prefix
    for (const auto& entry : g_defaultSchema) {
        std::string envKey = prefix + "_" + entry.key;
        const char* envValue = std::getenv(envKey.c_str());
        if (envValue) {
            set(entry.key, std::string(envValue), ConfigSource::Environment);
        }
    }
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    // Add header comment
    file << "# NLM Configuration File\n";
    file << "# Generated by NLM Configuration System\n\n";
    
    for (const auto& entry : pImpl->entries) {
        file << "# " << entry.description << "\n";
        file << entry.key << " = ";
        
        // Use appropriate formatting based on type
        std::visit([&file](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                file << "\"" << arg << "\"";
            } else if constexpr (std::is_same_v<T, bool>) {
                file << (arg ? "true" : "false");
            } else {
                file << arg;
            }
        }, entry.value);
        file << "\n\n";
    }
    
    return true;
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

template<typename T>
T Config::getRequired(const std::string& key) const {
    auto val = get<T>(key);
    if (!val.has_value()) {
        throw config::ConfigNotFoundException(key);
    }
    return val.value();
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        it->value = value;
        it->source = source;
    } else {
        pImpl->entries.emplace_back(key, value, source);
    }
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

bool Config::validate() const {
    if (g_defaultSchema.empty()) {
        return true; // No schema to validate against
    }
    
    auto errors = validate(g_defaultSchema);
    return errors.empty();
}

std::vector<std::string> Config::validate(const std::vector<ConfigSchema>& schema) const {
    std::vector<std::string> errors;
    
    for (const auto& schemaEntry : schema) {
        bool hasValue = has(schemaEntry.key);
        
        // Check if required
        if (schemaEntry.required && !hasValue) {
            errors.push_back("Required configuration key '" + schemaEntry.key + "' is missing");
            continue;
        }
        
        // If value exists, validate it
        if (hasValue) {
            try {
                // Get the actual value
                auto actualValue = getByKey(schemaEntry.key);
                
                // Check type matches
                if (!validateValueType(actualValue, schemaEntry.type)) {
                    errors.push_back("Configuration key '" + schemaEntry.key + 
                                   "' has wrong type. Expected " + typeName(schemaEntry.type) +
                                   ", got " + typeName(actualValue));
                }
                
                // Check regex validation if provided
                if (!schemaEntry.validationRegex.empty()) {
                    std::string strValue;
                    if (std::holds_alternative<std::string>(actualValue)) {
                        strValue = std::get<std::string>(actualValue);
                    } else {
                        // Convert other types to string for regex matching
                        std::ostringstream oss;
                        oss << actualValue;
                        strValue = oss.str();
                    }
                    
                    if (!matchesRegex(strValue, schemaEntry.validationRegex)) {
                        errors.push_back("Configuration key '" + schemaEntry.key +
                                       "' value '" + strValue + "' does not match pattern " +
                                       schemaEntry.validationRegex);
                    }
                }
                
            } catch (const std::exception& e) {
                errors.push_back("Error validating configuration key '" + schemaEntry.key +
                               "': " + e.what());
            }
        }
    }
    
    return errors;
}

void Config::setDefaultSchema(const std::vector<ConfigSchema>& schema) {
    g_defaultSchema = schema;
}

const std::vector<ConfigSchema>& Config::getDefaultSchema() {
    return g_defaultSchema;
}

bool Config::isEnvironmentVariable(const std::string& key) {
    std::string envKey = "NLM_" + key;
    return std::getenv(envKey.c_str()) != nullptr;
}

std::string Config::getEnvironmentVariable(const std::string& key) {
    std::string envKey = "NLM_" + key;
    const char* value = std::getenv(envKey.c_str());
    return value ? value : "";
}

bool Config::matchesRegex(const std::string& value, const std::string& regex) {
    try {
        std::regex pattern(regex);
        return std::regex_match(value, pattern);
    } catch (const std::regex_error&) {
        return false;
    }
}

bool Config::validateValueType(const ConfigValue& value, const ConfigValue& type) {
    return std::visit([](auto&& val, auto&& typeVal) {
        using ValType = std::decay_t<decltype(val)>;
        using TypeType = std::decay_t<decltype(typeVal)>;
        
        if constexpr (std::is_same_v<ValType, TypeType>) {
            return true;
        } else {
            // Allow some conversions
            if constexpr (std::is_same_v<TypeType, std::string>) {
                return true; // Any type can be converted to string
            } else if constexpr (std::is_same_v<TypeType, int> && std::is_same_v<ValType, double>) {
                return std::abs(static_cast<double>(std::get<double>(val)) - static_cast<double>(std::get<int>(typeVal))) < 1e-9;
            } else {
                return false;
            }
        }
    }, value, type);
}

std::string Config::typeName(const ConfigValue& value) {
    return std::visit([](auto&& val) {
        using T = std::decay_t<decltype(val)>;
        if constexpr (std::is_same_v<T, int>) return "int";
        else if constexpr (std::is_same_v<T, int64_t>) return "int64_t";
        else if constexpr (std::is_same_v<T, double>) return "double";
        else if constexpr (std::is_same_v<T, bool>) return "bool";
        else if constexpr (std::is_same_v<T, std::string>) return "string";
        else if constexpr (std::is_same_v<T, std::vector<int>>) return "vector<int>";
        else if constexpr (std::is_same_v<T, std::vector<double>>) return "vector<double>";
        else if constexpr (std::is_same_v<T, std::vector<std::string>>) return "vector<string>";
        else return "unknown";
    }, value);
}

ConfigValue Config::getByKey(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        throw config::ConfigNotFoundException(key);
    }
    
    return it->value;
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::toLower(const std::string& str) {
    std::string result = str;
    std::transform(result.begin(), result.end(), result.begin(), ::tolower);
    return result;
}

