    std::string ConfigurationGenerator::GenerateCustomConfig(const std::map<std::string, std::string>& customSettings) {
        std::stringstream config;
        config << "# NLM Custom Configuration\n";
        config << "# Generated from custom settings\n\n";
        
        // Parse and organize settings by section
        std::map<std::string, std::map<std::string, std::string>> sections;
        
        for (const auto& setting : customSettings) {
            size_t dotPos = setting.first.find('.');
            if (dotPos != std::string::npos) {
                std::string section = setting.first.substr(0, dotPos);
                std::string key = setting.first.substr(dotPos + 1);
                sections[section][key] = setting.second;
            }
        }
        
        // Output sections
        for (const auto& sectionPair : sections) {
            config << "[" << sectionPair.first << "]\n";
            for (const auto& settingPair : sectionPair.second) {
                config << settingPair.first << " = " << settingPair.second << "\n";
            }
            config << "\n";
        }
        
        return config.str();
    }

