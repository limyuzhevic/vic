    bool ConfigurationValidator::ValidateParameter(const std::string& name, const std::string& value) {
        // Basic validation logic - can be extended with more sophisticated rules
        if (name.empty() || value.empty()) {
            return false;
        }
        
        // Check for basic pattern validation
        if (name.find('.') == std::string::npos) {
            return false; // Should have section.subsection format
        }
        
        return true;
    }

    bool ConfigurationValidator::ValidateFile(const std::string& filepath) {
        std::ifstream file(filepath);
        if (!file.is_open()) {
            return false;
        }
        
        // Basic file validation - can be extended with format checking
        std::string line;
        size_t lineNumber = 0;
        while (std::getline(file, line)) {
            lineNumber++;
            // Skip comments and empty lines
            if (line.empty() || line[0] == '#') {
                continue;
            }
            
            // Check for basic format: parameter = value
            size_t equalsPos = line.find('=');
            if (equalsPos == std::string::npos) {
                // Could return specific error about malformed line
                continue;
            }
        }
        
        return true;
    }

