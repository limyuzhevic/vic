    std::string ConfigurationComparator::GenerateDiffReport(const ComparisonResult& result) {
        std::stringstream report;
        report << "Configuration Comparison Report\n";
        report << "================================\n\n";
        
        if (!result.differences.empty()) {
            report << "Differences:\n";
            for (const auto& diff : result.differences) {
                report << "  - " << diff << "\n";
            }
            report << "\n";
        }
        
        if (!result.similarities.empty()) {
            report << "Similarities:\n";
            for (const auto& sim : result.similarities) {
                report << "  + " << sim << "\n";
            }
            report << "\n";
        }
        
        report << "Similarity Score: " << result.similarityScore << "%\n";
        
        return report.str();
    }

