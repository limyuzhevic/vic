bool Config::loadFromFile(const std::string& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    while (std::getline(file, line)) {
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            // Try to parse as different types (int, double, bool, list)
            if (value.empty()) {
                set(key, std::string(""), ConfigSource::File);
            } else if (value[0] == '"' && value[value.size() - 1] == '"') {
                // String value
                set(key, value.substr(1, value.size() - 2), ConfigSource::File);
            } else {
                // Try to parse as boolean
                if (value == "true" || value == "false") {
                    bool boolVal = (value == "true");
                    set(key, boolVal, ConfigSource::File);
                } else {
                    // Try to parse as number
                    size_t posDecimal;
                    try {
                        int intVal = std::stoi(value);
                        set(key, intVal, ConfigSource::File);
                    } catch (const std::invalid_argument&) {
                        try {
                            double doubleVal = std::stod(value);
                            set(key, doubleVal, ConfigSource::File);
                        } catch (const std::invalid_argument&) {
                            // Check if it's a list (comma-separated)
                            if (value.find(',') != std::string::npos) {
                                std::vector<int> intList;
                                std::stringstream ss(value);
                                std::string item;
                                while (std::getline(ss, item, ',')) {
                                    item = trim(item);
                                    try {
                                        intList.push_back(std::stoi(item));
                                    } catch (const std::invalid_argument&) {
                                        // If any item fails to parse, treat as string list
                                        std::vector<std::string> strList = {value};
                                        set(key, strList, ConfigSource::File);
                                        break;
                                    }
                                }
                                set(key, intList, ConfigSource::File);
                            } else {
                                // Try string list
                                std::vector<std::string> strList = {value};
                                set(key, strList, ConfigSource::File);
                            }
                        }
                    }
                }
            }
        }
    }
    
    return true;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    // Add header comment
    file << "# NLM Brain Configuration File\n";
    file << "# Generated by NLM Config System\n\n";
    
    for (const auto& entry : pImpl->entries) {
        file << "# " << entry.description << "\n";
        
        // Format value based on type
        std::visit([&file](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, int>) {
                file << entry.key << " = " << arg << "\n\n";
            } else if constexpr (std::is_same_v<T, int64_t>) {
                file << entry.key << " = " << arg << "\n\n";
            } else if constexpr (std::is_same_v<T, double>) {
                file << entry.key << " = " << arg << "\n\n";
            } else if constexpr (std::is_same_v<T, bool>) {
                file << entry.key << " = " << (arg ? "true" : "false") << "\n\n";
            } else if constexpr (std::is_same_v<T, std::string>) {
                file << entry.key << " = \"" << arg << "\"\n\n";
            } else if constexpr (std::is_same_v<T, std::vector<int>>) {
                file << entry.key << " = ";
                for (size_t i = 0; i < arg.size(); ++i) {
                    file << arg[i];
                    if (i < arg.size() - 1) file << ", ";
                }
                file << "\n\n";
            } else if constexpr (std::is_same_v<T, std::vector<double>>) {
                file << entry.key << " = ";
                for (size_t i = 0; i < arg.size(); ++i) {
                    file << arg[i];
                    if (i < arg.size() - 1) file << ", ";
                }
                file << "\n\n";
            } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                file << entry.key << " = ";
                for (size_t i = 0; i < arg.size(); ++i) {
                    file << "\"" << arg[i] << "\"";
                    if (i < arg.size() - 1) file << ", ";
                }
                file << "\n\n";
            }
        }, entry.value);
    }
    
    return true;
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        it->value = value;
        it->source = source;
    } else {
        pImpl->entries.emplace_back(key, value, source);
    }
}

void Config::set(const std::string& key, const std::vector<int>& values, ConfigSource source) {
    set(key, ConfigValue(values), source);
}

void Config::set(const std::string& key, const std::vector<double>& values, ConfigSource source) {
    set(key, ConfigValue(values), source);
}

void Config::set(const std::string& key, const std::vector<std::string>& values, ConfigSource source) {
    set(key, ConfigValue(values), source);
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

void Config::addDefaults(const std::string& key, const ConfigValue& value, const std::string& description) {
    // Check if key already has a runtime value
    if (has(key) && getConfigSource(key) == ConfigSource::Runtime) {
        return;  // Don't override runtime values with defaults
    }
    
    // If key doesn't exist or has a non-runtime source, add as default
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        if (it->source != ConfigSource::Runtime) {
            it->value = value;
            it->description = description;
            it->source = ConfigSource::Default;
        }
    } else {
        pImpl->entries.emplace_back(key, value, ConfigSource::Default, description);
    }
}

std::optional<ConfigValue> Config::getDefault(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key && e.source == ConfigSource::Default; });
    
    if (it != pImpl->entries.end()) {
        return it->value;
    }
    
    return std::nullopt;
}

bool Config::hasDefault(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key && e.source == ConfigSource::Default; });
    
    return it != pImpl->entries.end();
}

ConfigSource Config::getConfigSource(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        return it->source;
    }
    
    return ConfigSource::Default;
}

void Config::merge(const Config& other) {
    for (const auto& otherEntry : other.pImpl->entries) {
        auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&otherEntry](const ConfigEntry& e) { return e.key == otherEntry.key; });
        
        if (it != pImpl->entries.end()) {
            // Override existing value
            it->value = otherEntry.value;
            it->source = otherEntry.source;
            it->description = otherEntry.description;
        } else {
            // Add new entry
            pImpl->entries.push_back(otherEntry);
        }
    }
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::toLower(const std::string& str) {
    std::string result = str;
    std::transform(result.begin(), result.end(), result.begin(), ::tolower);
    return result;
}

