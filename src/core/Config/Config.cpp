bool Config::loadFromFile(const std::string& filepath) {
    // Try JSON first (preferred format)
    auto jsonResult = loadFromJsonFile(filepath);
    if (jsonResult) {
        return true;
    }
    
    // Fall back to simple key=value format for backward compatibility
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    // Try to detect file type by extension and content
    std::string extension = "";
    size_t dotPos = filepath.find_last_of('.');
    if (dotPos != std::string::npos) {
        extension = filepath.substr(dotPos + 1);
        if (toLower(extension) == "json") {
            return false;  // JSON failed, don't try fallback
        }
    }
    
    // Simple key=value format (legacy)
    std::string line;
    int lineNumber = 0;
    while (std::getline(file, line)) {
        lineNumber++;
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
        } else {
            // Log warning for malformed line
            if (lineNumber <= 10) {  // Only log first 10 malformed lines to avoid spam
                NLM_LOG_WARNING("Malformed config line in " + filepath + ": " + line);
            }
        }
    }
    
    return true;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    // Auto-detect format based on file extension
    std::string extension = "";
    size_t dotPos = filepath.find_last_of('.');
    if (dotPos != std::string::npos) {
        extension = filepath.substr(dotPos + 1);
        if (toLower(extension) == "json") {
            return saveToJsonFile(filepath);
        }
    }
    
    // Default to simple key=value format for backward compatibility
    std::ofstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    file << "# NLM Configuration File\n";
    file << "# Generated by NLM configuration system\n\n";
    
    for (const auto& entry : pImpl->entries) {
        file << "# " << (entry.description.empty() ? "" : entry.description) << "\n";
        file << "# Source: " << static_cast<int>(entry.source) << "\n";
        file << entry.key << " = ";
        
        // Format value based on type
        std::visit([&file](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                file << "\"" << arg << "\"";
            } else if constexpr (std::is_same_v<T, std::vector<int>>) {
                file << "[";
                for (size_t i = 0; i < arg.size(); ++i) {
                    if (i > 0) file << ", ";
                    file << arg[i];
                }
                file << "]";
            } else if constexpr (std::is_same_v<T, std::vector<double>>) {
                file << "[";
                for (size_t i = 0; i < arg.size(); ++i) {
                    if (i > 0) file << ", ";
                    file << arg[i];
                }
                file << "]";
            } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                file << "[";
                for (size_t i = 0; i < arg.size(); ++i) {
                    if (i > 0) file << ", ";
                    file << "\"" << arg[i] << "\"";
                }
                file << "]";
            } else {
                file << arg;
            }
        }, entry.value);
        
        file << "\n\n";
    }
    
    return true;
}

// JSON loading implementation
bool Config::loadFromJsonFile(const std::string& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    try {
        nlohmann::json jsonData;
        file >> jsonData;
        
        // Clear existing entries
        clear();
        
        // Parse JSON data
        for (auto it = jsonData.begin(); it != jsonData.end(); ++it) {
            std::string key = it.key();
            
            // Convert JSON value to ConfigValue
            ConfigValue configValue;
            try {
                if (it->is_string()) {
                    configValue = it->get<std::string>();
                } else if (it->is_number_integer()) {
                    configValue = it->get<int64_t>();
                } else if (it->is_number_float()) {
                    configValue = it->get<double>();
                } else if (it->is_boolean()) {
                    configValue = it->get<bool>();
                } else if (it->is_array()) {
                    // Determine array element type
                    if (!it->empty()) {
                        if (it->front().is_number_integer()) {
                            std::vector<int64_t> intArray;
                            for (const auto& item : *it) {
                                intArray.push_back(item.get<int64_t>());
                            }
                            configValue = intArray;
                        } else if (it->front().is_number_float()) {
                            std::vector<double> doubleArray;
                            for (const auto& item : *it) {
                                doubleArray.push_back(item.get<double>());
                            }
                            configValue = doubleArray;
                        } else if (it->front().is_string()) {
                            std::vector<std::string> stringArray;
                            for (const auto& item : *it) {
                                stringArray.push_back(item.get<std::string>());
                            }
                            configValue = stringArray;
                        } else {
                            // Default to string array
                            std::vector<std::string> stringArray;
                            for (const auto& item : *it) {
                                stringArray.push_back(item.dump());
                            }
                            configValue = stringArray;
                        }
                    } else {
                        configValue = std::vector<std::string>{};
                    }
                } else {
                    // Default to string representation
                    configValue = it->dump();
                }
                
                set(key, configValue, ConfigSource::File);
            } catch (const std::exception& e) {
                NLM_LOG_WARNING("Failed to convert JSON value for key '" + key + "': " + e.what());
                continue;
            }
        }
        
        return true;
    } catch (const nlohmann::json::parse_error& e) {
        NLM_LOG_ERROR("JSON parse error in " + filepath + ": " + e.what());
        return false;
    } catch (const std::exception& e) {
        NLM_LOG_ERROR("Error loading JSON config from " + filepath + ": " + e.what());
        return false;
    }
}

// JSON saving implementation
bool Config::saveToJsonFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    try {
        nlohmann::json jsonData;
        
        for (const auto& entry : pImpl->entries) {
            // Convert ConfigValue to JSON
            nlohmann::json jsonValue;
            try {
                std::visit([&jsonValue](auto&& arg) {
                    using T = std::decay_t<decltype(arg)>;
                    if constexpr (std::is_same_v<T, int64_t>) {
                        jsonValue = arg;
                    } else if constexpr (std::is_same_v<T, double>) {
                        jsonValue = arg;
                    } else if constexpr (std::is_same_v<T, bool>) {
                        jsonValue = arg;
                    } else if constexpr (std::is_same_v<T, std::string>) {
                        jsonValue = arg;
                    } else if constexpr (std::is_same_v<T, std::vector<int64_t>>) {
                        jsonValue = arg;
                    } else if constexpr (std::is_same_v<T, std::vector<double>>) {
                        jsonValue = arg;
                    } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                        jsonValue = arg;
                    } else {
                        // Fallback for unknown types
                        jsonValue = "unknown_type";
                    }
                }, entry.value);
                
                jsonData[entry.key] = jsonValue;
            } catch (const std::exception& e) {
                NLM_LOG_WARNING("Failed to convert config value for key '" + entry.key + "' to JSON: " + e.what());
                continue;
            }
        }
        
        // Write formatted JSON with pretty print
        file << jsonData.dump(2);
        file << "\n";  // Final newline
        
        return true;
    } catch (const std::exception& e) {
        NLM_LOG_ERROR("Error saving JSON config to " + filepath + ": " + e.what());
        return false;
    }
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        it->value = value;
        it->source = source;
    } else {
        pImpl->entries.emplace_back(key, value, source);
    }
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::toLower(const std::string& str) {
    std::string result = str;
    std::transform(result.begin(), result.end(), result.begin(), ::tolower);
    return result;
}

