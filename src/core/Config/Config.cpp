bool Config::loadFromFile(const std::string& filepath) {
    // Try to parse as JSON first
    try {
        std::ifstream file(filepath);
        if (!file.is_open()) {
            return false;
        }
        
        nlohmann::json jsonData;
        file >> jsonData;
        
        // Convert JSON to config entries
        for (auto it = jsonData.begin(); it != jsonData.end(); ++it) {
            std::string key = it.key();
            const nlohmann::json& value = it.value();
            
            // Convert JSON value to ConfigValue
            ConfigValue configValue;
            if (value.is_string()) {
                configValue = value.get<std::string>();
            } else if (value.is_number_integer()) {
                configValue = value.get<int64_t>();
            } else if (value.is_number_float()) {
                configValue = value.get<double>();
            } else if (value.is_boolean()) {
                configValue = value.get<bool>();
            } else if (value.is_array()) {
                // Handle arrays - convert to vector
                if (value.empty()) {
                    // Create appropriate empty vector
                    configValue = std::vector<int>{};
                } else if (value[0].is_string()) {
                    std::vector<std::string> strVec;
                    strVec.reserve(value.size());
                    for (const auto& item : value) {
                        strVec.push_back(item.get<std::string>());
                    }
                    configValue = strVec;
                } else if (value[0].is_number_integer()) {
                    std::vector<int> intVec;
                    intVec.reserve(value.size());
                    for (const auto& item : value) {
                        intVec.push_back(item.get<int64_t>());
                    }
                    configValue = intVec;
                } else {
                    std::vector<double> doubleVec;
                    doubleVec.reserve(value.size());
                    for (const auto& item : value) {
                        doubleVec.push_back(item.get<double>());
                    }
                    configValue = doubleVec;
                }
            } else {
                // Skip unsupported types
                continue;
            }
            
            set(key, configValue, ConfigSource::File);
        }
        
        return true;
    } catch (const std::exception&) {
        // Fall back to simple key=value format
    }
    
    // Fallback to simple key=value format
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    while (std::getline(file, line)) {
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
        }
    }
    
    return true;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    file << "# NLM Configuration File (JSON format)" << std::endl;
    file << "# Generated by NLM configuration system" << std::endl;
    file << std::endl;
    
    nlohmann::json jsonData;
    
    for (const auto& entry : pImpl->entries) {
        // Convert ConfigValue to nlohmann::json
        nlohmann::json jsonValue;
        std::visit([&](auto&& arg) {
            jsonValue = arg;
        }, entry.value);
        
        jsonData[entry.key] = jsonValue;
    }
    
    // Write JSON to file with indentation for readability
    file << std::setw(2) << jsonData << std::endl;
    
    return true;
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        it->value = value;
        it->source = source;
    } else {
        pImpl->entries.emplace_back(key, value, source);
    }
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

// Implementation of batch operations
void Config::setBatch(const std::vector<std::pair<std::string, ConfigValue>>& values) {
    for (const auto& pair : values) {
        set(pair.first, pair.second, ConfigSource::Runtime);
    }
}

// Implementation of parameter validation
bool Config::validateParameter(const std::string& key, const ConfigValue& value, std::string& error) const {
    auto info = getParameterInfo(key);
    if (info.name.empty()) {
        return true;  // Unknown parameter, allow it
    }
    
    // Type checking
    bool typeValid = false;
    if (std::holds_alternative<int>(value)) {
        typeValid = info.type == "int";
    } else if (std::holds_alternative<int64_t>(value)) {
        typeValid = info.type == "int" || info.type == "int64_t";
    } else if (std::holds_alternative<double>(value)) {
        typeValid = info.type == "double" || info.type == "float";
    } else if (std::holds_alternative<bool>(value)) {
        typeValid = info.type == "bool";
    } else if (std::holds_alternative<std::string>(value)) {
        typeValid = info.type == "string";
    } else if (std::holds_alternative<std::vector<int>>(value)) {
        typeValid = info.type == "int[]";
    } else if (std::holds_alternative<std::vector<double>>(value)) {
        typeValid = info.type == "double[]";
    } else if (std::holds_alternative<std::vector<std::string>>(value)) {
        typeValid = info.type == "string[]";
    }
    
    if (!typeValid) {
        error = "Type mismatch for parameter '" + key + "'. Expected " + info.type + ".";
        return false;
    }
    
    // Range checking for numeric types
    double numValue = 0.0;
    if (std::holds_alternative<int>(value)) {
        numValue = static_cast<double>(std::get<int>(value));
    } else if (std::holds_alternative<int64_t>(value)) {
        numValue = static_cast<double>(std::get<int64_t>(value));
    } else if (std::holds_alternative<double>(value)) {
        numValue = std::get<double>(value);
    }
    
    if (info.minValue && numValue < *info.minValue) {
        error = "Value for parameter '" + key + "' is below minimum allowed value " + std::to_string(*info.minValue) + ".";
        return false;
    }
    
    if (info.maxValue && numValue > *info.maxValue) {
        error = "Value for parameter '" + key + "' exceeds maximum allowed value " + std::to_string(*info.maxValue) + ".";
        return false;
    }
    
    // Enum checking for string values
    if (std::holds_alternative<std::string>(value)) {
        const std::string& strValue = std::get<std::string>(value);
        bool validEnum = true;
        for (const auto& validVal : info.validValues) {
            if (strValue == validVal) {
                validEnum = true;
                break;
            }
        }
        if (!validEnum && !info.validValues.empty()) {
            error = "Value for parameter '" + key + "' is not a valid option.";
            return false;
        }
    }
    
    return true;
}

