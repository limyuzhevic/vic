bool Config::loadFromFile(const std::string& filepath) {
    // TODO PHASE 2: Implement proper JSON/YAML parser
    // PLACEHOLDER - Phase 1 uses a simple key=value format
    
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    size_t lineNumber = 0;
    bool success = true;
    
    while (std::getline(file, line)) {
        ++lineNumber;
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
        } else {
            // Log warning about malformed line
            std::cerr << "WARNING: Malformed config line in " << filepath << ":" 
                     << lineNumber << ": '" << line << "' (missing '=')" << std::endl;
            success = false;
        }
    }
    
    file.close();
    return success;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            } else {
                // Log warning about malformed argument
                std::cerr << "WARNING: Malformed command line argument: '" << arg << "' (missing '=')" << std::endl;
                return false;
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        } else {
            // Log warning about malformed argument
            std::cerr << "WARNING: Malformed command line argument: '" << arg << "' (should be -key value or --key=value)" << std::endl;
            return false;
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    // Write header
    file << "# NLM Configuration File" << std::endl;
    file << "# Generated by NLM Phase 6" << std::endl;
    file << "# Do not edit manually unless you know what you're doing" << std::endl;
    file << std::endl;
    
    for (const auto& entry : pImpl->entries) {
        file << "# " << entry.description << "\n";
        file << entry.key << " = ";
        
        // Write the value appropriately
        std::visit([&file](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                file << "\"" << arg << "\"";
            } else {
                file << arg;
            }
        }, entry.value);
        
        file << "\n\n";
    }
    
    file.close();
    return true;
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        it->value = value;
        it->source = source;
    } else {
        pImpl->entries.emplace_back(key, value, source);
    }
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::toLower(const std::string& str) {
    std::string result = str;
    std::transform(result.begin(), result.end(), result.begin(), ::tolower);
    return result;
}

void Config::validate(const std::unordered_set<std::string>& requiredKeys,
                     const std::unordered_map<std::string, std::function<bool(const ConfigValue&)>>& validators) {
    std::vector<std::string> errors;
    
    // Check required keys
    for (const auto& key : requiredKeys) {
        if (!has(key)) {
            errors.push_back("Missing required key: '" + key + "'");
        }
    }
    
    // Check custom validators
    for (const auto& [key, validator] : validators) {
        if (has(key)) {
            auto valueOpt = get<std::string>(key);  // Simplified - would need templated approach
            if (valueOpt && !validator(*valueOpt)) {
                errors.push_back("Validation failed for key: '" + key + "'");
            }
        }
    }
    
    if (!errors.empty()) {
        std::string errorMsg = "Configuration validation failed:\n";
        for (const auto& error : errors) {
            errorMsg += "  - " + error + "\n";
        }
        throw std::runtime_error(errorMsg);
    }
}

bool Config::validateAndFix(std::unordered_set<std::string>& outMissingKeys,
                           std::vector<std::string>& outWarnings) {
    bool isValid = true;
    
    // Check for common configuration issues
    if (has("random_seed")) {
        auto seedOpt = get<int64_t>("random_seed");
        if (seedOpt && (*seedOpt < 0 || *seedOpt > 2147483647)) {
            outWarnings.push_back("random_seed " + std::to_string(*seedOpt) + 
                                " is outside typical range [0, 2147483647]");
        }
    }
    
    if (has("neuron_count")) {
        auto countOpt = get<int64_t>("neuron_count");
        if (countOpt && (*countOpt <= 0)) {
            outWarnings.push_back("neuron_count must be positive, got " + std::to_string(*countOpt));
            isValid = false;
        } else if (countOpt && (*countOpt > 100000)) {
            outWarnings.push_back("neuron_count " + std::to_string(*countOpt) + 
                                " is very large, may impact performance");
        }
    }
    
    if (has("simulation_timestep")) {
        auto timestepOpt = get<double>("simulation_timestep");
        if (timestepOpt && (*timestepOpt <= 0.0)) {
            outWarnings.push_back("simulation_timestep must be positive, got " + std::to_string(*timestepOpt));
            isValid = false;
        } else if (timestepOpt && (*timestepOpt > 1.0)) {
            outWarnings.push_back("simulation_timestep " + std::to_string(*timestepOpt) + 
                                " is very large, may impact simulation accuracy");
        }
    }
    
    // Check for negative values in other parameters
    for (const auto& key : getKeys()) {
        auto valueOpt = get<double>(key);
        if (valueOpt && *valueOpt < 0.0) {
            outWarnings.push_back("Parameter '" + key + "' has negative value " + std::to_string(*valueOpt));
        }
    }
    
    return isValid;
}
