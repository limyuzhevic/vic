std::optional<std::string> Config::loadFromJSONFile(const std::string& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return std::nullopt;
    }
    
    std::string jsonContent((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
    return jsonContent;
}

std::optional<std::string> Config::loadFromYAMLFile(const std::string& filepath) {
    // For now, treat YAML as a simplified JSON for backward compatibility
    // In a full implementation, you would use a YAML parser library
    return loadFromJSONFile(filepath);
}

void Config::applyJSON(const std::string& json) {
    // Simplified JSON parsing for basic key-value pairs
    // This is a basic implementation - for production use, consider a proper JSON library
    std::stringstream ss(json);
    std::string line;
    
    while (std::getline(ss, line)) {
        line = trim(line);
        if (line.empty() || line[0] == '{' || line[0] == '}' || line[0] == '[' || line[0] == ']') {
            continue;
        }
        
        // Parse key-value pairs in JSON format: "key": "value", "key": value
        size_t pos = line.find('"');
        if (pos != std::string::npos) {
            size_t endKey = line.find('"', pos + 1);
            if (endKey != std::string::npos) {
                std::string key = line.substr(pos + 1, endKey - pos - 1);
                
                size_t colonPos = line.find(':', endKey);
                if (colonPos != std::string::npos) {
                    std::string value = line.substr(colonPos + 1);
                    value = trim(value);
                    
                    // Remove trailing comma
                    if (!value.empty() && value.back() == ',') {
                        value = value.substr(0, value.size() - 1);
                    }
                    
                    // Remove quotes if present
                    if (value.size() >= 2 && value.front() == '"' && value.back() == '"') {
                        value = value.substr(1, value.size() - 2);
                    }
                    
                    set(key, value, ConfigSource::File);
                }
            }
        }
    }
}

void Config::applyYAML(const std::string& yaml) {
    // Simplified YAML parsing - treat YAML as key=value pairs
    // YAML is a superset of JSON, but for basic cases they look similar
    std::stringstream ss(yaml);
    std::string line;
    
    while (std::getline(ss, line)) {
        line = trim(line);
        if (line.empty() || line[0] == '{' || line[0] == '}' || line[0] == '[' || line[0] == ']') {
            continue;
        }
        
        // Handle YAML key-value pairs: key: value
        size_t pos = line.find(':');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && value.front() == '"' && value.back() == '"') {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
        }
    }
}
