struct Config::Impl {
    std::vector<ConfigEntry> entries;
    std::map<std::string, ValidationResult(*)(const ConfigValue&)> validators;
};

Config::Config() : pImpl(std::make_unique<Impl>()) {
    // Initialize built-in validators
    pImpl->validators["neuron_count"] = [](const ConfigValue& v) {
        try {
            int64_t count = std::get<int64_t>(v);
            return count > 0 && count < 100000 ? ValidationResult() : ValidationResult(false, "Neuron count must be between 1 and 100000");
        } catch (...) {
            return ValidationResult(false, "Invalid neuron count type");
        }
    };
    
    pImpl->validators["connection_probability"] = [](const ConfigValue& v) {
        try {
            double prob = std::get<double>(v);
            return prob >= 0.0 && prob <= 1.0 ? ValidationResult() : ValidationResult(false, "Connection probability must be between 0.0 and 1.0");
        } catch (...) {
            return ValidationResult(false, "Invalid connection probability type");
        }
    };
    
    pImpl->validators["simulation_timestep"] = [](const ConfigValue& v) {
        try {
            double timestep = std::get<double>(v);
            return timestep > 0.0 && timestep < 1.0 ? ValidationResult() : ValidationResult(false, "Timestep must be between 0.0 and 1.0");
        } catch (...) {
            return ValidationResult(false, "Invalid timestep type");
        }
    };
}

