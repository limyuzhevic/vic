bool Config::loadFromFile(const std::string& filepath) {
    // Enhanced file format support with backward compatibility
    // Try JSON format first (Phase 5+)
    if (tryLoadFromJSON(filepath)) {
        NLM_LOG_INFO("Loaded configuration from JSON: " + filepath);
        return true;
    }
    
    // Try YAML format (Phase 5+)
    if (tryLoadFromYAML(filepath)) {
        NLM_LOG_INFO("Loaded configuration from YAML: " + filepath);
        return true;
    }
    
    // Fall back to simple key=value format (backward compatibility)
    NLM_LOG_INFO("Trying key=value format for: " + filepath);
    
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    while (std::getline(file, line)) {
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
        }
    }
    
    return true;
}

