// Configuration validation implementation
void Config::addValidationRule(std::unique_ptr<ValidationRule> rule) {
    pImpl->validationRules.push_back(std::move(rule));
    pImpl->validationCacheValid = false;
}

bool Config::validate() const {
    return !getValidationErrors().empty();
}

std::vector<ConfigValidationError> Config::getValidationErrors() const {
    if (!pImpl->validationCacheValid) {
        pImpl->validationErrors.clear();
        for (const auto& rule : pImpl->validationRules) {
            auto errors = rule->validate(*this);
            pImpl->validationErrors.insert(pImpl->validationErrors.end(), errors.begin(), errors.end());
        }
        pImpl->validationCacheValid = true;
    }
    return pImpl->validationErrors;
}

std::string Config::getValidationSummary() const {
    auto errors = getValidationErrors();
    std::ostringstream oss;
    oss << "Configuration validation: ";
    if (errors.empty()) {
        oss << "PASS (" << pImpl->validationRules.size() << " rules checked)";
    } else {
        oss << "FAIL (" << errors.size() << " error(s))\n";
        for (const auto& error : errors) {
            oss << "  - [" << static_cast<int>(error.code) << "] " << error.message << " (key: " << error.key << ")\n";
        }
    }
    return oss.str();
}

// Configuration merging implementation
void Config::merge(const Config& other) {
    for (const auto& entry : other.pImpl->entries) {
        // Check if key already exists
        auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
                               [&entry](const ConfigEntry& e) { return e.key == entry.key; });
        if (it != pImpl->entries.end()) {
            // Keep the existing entry (don't overwrite)
            it->source = ConfigSource::Runtime; // Mark as user override
        } else {
            // Add new entry
            pImpl->entries.push_back(entry);
        }
    }
    pImpl->validationCacheValid = false;
}

Config Config::mergeConfigs(const std::vector<Config>& configs) {
    Config mergedConfig;
    for (const auto& config : configs) {
        mergedConfig.merge(config);
    }
    return mergedConfig;
}

// Get configuration by source implementation
std::vector<ConfigEntry> Config::getEntriesBySource(ConfigSource source) const {
    std::vector<ConfigEntry> entries;
    for (const auto& entry : pImpl->entries) {
        if (entry.source == source) {
            entries.push_back(entry);
        }
    }
    return entries;
}

// Configuration comparison implementation
bool Config::equals(const Config& other) const {
    if (pImpl->entries.size() != other.pImpl->entries.size()) {
        return false;
    }
    for (const auto& entry : pImpl->entries) {
        auto it = std::find_if(other.pImpl->entries.begin(), other.pImpl->entries.end(),
                               [&entry](const ConfigEntry& e) { return e.key == entry.key; });
        if (it == other.pImpl->entries.end() || it->value != entry.value) {
            return false;
        }
    }
    return true;
}

