bool Config::loadFromFile(const std::string& filepath) {
    // Try JSON first
    if (loadFromJSON(filepath)) {
        NLM_LOG_INFO("Loaded configuration from JSON file: " + filepath);
        return true;
    }
    
    // Fall back to simple key=value format
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    int lineNum = 0;
    bool hasErrors = false;
    while (std::getline(file, line)) {
        lineNum++;
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Validate key format (no spaces, reasonable length)
            if (key.empty() || key.find(' ') != std::string::npos || key.size() > 100) {
                NLM_LOG_WARNING("Invalid configuration key at line " + std::to_string(lineNum) + ": " + key);
                hasErrors = true;
                continue;
            }
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            try {
                set(key, value, ConfigSource::File);
            } catch (const std::exception& e) {
                NLM_LOG_ERROR("Error parsing config line " + std::to_string(lineNum) + ": " + std::string(e.what()));
                hasErrors = true;
            }
        } else {
            NLM_LOG_WARNING("Invalid configuration format at line " + std::to_string(lineNum) + ": " + line);
            hasErrors = true;
        }
    }
    
    if (hasErrors) {
        NLM_LOG_WARNING("Configuration file parsing completed with warnings");
    }
    
    return true;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    file << "# NLM Configuration File\n";
    file << "# Generated by NLM " << __DATE__ << " " << __TIME__ << "\n\n";
    
    for (const auto& entry : pImpl->entries) {
        // Skip internal/private keys
        if (entry.key.find('_') == 0) {
            continue;
        }
        
        file << "# " << entry.description << "\n";
        file << entry.key << " = ";
        
        // Convert ConfigValue to string representation
        std::visit([&file](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                file << "\"" << arg << "\"";
            } else if constexpr (std::is_same_v<T, bool>) {
                file << (arg ? "true" : "false");
            } else if constexpr (std::is_same_v<T, double>) {
                file << arg;
            } else if constexpr (std::is_same_v<T, int64_t>) {
                file << arg;
            } else if constexpr (std::is_integral_v<T>) {
                file << arg;
            } else {
                file << "";
            }
        }, entry.value);
        
        file << "\n\n";
    }
    
    return true;
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    // Validate key
    if (key.empty() || key.find(' ') != std::string::npos || key.size() > 100) {
        throw std::invalid_argument("Invalid configuration key: '" + key + "'. Keys must be non-empty, contain no spaces, and be at most 100 characters.");
    }
    
    // Auto-detect type based on content
    std::string normalizedValue = value;
    
    // Special handling for boolean values
    if (normalizedValue == "true" || normalizedValue == "false") {
        bool boolValue = (normalizedValue == "true");
        set(key, ConfigValue(boolValue), source);
        return;
    }
    
    // Special handling for numeric values
    bool isNumeric = true;
    bool hasDecimal = false;
    for (char c : normalizedValue) {
        if (!std::isdigit(c) && c != '.' && c != '-') {
            isNumeric = false;
            break;
        }
        if (c == '.') hasDecimal = true;
    }
    
    if (isNumeric) {
        try {
            // Try double first for floating point
            size_t pos;
            double doubleValue = std::stod(normalizedValue, &pos);
            if (pos == normalizedValue.size()) {
                set(key, ConfigValue(doubleValue), source);
                return;
            }
            
            // Try int64_t if no decimal point
            if (!hasDecimal) {
                int64_t intValue = std::stoll(normalizedValue);
                set(key, ConfigValue(intValue), source);
                return;
            }
        } catch (...) {
            // Not a number, continue with string
        }
    }
    
    // Default to string
    set(key, ConfigValue(normalizedValue), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        it->value = value;
        it->source = source;
    } else {
        pImpl->entries.emplace_back(key, value, source);
    }
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::toLower(const std::string& str) {
    std::string result = str;
    std::transform(result.begin(), result.end(), result.begin(), ::tolower);
    return result;
}

bool Config::loadFromJSON(const std::string& filepath) {
    // Simple JSON parsing - looks for JSON object { "key": value, ... }
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    // Read entire file
    std::string content((std::istreambuf_iterator<char>(file)), 
                       std::istreambuf_iterator<char>());
    
    // Remove whitespace for simple parsing
    std::string cleanContent;
    for (char c : content) {
        if (!std::isspace(c)) {
            cleanContent += c;
        }
    }
    
    // Check if this looks like JSON
    if (cleanContent.find('{') == std::string::npos || 
        cleanContent.find('}') == std::string::npos) {
        return false; // Not JSON format
    }
    
    // Simple JSON parsing - extract key:value pairs
    // This is a simplified implementation for demonstration
    size_t pos = cleanContent.find('{');
    if (pos == std::string::npos) return false;
    
    pos++; // Skip {
    size_t endPos = cleanContent.rfind('}');
    if (endPos == std::string::npos) return false;
    
    std::string jsonContent = cleanContent.substr(pos, endPos - pos);
    
    // Parse key:value pairs
    size_t commaPos = 0;
    while ((commaPos = jsonContent.find(",")) != std::string::npos) {
        std::string pair = jsonContent.substr(0, commaPos);
        parseJSONKeyValue(pair);
        jsonContent.erase(0, commaPos + 1);
    }
    parseJSONKeyValue(jsonContent);
    
    return true;
}

void Config::parseJSONKeyValue(const std::string& pair) {
    size_t colonPos = pair.find(':');
    if (colonPos == std::string::npos) {
        return;
    }
    
    std::string key = pair.substr(0, colonPos);
    std::string value = pair.substr(colonPos + 1);
    
    // Remove quotes from key
    key = trim(key);
    if (key.size() >= 2 && ((key.front() == '"' && key.back() == '"') ||
                           (key.front() == '\'' && key.back() == '\''))) {
        key = key.substr(1, key.size() - 2);
    }
    
    key = trim(key);
    value = trim(value);
    
    // Handle JSON null
    if (value == "null") {
        value = "";
    }
    
    set(key, value, ConfigSource::File);
}

