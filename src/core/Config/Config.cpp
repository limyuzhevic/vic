// Simple JSON parser - handles key-value pairs and basic objects
std::unordered_map<std::string, std::string> parseJSON(const std::string& jsonStr) {
    std::unordered_map<std::string, std::string> config;
    
    // Remove comments
    std::string content = jsonStr;
    size_t commentPos = content.find("//");
    while (commentPos != std::string::npos) {
        size_t newLinePos = content.find('\n', commentPos);
        if (newLinePos != std::string::npos) {
            content.erase(commentPos, newLinePos - commentPos);
        } else {
            content.erase(commentPos);
            break;
        }
        commentPos = content.find("//");
    }
    
    // Parse as simple key=value format (for now, supports both JSON and simple format)
    std::istringstream stream(content);
    std::string line;
    
    while (std::getline(stream, line)) {
        line = trim(line);
        if (line.empty() || line[0] == '#') {
            continue;
        }
        
        // Check if it's a JSON object or simple key=value
        if (line[0] == '{') {
            // Handle JSON object - for simplicity, we'll process as key=value pairs
            // Extract content between braces
            std::string inner = line.substr(1, line.length() - 2);
            std::istringstream innerStream(inner);
            std::string pair;
            
            while (std::getline(innerStream, pair, ',')) {
                pair = trim(pair);
                size_t pos = pair.find('=');
                if (pos != std::string::npos) {
                    std::string key = trim(pair.substr(0, pos));
                    std::string value = trim(pair.substr(pos + 1));
                    // Remove quotes from key and value
                    if (key.size() >= 2 && key.front() == '"' && key.back() == '"') {
                        key = key.substr(1, key.size() - 2);
                    }
                    if (value.size() >= 2 && value.front() == '"' && value.back() == '"') {
                        value = value.substr(1, value.size() - 2);
                    }
                    config[key] = value;
                }
            }
        } else {
            // Simple key=value format
            size_t pos = line.find('=');
            if (pos != std::string::npos) {
                std::string key = trim(line.substr(0, pos));
                std::string value = trim(line.substr(pos + 1));
                
                // Remove quotes if present
                if (value.size() >= 2 && 
                    ((value.front() == '"' && value.back() == '"') ||
                     (value.front() == '\'' && value.back() == '\''))) {
                    value = value.substr(1, value.size() - 2);
                }
                
                config[key] = value;
            }
        }
    }
    
    return config;
}

bool validateConfigValue(const std::string& key, const std::string& value, ConfigSource source) {
    // Basic validation - can be extended based on specific key requirements
    if (key.empty()) {
        return false;
    }
    
    // Validate known keys
    static const std::unordered_set<std::string> validKeys = {
        "random_seed", "simulation_timestep", "neuron_count", "region_count",
        "connection_probability", "plasticity_learning_rate", "stdp_ltp_weight",
        "stdp_ltd_weight", "stdp_time_constant", "development_synaptogenesis_rate",
        "development_pruning_rate", "dopamine_baseline", "reward_discount_factor",
        "environment_name", "environment_width", "environment_height", "log_level",
        "log_to_file", "log_filename", "max_simulation_steps", "simulation_time_limit",
        "visualization_enabled", "visualization_update_rate"
    };
    
    if (validKeys.find(toLower(key)) == validKeys.end()) {
        return false; // Unknown key, but don't fail - allow for future extensibility
    }
    
    return true;
}

