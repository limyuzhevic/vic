bool Config::loadFromFile(const std::string& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
        NLM_LOG_WARNING("Cannot open config file: " + filepath);
        return false;
    }
    
    std::string line;
    size_t lineNumber = 0;
    while (std::getline(file, line)) {
        ++lineNumber;
        
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse key=value pairs with error handling
        size_t pos = line.find('=');
        if (pos == std::string::npos) {
            NLM_LOG_WARNING("Invalid config line " + std::to_string(lineNumber) + " in " + filepath + ": missing '='");
            continue;  // Skip malformed lines
        }
        
        try {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            if (key.empty()) {
                NLM_LOG_WARNING("Empty key at line " + std::to_string(lineNumber) + " in " + filepath);
                continue;
            }
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
            
        } catch (const std::exception& e) {
            NLM_LOG_WARNING("Error parsing config line " + std::to_string(lineNumber) + " in " + filepath + ": " + e.what());
            continue;
        }
    }
    
    NLM_LOG_INFO("Loaded configuration from: " + filepath + " (" + std::to_string(pImpl->entries.size()) + " entries)");
    return true;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open config file for writing: " + filepath);
        return false;
    }
    
    try {
        file << "# NLM Configuration File (Saved at " << getCurrentTimestamp() << ")\n";
        file << "# DO NOT EDIT THIS FILE - It will be overwritten\n\n";
        
        for (const auto& entry : pImpl->entries) {
            file << "# " << entry.description << "\n";
            file << entry.key << " = ";
            
            // Write the actual value based on type
            std::visit([&file](auto&& arg) {
                using T = std::decay_t<decltype(arg)>;
                if constexpr (std::is_same_v<T, std::string>) {
                    file << "\"" << arg << "\"";
                } else if constexpr (std::is_same_v<T, bool>) {
                    file << (arg ? "true" : "false");
                } else if constexpr (std::is_same_v<T, std::vector<int>>) {
                    file << "["; 
                    for (size_t i = 0; i < arg.size(); ++i) {
                        file << arg[i];
                        if (i < arg.size() - 1) file << ", ";
                    }
                    file << "]";
                } else if constexpr (std::is_same_v<T, std::vector<double>>) {
                    file << "["; 
                    for (size_t i = 0; i < arg.size(); ++i) {
                        file << arg[i];
                        if (i < arg.size() - 1) file << ", ";
                    }
                    file << "]";
                } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                    file << "["; 
                    for (size_t i = 0; i < arg.size(); ++i) {
                        file << "\"" << arg[i] << "\"";
                        if (i < arg.size() - 1) file << ", ";
                    }
                    file << "]";
                } else {
                    file << arg;
                }
            }, entry.value);
            
            file << "  # Source: " << static_cast<int>(entry.source) << "\n\n";
        }
        
        file.flush();
        NLM_LOG_INFO("Configuration saved to: " + filepath);
        return true;
        
    } catch (const std::exception& e) {
        NLM_LOG_ERROR("Exception saving config to " + filepath + ": " + e.what());
        return false;
    }
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        it->value = value;
        it->source = source;
    } else {
        pImpl->entries.emplace_back(key, value, source);
    }
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

bool Config::validate() const {
    bool isValid = true;
    
    for (const auto& entry : pImpl->entries) {
        bool entryValid = true;
        
        // Validate based on key name and type
        if (entry.key == "random_seed") {
            if (!std::holds_alternative<int64_t>(entry.value) && 
                !std::holds_alternative<int>(entry.value)) {
                NLM_LOG_WARNING("Config validation warning: random_seed should be integer");
                entryValid = false;
            }
        } else if (entry.key == "simulation_timestep") {
            if (!std::holds_alternative<double>(entry.value)) {
                NLM_LOG_WARNING("Config validation warning: simulation_timestep should be double");
                entryValid = false;
            } else {
                double timestep = std::get<double>(entry.value);
                if (timestep <= 0.0 || timestep > 1.0) {
                    NLM_LOG_WARNING("Config validation warning: simulation_timestep should be between 0 and 1.0");
                    entryValid = false;
                }
            }
        } else if (entry.key == "neuron_count") {
            if (!std::holds_alternative<int64_t>(entry.value) && 
                !std::holds_alternative<int>(entry.value)) {
                NLM_LOG_WARNING("Config validation warning: neuron_count should be integer");
                entryValid = false;
            }
        } else if (entry.key == "region_count") {
            if (!std::holds_alternative<int64_t>(entry.value) && 
                !std::holds_alternative<int>(entry.value)) {
                NLM_LOG_WARNING("Config validation warning: region_count should be integer");
                entryValid = false;
            }
        } else if (entry.key == "connection_probability") {
            if (!std::holds_alternative<float>(entry.value) && 
                !std::holds_alternative<double>(entry.value)) {
                NLM_LOG_WARNING("Config validation warning: connection_probability should be float/double");
                entryValid = false;
            } else {
                double prob = std::holds_alternative<float>(entry.value) ? 
                    static_cast<double>(std::get<float>(entry.value)) : 
                    std::get<double>(entry.value);
                if (prob < 0.0 || prob > 1.0) {
                    NLM_LOG_WARNING("Config validation warning: connection_probability should be between 0.0 and 1.0");
                    entryValid = false;
                }
            }
        } else if (entry.key.find("stdp_") == 0 || entry.key.find("plasticity_") == 0 || 
                   entry.key.find("dopamine_") == 0 || entry.key.find("curiosity_") == 0 ||
                   entry.key.find("reward_") == 0) {
            if (!std::holds_alternative<float>(entry.value) && 
                !std::holds_alternative<double>(entry.value)) {
                NLM_LOG_WARNING("Config validation warning: " + entry.key + " should be numeric");
                entryValid = false;
            }
        }
        
        if (!entryValid) {
            isValid = false;
        }
    }
    
    if (isValid) {
        NLM_LOG_INFO("Configuration validation passed");
    } else {
        NLM_LOG_WARNING("Configuration validation completed with warnings");
    }
    
    return isValid;
}

// Add documentation for the Config class
void Config::logConfigSummary() const {
    NLM_LOG_INFO("=== NLM Configuration Summary ===");
    NLM_LOG_INFO("Total entries: " + std::to_string(pImpl->entries.size()));
    
    // Count entries by source
    int fileEntries = 0, defaultEntries = 0, cmdLineEntries = 0, runtimeEntries = 0;
    for (const auto& entry : pImpl->entries) {
        switch (entry.source) {
            case ConfigSource::File: fileEntries++; break;
            case ConfigSource::Default: defaultEntries++; break;
            case ConfigSource::CommandLine: cmdLineEntries++; break;
            case ConfigSource::Runtime: runtimeEntries++; break;
        }
    }
    
    if (fileEntries > 0) NLM_LOG_INFO("  From file: " + std::to_string(fileEntries));
    if (defaultEntries > 0) NLM_LOG_INFO("  Default: " + std::to_string(defaultEntries));
    if (cmdLineEntries > 0) NLM_LOG_INFO("  From command line: " + std::to_string(cmdLineEntries));
    if (runtimeEntries > 0) NLM_LOG_INFO("  Runtime set: " + std::to_string(runtimeEntries));
    
    // Validate and log important entries
    NLM_LOG_INFO("");
    NLM_LOG_INFO("Key configuration values:");
    
    // Get commonly used values
    auto seed = getOr<int64_t>("random_seed", 42);
    auto timestep = getOr<double>("simulation_timestep", 0.001);
    auto neurons = getOr<int64_t>("neuron_count", 1000);
    auto regions = getOr<int64_t>("region_count", 1);
    
    NLM_LOG_INFO("  Random seed: " + std::to_string(seed));
    NLM_LOG_INFO("  Simulation timestep: " + std::to_string(timestep) + "s");
    NLM_LOG_INFO("  Neuron count: " + std::to_string(neurons));
    NLM_LOG_INFO("  Region count: " + std::to_string(regions));
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::getCurrentTimestamp() {
    auto now = std::chrono::system_clock::now();
    auto in_time_t = std::chrono::system_clock::to_time_t(now);
    std::stringstream ss;
    ss << std::put_time(std::localtime(&in_time_t), "%Y-%m-%d %H:%M:%S");
    return ss.str();
}

