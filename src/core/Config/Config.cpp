bool Config::loadFromFile(const std::string& filepath) {
    // Try to detect file format based on extension
    std::string extension = "";
    if (filepath.size() >= 4) {
        extension = filepath.substr(filepath.size() - 4);
    }
    
    // Convert to lowercase for comparison
    std::transform(extension.begin(), extension.end(), extension.begin(), ::tolower);
    
    // Try JSON format first
    if (extension == ".json") {
        return loadFromJsonFile(filepath);
    } else if (extension == ".yaml" || extension == ".yml") {
        // TODO: Implement YAML support
        // For now, fallback to simple format
        NLM_LOG_WARNING("YAML format not yet supported, using simple format");
    } else if (extension == ".cfg") {
        // Check if it's a simple key=value format or JSON
        return loadFromFile(filepath); // Recursive call for simple format
    }
    
    // Try simple key=value format (backward compatibility)
    return loadFromSimpleFile(filepath);
}

bool Config::loadFromJsonFile(const std::string& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open JSON config file: " + filepath);
        return false;
    }
    
    try {
        nlohmann::json jsonData = nlohmann::json::parse(file);
        
        // Clear existing entries
        clear();
        
        // Parse JSON object
        for (auto it = jsonData.begin(); it != jsonData.end(); ++it) {
            std::string key = it.key();
            
            ConfigSource source = ConfigSource::File;
            if (key.find("cli_") == 0) {
                source = ConfigSource::CommandLine;
                key = key.substr(4); // Remove "cli_" prefix
            }
            
            ConfigValue value;
            const auto& jsonValue = *it;
            
            if (jsonValue.is_string()) {
                value = jsonValue.get<std::string>();
            } else if (jsonValue.is_number_integer()) {
                value = jsonValue.get<int64_t>();
            } else if (jsonValue.is_number_float()) {
                value = jsonValue.get<double>();
            } else if (jsonValue.is_boolean()) {
                value = jsonValue.get<bool>();
            } else if (jsonValue.is_array()) {
                // Convert array to vector of strings for now
                std::vector<std::string> strArray;
                for (const auto& item : jsonValue) {
                    strArray.push_back(item.get<std::string>());
                }
                value = strArray;
            } else {
                NLM_LOG_WARNING("Unsupported JSON value type for key: " + key);
                continue;
            }
            
            set(key, value, source);
        }
        
        NLM_LOG_INFO("Loaded JSON configuration from: " + filepath);
        return true;
        
    } catch (const nlohmann::json::parse_error& e) {
        NLM_LOG_ERROR("JSON parse error in file " + filepath + ": " + e.what());
        return false;
    } catch (const std::exception& e) {
        NLM_LOG_ERROR("Error reading JSON config file " + filepath + ": " + e.what());
        return false;
    }
}

bool Config::loadFromSimpleFile(const std::string& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    while (std::getline(file, line)) {
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
        }
    }
    
    return true;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format (modern)
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format (traditional)
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    // Try to detect file format based on extension
    std::string extension = "";
    if (filepath.size() >= 4) {
        extension = filepath.substr(filepath.size() - 4);
    }
    
    std::transform(extension.begin(), extension.end(), extension.begin(), ::tolower);
    
    // Use JSON format for .json files, simple format for others
    if (extension == ".json") {
        return saveToJsonFile(filepath);
    } else {
        return saveToSimpleFile(filepath);
    }
}

bool Config::saveToJsonFile(const std::string& filepath) const {
    try {
        nlohmann::json jsonData;
        
        for (const auto& entry : pImpl->entries) {
            std::string key = entry.key;
            if (entry.source == ConfigSource::CommandLine) {
                key = "cli_" + key; // Prefix with cli_ for command line entries
            }
            
            jsonData[key] = std::visit([](auto&& arg) -> nlohmann::json {
                using T = std::decay_t<decltype(arg)>;
                if constexpr (std::is_same_v<T, int>) {
                    return arg;
                } else if constexpr (std::is_same_v<T, int64_t>) {
                    return arg;
                } else if constexpr (std::is_same_v<T, double>) {
                    return arg;
                } else if constexpr (std::is_same_v<T, bool>) {
                    return arg;
                } else if constexpr (std::is_same_v<T, std::string>) {
                    return arg;
                } else if constexpr (std::is_same_v<T, std::vector<int>>) {
                    nlohmann::json arr = nlohmann::json::array();
                    for (const auto& item : arg) {
                        arr.push_back(item);
                    }
                    return arr;
                } else if constexpr (std::is_same_v<T, std::vector<double>>) {
                    nlohmann::json arr = nlohmann::json::array();
                    for (const auto& item : arg) {
                        arr.push_back(item);
                    }
                    return arr;
                } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                    nlohmann::json arr = nlohmann::json::array();
                    for (const auto& item : arg) {
                        arr.push_back(item);
                    }
                    return arr;
                } else {
                    return nullptr;
                }
            }, entry.value);
        }
        
        std::ofstream file(filepath);
        if (!file.is_open()) {
            return false;
        }
        
        file << jsonData.dump(2); // Pretty print with 2-space indentation
        
        return true;
        
    } catch (const std::exception& e) {
        NLM_LOG_ERROR("Error writing JSON config file " + filepath + ": " + e.what());
        return false;
    }
}

bool Config::saveToSimpleFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    for (const auto& entry : pImpl->entries) {
        file << "# " << entry.description << "\n";
        file << entry.key << " = ";
        
        std::visit([&file](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                file << "\"" << arg << "\"";
            } else if constexpr (std::is_same_v<T, std::vector<int>>) {
                file << "[";
                for (size_t i = 0; i < arg.size(); ++i) {
                    if (i > 0) file << ", ";
                    file << arg[i];
                }
                file << "]";
            } else if constexpr (std::is_same_v<T, std::vector<double>>) {
                file << "[";
                for (size_t i = 0; i < arg.size(); ++i) {
                    if (i > 0) file << ", ";
                    file << arg[i];
                }
                file << "]";
            } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                file << "[";
                for (size_t i = 0; i < arg.size(); ++i) {
                    if (i > 0) file << ", ";
                    file << "\"" << arg[i] << "\"";
                }
                file << "]";
            } else {
                file << arg;
            }
        }, entry.value);
        
        file << "\n\n";
    }
    
    return true;
}

