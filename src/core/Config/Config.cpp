bool Config::loadFromFile(const std::string& filepath) {
    // TODO PHASE 2: Implement proper JSON/YAML parser
    // PLACEHOLDER - Phase 1 uses a simple key=value format
    
    std::ifstream file(filepath);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open config file: " << filepath);
        return false;
    }
    
    std::string line;
    int lineNumber = 0;
    bool hasErrors = false;
    
    while (std::getline(file, line)) {
        lineNumber++;
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Validate key format
            if (key.empty()) {
                NLM_LOG_WARNING("Empty key at line " << lineNumber);
                hasErrors = true;
                continue;
            }
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            try {
                set(key, value, ConfigSource::File);
                NLM_LOG_DEBUG("Loaded config: " << key << " = " << value);
            } catch (const std::exception& e) {
                NLM_LOG_ERROR("Error parsing config at line " << lineNumber << ": " << e.what());
                NLM_LOG_ERROR("  Line content: " << line);
                hasErrors = true;
            }
        } else {
            NLM_LOG_WARNING("Invalid config format at line " << lineNumber << ": " << line);
            hasErrors = true;
        }
    }
    
    if (hasErrors) {
        NLM_LOG_WARNING("Config file " << filepath << " loaded with errors");
    } else {
        NLM_LOG_INFO("Successfully loaded configuration from: " << filepath);
    }
    
    return !hasErrors;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
                NLM_LOG_DEBUG("Loaded config from args: " << key << " = " << value);
            } else {
                NLM_LOG_WARNING("Invalid command line argument format: " << arg);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
            NLM_LOG_DEBUG("Loaded config from args: " << key << " = " << value);
        } else {
            NLM_LOG_WARNING("Unhandled command line argument: " << arg);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to save config file: " << filepath);
        return false;
    }
    
    file << "# NLM Configuration File" << std::endl;
    file << "# Generated by NLM on " << getCurrentTimestamp() << std::endl;
    file << std::endl;
    
    for (const auto& entry : pImpl->entries) {
        file << "# " << entry.description << "\n";
        file << entry.key << " = ";
        
        // Proper serialization based on type
        std::visit([&file](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                file << "\"" << arg << "\"";
            } else if constexpr (std::is_same_v<T, bool>) {
                file << (arg ? "true" : "false");
            } else if constexpr (std::is_same_v<T, int> || 
                                std::is_same_v<T, int64_t> || 
                                std::is_same_v<T, float> || 
                                std::is_same_v<T, double>) {
                file << arg;
            } else {
                file << arg;
            }
        }, entry.value);
        
        file << "  # Source: " << static_cast<int>(entry.source) << std::endl;
    }
    
    file << std::endl;
    file << "# End of configuration" << std::endl;
    
    NLM_LOG_INFO("Configuration saved to: " << filepath);
    return true;
}

std::string Config::getCurrentTimestamp() const {
    auto now = std::chrono::system_clock::now();
    auto time = std::chrono::system_clock::to_time_t(now);
    std::stringstream ss;
    ss << std::put_time(std::localtime(&time), "%Y-%m-%d %H:%M:%S");
    return ss.str();
}

ConfigValidationResult Config::validateFull() const {
    ConfigValidationResult result;
    
    // Check for required keys
    const std::vector<std::string> requiredKeys = {
        "random_seed",
        "simulation_timestep", 
        "neuron_count",
        "region_count"
    };
    
    for (const auto& key : requiredKeys) {
        if (!has(key)) {
            result.errors.push_back("Missing required configuration key: " + key);
        }
    }
    
    // Validate specific key ranges and formats
    if (has("neuron_count")) {
        int neuronCount = getOr<int>("neuron_count", -1);
        if (neuronCount <= 0 || neuronCount > 10000) {
            result.errors.push_back("Invalid neuron_count: " << neuronCount << ". Must be in range [1, 10000]");
        }
    }
    
    if (has("region_count")) {
        int regionCount = getOr<int>("region_count", -1);
        if (regionCount <= 0 || regionCount > 100) {
            result.errors.push_back("Invalid region_count: " << regionCount << ". Must be in range [1, 100]");
        }
    }
    
    if (has("simulation_timestep")) {
        double timestep = getOr<double>("simulation_timestep", -1.0);
        if (timestep <= 0 || timestep > 1.0) {
            result.errors.push_back("Invalid simulation_timestep: " << timestep << ". Must be in range (0, 1.0]");
        }
    }
    
    if (has("connection_probability")) {
        double prob = getOr<double>("connection_probability", -1.0);
        if (prob < 0 || prob > 1.0) {
            result.errors.push_back("Invalid connection_probability: " << prob << ". Must be in range [0, 1.0]");
        }
    }
    
    if (has("random_seed")) {
        int64_t seed = getOr<int64_t>("random_seed", -1);
        if (seed < 0) {
            result.errors.push_back("Invalid random_seed: " << seed << ". Must be non-negative");
        }
    }
    
    // Check for conflicting configurations
    if (has("plasticity_stdp_enable") && has("plasticity_hebbian_enable")) {
        bool stdp = getOr<bool>("plasticity_stdp_enable", true);
        bool hebbian = getOr<bool>("plasticity_hebbian_enable", true);
        if (!stdp && !hebbian) {
            result.warnings.push_back("Both STDP and Hebbian plasticity are disabled. This may result in no learning.");
        }
    }
    
    // Check for consistency between settings
    if (has("neuromod_curiosity_enable") && has("neuromod_novelty_enable")) {
        bool curiosity = getOr<bool>("neuromod_curiosity_enable", true);
        bool novelty = getOr<bool>("neuromod_novelty_enable", true);
        if (!curiosity && !novelty) {
            result.warnings.push_back("Both curiosity and novelty detection are disabled. This may reduce exploration behavior.");
        }
    }
    
    // Performance warnings for large configurations
    if (has("neuron_count") && has("connection_probability")) {
        int neuronCount = getOr<int>("neuron_count", 0);
        double connProb = getOr<double>("connection_probability", 0.0);
        if (neuronCount > 5000 && connProb > 0.2) {
            result.warnings.push_back("Large network with high connectivity may cause performance issues. Consider reducing neuron_count or connection_probability.");
        }
    }
    
    result.isValid = result.errors.empty();
    return result;
}

PerformanceProfiler::PerformanceProfiler() : enabled(false), startTime(std::chrono::high_resolution_clock::now()) {}

void PerformanceProfiler::enable() {
    enabled = true;
    startTime = std::chrono::high_resolution_clock::now();
    NLM_LOG_INFO("Performance profiler enabled.");
}

void PerformanceProfiler::disable() {
    if (enabled) {
        auto endTime = std::chrono::high_resolution_clock::now();
        auto duration = std::chrono::duration_cast<std::chrono::milliseconds>(endTime - startTime);
        NLM_LOG_INFO("Performance profiler disabled. Total time: " << duration.count() / 1000.0 << "s");
        enabled = false;
    }
}

double PerformanceProfiler::getElapsedTime() const {
    if (!enabled) return 0.0;
    auto endTime = std::chrono::high_resolution_clock::now();
    auto duration = std::chrono::duration_cast<std::chrono::milliseconds>(endTime - startTime);
    return duration.count() / 1000.0;
}

void PerformanceProfiler::logStep(int step, int totalSteps) {
    if (enabled && verbose && step % 100 == 0) {
        double elapsed = getElapsedTime();
        double estimatedTotal = (elapsed / step) * totalSteps;
        double remaining = estimatedTotal - elapsed;
        NLM_LOG_INFO("Progress: Step " << step << "/" << totalSteps << " (" << std::setprecision(2) << (step * 100.0 / totalSteps) << "%)");
        NLM_LOG_INFO("  Elapsed: " << std::setprecision(3) << elapsed << "s, Estimated total: " << std::setprecision(3) << estimatedTotal << "s, Remaining: " << std::setprecision(3) << remaining << "s");
    }
}

