bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

bool Config::validate() const {
    std::vector<std::string> errors = getValidationErrors();
    return errors.empty();
}

std::vector<std::string> Config::getValidationErrors() const {
    std::vector<std::string> errors;
    
    // Check for required configuration keys
    std::vector<std::string> requiredKeys = {
        "neuron_count",
        "region_count",
        "connection_probability",
        "simulation_timestep"
    };
    
    for (const auto& key : requiredKeys) {
        if (!has(key)) {
            errors.push_back("Missing required configuration key: " + key);
        }
    }
    
    // Validate numeric ranges
    if (has("neuron_count")) {
        auto neuronCountOpt = get<size_t>("neuron_count");
        if (neuronCountOpt && *neuronCountOpt == 0) {
            errors.push_back("neuron_count must be greater than 0");
        }
    }
    
    if (has("region_count")) {
        auto regionCountOpt = get<size_t>("region_count");
        if (regionCountOpt && *regionCountOpt == 0) {
            errors.push_back("region_count must be greater than 0");
        }
    }
    
    if (has("connection_probability")) {
        auto probOpt = get<double>("connection_probability");
        if (probOpt) {
            double prob = *probOpt;
            if (prob < 0.0 || prob > 1.0) {
                errors.push_back("connection_probability must be between 0.0 and 1.0");
            }
        }
    }
    
    if (has("simulation_timestep")) {
        auto timestepOpt = get<double>("simulation_timestep");
        if (timestepOpt && *timestepOpt <= 0.0) {
            errors.push_back("simulation_timestep must be positive");
        }
    }
    
    // Check for duplicate dopamine_baseline (config validation)
    // Note: This is handled at the config file level, but we can also check at runtime
    
    return errors;
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::toLower(const std::string& str) {
    std::string result = str;
    std::transform(result.begin(), result.end(), result.begin(), ::tolower);
    return result;
}

