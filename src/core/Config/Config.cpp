/**
 * Validate configuration values against known parameters
 * @param strict If true, only known parameters are allowed
 * @return vector of error messages (empty if valid)
 */
std::vector<std::string> Config::validate(bool strict) const {
    std::vector<std::string> errors;
    
    // Define known configuration parameters
    const std::unordered_map<std::string, std::function<bool(const ConfigValue&)>> validators = {
        {"neuron_count", [](const ConfigValue& v) {
            if (auto* val = std::get_if<int64_t>(&v)) return (*val > 0 && *val <= 100000);
            return false;
        }},
        {"region_count", [](const ConfigValue& v) {
            if (auto* val = std::get_if<int64_t>(&v)) return (*val > 0 && *val <= 1000);
            return false;
        }},
        {"connection_probability", [](const ConfigValue& v) {
            if (auto* val = std::get_if<double>(&v)) return (*val >= 0.0 && *val <= 1.0);
            return false;
        }},
        {"simulation_timestep", [](const ConfigValue& v) {
            if (auto* val = std::get_if<double>(&v)) return (*val > 0.0 && *val <= 1.0);
            return false;
        }},
        {"stdp_ltp_weight", [](const ConfigValue& v) {
            if (auto* val = std::get_if<double>(&v)) return (*val >= 0.0 && *val <= 1.0);
            return false;
        }},
        {"stdp_ltd_weight", [](const ConfigValue& v) {
            if (auto* val = std::get_if<double>(&v)) return (*val >= 0.0 && *val <= 1.0);
            return false;
        }},
        {"enable_checkpointing", [](const ConfigValue& v) {
            return std::holds_alternative<bool>(v);
        }},
        {"enable_replay", [](const ConfigValue& v) {
            return std::holds_alternative<bool>(v);
        }},
        {"enable_development", [](const ConfigValue& v) {
            return std::holds_alternative<bool>(v);
        }},
        {"random_seed", [](const ConfigValue& v) {
            if (auto* val = std::get_if<int64_t>(&v)) return (*val >= 0);
            return false;
        }},
    };
    
    for (const auto& entry : pImpl->entries) {
        const auto& key = entry.key;
        const auto& value = entry.value;
        
        // Check if it's a known parameter
        auto it = validators.find(key);
        if (it != validators.end()) {
            if (!it->second(value)) {
                errors.push_back("Invalid value for parameter '" + key + "': ");
                // Add human-readable value
                std::ostringstream oss;
                std::visit([&oss](const auto& val) {
                    oss << val;
                }, value);
                errors.back() += oss.str();
            }
        } else if (strict) {
            errors.push_back("Unknown configuration parameter: '" + key + "'");
        }
    }
    
    return errors;
}

/**
 * Get configuration parameter description (if available)
 * @param key Configuration parameter key
 * @return Description or empty string if not found
 */
std::string Config::getParameterDescription(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
                          [&key](const ConfigEntry& e) { return e.key == key; });
    return (it != pImpl->entries.end()) ? it->description : "";
}

/**
 * Merge configuration from another Config object
 * @param other Config object to merge
 * @param overrideSources If true, overwrite entries from other sources
 */
void Config::merge(const Config& other, bool overrideSources) {
    for (const auto& otherEntry : other.pImpl->entries) {
        auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
                              [&otherEntry](const ConfigEntry& e) { return e.key == otherEntry.key; });
        
        if (it != pImpl->entries.end()) {
            if (overrideSources || otherEntry.source != ConfigSource::File) {
                // Use the other entry's value and source
                it->value = otherEntry.value;
                it->source = otherEntry.source;
            }
            // If we keep the existing one, update description if empty
            else if (it->description.empty() && !otherEntry.description.empty()) {
                it->description = otherEntry.description;
            }
        } else {
            pImpl->entries.push_back(otherEntry);
        }
    }
}

/**
 * Get all configuration values as strings
 * @return Map of key-value pairs as strings
 */
std::unordered_map<std::string, std::string> Config::getAllAsStrings() const {
    std::unordered_map<std::string, std::string> result;
    
    for (const auto& entry : pImpl->entries) {
        std::ostringstream oss;
        std::visit([&oss](const auto& value) {
            oss << value;
        }, entry.value);
        result[entry.key] = oss.str();
    }
    
    return result;
}

/**
 * Check if configuration value matches expected pattern
 * @param key Configuration parameter key
 * @param pattern Expected pattern (regex)
 * @return true if matches pattern or no validation
 */
bool Config::validatePattern(const std::string& key, const std::string& pattern) const {
    if (!has(key)) return true;
    
    auto value = get<std::string>(key);
    if (!value.has_value()) return false;
    
    // Simple pattern matching (could be replaced with proper regex)
    if (pattern == "bool") {
        return value.value() == "true" || value.value() == "false";
    } else if (pattern == "int") {
        try {
            size_t pos;
            int val = std::stoi(value.value(), &pos);
            return pos == value.value().size();
        } catch (...) {
            return false;
        }
    } else if (pattern == "float") {
        try {
            size_t pos;
            float val = std::stof(value.value(), &pos);
            return pos == value.value().size();
        } catch (...) {
            return false;
        }
    }
    
    return true; // Unknown pattern, accept anything
}
