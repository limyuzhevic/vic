struct Config::Impl {
    std::vector<ConfigEntry> entries;
    std::vector<std::unique_ptr<ValidationRule>> validationRules;
    mutable std::vector<ConfigValidationError> validationErrors;
    mutable bool validationCacheValid = false;
};

