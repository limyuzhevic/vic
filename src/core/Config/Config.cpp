// Validate configuration
bool Config::validate() const {
    std::vector<std::string> errors = getValidationErrors();
    if (!errors.empty()) {
        NLM_LOG_ERROR("Configuration validation failed with " + std::to_string(errors.size()) + " errors");
        for (const auto& error : errors) {
            NLM_LOG_ERROR("  " + error);
        }
        return false;
    }
    return true;
}

// Get validation errors
std::vector<std::string> Config::getValidationErrors() const {
    std::vector<std::string> errors;
    
    for (const auto& entry : pImpl->entries) {
        if (entry.key.empty()) {
            errors.push_back("Empty key found");
        }
        
        if (entry.key.find(' ') != std::string::npos) {
            errors.push_back("Key contains whitespace: " + entry.key);
        }
    }
    
    return errors;
}

// Get configuration statistics
Config::Stats Config::getStats() const {
    Stats stats;
    stats.totalEntries = pImpl->entries.size();
    stats.defaultEntries = 0;
    stats.fileEntries = 0;
    stats.commandLineEntries = 0;
    stats.runtimeEntries = 0;
    stats.entropy = 0.0;
    
    for (const auto& entry : pImpl->entries) {
        switch (entry.source) {
            case ConfigSource::Default: stats.defaultEntries++; break;
            case ConfigSource::File: stats.fileEntries++; break;
            case ConfigSource::CommandLine: stats.commandLineEntries++; break;
            case ConfigSource::Runtime: stats.runtimeEntries++; break;
        }
    }
    
    // Simple entropy calculation (based on distribution of sources)
    if (stats.totalEntries > 0) {
        double total = static_cast<double>(stats.totalEntries);
        double entropy = 0.0;
        for (size_t count : {stats.defaultEntries, stats.fileEntries, 
                            stats.commandLineEntries, stats.runtimeEntries}) {
            if (count > 0) {
                double p = count / total;
                entropy -= p * std::log2(p);
            }
        }
        stats.entropy = entropy;
    }
    
    return stats;
}

// Get configuration hash for change detection
std::string Config::getHash() const {
    std::hash<std::string> hasher;
    std::string hashString;
    
    for (const auto& entry : pImpl->entries) {
        hashString += entry.key + "=";
        std::visit([&hashString](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                hashString += arg;
            } else {
                hashString += std::to_string(arg);
            }
        }, entry.value);
        hashString += "&";
    }
    
    return std::to_string(hasher(hashString));
}

// Compare configurations
bool Config::equals(const Config& other) const {
    if (pImpl->entries.size() != other.pImpl->entries.size()) {
        return false;
    }
    
    for (const auto& entry : pImpl->entries) {
        auto otherIt = std::find_if(other.pImpl->entries.begin(), other.pImpl->entries.end(),
            [&entry](const ConfigEntry& e) { return e.key == entry.key; });
        
        if (otherIt == other.pImpl->entries.end()) {
            return false;
        }
        
        if (otherIt->value != entry.value || otherIt->source != entry.source) {
            return false;
        }
    }
    
    return true;
}

