// Helper function to convert ConfigValue to JSON
nlohmann::json Config::configValueToJSON(const ConfigValue& value) const {
    return std::visit([](const auto& v) -> nlohmann::json {
        using T = std::decay_t<decltype(v)>;
        
        if constexpr (std::is_same_v<T, int>) {
            return v;
        } else if constexpr (std::is_same_v<T, int64_t>) {
            return v;
        } else if constexpr (std::is_same_v<T, double>) {
            return v;
        } else if constexpr (std::is_same_v<T, bool>) {
            return v;
        } else if constexpr (std::is_same_v<T, std::string>) {
            return v;
        } else if constexpr (std::is_same_v<T, std::vector<int>>) {
            return nlohmann::json::array();
        } else if constexpr (std::is_same_v<T, std::vector<double>>) {
            return nlohmann::json::array();
        } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
            return nlohmann::json::array();
        }
    }, value);
}

// Helper function to convert JSON to ConfigValue
ConfigValue Config::configValueFromJSON(const nlohmann::json& jsonValue) const {
    if (jsonValue.is_number()) {
        if (jsonValue.is_number_integer()) {
            return jsonValue.get<int64_t>();
        } else {
            return jsonValue.get<double>();
        }
    } else if (jsonValue.is_boolean()) {
        return jsonValue.get<bool>();
    } else if (jsonValue.is_string()) {
        return jsonValue.get<std::string>();
    } else if (jsonValue.is_array()) {
        // Check if array contains numbers or strings
        bool allNumbers = std::all_of(jsonValue.begin(), jsonValue.end(), 
                                     [](const nlohmann::json& item) { return item.is_number(); });
        bool allStrings = std::all_of(jsonValue.begin(), jsonValue.end(),
                                      [](const nlohmann::json& item) { return item.is_string(); });
        
        if (allNumbers) {
            std::vector<double> vec;
            for (const auto& item : jsonValue) {
                vec.push_back(item.get<double>());
            }
            return vec;
        } else if (allStrings) {
            std::vector<std::string> vec;
            for (const auto& item : jsonValue) {
                vec.push_back(item.get<std::string>());
            }
            return vec;
        }
        
        // If mixed, return as array of JSON values (not supported)
        throw std::runtime_error("Unsupported JSON array type");
    }
    
    // Default case
    return 0;
}
