bool Config::loadFromFile(const std::string& filepath) {
    // Load configuration from JSON/YAML file with robust parsing
    std::ifstream file(filepath);
    if (!file.is_open()) {
        Logger::getGlobal().error("Failed to open config file: " + filepath);
        return false;
    }
    
    try {
        // Read entire file into string
        std::stringstream buffer;
        buffer << file.rdbuf();
        std::string content = buffer.str();
        
        // Try JSON parsing first
        if (parseJSONFormat(content)) {
            return true;
        }
        
        // Fallback to YAML parsing if available
        if (parseYAMLFormat(content)) {
            return true;
        }
        
        // Final fallback: simple key=value format
        return parseSimpleFormat(content, ConfigSource::File);
    } catch (const std::exception& e) {
        Logger::getGlobal().error("Error reading config file " + filepath + ": " + std::string(e.what()));
        return false;
    }
}

bool Config::loadFromArgs(int argc, char** argv) {
    if (argc <= 1 || argv == nullptr) {
        return false;
    }
    
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos && pos > 2) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    // Save configuration to a well-formatted file
    std::ofstream file(filepath);
    if (!file.is_open()) {
        Logger::getGlobal().error("Failed to save config file: " + filepath);
        return false;
    }
    
    // Write header
    file << "# NLM Configuration File\n";
    file << "# Generated by NLM Configuration System\n";
    file << "# Version: 1.0\n\n";
    
    // Write all entries with proper formatting
    for (const auto& entry : pImpl->entries) {
        // Add section comment if description contains a section marker
        if (!entry.description.empty()) {
            file << "# " << entry.description << "\n";
        }
        
        // Format value based on type
        std::visit([&](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                // Quote strings that contain special characters
                if (arg.find(' ') != std::string::npos || arg.find('=') != std::string::npos || 
                    arg.find('#') != std::string::npos) {
                    file << entry.key << " = \"" << arg << "\"\n";
                } else {
                    file << entry.key << " = " << arg << "\n";
                }
            } else if constexpr (std::is_same_v<T, std::vector<int>> || 
                                 std::is_same_v<T, std::vector<double>> || 
                                 std::is_same_v<T, std::vector<std::string>>) {
                file << entry.key << " = [";
                for (size_t i = 0; i < arg.size(); ++i) {
                    if (i > 0) file << ", ";
                    if constexpr (std::is_same_v<T, std::vector<std::string>) {
                        file << "\"" << arg[i] << "\"";
                    } else {
                        file << arg[i];
                    }
                }
                file << "]\n";
            } else {
                // Basic types
                file << entry.key << " = " << arg << "\n";
            }
        }, entry.value);
        
        // Add source information
        file << "# Source: " << static_cast<int>(entry.source) << "\n\n";
    }
    
    file << "# End of configuration\n";
    return true;
}

std::string Config::saveToFile(const std::string& filepath) const {
    saveToFile(filepath);
    return filepath;
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        Logger::getGlobal().debug("Config key not found: " + key);
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        Logger::getGlobal().warning("Type mismatch for config key: " + key);
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    if (!val.has_value()) {
        Logger::getGlobal().debug("Using default value for config key: " + key);
        return defaultValue;
    }
    return val.value();
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    if (key.empty()) {
        Logger::getGlobal().warning("Attempted to set empty config key");
        return;
    }
    
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it != pImpl->entries.end()) {
        it->value = value;
        it->source = source;
    } else {
        pImpl->entries.emplace_back(key, value, source);
    }
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    if (key.empty()) {
        Logger::getGlobal().warning("Attempted to remove empty config key");
        return;
    }
    
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

bool Config::parseJSONFormat(const std::string& content) {
    try {
        // Use nlohmann::json if available
#ifdef NLM_WITH_JSON
        auto json = nlohmann::json::parse(content);
        for (auto it = json.begin(); it != json.end(); ++it) {
            std::string key = it.key();
            set(key, *it, ConfigSource::File);
        }
        return true;
#else
#endif
        return false;
    } catch (const std::exception&) {
        return false;
    }
}

bool Config::parseYAMLFormat(const std::string& content) {
    try {
        // Use YAML-cpp if available
#ifdef NLM_WITH_YAML
        auto yaml = YAML::Load(content);
        for (auto it = yaml.begin(); it != yaml.end(); ++it) {
            std::string key = it->first.as<std::string>();
            set(key, *it, ConfigSource::File);
        }
        return true;
#else
#endif
        return false;
    } catch (const std::exception&) {
        return false;
    }
}

bool Config::parseSimpleFormat(const std::string& content, ConfigSource source) {
    std::stringstream stream(content);
    std::string line;
    int lineNum = 0;
    
    while (std::getline(stream, line)) {
        ++lineNum;
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove surrounding quotes
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, source);
        } else {
            // If no '=', treat as a key with empty value
            std::string key = line;
            set(key, "", source);
        }
    }
    
    return true;
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::toLower(const std::string& str) {
    std::string result = str;
    std::transform(result.begin(), result.end(), result.begin(), ::tolower);
    return result;
}

