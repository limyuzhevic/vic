bool ConfigValidator::validateConfig(const Config& config) {
    std::vector<std::string> errors;
    
    for (const auto& key : config.getKeys()) {
        std::string validationError = validateValue(key, config.pImpl->entries);
        if (!validationError.empty()) {
            errors.push_back(validationError);
        }
    }
    
    return errors.empty();
}

std::string ConfigValidator::validateValue(const std::string& key, const ConfigValue& value) {
    std::string error = "";
    
    // Basic validation for known keys
    if (key == "simulation_timestep") {
        double* val = std::get_if<double>(&value);
        if (val) {
            if (*val < ValidationConstants::MinTimestep || *val > ValidationConstants::MaxTimestep) {
                error = "Invalid simulation_timestep: must be between " + std::to_string(ValidationConstants::MinTimestep) + " and " + std::to_string(ValidationConstants::MaxTimestep);
            }
        }
    }
    else if (key == "neuron_count") {
        int64_t* val = std::get_if<int64_t>(&value);
        if (val) {
            if (*val < ValidationConstants::MinNeuronCount || *val > ValidationConstants::MaxNeuronCount) {
                error = "Invalid neuron_count: must be between " + std::to_string(ValidationConstants::MinNeuronCount) + " and " + std::to_string(ValidationConstants::MaxNeuronCount);
            }
        }
    }
    else if (key == "region_count") {
        int64_t* val = std::get_if<int64_t>(&value);
        if (val) {
            if (*val < ValidationConstants::MinRegionCount || *val > ValidationConstants::MaxRegionCount) {
                error = "Invalid region_count: must be between " + std::to_string(ValidationConstants::MinRegionCount) + " and " + std::to_string(ValidationConstants::MaxRegionCount);
            }
        }
    }
    else if (key == "connection_probability") {
        float* val = std::get_if<float>(&value);
        if (val) {
            if (*val < ValidationConstants::MinConnectionProbability || *val > ValidationConstants::MaxConnectionProbability) {
                error = "Invalid connection_probability: must be between " + std::to_string(ValidationConstants::MinConnectionProbability) + " and " + std::to_string(ValidationConstants::MaxConnectionProbability);
            }
        }
    }
    else if (key == "environment_name") {
        std::string* val = std::get_if<std::string>(&value);
        if (val) {
            bool validName = false;
            for (int i = 0; ValidationConstants::ValidEnvironmentNames[i] != nullptr; ++i) {
                if (*val == ValidationConstants::ValidEnvironmentNames[i]) {
                    validName = true;
                    break;
                }
            }
            if (!validName) {
                error = "Invalid environment_name: must be one of GridWorld, ContinuousSpace, or EmptyWorld";
            }
        }
    }
    
    return error;
}

