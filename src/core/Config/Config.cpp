// Set multiple configuration values at once
void Config::setBatch(const std::vector<std::pair<std::string, std::string>>& configs) {
    NLM_LOG_INFO("Setting batch of " + std::to_string(configs.size()) + " config values");
    for (const auto& config : configs) {
        try {
            set(config.first, config.second, ConfigSource::Runtime);
            NLM_LOG_DEBUG("Batch set: " + config.first + " = " + config.second);
        } catch (const std::exception& e) {
            NLM_LOG_ERROR("Error in batch config: " + config.first + " = " + config.second + ": " + std::string(e.what()));
        }
    }
}

// Get configuration as JSON-like string
std::string Config::toJSON() const {
    std::ostringstream oss;
    oss << "{\n";
    for (size_t i = 0; i < pImpl->entries.size(); ++i) {
        const auto& entry = pImpl->entries[i];
        oss << "  \"" << entry.key << "\": ";
        
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else if constexpr (std::is_same_v<T, bool>) {
                oss << (arg ? "true" : "false");
            } else if constexpr (std::is_same_v<T, std::vector<int>> ||
                                 std::is_same_v<T, std::vector<double>> ||
                                 std::is_same_v<T, std::vector<std::string>>) {
                oss << "[";
                for (size_t j = 0; j < arg.size(); ++j) {
                    if (j) oss << ", ";
                    if constexpr (std::is_same_v<T, std::string>) {
                        oss << "\"" << arg[j] << "\"";
                    } else {
                        oss << arg[j];
                    }
                }
                oss << "]";
            } else {
                oss << arg;
            }
        }, entry.value);
        
        if (i < pImpl->entries.size() - 1) oss << ",\n";
    }
    oss << "\n}\n";
    return oss.str();
}

// Merge with another config (overwrites existing values)
void Config::merge(const Config& other) {
    NLM_LOG_INFO("Merging configuration from another Config object");
    for (const auto& entry : other.pImpl->entries) {
        // Only overwrite if the key doesn't exist or comes from a higher priority source
        auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&entry](const ConfigEntry& e) { return e.key == entry.key; });
        
        if (it == pImpl->entries.end() || 
            static_cast<int>(entry.source) > static_cast<int>(it->source)) {
            pImpl->entries.push_back(entry);
            NLM_LOG_DEBUG("Merged config: " + entry.key + " = " + (std::string)entry.value);
        }
    }
}

// Create a copy of current config
std::shared_ptr<Config> Config::clone() const {
    auto newConfig = std::make_shared<Config>();
    newConfig->pImpl->entries = pImpl->entries;
    NLM_LOG_INFO("Cloned configuration with " + std::to_string(pImpl->entries.size()) + " entries");
    return newConfig;
}

