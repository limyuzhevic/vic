bool Config::loadFromFile(const std::string& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    while (std::getline(file, line)) {
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
        }
    }
    
    return true;
}

bool Config::loadFromArgs(int argc, char** argv) {
    try {
        for (int i = 1; i < argc; ++i) {
            std::string arg(argv[i]);
            
            // Handle --key=value format
            if (arg.substr(0, 2) == "--") {
                size_t pos = arg.find('=');
                if (pos != std::string::npos) {
                    std::string key = arg.substr(2, pos - 2);
                    std::string value = arg.substr(pos + 1);
                    set(key, value, ConfigSource::CommandLine);
                } else {
                    // Handle --key value format where next arg is value
                    if (i + 1 < argc && argv[i + 1][0] != '-') {
                        std::string key = arg.substr(2);
                        std::string value = argv[++i];
                        set(key, value, ConfigSource::CommandLine);
                    }
                }
            }
            // Handle -key value format
            else if (arg[0] == '-' && i + 1 < argc && argv[i + 1][0] != '-') {
                std::string key = arg.substr(1);
                std::string value = argv[++i];
                set(key, value, ConfigSource::CommandLine);
            }
        }
        return true;
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception loading from args: ") + e.what());
        return false;
    }
}

bool Config::saveToFile(const std::string& filepath) const {
    try {
        std::ofstream file(filepath);
        if (!file.is_open()) {
            return false;
        }
        
        // Add metadata comment
        file << "# NLM Configuration File (Phase 5+ format)\n";
        file << "# Generated by NLM Config class\n\n";
        
        for (const auto& entry : pImpl->entries) {
            file << "# " << entry.description << "\n";
            file << "# Source: " << static_cast<int>(entry.source) << "\n";
            
            // Format based on value type
            std::visit([&file](auto&& arg) {
                using T = std::decay_t<decltype(arg)>;
                if constexpr (std::is_same_v<T, std::string>) {
                    file << entry.key << " = \"" << arg << "\"\n";
                } else if constexpr (std::is_same_v<T, std::vector<int>>) {
                    file << entry.key << " = [";
                    for (size_t i = 0; i < arg.size(); ++i) {
                        if (i) file << ", ";
                        file << arg[i];
                    }
                    file << "]\n";
                } else if constexpr (std::is_same_v<T, std::vector<double>>) {
                    file << entry.key << " = [";
                    for (size_t i = 0; i < arg.size(); ++i) {
                        if (i) file << ", ";
                        file << arg[i];
                    }
                    file << "]\n";
                } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                    file << entry.key << " = [";
                    for (size_t i = 0; i < arg.size(); ++i) {
                        if (i) file << ", ";
                        file << "\"" << arg[i] << "\"";
                    }
                    file << "]\n";
                } else {
                    file << entry.key << " = " << arg << "\n";
                }
            }, entry.value);
            
            file << "\n";
        }
        
        return true;
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception saving config to file ") + filepath + ": " + e.what());
        return false;
    }
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    try {
        // Validate key
        if (key.empty()) {
            throw std::invalid_argument("Config key cannot be empty");
        }
        
        // Validate key format (basic)
        if (key.find('=') != std::string::npos) {
            throw std::invalid_argument("Config key cannot contain '=' character");
        }
        
        auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; });
        
        if (it != pImpl->entries.end()) {
            it->value = value;
            it->source = source;
        } else {
            pImpl->entries.emplace_back(key, value, source);
        }
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception setting config key ") + key + ": " + e.what());
        throw; // Re-throw after logging
    }
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int64_t value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

namespace {
    bool isValidKey(const std::string& key) {
        return !key.empty() && key.find('=') == std::string::npos;
    }
    
    bool isValidValue(const ConfigValue& value) {
        // Basic validation - can be expanded as needed
        std::visit([](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                // Validate string length and content
                if (arg.size() > 1024) {
                    throw std::invalid_argument("String value too long (max 1024 characters)");
                }
            } else if constexpr (std::is_same_v<T, double>) {
                // Validate numeric range
                if (std::isnan(arg) || std::isinf(arg)) {
                    throw std::invalid_argument("Invalid numeric value (NaN or infinity)");
                }
            }
        }, value);
        return true;
    }
} // namespace

bool Config::has(const std::string& key) const {
    try {
        return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; });
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception checking key existence for ") + key + ": " + e.what());
        return false;
    }
}

void Config::remove(const std::string& key) {
    try {
        pImpl->entries.erase(
            std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
                [&key](const ConfigEntry& e) { return e.key == key; }),
            pImpl->entries.end()
        );
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception removing key ") + key + ": " + e.what());
    }
}

std::vector<std::string> Config::getKeys() const {
    try {
        std::vector<std::string> keys;
        keys.reserve(pImpl->entries.size());
        for (const auto& entry : pImpl->entries) {
            keys.push_back(entry.key);
        }
        return keys;
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception getting keys: ") + e.what());
        return {};
    }
}

void Config::clear() {
    try {
        pImpl->entries.clear();
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception clearing config: ") + e.what());
    }
}

std::string Config::summary() const {
    try {
        std::ostringstream oss;
        oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
        for (const auto& entry : pImpl->entries) {
            oss << "  " << entry.key << " = [";
            std::visit([&oss](auto&& arg) {
                using T = std::decay_t<decltype(arg)>;
                if constexpr (std::is_same_v<T, std::string>) {
                    oss << "\"" << arg << "\"";
                } else if constexpr (std::is_same_v<T, std::vector<int>> ||
                                     std::is_same_v<T, std::vector<double>> ||
                                     std::is_same_v<T, std::vector<std::string>>) {
                    oss << "[";
                    for (size_t i = 0; i < arg.size(); ++i) {
                        if (i) oss << ", ";
                        if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                            oss << "\"" << arg[i] << "\"";
                        } else {
                            oss << arg[i];
                        }
                    }
                    oss << "]";
                } else {
                    oss << arg;
                }
            }, entry.value);
            oss << "] (" << static_cast<int>(entry.source) << ")\n";
        }
        return oss.str();
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception generating summary: ") + e.what());
        return "Error generating configuration summary";
    }
}

std::string Config::trim(const std::string& str) {
    try {
        size_t start = str.find_first_not_of(" \t\r\n");
        if (start == std::string::npos) return "";
        size_t end = str.find_last_not_of(" \t\r\n");
        return str.substr(start, end - start + 1);
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception trimming string: ") + e.what());
        return str; // Return original string on error
    }
}

std::string Config::toLower(const std::string& str) {
    try {
        std::string result = str;
        std::transform(result.begin(), result.end(), result.begin(), ::tolower);
        return result;
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception converting to lower case: ") + e.what());
        return str; // Return original string on error
    }
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    try {
        if (key.empty()) {
            NLM_LOG_WARNING("Empty key provided to Config::get");
            return std::nullopt;
        }
        
        auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; });
        if (it == pImpl->entries.end()) {
            return std::nullopt;
        }
        
        return std::visit([](auto&& v) -> std::optional<T> {
            using V = std::decay_t<decltype(v)>;
            if constexpr (std::is_same_v<V, T>) {
                return v;
            } else if constexpr (std::is_arithmetic_v<V> && std::is_arithmetic_v<T>) {
                return static_cast<T>(v);
            } else {
                return std::nullopt;
            }
        }, it->value);
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception getting config value for ") + key + ": " + e.what());
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    try {
        auto val = get<T>(key);
        return val.has_value() ? val.value() : defaultValue;
    } catch (const std::exception& e) {
        NLM_LOG_ERROR(std::string("Exception getting default config value for ") + key + ": " + e.what());
        return defaultValue;
    }
}

