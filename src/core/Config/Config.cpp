    void parseAndSetValue(const std::string& key, const std::string& valueStr) {
        // Try to parse as different types in order of preference
        // bool
        if (valueStr == "true" || valueStr == "false") {
            bool boolVal = (valueStr == "true");
            set(key, boolVal, ConfigSource::File);
            return;
        }
        
        // integer
        try {
            size_t pos;
            int intVal = std::stoi(valueStr, &pos);
            if (pos == valueStr.size()) {
                set(key, intVal, ConfigSource::File);
                return;
            }
        } catch (...) {}
        
        // int64_t
        try {
            size_t pos;
            int64_t int64Val = std::stoll(valueStr, &pos);
            if (pos == valueStr.size()) {
                set(key, int64Val, ConfigSource::File);
                return;
            }
        } catch (...) {}
        
        // double
        try {
            size_t pos;
            double doubleVal = std::stod(valueStr, &pos);
            if (pos == valueStr.size()) {
                set(key, doubleVal, ConfigSource::File);
                return;
            }
        } catch (...) {}
        
        // Default to string
        set(key, valueStr, ConfigSource::File);
    }
    
    // Add JSON loading method
    bool loadFromJsonFile(const std::string& filepath) {
        // For now, implement a simple JSON-like parser
        // In a real implementation, this would use a JSON library like nlohmann/json
        // For this project, we'll implement a basic JSON parser
        std::ifstream file(filepath);
        if (!file.is_open()) {
            return false;
        }
        
        std::string content((std::istreambuf_iterator<char>(file)), 
                            std::istreambuf_iterator<char>());
        
        // Simple JSON parsing - handles basic object format: {"key": "value", "num": 42}
        if (content.find("{") != 0 || content.back() != '}') {
            return false; // Not a JSON object
        }
        
        // Remove braces
        content = content.substr(1, content.size() - 2);
        
        // Parse key-value pairs
        size_t pos = 0;
        while (pos < content.size()) {
            // Find next key
            size_t keyStart = content.find('"', pos);
            if (keyStart == std::string::npos) break;
            
            size_t keyEnd = content.find('"', keyStart + 1);
            if (keyEnd == std::string::npos) break;
            
            std::string key = content.substr(keyStart + 1, keyEnd - keyStart - 1);
            pos = keyEnd + 1;
            
            // Skip whitespace and colon
            while (pos < content.size() && (content[pos] == ' ' || content[pos] == '\t' || content[pos] == ':')) {
                pos++;
            }
            
            // Find value
            if (pos >= content.size()) break;
            
            char quoteChar = content[pos];
            if (quoteChar == '"') {
                // String value
                size_t valueEnd = content.find('"', pos + 1);
                if (valueEnd == std::string::npos) break;
                
                std::string value = content.substr(pos + 1, valueEnd - pos - 1);
                set(key, value, ConfigSource::File);
                pos = valueEnd + 2; // Skip closing quote and comma
            } else if (quoteChar == 'n' && content.substr(pos, 4) == "null") {
                // null value - treat as empty string
                set(key, "", ConfigSource::File);
                pos += 4;
            } else {
                // Try to find number or boolean
                size_t valueEnd = content.find(',', pos);
                if (valueEnd == std::string::npos) {
                    valueEnd = content.find('}', pos);
                }
                if (valueEnd == std::string::npos) break;
                
                std::string valueStr = content.substr(pos, valueEnd - pos);
                
                // Skip whitespace at end
                while (!valueStr.empty() && (valueStr.back() == ' ' || valueStr.back() == '\t')) {
                    valueStr.pop_back();
                }
                
                if (!valueStr.empty()) {
                    parseAndSetValue(key, valueStr);
                }
                
                pos = valueEnd + 1;
            }
            
            // Skip comma
            while (pos < content.size() && (content[pos] == ',' || content[pos] == ' ' || content[pos] == '\t')) {
                pos++;
            }
        }
        
        return true;
    }

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::getCurrentTimeString() {
    auto now = std::chrono::system_clock::now();
    auto time = std::chrono::system_clock::to_time_t(now);
    std::stringstream ss;
    ss << std::put_time(std::localtime(&time), "%Y-%m-%d %H:%M:%S");
    return ss.str();
}
