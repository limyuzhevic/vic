// Configuration validation and schema support

bool Config::validateKeyValue(const std::string& key, const std::string& value) {
    // Basic validation - check for empty values
    if (key.empty() || value.empty()) {
        return false;
    }
    
    // Key-specific validation (basic checks)
    if (key == "neuron_count") {
        try {
            int64_t neuronCount = std::stoll(value);
            if (neuronCount <= 0 || neuronCount > 100000) {
                return false;
            }
        } catch (const std::exception&) {
            return false;
        }
    } else if (key == "connection_probability") {
        try {
            float prob = std::stof(value);
            if (prob <= 0.0f || prob > 1.0f) {
                return false;
            }
        } catch (const std::exception&) {
            return false;
        }
    }
    
    // For other keys, accept any reasonable value
    return true;
}

// Helper function to convert ConfigValue to string for logging
std::string Config::toString(const ConfigValue& value) {
    std::ostringstream oss;
    std::visit([&oss](auto&& arg) {
        using T = std::decay_t<decltype(arg)>;
        if constexpr (std::is_same_v<T, std::string>) {
            oss << "\"" << arg << "\"";
        } else if constexpr (std::is_same_v<T, bool>) {
            oss << (arg ? "true" : "false");
        } else if constexpr (std::is_arithmetic_v<T>) {
            oss << arg;
        } else if constexpr (std::is_same_v<T, std::vector<int>> ||
                             std::is_same_v<T, std::vector<double>> ||
                             std::is_same_v<T, std::vector<std::string>>) {
            oss << "[";
            for (size_t i = 0; i < arg.size(); ++i) {
                if (i) oss << ", ";
                oss << arg[i];
            }
            oss << "]";
        } else {
            oss << "UNKNOWN_TYPE";
        }
    }, value);
    return oss.str();
}

bool Config::validateEntry(const ConfigEntry& entry) {
    // Basic validation for common configuration keys
    if (entry.key == "neuron_count") {
        auto neuronCount = std::get_if<int64_t>(&entry.value);
        if (neuronCount) {
            return (*neuronCount > 0 && *neuronCount <= 100000);
        }
    } else if (entry.key == "connection_probability") {
        auto prob = std::get_if<float>(&entry.value);
        if (prob) {
            return (*prob >= 0.0f && *prob <= 1.0f);
        }
    } else if (entry.key == "simulation_timestep") {
        auto timestep = std::get_if<double>(&entry.value);
        if (timestep) {
            return (*timestep > 0.0 && *timestep <= 1.0);
        }
    } else if (entry.key == "random_seed") {
        auto seed = std::get_if<int64_t>(&entry.value);
        if (seed) {
            return (*seed >= 0);
        }
    }
    
    // For other keys, basic validation
    if (entry.key.empty()) {
        return false;
    }
    
    return true;
}

