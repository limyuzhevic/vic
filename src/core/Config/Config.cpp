ValidationResult Config::validate() const {
    ValidationResult overallValid;
    std::string allWarnings;
    
    for (const auto& entry : pImpl->entries) {
        // Check if there's a validator for this key
        auto validatorIt = pImpl->validators.find(entry.key);
        if (validatorIt != pImpl->validators.end()) {
            ValidationResult result = validatorIt->second(entry.value);
            if (!result.valid) {
                overallValid.valid = false;
                overallValid.errorMessage += "Key '" + entry.key + "': " + result.errorMessage + "; ";
            }
            if (!result.warningMessage.empty()) {
                allWarnings += "Key '" + entry.key + "': " + result.warningMessage + "; ";
            }
        }
    }
    
    overallValid.warningMessage = allWarnings;
    return overallValid;
}

