// Get source of configuration value
ConfigSource Config::getSource(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return ConfigSource::Default;
    }
    
    return it->source;
}

// Check if key exists and has valid value
bool Config::hasValid(const std::string& key) const {
    auto entry = getEntry(key);
    if (!entry) {
        return false;
    }
    
    // Basic validation - check key is not empty
    if (entry->key.empty()) {
        return false;
    }
    
    return true;
}

// Get all keys with source information
std::vector<std::pair<std::string, ConfigSource>> Config::getKeySources() const {
    std::vector<std::pair<std::string, ConfigSource>> keySources;
    keySources.reserve(pImpl->entries.size());
    
    for (const auto& entry : pImpl->entries) {
        keySources.emplace_back(entry.key, entry.source);
    }
    
    return keySources;
}

// Clear configuration by source
void Config::clearBySource(ConfigSource source) {
    auto originalSize = pImpl->entries.size();
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [source](const ConfigEntry& e) { return e.source == source; }),
        pImpl->entries.end()
    );
    
    NLM_LOG_INFO("Cleared " + std::to_string(originalSize - pImpl->entries.size()) +
                 " config entries by source " + std::to_string(static_cast<int>(source)));
}

// Merge configurations
void Config::merge(const Config& other) {
    for (const auto& entry : other.pImpl->entries) {
        // Prefer existing entries, but keep other's if key doesn't exist
        if (!has(entry.key)) {
            pImpl->entries.push_back(entry);
        }
    }
    
    NLM_LOG_INFO("Merged " + std::to_string(other.pImpl->entries.size()) +
                 " configuration entries");
}

