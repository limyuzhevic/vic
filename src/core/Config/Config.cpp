// Helper Functions for JSON/YAML Parsing

static std::optional<std::string> tryParseJson(const std::string& content) {
    if (content.empty()) return std::nullopt;
    
    // Basic JSON detection - looks for typical JSON structure
    size_t pos = content.find_first_of("{[]");
    if (pos == std::string::npos) {
        return std::nullopt;
    }
    
    // Check if content looks like JSON
    size_t openBraces = std::count(content.begin(), content.end(), '{');
    size_t closeBraces = std::count(content.begin(), content.end(), '}');
    size_t openBrackets = std::count(content.begin(), content.end(), '[');
    size_t closeBrackets = std::count(content.begin(), content.end(), ']');
    
    // Simple validation - should have matching braces/brackets
    if ((openBraces > 0 && closeBraces == openBraces) || 
        (openBrackets > 0 && closeBrackets == openBrackets)) {
        return content;
    }
    
    return std::nullopt;
}

static std::optional<std::string> tryParseYaml(const std::string& content) {
    if (content.empty()) return std::nullopt;
    
    // Basic YAML detection - looks for typical YAML structure
    size_t pos = content.find_first_of(":-");
    if (pos == std::string::npos) {
        return std::nullopt;
    }
    
    // Check if content looks like YAML (key: value format)
    bool hasColon = false;
    bool hasDash = false;
    for (char c : content) {
        if (c == ':') hasColon = true;
        if (c == '-') hasDash = true;
    }
    
    if (hasColon || hasDash) {
        return content;
    }
    
    return std::nullopt;
}

static std::string normalizeJsonKeys(const std::string& jsonContent) {
    std::string result;
    bool inString = false;
    char quoteChar = '\0';
    
    for (size_t i = 0; i < jsonContent.size(); ++i) {
        char c = jsonContent[i];
        
        if (!inString && c == '"') {
            // Found key start
            inString = true;
            quoteChar = '"';
            result += c;
            
            // Find key end and normalize
            size_t keyEnd = jsonContent.find('"', i + 1);
            if (keyEnd != std::string::npos) {
                std::string key = jsonContent.substr(i + 1, keyEnd - i - 1);
                
                // Normalize key: lowercase, replace spaces and hyphens with underscores
                std::string normalizedKey;
                for (char kc : key) {
                    if (std::isspace(kc) || kc == '-') {
                        normalizedKey += '_';
                    } else {
                        normalizedKey += static_cast<char>(std::tolower(kc));
                    }
                }
                
                result += normalizedKey;
                i = keyEnd; // Skip to end of key
            }
        } else {
            result += c;
        }
    }
    
    return result;
}

static std::string normalizeYamlKeys(const std::string& yamlContent) {
    std::string result;
    size_t i = 0;
    
    while (i < yamlContent.size()) {
        char c = yamlContent[i];
        
        if (c == '-') {
            // YAML list item - skip the dash and following space
            result += c;
            i++;
            if (i < yamlContent.size() && std::isspace(yamlContent[i])) {
                i++;
            }
        } else if (c == ':') {
            // Key-value separator
            result += c;
            i++;
            
            // Add space after colon for readability
            if (i < yamlContent.size() && !std::isspace(yamlContent[i])) {
                result += ' ';
            }
        } else if (std::isspace(c)) {
            // Collapse multiple spaces
            result += ' ';
            i++;
            while (i < yamlContent.size() && std::isspace(yamlContent[i])) {
                i++;
            }
        } else {
            result += c;
            i++;
        }
    }
    
    return result;
}

static void parseJsonToConfig(const std::string& jsonContent, std::vector<ConfigEntry>& entries) {
    // Simple JSON parser for basic key-value pairs
    size_t pos = 0;
    while (pos < jsonContent.size()) {
        // Find key
        if (jsonContent[pos] != '"') {
            pos++;
            continue;
        }
        
        size_t keyStart = ++pos;
        while (pos < jsonContent.size() && jsonContent[pos] != '"') {
            pos++;
        }
        
        if (pos >= jsonContent.size()) break;
        
        std::string key = jsonContent.substr(keyStart, pos - keyStart);
        pos++; // Skip closing quote
        
        // Skip whitespace
        while (pos < jsonContent.size() && std::isspace(jsonContent[pos])) {
            pos++;
        }
        
        if (pos >= jsonContent.size() || jsonContent[pos] != ':') {
            continue;
        }
        
        pos++; // Skip colon
        
        // Skip whitespace
        while (pos < jsonContent.size() && std::isspace(jsonContent[pos])) {
            pos++;
        }
        
        // Parse value
        if (pos >= jsonContent.size()) break;
        
        // Find value end
        char valueChar = jsonContent[pos];
        size_t valueStart = pos;
        
        if (valueChar == '"') {
            // String value
            pos++;
            while (pos < jsonContent.size() && jsonContent[pos] != '"') {
                if (jsonContent[pos] == '\\' && pos + 1 < jsonContent.size()) {
                    pos += 2; // Skip escaped character
                } else {
                    pos++;
                }
            }
            if (pos < jsonContent.size()) pos++; // Skip closing quote
        } else if (valueChar == 't' || valueChar == 'f') {
            // Boolean value (true/false)
            while (pos < jsonContent.size() && std::isalpha(jsonContent[pos])) {
                pos++;
            }
        } else if (valueChar == 'n' || valueChar == 'N') {
            // Null or number
            while (pos < jsonContent.size() && (std::isalnum(jsonContent[pos]) || jsonContent[pos] == '.' || jsonContent[pos] == '-')) {
                pos++;
            }
        } else if (valueChar == '{' || valueChar == '[') {
            // Object or array - skip to closing
            int bracketCount = (valueChar == '{') ? 1 : 1;
            pos++;
            while (pos < jsonContent.size() && bracketCount > 0) {
                if (jsonContent[pos] == '{' || jsonContent[pos] == '[') {
                    bracketCount++;
                } else if (jsonContent[pos] == '}' || jsonContent[pos] == ']') {
                    bracketCount--;
                }
                pos++;
            }
        } else {
            // Number
            while (pos < jsonContent.size() && (std::isdigit(jsonContent[pos]) || jsonContent[pos] == '.' || jsonContent[pos] == '-' || jsonContent[pos] == 'e' || jsonContent[pos] == 'E')) {
                pos++;
            }
        }
        
        std::string valueStr = jsonContent.substr(valueStart, pos - valueStart);
        std::string normalizedKey = normalizeJsonKeys("\"" + key + "\": " + valueStr);
        
        // Extract just the key part
        size_t colonPos = normalizedKey.find(':');
        if (colonPos != std::string::npos) {
            std::string normalizedKeyName = normalizedKey.substr(0, colonPos);
            
            // Parse the value
            ConfigValue configValue;
            if (valueStr.find('.') != std::string::npos || valueStr.find('e') != std::string::npos) {
                try {
                    double doubleVal = std::stod(valueStr);
                    configValue = doubleVal;
                } catch (...) {
                    configValue = valueStr;
                }
            } else {
                try {
                    int intVal = std::stoi(valueStr);
                    configValue = intVal;
                } catch (...) {
                    configValue = valueStr;
                }
            }
            
            entries.emplace_back(normalizedKeyName, configValue, ConfigSource::File, "");
        }
    }
}

static void parseYamlToConfig(const std::string& yamlContent, std::vector<ConfigEntry>& entries) {
    // Simple YAML parser for basic key-value pairs
    size_t pos = 0;
    while (pos < yamlContent.size()) {
        // Skip whitespace
        while (pos < yamlContent.size() && std::isspace(yamlContent[pos])) {
            pos++;
        }
        
        if (pos >= yamlContent.size()) break;
        
        // Check for list item
        if (yamlContent[pos] == '-') {
            // YAML list - for now, just skip the dash and any value after it
            pos++; // Skip dash
            while (pos < yamlContent.size() && !std::isspace(yamlContent[pos])) {
                pos++;
            }
            continue;
        }
        
        // Find key (up to colon)
        size_t keyStart = pos;
        while (pos < yamlContent.size() && yamlContent[pos] != ':') {
            pos++;
        }
        
        if (pos >= yamlContent.size() || yamlContent[pos] != ':') {
            continue;
        }
        
        std::string key = yamlContent.substr(keyStart, pos - keyStart);
        
        // Trim key
        size_t keyEnd = key.find_last_not_of(" \t");
        if (keyEnd != std::string::npos) {
            key = key.substr(0, keyEnd + 1);
        }
        
        size_t colonPos = pos;
        pos++; // Skip colon
        
        // Skip whitespace after colon
        while (pos < yamlContent.size() && std::isspace(yamlContent[pos])) {
            pos++;
        }
        
        // Find value end (next key start or end of content)
        size_t valueStart = pos;
        while (pos < yamlContent.size()) {
            if (yamlContent[pos] == ':' && !std::isspace(yamlContent[pos])) {
                // Potential new key
                break;
            }
            pos++;
        }
        
        std::string valueStr = yamlContent.substr(valueStart, pos - valueStart);
        
        // Trim value
        size_t valueStartTrim = valueStr.find_first_not_of(" \t");
        size_t valueEndTrim = valueStr.find_last_not_of(" \t");
        if (valueStartTrim != std::string::npos && valueEndTrim != std::string::npos) {
            valueStr = valueStr.substr(valueStartTrim, valueEndTrim - valueStartTrim + 1);
        }
        
        // Normalize key
        std::string normalizedKey = key;
        for (char& c : normalizedKey) {
            if (std::isspace(c) || c == '-') {
                c = '_';
            } else {
                c = static_cast<char>(std::tolower(c));
            }
        }
        
        // Parse the value
        ConfigValue configValue;
        if (valueStr.empty()) {
            configValue = "";
        } else if (valueStr == "true" || valueStr == "false") {
            configValue = (valueStr == "true");
        } else if (valueStr.find('.') != std::string::npos || valueStr.find('e') != std::string::npos || valueStr.find('E') != std::string::npos) {
            try {
                double doubleVal = std::stod(valueStr);
                configValue = doubleVal;
            } catch (...) {
                configValue = valueStr;
            }
        } else {
            try {
                int intVal = std::stoi(valueStr);
                configValue = intVal;
            } catch (...) {
                configValue = valueStr;
            }
        }
        
        entries.emplace_back(normalizedKey, configValue, ConfigSource::File, "");
    }
}

static std::string convertJsonValueToString(const std::string& jsonValue) {
    std::string result;
    bool inString = false;
    char quoteChar = '\0';
    
    for (char c : jsonValue) {
        if (!inString && (c == '"' || c == '\'')) {
            inString = true;
            quoteChar = c;
            result += c;
        } else if (inString && c == quoteChar) {
            inString = false;
            result += c;
        } else if (inString && c == '\\' && result.back() != '\\') {
            result += c;
            if (++c < jsonValue.size()) {
                result += c;
            }
        } else {
            result += c;
        }
    }
    
    return result;
}

static std::string convertYamlValueToString(const std::string& yamlValue) {
    std::string result;
    
    for (char c : yamlValue) {
        if (c == '\'') {
            result += "\\'";
        } else if (c == '"') {
            result += "\\\"";
        } else {
            result += c;
        }
    }
    
    return result;
}
