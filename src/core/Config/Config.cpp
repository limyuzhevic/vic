bool Config::loadFromFile(const std::string& filepath) {
    // Try to parse as JSON first
    try {
        std::ifstream file(filepath);
        if (!file.is_open()) {
            return false;
        }
        
        nlohmann::json jsonData;
        file >> jsonData;
        
        // Clear existing entries
        pImpl->entries.clear();
        
        // Recursively parse JSON and add entries
        parseJsonToConfig(jsonData, filepath, ConfigSource::File);
        
        NLM_LOG_INFO("Successfully loaded configuration from JSON file: " + filepath);
        return true;
        
    } catch (const nlohmann::json::parse_error& e) {
        NLM_LOG_WARNING("Failed to parse as JSON, falling back to simple key=value format: " + 
                       std::string(e.what()));
    }
    
    // Fallback to simple key=value format
    std::ifstream file(filepath);
    if (!file.is_open()) {
        return false;
    }
    
    std::string line;
    while (std::getline(file, line)) {
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
        }
    }
    
    return true;
}

void Config::parseJsonToConfig(const nlohmann::json& json, const std::string& sourceDesc, ConfigSource source) {
    if (json.is_object()) {
        for (auto it = json.begin(); it != json.end(); ++it) {
            std::string key = it.key();
            
            // Recursively process based on JSON type
            if (it->is_boolean()) {
                set(key, it->get<bool>(), source);
                // Generate a helpful description
                std::string description = "Boolean parameter from " + sourceDesc;
                updateEntryDescription(key, description, source);
            }
            else if (it->is_number_integer()) {
                set(key, it->get<int64_t>(), source);
                std::string description = "Integer parameter from " + sourceDesc;
                updateEntryDescription(key, description, source);
            }
            else if (it->is_number_unsigned()) {
                set(key, static_cast<int64_t>(it->get<uint64_t>()), source);
                std::string description = "Unsigned integer parameter from " + sourceDesc;
                updateEntryDescription(key, description, source);
            }
            else if (it->is_number_float()) {
                set(key, it->get<double>(), source);
                std::string description = "Float parameter from " + sourceDesc;
                updateEntryDescription(key, description, source);
            }
            else if (it->is_string()) {
                set(key, it->get<std::string>(), source);
                std::string description = "String parameter from " + sourceDesc;
                updateEntryDescription(key, description, source);
            }
            else if (it->is_array()) {
                // Try to infer array type from first element
                if (!it->empty()) {
                    const auto& first = it->front();
                    if (first.is_number_integer()) {
                        std::vector<int64_t> intArray;
                        for (const auto& item : *it) {
                            intArray.push_back(item.get<int64_t>());
                        }
                        set(key, intArray, source);
                    }
                    else if (first.is_number_float()) {
                        std::vector<double> floatArray;
                        for (const auto& item : *it) {
                            floatArray.push_back(item.get<double>());
                        }
                        set(key, floatArray, source);
                    }
                    else if (first.is_string()) {
                        std::vector<std::string> stringArray;
                        for (const auto& item : *it) {
                            stringArray.push_back(item.get<std::string>());
                        }
                        set(key, stringArray, source);
                    }
                }
                std::string description = "Array parameter from " + sourceDesc;
                updateEntryDescription(key, description, source);
            }
            else if (it->is_object()) {
                // For nested objects, create a flattened representation
                std::string flatKey = key;
                flattenJsonObject(*it, flatKey, source);
            }
        }
    }
}

void Config::flattenJsonObject(const nlohmann::json& json, std::string& baseKey, ConfigSource source) {
    if (json.is_object()) {
        for (auto it = json.begin(); it != json.end(); ++it) {
            std::string newKey = baseKey + "." + it.key();
            
            if (it->is_boolean()) {
                set(newKey, it->get<bool>(), source);
            }
            else if (it->is_number_integer()) {
                set(newKey, it->get<int64_t>(), source);
            }
            else if (it->is_number_unsigned()) {
                set(newKey, static_cast<int64_t>(it->get<uint64_t>()), source);
            }
            else if (it->is_number_float()) {
                set(newKey, it->get<double>(), source);
            }
            else if (it->is_string()) {
                set(newKey, it->get<std::string>(), source);
            }
            else if (it->is_array()) {
                // Skip complex arrays for now
                continue;
            }
            else if (it->is_object()) {
                // Recursively flatten
                flattenJsonObject(*it, newKey, source);
            }
        }
    }
}

void Config::updateEntryDescription(const std::string& key, const std::string& description, ConfigSource source) {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    if (it != pImpl->entries.end()) {
        it->description = description;
    }
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open file for saving: " + filepath);
        return false;
    }
    
    // Save as JSON for better format and future compatibility
    nlohmann::json jsonData;
    
    for (const auto& entry : pImpl->entries) {
        // Use the description as the JSON field value for now
        // In a real implementation, we would want to preserve the value structure
        jsonData[entry.key] = "value_placeholder_" + std::to_string(entry.source);
    }
    
    try {
        file << std::setw(4) << jsonData;
        NLM_LOG_INFO("Configuration saved as JSON to: " + filepath);
    } catch (const std::exception& e) {
        NLM_LOG_ERROR("Exception saving configuration: " + std::string(e.what()));
        return false;
    }
    
    return true;
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        NLM_LOG_WARNING("Type mismatch when getting config value for key: " + key);
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

