bool Config::applyJSONPatch(const std::string& jsonPatch) {
    try {
        nlohmann::json patch = nlohmann::json::parse(jsonPatch);
        
        // Apply patch to configuration
        if (patch.contains("updates")) {
            const auto& updates = patch["updates"];
            
            for (const auto& update : updates) {
                if (update.is_object() && update.contains("key") && update.contains("value")) {
                    std::string key = update["key"].get<std::string>();
                    nlohmann::json value = update["value"];
                    
                    // Set value using the key
                    set(key, configValueFromJSON(value), ConfigSource::Runtime);
                }
            }
        }
        
        return true;
    } catch (const std::exception& e) {
        return false;
    }
}

