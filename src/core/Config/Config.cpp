// Validate configuration
bool Config::validate() const {
    std::vector<std::string> errors = getValidationErrors();
    if (!errors.empty()) {
        std::cerr << "Config validation failed:" << std::endl;
        for (const auto& error : errors) {
            std::cerr << "  - " << error << std::endl;
        }
        return false;
    }
    return true;
}

// Check if configuration has errors
std::vector<std::string> Config::getValidationErrors() const {
    std::vector<std::string> errors;
    
    // Check for required configuration keys
    std::vector<std::string> requiredKeys = {
        "brain.neuron_count",
        "simulation_timestep",
        "random_seed"
    };
    
    for (const auto& key : requiredKeys) {
        if (!has(key)) {
            errors.push_back("Missing required configuration key: " + key);
        }
    }
    
    // Validate type-specific constraints
    if (has("brain.neuron_count")) {
        if (auto val = get<size_t>("brain.neuron_count")) {
            if (*val == 0) {
                errors.push_back("brain.neuron_count must be greater than 0");
            } else if (*val > 1000000) {
                errors.push_back("brain.neuron_count too large (max: 1000000)");
            }
        }
    }
    
    if (has("simulation_timestep")) {
        if (auto val = get<double>("simulation_timestep")) {
            if (*val <= 0.0) {
                errors.push_back("simulation_timestep must be positive");
            } else if (*val > 0.1) {
                errors.push_back("simulation_timestep too large (max: 0.1s)");
            }
        }
    }
    
    return errors;
}
