bool Config::loadFromFile(const std::string& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open config file: " + filepath);
        return false;
    }
    
    std::string line;
    size_t lineNumber = 0;
    while (std::getline(file, line)) {
        ++lineNumber;
        
        // Skip empty lines and comments
        line = trim(line);
        if (line.empty() || line[0] == '#' || line[0] == '/') {
            continue;
        }
        
        // Parse simple key=value pairs
        size_t pos = line.find('=');
        if (pos != std::string::npos) {
            std::string key = trim(line.substr(0, pos));
            std::string value = trim(line.substr(pos + 1));
            
            // Validate key
            if (key.empty()) {
                NLM_LOG_WARNING("Empty key found in config file " + filepath + " at line " + std::to_string(lineNumber));
                continue;
            }
            
            // Remove quotes if present
            if (value.size() >= 2 && 
                ((value.front() == '"' && value.back() == '"') ||
                 (value.front() == '\'' && value.back() == '\''))) {
                value = value.substr(1, value.size() - 2);
            }
            
            set(key, value, ConfigSource::File);
            
            // Log important configuration settings
            if (key == "neuron_count" || key == "neuron_count") {
                NLM_LOG_INFO("Loaded configuration: " + key + " = " + value);
            }
        } else {
            NLM_LOG_WARNING("Invalid config line (no '=') in " + filepath + " at line " + std::to_string(lineNumber) + ": " + line);
        }
    }
    
    NLM_LOG_INFO("Successfully loaded config file: " + filepath + " (" + 
                 std::to_string(pImpl->entries.size()) + " entries)");
    return true;
}

bool Config::loadFromArgs(int argc, char** argv) {
    for (int i = 1; i < argc; ++i) {
        std::string arg(argv[i]);
        
        // Handle --key=value format
        if (arg.substr(0, 2) == "--") {
            size_t pos = arg.find('=');
            if (pos != std::string::npos) {
                std::string key = arg.substr(2, pos - 2);
                std::string value = arg.substr(pos + 1);
                set(key, value, ConfigSource::CommandLine);
            }
        }
        // Handle -key value format
        else if (arg[0] == '-' && i + 1 < argc) {
            std::string key = arg.substr(1);
            std::string value = argv[++i];
            set(key, value, ConfigSource::CommandLine);
        }
    }
    return true;
}

bool Config::saveToFile(const std::string& filepath) const {
    std::ofstream file(filepath);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open config file for writing: " + filepath);
        return false;
    }
    
    // Write file with proper formatting
    file << "# NLM Configuration File\n";
    file << "# Generated by NLM Brain Simulator\n";
    file << "# Format: key = value\n\n";
    
    for (const auto& entry : pImpl->entries) {
        file << "# " << entry.description << "\n";
        
        // Properly format the value based on its type
        std::visit([&file](const auto& value) {
            using T = std::decay_t<decltype(value)>;
            if constexpr (std::is_same_v<T, std::string>) {
                file << entry.key << " = \"" << value << "\"\n";
            } else if constexpr (std::is_same_v<T, bool>) {
                file << entry.key << " = " << (value ? "true" : "false") << "\n";
            } else if constexpr (std::is_same_v<T, int> || std::is_same_v<T, int64_t>) {
                file << entry.key << " = " << value << "\n";
            } else if constexpr (std::is_same_v<T, double>) {
                file << entry.key << " = " << value << "\n";
            } else if constexpr (std::is_same_v<T, std::vector<int>>) {
                file << entry.key << " = [";
                for (size_t i = 0; i < value.size(); ++i) {
                    file << value[i];
                    if (i < value.size() - 1) file << ", ";
                }
                file << "]\n";
            } else if constexpr (std::is_same_v<T, std::vector<double>>) {
                file << entry.key << " = [";
                for (size_t i = 0; i < value.size(); ++i) {
                    file << value[i];
                    if (i < value.size() - 1) file << ", ";
                }
                file << "]\n";
            } else if constexpr (std::is_same_v<T, std::vector<std::string>>) {
                file << entry.key << " = [\"";
                for (size_t i = 0; i < value.size(); ++i) {
                    file << value[i];
                    if (i < value.size() - 1) file << "\", \"";
                }
                file << "\"]\n";
            }
        }, entry.value);
        file << "\n";
    }
    
    file << "# End of configuration\n";
    
    if (!file.good()) {
        NLM_LOG_ERROR("Failed to write complete configuration to file: " + filepath);
        return false;
    }
    
    return true;
}

template<typename T>
std::optional<T> Config::get(const std::string& key) const {
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
    
    if (it == pImpl->entries.end()) {
        return std::nullopt;
    }
    
    try {
        return std::get<T>(it->value);
    } catch (const std::bad_variant_access&) {
        return std::nullopt;
    }
}

template<typename T>
T Config::getOr(const std::string& key, const T& defaultValue) const {
    auto val = get<T>(key);
    return val.has_value() ? val.value() : defaultValue;
}

void Config::set(const std::string& key, const ConfigValue& value, ConfigSource source) {
    // Validate key
    if (key.empty()) {
        throw std::invalid_argument("Configuration key cannot be empty");
    }
    
    // Remove any leading/trailing whitespace from key
    std::string trimmedKey = trim(key);
    if (trimmedKey.empty()) {
        throw std::invalid_argument("Configuration key cannot be only whitespace");
    }
    
    // Check if key already exists and source is stricter than new source
    auto it = std::find_if(pImpl->entries.begin(), pImpl->entries.end(),
        [&trimmedKey](const ConfigEntry& e) { return e.key == trimmedKey; });
    
    if (it != pImpl->entries.end()) {
        // Key exists - update if source is not stricter
        if (source == ConfigSource::Runtime) {
            // Runtime always overrides
            it->value = value;
            it->source = source;
            NLM_LOG_DEBUG("Updated config key '" + trimmedKey + "' with runtime value");
        } else if (source == ConfigSource::CommandLine && it->source != ConfigSource::Default) {
            // Command line overrides file and default
            it->value = value;
            it->source = source;
            NLM_LOG_INFO("Updated config key '" + trimmedKey + "' with command line value");
        } else if (source == ConfigSource::File && it->source == ConfigSource::Default) {
            // File can set default values
            it->value = value;
            it->source = source;
            NLM_LOG_DEBUG("Set config key '" + trimmedKey + "' with file value");
        } else {
            // Don't override existing values
            NLM_LOG_DEBUG("Ignoring update for config key '" + trimmedKey + "' (source conflict)");
        }
    } else {
        // New key
        pImpl->entries.emplace_back(trimmedKey, value, source);
        
        // Log important configuration settings
        if (trimmedKey == "neuron_count" || trimmedKey == "neuron_count" || 
            trimmedKey == "synapse_density" || trimmedKey == "connection_probability" ||
            trimmedKey == "plasticity.stdp.enable" || trimmedKey == "plasticity.hebbian.enable") {
            std::visit([&trimmedKey](const auto& val) {
                using T = std::decay_t<decltype(val)>;
                if constexpr (std::is_same_v<T, int> || std::is_same_v<T, int64_t>) {
                    NLM_LOG_INFO("Set config key '" + trimmedKey + "' = " + std::to_string(val));
                } else if constexpr (std::is_same_v<T, double>) {
                    NLM_LOG_INFO("Set config key '" + trimmedKey + "' = " + std::to_string(val));
                } else if constexpr (std::is_same_v<T, bool>) {
                    NLM_LOG_INFO("Set config key '" + trimmedKey + "' = " + (val ? "true" : "false"));
                }
            }, value);
        }
    }
}

void Config::set(const std::string& key, const std::string& value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, int value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, double value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

void Config::set(const std::string& key, bool value, ConfigSource source) {
    set(key, ConfigValue(value), source);
}

bool Config::has(const std::string& key) const {
    return std::any_of(pImpl->entries.begin(), pImpl->entries.end(),
        [&key](const ConfigEntry& e) { return e.key == key; });
}

void Config::remove(const std::string& key) {
    pImpl->entries.erase(
        std::remove_if(pImpl->entries.begin(), pImpl->entries.end(),
            [&key](const ConfigEntry& e) { return e.key == key; }),
        pImpl->entries.end()
    );
}

std::vector<std::string> Config::getKeys() const {
    std::vector<std::string> keys;
    keys.reserve(pImpl->entries.size());
    for (const auto& entry : pImpl->entries) {
        keys.push_back(entry.key);
    }
    return keys;
}

void Config::clear() {
    pImpl->entries.clear();
}

std::string Config::summary() const {
    std::ostringstream oss;
    oss << "Configuration (" << pImpl->entries.size() << " entries):\n";
    for (const auto& entry : pImpl->entries) {
        oss << "  " << entry.key << " = [";
        std::visit([&oss](auto&& arg) {
            using T = std::decay_t<decltype(arg)>;
            if constexpr (std::is_same_v<T, std::string>) {
                oss << "\"" << arg << "\"";
            } else {
                oss << arg;
            }
        }, entry.value);
        oss << "] (" << static_cast<int>(entry.source) << ")\n";
    }
    return oss.str();
}

std::string Config::trim(const std::string& str) {
    size_t start = str.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return "";
    size_t end = str.find_last_not_of(" \t\r\n");
    return str.substr(start, end - start + 1);
}

std::string Config::toLower(const std::string& str) {
    std::string result = str;
    std::transform(result.begin(), result.end(), result.begin(), ::tolower);
    return result;
}

