ConfigManager::ConfigManager(std::shared_ptr<Config> config)
    : config_(config), maxHistorySize_(100) {
    // Initialize current time
    currentTime_ = std::time(nullptr);
}

bool ConfigManager::loadConfigFromFile(const std::string& filename) {
    std::ifstream file(filename);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to open config file: " + filename);
        return false;
    }
    
    try {
        // Clear current config
        config_->clear();
        configMap_.clear();
        
        std::string line;
        size_t lineNum = 0;
        while (std::getline(file, line)) {
            ++lineNum;
            line = trim(line);
            
            // Skip empty lines and comments
            if (line.empty() || line[0] == '#') {
                continue;
            }
            
            // Parse key-value pairs
            size_t delimiterPos = line.find('=');
            if (delimiterPos == std::string::npos) {
                NLM_LOG_WARN("Invalid config line " + std::to_string(lineNum) + ": " + line);
                continue;
            }
            
            std::string key = trim(line.substr(0, delimiterPos));
            std::string value = trim(line.substr(delimiterPos + 1));
            
            // Remove quotes from value if present
            if (!value.empty() && value.front() == '"' && value.back() == '"') {
                value = value.substr(1, value.size() - 2);
            }
            
            setConfigValue(key, value);
        }
        
        NLM_LOG_INFO("Loaded configuration from: " + filename);
        addToHistory("Loaded " + filename);
        return true;
        
    } catch (const std::exception& e) {
        NLM_LOG_ERROR("Error loading config file " + filename + ": " + std::string(e.what()));
        return false;
    }
}

bool ConfigManager::saveConfigToFile(const std::string& filename) const {
    std::ofstream file(filename);
    if (!file.is_open()) {
        NLM_LOG_ERROR("Failed to create config file: " + filename);
        return false;
    }
    
    try {
        file << "# NLM Configuration File" << std::endl;
        file << "# Generated by NLM ConfigManager" << std::endl;
        file << "# " << std::ctime(&currentTime_) << std::endl;
        file << std::endl;
        
        // Save all configuration values
        for (const auto& pair : configMap_) {
            file << pair.first << " = " << pair.second << std::endl;
        }
        
        NLM_LOG_INFO("Saved configuration to: " + filename);
        addToHistory("Saved " + filename);
        return true;
        
    } catch (const std::exception& e) {
        NLM_LOG_ERROR("Error saving config file " + filename + ": " + std::string(e.what()));
        return false;
    }
}

bool ConfigManager::setConfigValue(const std::string& key, const std::string& value) {
    std::string normalizedKey = normalizeKey(key);
    std::string normalizedValue = normalizeValue(value);
    
    // Validate configuration value
    if (!validateConfigValue(normalizedKey, normalizedValue)) {
        NLM_LOG_ERROR("Invalid config value for " + normalizedKey + ": " + normalizedValue);
        return false;
    }
    
    // Store the value
    configMap_[normalizedKey] = normalizedValue;
    
    // Update config object
    applyConfigToCore(normalizedKey, normalizedValue);
    
    NLM_LOG_INFO("Set config " + normalizedKey + " = " + normalizedValue);
    return true;
}

std::string ConfigManager::getConfigValue(const std::string& key, const std::string& defaultValue) const {
    std::string normalizedKey = normalizeKey(key);
    
    auto it = configMap_.find(normalizedKey);
    if (it != configMap_.end()) {
        return it->second;
    }
    
    return defaultValue;
}

bool ConfigManager::hasConfig(const std::string& key) const {
    std::string normalizedKey = normalizeKey(key);
    return configMap_.find(normalizedKey) != configMap_.end();
}

void ConfigManager::removeConfig(const std::string& key) {
    std::string normalizedKey = normalizeKey(key);
    configMap_.erase(normalizedKey);
    NLM_LOG_INFO("Removed config: " + normalizedKey);
}

void ConfigManager::clearConfig() {
    configMap_.clear();
    NLM_LOG_INFO("Cleared all configuration values");
}

std::vector<std::string> ConfigManager::getConfigKeys() const {
    std::vector<std::string> keys;
    keys.reserve(configMap_.size());
    
    for (const auto& pair : configMap_) {
        keys.push_back(pair.first);
    }
    
    std::sort(keys.begin(), keys.end());
    return keys;
}

std::vector<std::string> ConfigManager::getConfigHistory() const {
    return history_;
}

void ConfigManager::addToHistory(const std::string& action) {
    history_.push_back(action + " at " + std::ctime(&currentTime_));
    
    // Trim history if too large
    if (history_.size() > maxHistorySize_) {
        history_.erase(history_.begin());
    }
}

void ConfigManager::setHistorySize(size_t size) {
    maxHistorySize_ = size;
    
    // Trim history if needed
    while (history_.size() > maxHistorySize_) {
        history_.erase(history_.begin());
    }
}

bool ConfigManager::validateConfigValue(const std::string& key, const std::string& value) {
    // Type validation based on key
    if (key == "neuron_count") {
        try {
            size_t count = std::stoul(value);
            return count > 0 && count <= 1000000;  // Reasonable limits
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "simulation_timestep") {
        try {
            double timestep = std::stod(value);
            return timestep > 0.0 && timestep <= 1.0;  // 1 second max timestep
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "region_count") {
        try {
            size_t regions = std::stoul(value);
            return regions > 0 && regions <= 100;
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "connection_probability") {
        try {
            float prob = std::stof(value);
            return prob >= 0.0f && prob <= 1.0f;
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "random_seed") {
        try {
            uint64_t seed = std::stoull(value);
            return seed > 0;
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "stdp_ltp_weight") {
        try {
            float weight = std::stof(value);
            return weight >= 0.0f && weight <= 10.0f;
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "stdp_ltd_weight") {
        try {
            float weight = std::stof(value);
            return weight >= 0.0f && weight <= 10.0f;
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "stdp_tau") {
        try {
            float tau = std::stof(value);
            return tau > 0.0f && tau <= 1000.0f;
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "synaptogenesis_rate") {
        try {
            float rate = std::stof(value);
            return rate >= 0.0f && rate <= 1.0f;
        } catch (...) {
            return false;
        }
    }
    
    else if (key == "pruning_rate") {
        try {
            float rate = std::stof(value);
            return rate >= 0.0f && rate <= 1.0f;
        } catch (...) {
            return false;
        }
    }
    
    // Default validation - accept any string value
    return true;
}

