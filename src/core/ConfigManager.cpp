std::string ConfigManager::normalizeKey(const std::string& key) {
    std::string normalized = key;
    // Convert to lowercase and replace spaces with underscores
    std::transform(normalized.begin(), normalized.end(), normalized.begin(), 
                   [](unsigned char c) { return std::tolower(c); });
    
    // Replace common separators
    size_t pos = 0;
    while ((pos = normalized.find('-', pos)) != std::string::npos) {
        normalized.replace(pos, 1, "_");
    }
    
    while ((pos = normalized.find(' ', pos)) != std::string::npos) {
        normalized.replace(pos, 1, "_");
    }
    
    return normalized;
}

std::string ConfigManager::normalizeValue(const std::string& value) {
    std::string normalized = value;
    // Trim whitespace
    size_t first = normalized.find_first_not_of(" \t\n\r");
    if (first != std::string::npos) {
        size_t last = normalized.find_last_not_of(" \t\n\r");
        normalized = normalized.substr(first, (last - first + 1));
    }
    return normalized;
}

std::string ConfigManager::trim(const std::string& str) {
    size_t first = str.find_first_not_of(" \t\n\r");
    if (first == std::string::npos) {
        return "";
    }
    size_t last = str.find_last_not_of(" \t\n\r");
    return str.substr(first, (last - first + 1));
}

