#pragma once

#include <string>
#include <memory>
#include <sstream>
#include <functional>
#include <vector>
#include <chrono>

namespace nlm {

// Log severity levels
enum class LogLevel {
    Debug = 0,
    Info = 1,
    Warning = 2,
    Error = 3,
    Critical = 4
};

// Log entry structure
struct LogEntry {
    LogLevel level;
    std::string message;
    std::string file;
    int line;
    std::string function;
    std::chrono::system_clock::time_point timestamp;
};

/**
 * @interface ILogger
 * @abstract Abstract base class for all logger implementations
 * @description Defines the interface for logging backends in the NLM system.
 *              Implement this interface to create custom logging implementations
 *              (console, file, network, etc.). The Logger class manages multiple
 *              logger instances and dispatches log entries to them.
 * @note Thread-safe implementations are recommended for concurrent environments
 * @version 1.0.0
 */
class ILogger {
public:
    /**
     * @virtual Destructor
     * @description Virtual destructor ensures proper cleanup of derived classes
     */
    virtual ~ILogger() = default;
    
    /**
     * @brief Write log entry
     * @param entry The log entry containing message, severity, source info, and timestamp
     * @description Logs a formatted entry through this logger implementation.
     *              The entry should be formatted according to the logger's
     *              specific requirements (console format, file format, etc.).
     * @note Log entries are typically generated by the Logger class's logging macros
     *       (NLM_LOG_DEBUG, NLM_LOG_INFO, etc.) which include file, line, and function
     *       information for debugging purposes.
     * @see LogEntry
     * @see Logger
     */
    virtual void log(const LogEntry& entry) = 0;
    
    /**
     * @brief Set minimum log level
     * @param level Minimum severity level to process (Debug, Info, Warning, Error, Critical)
     * @description Filters log entries - entries below this level are ignored.
     *              For example, if level is set to Warning, only Warning, Error, and
     *              Critical messages will be logged.
     * @note Changing the level affects future log calls only
     */
    virtual void setLevel(LogLevel level) = 0;
    
    /**
     * @brief Get current minimum log level
     * @return Current minimum log level
     * @description Retrieves the threshold level set by setLevel().
     *              Useful for checking what types of messages will be processed.
     */
    virtual LogLevel getLevel() const = 0;
};

/**
 * @class ConsoleLogger
 * @brief Concrete logger implementation that outputs to console (and optionally file)
 * @extends ILogger
 * @description Provides console-based logging with color support and optional file output.
 *              This is the default logger used by the global Logger instance.
 * @version 1.0.0
 */
class ConsoleLogger : public ILogger {
public:
    /**
     * @brief Construct with default settings (Info level, colors enabled)
     * @description Creates a console logger that outputs to stdout with default
     *              configuration. Call setLevel() to adjust verbosity.
     */
    ConsoleLogger();
    
    /**
     * @brief Construct with specified log level
     * @param level Initial minimum log level (default: Info)
     * @description Creates a console logger with custom initial level, useful for
     *              creating specialized loggers with different verbosity settings.
     */
    explicit ConsoleLogger(LogLevel level);
    
    /**
     * @virtual Destructor
     * @description Cleans up internal resources and file handles
     */
    ~ConsoleLogger() override;
    
    /**
     * @override
     * @copydoc ILogger::log
     */
    void log(const LogEntry& entry) override;
    
    /**
     * @override
     * @copydoc ILogger::setLevel
     */
    void setLevel(LogLevel level) override;
    
    /**
     * @override
     * @copydoc ILogger::getLevel
     */
    LogLevel getLevel() const override;
    
    /**
     * @brief Enable or disable color output
     * @param useColors true to enable ANSI color codes, false for monochrome
     * @description Colors make log entries more readable by highlighting severity
     *              levels (e.g., red for errors, green for info).
     * @note Colors are only used if the output target supports them (terminal)
     * @see NLM_LOG_* macros
     */
    void setUseColors(bool useColors);
    
    /**
     * @brief Check if color output is enabled
     * @return true if colors are enabled, false otherwise
     * @see setUseColors
     */
    bool getUseColors() const;
    
    /**
     * @brief Add file output in addition to console
     * @param filepath Path to log file (will be appended to)
     * @description Opens the specified file for appending log entries.
     *              The file remains open until closeOutputFile() is called or
     *              the logger is destroyed. Use clearLoggers() to remove file output.
     * @note Multiple file outputs can be added by calling setOutputFile multiple times
     * @see closeOutputFile
     * @see clearLoggers
     */
    void setOutputFile(const std::string& filepath);
    
    /**
     * @brief Close the log file and remove file output
     * @description Closes the file handle and stops writing to file.
     *              The file is not deleted.
     * @note Safe to call even if no file is open
     * @see setOutputFile
     */
    void closeOutputFile();
    
private:
    struct Impl;
    std::unique_ptr<Impl> pImpl;
    
    /**
     * @brief Convert log level enum to string representation
     * @param level Log level to convert
     * @return String representation (e.g., "DEBUG", "INFO")
     * @description Internal helper for formatting log entries.
     */
    std::string levelToString(LogLevel level) const;
    
    /**
     * @brief Get ANSI color code for log level
     * @param level Log level to get color for
     * @return ANSI escape code for the level's color (empty string if colors disabled)
     * @description Generates terminal color codes for syntax highlighting.
     */
    std::string levelToColor(LogLevel level) const;
};

/**
 * @class Logger
 * @brief Main logging system that manages multiple logger implementations
 * @description The Logger class serves as the central logging interface for the NLM system.
 *              It manages a collection of ILogger implementations (ConsoleLogger, etc.)
 *              and provides convenience macros (NLM_LOG_DEBUG, NLM_LOG_INFO, etc.) for
 *              easy logging throughout the codebase. Supports hierarchical log levels
 *              and file output.
 * @note Thread-safe for concurrent logging from multiple threads
 * @warning Log entries with lower severity than the minimum level are silently discarded
 * @version 1.0.0
 * @copyright Copyright (c) 2024 NLM Team
 */
class Logger {
public:
    /**
     * @brief Construct logger with default configuration
     * @description Creates a logger with a default ConsoleLogger instance
     *              at Info log level. Use addLogger() to add additional sinks.
     */
    Logger();
    
    /**
     * @virtual Destructor
     * @description Cleans up all registered logger instances and resources
     */
    ~Logger();
    
    // Disable copying, enable moving
    Logger(const Logger&) = delete;
    Logger& operator=(const Logger&) = delete;
    
    /**
     * @brief Add a logger sink to the system
     * @param logger Shared pointer to ILogger implementation to add
     * @description Adds a new logging backend (e.g., ConsoleLogger, file logger).
     *              The logger is shared and can be used by multiple Logger instances.
     *              Added loggers receive log entries in the order they were added.
     * @note The Logger takes ownership of the shared pointer
     * @see removeLogger
     * @see clearLoggers
     */
    void addLogger(std::shared_ptr<ILogger> logger);
    
    /**
     * @brief Remove all logger sinks
     * @description Clears all registered loggers, stopping all output.
     *              After this call, log messages will not be output anywhere
     *              until new loggers are added.
     * @note Use addLogger() to restore logging functionality
     * @see addLogger
     */
    void clearLoggers();
    
    /**
     * @brief Set minimum log level for all loggers
     * @param level Minimum severity level (Debug, Info, Warning, Error, Critical)
     * @description Sets the global minimum log level. Loggers below this level
     *              are filtered out before being dispatched to sinks.
     * @note Individual logger levels can be set separately via their setLevel() methods
     * @see LogLevel
     * @see ILogger::setLevel
     */
    void setLevel(LogLevel level);
    
    /**
     * @brief Log formatted message through the logger system
     * @param level Log severity level
     * @param message Text message to log (up to 1024 characters)
     * @param file Source file name (typically __FILE__ macro)
     * @param line Source line number (typically __LINE__ macro)
     * @param function Function name (typically __func__ macro)
     * @description Core logging function that formats the message with source location
     *              and timestamp, then dispatches to all registered logger sinks.
     *              Use the NLM_LOG_* convenience macros for easier logging.
     * @warning Messages longer than 1024 characters may be truncated
     * @note Source location info helps with debugging by showing exactly where log
     *       messages originate in the codebase
     * @see NLM_LOG_DEBUG
     * @see NLM_LOG_INFO
     * @see LogEntry
     */
    void log(LogLevel level, const std::string& message, 
             const std::string& file = "", int line = 0, 
             const std::string& function = "");
    
    /**
     * @brief Convenience logging method for Debug level
     * @param message Message to log
     * @param file Source file (default: empty string, uses __FILE__ when called via macro)
     * @param line Source line number (default: 0)
     * @param function Function name (default: empty string)
     * @description Logs Debug-level messages. Messages are only logged if the
     *              minimum log level allows Debug messages (usually used for
     *              development and troubleshooting).
     * @note Prefer NLM_LOG_DEBUG macro for source location tracking
     * @see log
     * @see NLM_LOG_DEBUG
     */
    void debug(const std::string& message, const std::string& file = "", int line = 0, const std::string& function = "");
    
    /**
     * @brief Convenience logging method for Info level
     * @param message Message to log
     * @param file Source file (default: empty string, uses __FILE__ when called via macro)
     * @param line Source line number (default: 0)
     * @param function Function name (default: empty string)
     * @description Logs informational messages about system operation.
     *              Useful for tracking program flow and operational status.
     * @note Prefer NLM_LOG_INFO macro for source location tracking
     * @see log
     * @see NLM_LOG_INFO
     */
    void info(const std::string& message, const std::string& file = "", int line = 0, const std::string& function = "");
    
    /**
     * @brief Convenience logging method for Warning level
     * @param message Message to log
     * @param file Source file (default: empty string, uses __FILE__ when called via macro)
     * @param line Source line number (default: 0)
     * @param function Function name (default: empty string)
     * @description Logs warning messages that may indicate potential issues
     *              but don't prevent program execution.
     * @note Prefer NLM_LOG_WARNING macro for source location tracking
     * @see log
     * @see NLM_LOG_WARNING
     */
    void warning(const std::string& message, const std::string& file = "", int line = 0, const std::string& function = "");
    
    /**
     * @brief Convenience logging method for Error level
     * @param message Message to log
     * @param file Source file (default: empty string, uses __FILE__ when called via macro)
     * @param line Source line number (default: 0)
     * @param function Function name (default: empty string)
     * @description Logs error messages for non-fatal errors that are handled
     *              gracefully (e.g., configuration errors, invalid inputs).
     * @note Prefer NLM_LOG_ERROR macro for source location tracking
     * @see log
     * @see NLM_LOG_ERROR
     */
    void error(const std::string& message, const std::string& file = "", int line = 0, const std::string& function = "");
    
    /**
     * @brief Convenience logging method for Critical level
     * @param message Message to log
     * @param file Source file (default: empty string, uses __FILE__ when called via macro)
     * @param line Source line number (default: 0)
     * @param function Function name (default: empty string)
     * @description Logs critical messages for fatal errors that prevent
     *              continuation (e.g., out-of-memory, corrupted state).
     * @note Prefer NLM_LOG_CRITICAL macro for source location tracking
     * @see log
     * @see NLM_LOG_CRITICAL
     */
    void critical(const std::string& message, const std::string& file = "", int line = 0, const std::string& function = "");
    
    /**
     * @brief Check if log level is enabled
     * @param level Log level to check
     * @return true if messages at this level will be logged, false otherwise
     * @description Useful for conditional logging to avoid expensive string formatting
     *              when the message won't be output anyway.
     * @note This only checks the global minimum level, not individual logger levels
     * @see setLevel
     */
    bool isEnabled(LogLevel level) const;
    
    /**
     * @brief Get global logger instance
     * @return Reference to the global Logger singleton
     * @description Returns the singleton global logger instance used throughout
     *              the NLM system. Call setGlobal() to replace with custom implementation.
     * @note The global logger is automatically initialized with a ConsoleLogger at
     *       Info level when first accessed
     * @see setGlobal
     * @see getGlobal
     */
    static Logger& getGlobal();
    
    /**
     * @brief Replace the global logger instance
     * @param logger Shared pointer to new Logger implementation
     * @description Replaces the global logger singleton. Use this to replace the
     *              default ConsoleLogger with custom logging implementations
     *              (e.g., file-based, network-based, etc.).
     * @note Careful: This affects all logging in the application
     * @see getGlobal
     */
    static void setGlobal(std::shared_ptr<Logger> logger);
    
private:
    struct Impl;
    std::unique_ptr<Impl> pImpl;
};

// Convenience macro for file/line/function info
#define NLM_LOG_DEBUG(msg) nlm::Logger::getGlobal().debug(msg, __FILE__, __LINE__, __func__)
#define NLM_LOG_INFO(msg) nlm::Logger::getGlobal().info(msg, __FILE__, __LINE__, __func__)
#define NLM_LOG_WARNING(msg) nlm::Logger::getGlobal().warning(msg, __FILE__, __LINE__, __func__)
#define NLM_LOG_ERROR(msg) nlm::Logger::getGlobal().error(msg, __FILE__, __LINE__, __func__)
#define NLM_LOG_CRITICAL(msg) nlm::Logger::getGlobal().critical(msg, __FILE__, __LINE__, __func__)

/**
 * @brief Stream-style logging helper for verbose logging
 * @description Creates a temporary stream object that formats and logs messages
 *              when the stream is destroyed (at end of scope). This provides
 *              C++-style formatted logging without manually converting all arguments
 *              to strings.
 * @note Intended for debugging and development - use sparingly in production
 *       due to potential performance overhead
 * @see NLM_LOG_STREAM
 * @version 1.0.0
 */
class LogStream {
public:
    /**
     * @brief Construct stream for logging at specified level
     * @param level Log severity level
     * @param file Source file name (typically __FILE__)
     * @param line Source line number (typically __LINE__)
     * @param function Function name (typically __func__)
     * @description Creates a stream that will log when destroyed.
     *              The stream accumulates log content via operator<<, then formats
     *              and logs the complete message at the specified level.
     */
    LogStream(LogLevel level, const std::string& file, int line, const std::string& function);
    
    /**
     * @brief Destructor logs accumulated stream content
     * @description Formats the accumulated content from the stringstream
     *              and logs it through the global logger. This is the key
     *              operator that makes LogStream work like a temporary stream.
     */
    ~LogStream();
    
    /**
     * @brief Stream insertion operator for formatted logging
     * @tparam T Type of value to log
     * @param value Value to convert to string and accumulate
     * @return Reference to this stream for further operations
     * @description Converts any type that can be streamed to string
     *              and appends it to the internal buffer. Supports
     *              primitive types, strings, objects with operator<<,
     *              etc. Similar to std::ostringstream.
     * @note No immediate logging occurs - the message is buffered until
     *       the stream object is destroyed
     */
    template<typename T>
    LogStream& operator<<(const T& value) {
        oss_ << value;
        return *this;
    }
    
private:
    LogLevel level_;
    std::ostringstream oss_;
    std::string file_;
    int line_;
    std::string function_;
};

#define NLM_LOG_STREAM(level) nlm::LogStream(level, __FILE__, __LINE__, __func__)

} // namespace nlm
