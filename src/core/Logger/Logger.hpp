// Stream-style logging helper with context
class LogStreamWithContext {
public:
    LogStreamWithContext(LogLevel level, const std::string& file, int line, const std::string& function,
                        const std::string& category = "");
    ~LogStreamWithContext();
    
    template<typename T>
    LogStreamWithContext& operator<<(const T& value) {
        oss_ << value;
        return *this;
    }
    
    // Category for structured logging
    LogStreamWithContext& category(const std::string& cat) {
        category_ = cat;
        return *this;
    }
    
private:
    LogLevel level_;
    std::ostringstream oss_;
    std::string file_;
    int line_;
    std::string function_;
    std::string category_;
};

#define NLM_LOG_STREAM_CONTEXT(level, category) nlm::LogStreamWithContext(level, __FILE__, __LINE__, __func__, category)

