std::string ConsoleLogger::levelToString(LogLevel level) const {
    switch (level) {
        case LogLevel::Debug: return "DEBUG";
        case LogLevel::Info: return "INFO";
        case LogLevel::Warning: return "WARN";
        case LogLevel::Error: return "ERROR";
        case LogLevel::Critical: return "CRIT";
        default: return "UNKNOWN";
    }
}

std::string ConsoleLogger::levelToColor(LogLevel level) const {
    switch (level) {
        case LogLevel::Debug: return "\033[36m";    // Cyan
        case LogLevel::Info: return "\033[32m";      // Green
        case LogLevel::Warning: return "\033[33m";   // Yellow
        case LogLevel::Error: return "\033[31m";     // Red
        case LogLevel::Critical: return "\033[35m"; // Magenta
        default: return "\033[0m";
    }
}

std::string ConsoleLogger::formatTimestamp(const std::chrono::system_clock::time_point& timestamp) const {
    auto time = std::chrono::system_clock::to_time_t(timestamp);
    std::ostringstream oss;
    oss << std::put_time(std::localtime(&time), "%Y-%m-%d %H:%M:%S");
    return oss.str();
}

std::string ConsoleLogger::formatProgress(double progress) const {
    if (progress < 0.0) progress = 0.0;
    if (progress > 1.0) progress = 1.0;
    
    int percentage = static_cast<int>(progress * 100.0);
    std::ostringstream oss;
    oss << "[" << std::string(static_cast<size_t>(progress * 50), '=') 
        << (progress < 1.0 ? ">" : "=") 
        << std::string(50 - static_cast<size_t>(progress * 50) - 1, ' ') << "] " 
        << percentage << "%";
    return oss.str();
}

void ConsoleLogger::progressStarted(const std::string& taskName) {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    pImpl->activeProgress.emplace_back(taskName);
    std::cout << "\n" << levelToColor(LogLevel::Info) 
              << "=== PROGRESS: " << taskName << " ===\033[0m\n";
}

void ConsoleLogger::progressUpdated(const std::string& taskName, double progress) {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    
    // Find the progress task
    for (auto& prog : pImpl->activeProgress) {
        if (prog.taskName == taskName) {
            prog.progress = progress;
            std::cout << "\r" << levelToColor(LogLevel::Info) 
                      << "Progress: " << taskName << " " 
                      << formatProgress(progress) << " "
                      << std::fixed << std::setprecision(1) << (progress * 100.0) << "%"
                      << "\033[0m";
            std::cout.flush();
            return;
        }
    }
}

void ConsoleLogger::progressCompleted(const std::string& taskName, bool success) {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    
    // Find and remove the progress task
    auto it = std::remove_if(pImpl->activeProgress.begin(), pImpl->activeProgress.end(),
                           [&taskName](const ProgressInfo& prog) { return prog.taskName == taskName; });
    pImpl->activeProgress.erase(it, pImpl->activeProgress.end());
    
    if (success) {
        std::cout << "\r" << levelToColor(LogLevel::Info) 
                  << "Progress: " << taskName << " " 
                  << formatProgress(1.0) << " 100.0% - COMPLETED"
                  << "\033[0m\n";
    } else {
        std::cout << "\r" << levelToColor(LogLevel::Error) 
                  << "Progress: " << taskName << " " 
                  << formatProgress(1.0) << " 100.0% - FAILED"
                  << "\033[0m\n";
    }
}

void ConsoleLogger::progressFailed(const std::string& taskName, const std::string& error) {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    
    // Find and remove the progress task
    auto it = std::remove_if(pImpl->activeProgress.begin(), pImpl->activeProgress.end(),
                           [&taskName](const ProgressInfo& prog) { return prog.taskName == taskName; });
    pImpl->activeProgress.erase(it, pImpl->activeProgress.end());
    
    std::cout << "\r" << levelToColor(LogLevel::Error) 
              << "Progress: " << taskName << " - FAILED: " << error
              << "\033[0m\n";
}

// Logger class implementation
struct Logger::Impl {
    std::vector<std::shared_ptr<ILogger>> loggers;
    std::mutex mutex;
};

Logger::Logger() : pImpl(std::make_unique<Impl>()) {}

Logger::~Logger() = default;

void Logger::addLogger(std::shared_ptr<ILogger> logger) {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    pImpl->loggers.push_back(logger);
}

void Logger::clearLoggers() {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    pImpl->loggers.clear();
}

void Logger::setLevel(LogLevel level) {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    for (auto& logger : pImpl->loggers) {
        logger->setLevel(level);
    }
}

void Logger::log(LogLevel level, const std::string& message,
                const std::string& file, int line, const std::string& function) {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    
    LogEntry entry;
    entry.level = level;
    entry.message = message;
    entry.file = file;
    entry.line = line;
    entry.function = function;
    entry.timestamp = std::chrono::system_clock::now();
    
    for (auto& logger : pImpl->loggers) {
        logger->log(entry);
    }
}

void Logger::debug(const std::string& message, const std::string& file, int line, const std::string& function) {
    log(LogLevel::Debug, message, file, line, function);
}

void Logger::info(const std::string& message, const std::string& file, int line, const std::string& function) {
    log(LogLevel::Info, message, file, line, function);
}

void Logger::warning(const std::string& message, const std::string& file, int line, const std::string& function) {
    log(LogLevel::Warning, message, file, line, function);
}

void Logger::error(const std::string& message, const std::string& file, int line, const std::string& function) {
    log(LogLevel::Error, message, file, line, function);
}

void Logger::critical(const std::string& message, const std::string& file, int line, const std::string& function) {
    log(LogLevel::Critical, message, file, line, function);
}

bool Logger::isEnabled(LogLevel level) const {
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    for (auto& logger : pImpl->loggers) {
        if (logger->getLevel() <= level) {
            return true;
        }
    }
    return false;
}

