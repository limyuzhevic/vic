// Enhanced ConsoleLogger with better error handling and validation

struct ConsoleLogger::Impl {
    LogLevel level = LogLevel::Info;
    bool useColors = true;
    std::ofstream fileOut;
    std::mutex mutex;
    bool fileInitialized = false;
    std::string lastFileError;
};

ConsoleLogger::ConsoleLogger() : pImpl(std::make_unique<Impl>()) {}

ConsoleLogger::ConsoleLogger(LogLevel level) : pImpl(std::make_unique<Impl>()) {
    pImpl->level = level;
}

ConsoleLogger::~ConsoleLogger() = default;

void ConsoleLogger::log(const LogEntry& entry) {
    if (entry.level < pImpl->level) {
        return;
    }
    
    // Validate log entry
    if (entry.message.empty() && entry.level != LogLevel::Debug) {
        // Empty messages are only allowed for debug level
        return;
    }
    
    std::lock_guard<std::mutex> lock(pImpl->mutex);
    
    std::ostringstream oss;
    oss << "[" << levelToString(entry.level) << "] ";
    
    // Add timestamp with error handling
    auto time = std::chrono::system_clock::to_time_t(entry.timestamp);
    std::tm tm_buf;
    if (std::localtime_s(&tm_buf, &time) == 0) {
        oss << std::put_time(&tm_buf, "%Y-%m-%d %H:%M:%S");
    } else {
        oss << "invalid_time";
    }
    
    oss << " " << entry.message;
    
    std::string output = oss.str();
    
    // Console output with error handling
    if (entry.level <= LogLevel::Critical) {
        try {
            if (pImpl->useColors) {
                std::cout << levelToColor(entry.level) << output << "\033[0m\n";
            } else {
                std::cout << output << "\n";
            }
            // Flush console output for critical messages
            if (entry.level == LogLevel::Critical) {
                std::cout.flush();
            }
        } catch (const std::exception& e) {
            // Fallback: write to stderr if console output fails
            std::cerr << "[ERROR] Failed to log message: " << e.what() << std::endl;
            std::cerr << "Original message: " << output << std::endl;
        }
    }
    
    // File output with better error handling
    if (pImpl->fileInitialized && pImpl->fileOut.is_open()) {
        try {
            pImpl->fileOut << output << "\n";
            pImpl->fileOut.flush();
        } catch (const std::exception& e) {
            pImpl->lastFileError = "File write error: " + std::string(e.what());
            // Close file if it becomes invalid
            if (!pImpl->fileOut.good()) {
                pImpl->fileOut.close();
                pImpl->fileInitialized = false;
            }
        }
    } else if (pImpl->fileInitialized && !pImpl->fileOut.is_open()) {
        pImpl->lastFileError = "File stream not open";
        pImpl->fileInitialized = false;
    }
}

void ConsoleLogger::setLevel(LogLevel level) {
    if (level < LogLevel::Debug || level > LogLevel::Critical) {
        NLM_LOG_ERROR("Invalid log level: " + std::to_string(static_cast<int>(level)));
        return;
    }
    pImpl->level = level;
}

LogLevel ConsoleLogger::getLevel() const {
    return pImpl->level;
}

