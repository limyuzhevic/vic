// SimpleConfig implementation
void SimpleConfig::loadFromFile(const std::string& filename) {
    std::ifstream file(filename);
    if (!file.is_open()) {
        errorMessages.push_back("Cannot open config file: " + filename);
        return;
    }
    
    std::string line;
    int lineNum = 0;
    while (std::getline(file, line)) {
        ++lineNum;
        line.erase(0, line.find_first_not_of(" \t\r\n"));
        line.erase(line.find_last_not_of(" \t\r\n"));
        
        if (line.empty() || line[0] == '#') {
            continue;
        }
        
        size_t equals = line.find('=');
        if (equals == std::string::npos) {
            errorMessages.push_back("Invalid config syntax at line " + std::to_string(lineNum) + ": " + line);
            continue;
        }
        
        std::string key = line.substr(0, equals);
        std::string value = line.substr(equals + 1);
        
        // Trim whitespace
        key.erase(key.find_last_not_of(" \t\r\n"));
        value.erase(0, value.find_first_not_of(" \t\r\n"));
        value.erase(value.find_last_not_of(" \t\r\n"));
        
        // Validate key
        if (!validateKey(key)) {
            errorMessages.push_back("Invalid config key at line " + std::to_string(lineNum) + ": " + key);
            continue;
        }
        
        configValues[key] = value;
    }
    
    file.close();
}

void SimpleConfig::saveToFile(const std::string& filename) const {
    std::ofstream file(filename);
    if (!file.is_open()) {
        errorMessages.push_back("Cannot create config file: " + filename);
        return;
    }
    
    file << "# NLM Configuration File\n";
    file << "# Generated by SimpleNLMCLI\n\n";
    
    for (const auto& pair : configValues) {
        file << pair.first << " = " << pair.second << "\n";
    }
    
    file.close();
}

void SimpleConfig::setValue(const std::string& key, const std::string& value) {
    if (!validateKey(key)) {
        errorMessages.push_back("Invalid config key: " + key);
        return;
    }
    configValues[key] = value;
}

std::string SimpleConfig::getValue(const std::string& key, const std::string& defaultValue) const {
    auto it = configValues.find(key);
    return it != configValues.end() ? it->second : defaultValue;
}

bool SimpleConfig::validate() const {
    errorMessages.clear();
    bool isValid = true;
    
    for (const auto& pair : configValues) {
        if (!validateValue(pair.first, pair.second)) {
            isValid = false;
        }
    }
    
    return isValid;
}

bool SimpleConfig::validateKey(const std::string& key) const {
    return std::find(validKeys.begin(), validKeys.end(), key) != validKeys.end();
}

bool SimpleConfig::validateValue(const std::string& key, const std::string& value) const {
    if (!validateKey(key)) {
        return false;
    }
    
    // Basic value validation
    if (value.empty()) {
        errorMessages.push_back("Empty value for key: " + key);
        return false;
    }
    
    return true;
}

