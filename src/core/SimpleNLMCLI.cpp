bool SimpleNLMCLI::setEnv(const std::vector<std::string>& args) {
    if (args.empty()) {
        printError("Please specify a variable name: nlm env <variable> [value]");
        return false;
    }
    
    std::string key = args[0];
    std::string value = args.size() > 1 ? args[1] : "";
    
    config.setValue(key, value);
    printSuccess("Environment variable set: " + key + " = " + value);
    return true;
}

bool SimpleNLMCLI::showEnv(const std::vector<std::string>& args) {
    if (args.empty()) {
        std::cout << "Current Environment Configuration:" << std::endl;
        for (const auto& pair : config.configValues) {
            std::cout << "  " << pair.first << " = " << pair.second << std::endl;
        }
        return true;
    } else {
        std::string key = args[0];
        std::string value = config.getValue(key);
        if (value.empty()) {
            printError("Environment variable not found: " + key);
            return false;
        }
        std::cout << key << " = " << value << std::endl;
        return true;
    }
}

