bool SimpleNLMCLI::configure(const std::vector<std::string>& args) {
    if (args.empty()) {
        printError("Please specify a configuration file: nlm configure <filename>");
        return false;
    }
    
    std::string filename = args[0];
    NLM_LOG_INFO("Loading configuration from: " + filename);
    
    if (!validateConfigFile(filename)) {
        printError("Configuration validation failed");
        return false;
    }
    
    config.loadFromFile(filename);
    
    if (config.validate()) {
        printSuccess("Configuration loaded and validated successfully!");
        return true;
    } else {
        printError("Configuration validation failed:");
        for (const std::string& error : config.getErrorMessages()) {
            printError("  " + error);
        }
        return false;
    }
}

