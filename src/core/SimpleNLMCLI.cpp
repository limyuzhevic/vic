    bool stdpTest = std::find(args.begin(), args.end(), "--stdp") != args.end();
    bool learningTest = std::find(args.begin(), args.end(), "--learning") != args.end();
    
    // Apply Phase 2 configuration for quick test
    applyPhaseConfig("phase2");
    
    // Run tests based on flags
    if (connectivityTest) {
        return runPhase2ConnectivityTest();
    }
    
    if (plasticityTest) {
        return runPhase2PlasticityTest();
    }
    
    if (stdpTest) {
        return runPhase2STDPTest();
    }
    
    if (learningTest) {
        return runPhase2LearningTest();
    }
    
