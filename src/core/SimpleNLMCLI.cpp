bool SimpleNLMCLI::validateConfigFile(const std::string& filename) {
    if (!std::filesystem::exists(filename)) {
        printError("Configuration file does not exist: " + filename);
        return false;
    }
    
    std::ifstream file(filename);
    if (!file.is_open()) {
        printError("Cannot open configuration file: " + filename);
        return false;
    }
    
    file.close();
    return true;
}

