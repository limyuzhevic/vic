SimpleNLMCLI::SimpleNLMCLI() : verboseMode(false), quietMode(false) {
    // Initialize logging
    auto logger = std::make_shared<Logger>();
    auto consoleLogger = std::make_shared<ConsoleLogger>(LogLevel::Info);
    logger->addLogger(consoleLogger);
    Logger::setGlobal(logger);
    
    NLM_LOG_INFO("Initializing SimpleNLMCLI...");
    
    registerCommands();
    printWelcome();
}

bool SimpleNLMCLI::execute(int argc, char** argv) {
    if (argc < 2) {
        printHelp();
        return false;
    }
    
    std::string command = argv[1];
    std::vector<std::string> args;
    
    for (int i = 2; i < argc; ++i) {
        args.push_back(argv[i]);
    }
    
    return execute(command, args);
}

bool SimpleNLMCLI::execute(const std::string& command, const std::vector<std::string>& args) {
    // Check for quick commands
    if (command == "quick") {
        return runQuick(args);
    }
    
    if (command == "quicktest") {
        return runQuickTest(args);
    }
    
    if (command == "bench") {
        return runBenchmarkQuick(args);
    }
    
    // Check for regular commands
    auto cmdIt = commands.find(command);
    if (cmdIt != commands.end()) {
        return cmdIt->second.handler(args);
    }
    
    // Check for demo commands
    if (command == "phase2" || command == "phase3" || command == "phase4" || command == "phase6") {
        return executePhase(command, args);
    }
    
    // Check for benchmark command
    if (command == "benchmark") {
        return runBenchmark(args);
    }
    
    // Check for configuration commands
    if (command == "configure") {
        return configure(args);
    }
    
    if (command == "save") {
        return saveConfig(args);
    }
    
    if (command == "load") {
        return loadConfig(args);
    }
    
    // Unknown command
    printError("Unknown command: " + command);
    printHelp();
    return false;
}

