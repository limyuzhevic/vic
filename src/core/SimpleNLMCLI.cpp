bool SimpleNLMCLI::executePhase(const std::string& phase, const std::vector<std::string>& args) {
    std::string demoName = "nlm_" + phase + "_demo";
    std::string command = demoName;
    
    std::string fullCommand = command;
    for (const std::string& arg : args) {
        fullCommand += " " + arg;
    }
    
    NLM_LOG_INFO("Executing: " + fullCommand);
    return system(fullCommand.c_str()) == 0;
}

