bool ConfigUtils::backupConfiguration(const std::string& configFile,
                                      const std::string& backupDir) {
    if (!FileSystem::directoryExists(backupDir)) {
        if (!FileSystem::createDirectory(backupDir, true)) {
            return false;
        }
    }
    
    std::filesystem::path sourcePath(configFile);
    std::string timestamp = std::to_string(std::chrono::duration_cast<std::chrono::milliseconds>(
        std::chrono::system_clock::now().time_since_epoch()).count());
    
    std::string backupPath = backupDir + "/config_backup_" + timestamp + ".cfg";
    
    return FileSystem::copyFile(configFile, backupPath);
}

bool ConfigUtils::restoreConfiguration(const std::string& configFile,
                                       const std::string& backupFile) {
    if (!FileSystem::fileExists(backupFile)) {
        std::cerr << "Error: Backup file does not exist: " << backupFile << std::endl;
        return false;
    }
    
    return FileSystem::copyFile(backupFile, configFile);
}

std::vector<std::string> ConfigUtils::listBackups(const std::string& backupDir) {
    std::vector<std::string> backups;
    
    if (!FileSystem::directoryExists(backupDir)) {
        return backups;
    }
    
    for (const auto& entry : std::filesystem::directory_iterator(backupDir)) {
        if (entry.is_regular_file() && entry.path().extension() == ".cfg") {
            backups.push_back(entry.path().string());
        }
    }
    
    // Sort by modification time (newest first)
    std::sort(backups.begin(), backups.end(),
              [](const std::string& a, const std::string& b) {
                  return std::filesystem::last_write_time(std::filesystem::path(a)) >
                         std::filesystem::last_write_time(std::filesystem::path(b));
              });
    
    return backups;
}

bool ConfigUtils::compareConfigurations(const std::string& configFile1,
                                        const std::string& configFile2) {
    auto config1 = parseSimpleConfig(FileSystem::readFile(configFile1));
    auto config2 = parseSimpleConfig(FileSystem::readFile(configFile2));
    
    return config1 == config2;
}

std::string ConfigUtils::diffConfigurations(const std::string& configFile1,
                                            const std::string& configFile2) {
    auto config1 = parseSimpleConfig(FileSystem::readFile(configFile1));
    auto config2 = parseSimpleConfig(FileSystem::readFile(configFile2));
    
    std::ostringstream oss;
    bool hasDiffs = false;
    
    // Check for differences in config1
    for (const auto& pair : config1) {
        auto it = config2.find(pair.first);
        if (it == config2.end() || it->second != pair.second) {
            if (hasDiffs) oss << "---\n";
            oss << "- " << pair.first << " = \"" << pair.second << "\"\n";
            hasDiffs = true;
        }
    }
    
    // Check for differences in config2 (keys not in config1)
    for (const auto& pair : config2) {
        if (config1.find(pair.first) == config1.end()) {
            if (hasDiffs) oss << "---\n";
            oss << "+ " << pair.first << " = \"" << pair.second << "\"\n";
            hasDiffs = true;
        }
    }
    
    if (!hasDiffs) {
        oss << "Configurations are identical.\n";
    }
    
    return oss.str();
}

std::string ConfigUtils::getConfigurationStatistics(const std::string& configFile) {
    auto config = parseSimpleConfig(FileSystem::readFile(configFile));
    
    std::ostringstream oss;
    oss << "Configuration Statistics:" << std::endl;
    oss << "  Total entries: " << config.size() << std::endl;
    
    // Count by type
    int intCount = 0, floatCount = 0, boolCount = 0, stringCount = 0;
    
    for (const auto& pair : config) {
        const std::string& value = pair.second;
        if (value == "true" || value == "false") {
            boolCount++;
        } else {
            try {
                std::stoi(value);
                intCount++;
            } catch (const std::exception&) {
                try {
                    std::stod(value);
                    floatCount++;
                } catch (const std::exception&) {
                    stringCount++;
                }
            }
        }
    }
    
    oss << "  Integer values: " << intCount << std::endl;
    oss << "  Float values: " << floatCount << std::endl;
    oss << "  Boolean values: " << boolCount << std::endl;
    oss << "  String values: " << stringCount << std::endl;
    
    return oss.str();
}

std::string ConfigUtils::getConfigurationHealthReport(const std::string& configFile) {
    std::ostringstream oss;
    oss << "Configuration Health Report" << std::endl;
    oss << "===========================" << std::endl;
    
    // Read and parse configuration
    auto config = parseSimpleConfig(FileSystem::readFile(configFile));
    
    // Check for required keys
    std::vector<std::string> requiredKeys = {"neuron_count", "region_count", "simulation_timestep"};
    int missingCount = 0;
    
    for (const auto& key : requiredKeys) {
        if (config.find(key) == config.end()) {
            oss << "ERROR: Missing required key: " << key << std::endl;
            missingCount++;
        }
    }
    
    if (missingCount == 0) {
        oss << "OK: All required configuration keys present." << std::endl;
    }
    
    // Check for valid values
    oss << std::endl << "Value Validation:" << std::endl;
    
    // Validate neuron_count
    auto it = config.find("neuron_count");
    if (it != config.end()) {
        try {
            int value = std::stoi(it->second);
            if (value >= 10 && value <= 1000000) {
                oss << "OK: neuron_count = " << value << " (valid range: 10-1000000)" << std::endl;
            } else {
                oss << "WARNING: neuron_count = " << value << " (out of recommended range)" << std::endl;
            }
        } catch (const std::exception&) {
            oss << "ERROR: neuron_count has invalid format: " << it->second << std::endl;
        }
    }
    
    // Validate region_count
    it = config.find("region_count");
    if (it != config.end()) {
        try {
            int value = std::stoi(it->second);
            if (value >= 1 && value <= 100) {
                oss << "OK: region_count = " << value << " (valid range: 1-100)" << std::endl;
            } else {
                oss << "WARNING: region_count = " << value << " (out of recommended range)" << std::endl;
            }
        } catch (const std::exception&) {
            oss << "ERROR: region_count has invalid format: " << it->second << std::endl;
        }
    }
    
    // Validate simulation_timestep
    it = config.find("simulation_timestep");
    if (it != config.end()) {
        try {
            double value = std::stod(it->second);
            if (value > 0.0 && value <= 1.0) {
                oss << "OK: simulation_timestep = " << value << "s (valid range: 0.000001-1.0s)" << std::endl;
            } else {
                oss << "WARNING: simulation_timestep = " << value << " (out of recommended range)" << std::endl;
            }
        } catch (const std::exception&) {
            oss << "ERROR: simulation_timestep has invalid format: " << it->second << std::endl;
        }
    }
    
    return oss.str();
}

bool ConfigUtils::exportConfiguration(const std::string& configFile,
                                      const std::string& exportFile) {
    std::ifstream sourceFile(configFile);
    if (!sourceFile) {
        return false;
    }
    
    std::string content((std::istreambuf_iterator<char>(sourceFile)), std::istreambuf_iterator<char>());
    
    // Add metadata to indicate this is an exported configuration
    std::ostringstream oss;
    oss << "# Exported Configuration\n";
    oss << "# Exported from: " << configFile << "\n";
    oss << "# Export timestamp: " << std::chrono::system_clock::now() << "\n\n";
    oss << content;
    
    return FileSystem::writeFile(exportFile, oss.str());
}

bool ConfigUtils::importConfiguration(const std::string& configFile,
                                      const std::string& exportFile) {
    if (!FileSystem::fileExists(exportFile)) {
        return false;
    }
    
    // Validate that the export file is a valid configuration
    std::string content = FileSystem::readFile(exportFile);
    if (content.empty() || !StringUtils::contains(content, "Exported Configuration")) {
        std::cerr << "Error: Invalid export file format" << std::endl;
        return false;
    }
    
    // Remove metadata lines and keep only the configuration
    std::istringstream stream(content);
    std::ostringstream cleanedConfig;
    bool inConfig = false;
    
    for (std::string line; std::getline(stream, line); ) {
        if (StringUtils::startsWith(line, "# Exported Configuration")) {
            inConfig = true;
            continue;
        }
        if (StringUtils::startsWith(line, "# Export timestamp:")) {
            continue;
        }
        if (StringUtils::startsWith(line, "# Exported from:")) {
            continue;
        }
        if (StringUtils::startsWith(line, "#")) {
            continue;
        }
        
        if (inConfig) {
            cleanedConfig << line << "\n";
        }
    }
    
    return FileSystem::writeFile(configFile, cleanedConfig.str());
}

std::string ConfigUtils::getConfigurationVersion(const std::string& configFile) {
    std::ifstream file(configFile);
    if (!file) {
        return "unknown";
    }
    
    std::string content((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
    
    // Look for version information
    std::istringstream stream(content);
    std::string line;
    while (std::getline(stream, line)) {
        if (StringUtils::startsWith(line, "# Version:")) {
            return StringUtils::trim(line.substr(10));
        }
    }
    
    return "unknown";
}

bool ConfigUtils::updateConfigurationVersion(const std::string& configFile,
                                             const std::string& version) {
    std::ifstream file(configFile);
    if (!file) {
        return false;
    }
    
    std::string content((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
    
    // Add or update version information
    std::istringstream stream(content);
    std::ostringstream newContent;
    bool versionFound = false;
    
    for (std::string line; std::getline(stream, line); ) {
        if (StringUtils::startsWith(line, "# Version:")) {
            newContent << "# Version: " << version << "\n";
            versionFound = true;
        } else {
            newContent << line << "\n";
        }
    }
    
    if (!versionFound) {
        // Add version to the beginning of the file
        newContent.seekp(0, std::ios::beg);
        newContent << "# Version: " << version << "\n" << content;
    }
    
    return FileSystem::writeFile(configFile, newContent.str());
}

