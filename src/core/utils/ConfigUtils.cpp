bool ConfigUtils::validateConfiguration(const std::string& configFile) {
    std::ifstream file(configFile);
    if (!file) {
        std::cerr << "Error: Cannot open configuration file: " << configFile << std::endl;
        return false;
    }
    
    std::string content((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
    auto config = parseSimpleConfig(content);
    
    return validateConfiguration(config);
}

std::string ConfigUtils::validateConfiguration(const std::unordered_map<std::string, std::string>& config) {
    std::ostringstream oss;
    bool hasErrors = false;
    
    // Check for required sections (simplified validation)
    std::vector<std::string> requiredKeys = {"neuron_count", "region_count", "simulation_timestep"};
    
    for (const auto& key : requiredKeys) {
        if (config.find(key) == config.end()) {
            oss << "Error: Missing required configuration key: " << key << "\n";
            hasErrors = true;
        }
    }
    
    // Validate numeric values
    for (const auto& pair : config) {
        if (pair.first == "neuron_count") {
            try {
                int value = std::stoi(pair.second);
                if (value < 10 || value > 1000000) {
                    oss << "Error: neuron_count out of range: " << value << " (valid: 10-1000000)\n";
                    hasErrors = true;
                }
            } catch (const std::exception&) {
                oss << "Error: Invalid neuron_count value: " << pair.second << "\n";
                hasErrors = true;
            }
        } else if (pair.first == "region_count") {
            try {
                int value = std::stoi(pair.second);
                if (value < 1 || value > 1000) {
                    oss << "Error: region_count out of range: " << value << " (valid: 1-1000)\n";
                    hasErrors = true;
                }
            } catch (const std::exception&) {
                oss << "Error: Invalid region_count value: " << pair.second << "\n";
                hasErrors = true;
            }
        } else if (pair.first == "simulation_timestep") {
            try {
                double value = std::stod(pair.second);
                if (value <= 0.0 || value > 1.0) {
                    oss << "Error: simulation_timestep out of valid range: " << value << " (valid: 0.000001-1.0)\n";
                    hasErrors = true;
                }
            } catch (const std::exception&) {
                oss << "Error: Invalid simulation_timestep value: " << pair.second << "\n";
                hasErrors = true;
            }
        }
    }
    
    if (!hasErrors) {
        oss << "Configuration validation passed!\n";
    }
    
    return oss.str();
}

std::string ConfigUtils::getConfigurationErrors(const std::string& configFile) {
    std::ifstream file(configFile);
    if (!file) {
        return "Error: Cannot open configuration file: " + configFile;
    }
    
    std::string content((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
    auto config = parseSimpleConfig(content);
    
    return validateConfiguration(config);
}

std::unordered_map<std::string, std::string> ConfigUtils::mergeConfigurations(
    const std::unordered_map<std::string, std::string>& base,
    const std::unordered_map<std::string, std::string>& override) {
    std::unordered_map<std::string, std::string> result = base;
    
    for (const auto& pair : override) {
        result[pair.first] = pair.second;
    }
    
    return result;
}

std::unordered_map<std::string, std::string> ConfigUtils::mergeConfigurations(
    const std::string& file1, const std::string& file2) {
    std::unordered_map<std::string, std::string> config1, config2;
    
    std::ifstream file1Stream(file1);
    if (file1Stream) {
        std::string content1((std::istreambuf_iterator<char>(file1Stream)), std::istreambuf_iterator<char>());
        config1 = parseSimpleConfig(content1);
    }
    
    std::ifstream file2Stream(file2);
    if (file2Stream) {
        std::string content2((std::istreambuf_iterator<char>(file2Stream)), std::istreambuf_iterator<char>());
        config2 = parseSimpleConfig(content2);
    }
    
    return mergeConfigurations(config1, config2);
}

