    def load_config(self):
        """Load demo configuration."""
        default_config = {
            "random_seed": "42",
            "neuron_count": "1000",
            "simulation_timestep": "0.001",
            "log_level": "INFO",
            "plasticity_learning_rate": "0.01",
            "stdp_ltp_weight": "0.02",
            "stdp_ltd_weight": "0.015",
            "synaptogenesis_rate": "0.0001",
            "environment_name": "GridWorld",
            "environment_width": "10",
            "environment_height": "10"
        }
        
        self.config = default_config.copy()
        
        # Save to config file
        self.save_config()
        
        print("✅ Configuration loaded and saved to:", self.config_file)
    
    def save_config(self):
        """Save configuration to file."""
        try:
            with open(self.config_file, 'w') as f:
                f.write("# NLM Demo Configuration\n")
                f.write("# Generated by Python Demo Wrapper\n")
                f.write("# " + datetime.now().isoformat() + "\n\n")
                
                for key, value in self.config.items():
                    f.write(f"{key} = {value}\n")
            
            return True
        except Exception as e:
            print(f"❌ Error saving configuration: {e}")
            return False
    
    def validate_config(self):
        """Validate configuration."""
        print("🔍 Validating configuration...")
        
        errors = []
        
        # Check required fields
        required_fields = ["random_seed", "neuron_count", "simulation_timestep", "log_level"]
        for field in required_fields:
            if field not in self.config:
                errors.append(f"Missing required field: {field}")
        
        # Type validation
        if "random_seed" in self.config:
            try:
                int(self.config["random_seed"])
            except ValueError:
                errors.append("random_seed must be an integer")
        
        if "neuron_count" in self.config:
            try:
                count = int(self.config["neuron_count"])
                if count <= 0:
                    errors.append("neuron_count must be positive")
            except ValueError:
                errors.append("neuron_count must be an integer")
        
        if "simulation_timestep" in self.config:
            try:
                dt = float(self.config["simulation_timestep"])
                if dt <= 0:
                    errors.append("simulation_timestep must be positive")
            except ValueError:
                errors.append("simulation_timestep must be a number")
        
        if "log_level" in self.config:
            valid_levels = ["TRACE", "DEBUG", "INFO", "WARN", "ERROR", "CRITICAL", "OFF"]
            if self.config["log_level"] not in valid_levels:
                errors.append(f"log_level must be one of: {', '.join(valid_levels)}")
        
        if errors:
            print("❌ Configuration validation failed:")
            for error in errors:
                print(f"   • {error}")
            return False
        else:
            print("✅ Configuration validation passed")
            return True
    
    def show_config(self):
        """Show current configuration."""
        print("📋 Current Configuration:")
        for key, value in self.config.items():
            print(f"   {key}: {value}")
    
    def set_config(self, key, value):
        """Set a configuration value."""
        if key in ["random_seed", "neuron_count"]:
            try:
                int(value)
            except ValueError:
                print(f"❌ {key} must be an integer")
                return False
        
        if key == "simulation_timestep":
            try:
                float(value)
            except ValueError:
                print(f"❌ {key} must be a number")
                return False
        
        if key == "log_level":
            valid_levels = ["TRACE", "DEBUG", "INFO", "WARN", "ERROR", "CRITICAL", "OFF"]
            if value.upper() not in valid_levels:
                print(f"❌ {key} must be one of: {', '.join(valid_levels)}")
                return False
            value = value.upper()
        
        self.config[key] = value
        self.save_config()
        print(f"✅ Set {key} = {value}")
        return True
    
    def run_demo(self):
        """Run the demo interface."""
        print("🎮 Starting NLM Advanced CLI Demo Interface")
        print("===========================================")
        print()
        
        print("Available Commands:")
        print("  help                    - Show this help")
        print("  config                  - Show current configuration")
        print("  config set <key> <value> - Set a configuration value")
        print("  validate                - Validate configuration")
        print("  phase2                  - Run Phase 2 demo")
        print("  phase3                  - Run Phase 3 demo")
        print("  phase4                  - Run Phase 4 demo")
        print("  phase5                  - Run Phase 5 demo")
        print("  phase6                  - Run Phase 6 demo")
        print("  exit/quit              - Exit demo")
        print()
        
        while True:
            try:
                command = input("nlm-demo> ").strip()
                
                if not command:
                    continue
                
                if command.lower() in ["exit", "quit", "q"]:
                    print("👋 Goodbye! Thanks for using the NLM Advanced CLI Demo.")
                    break
                
                elif command.lower() == "help":
                    self.print_help()
                
                elif command.lower() == "config":
                    self.show_config()
                
                elif command.lower().startswith("config set "):
                    parts = command.split(" ", 3)
                    if len(parts) == 4:
                        key = parts[2]
                        value = parts[3]
                        self.set_config(key, value)
                    else:
                        print("❌ Usage: config set <key> <value>")
                
                elif command.lower() == "validate":
                    self.validate_config()
                
                elif command.lower() == "phase2":
                    self.run_phase2_demo()
                
                elif command.lower() == "phase3":
                    self.run_phase3_demo()
                
                elif command.lower() == "phase4":
                    self.run_phase4_demo()
                
                elif command.lower() == "phase5":
                    self.run_phase5_demo()
                
                elif command.lower() == "phase6":
                    self.run_phase6_demo()
                
                else:
                    print(f"❌ Unknown command: {command}")
                    print("Type 'help' for available commands.")
                
            except KeyboardInterrupt:
                print("\n👋 Demo interrupted by user. Goodbye!")
                break
            except Exception as e:
                print(f"❌ Error: {e}")
    
