// RewardModulatedSTDP implementations
struct RewardModulatedSTDP::Impl {
    float learningRate;
    float predictionError;
    float baseline;
    
    Impl() : learningRate(0.001f), predictionError(0.0f), baseline(0.0f) {}
};

RewardModulatedSTDP::RewardModulatedSTDP() : pImpl(new Impl) {}

RewardModulatedSTDP::~RewardModulatedSTDP() = default;

void RewardModulatedSTDP::update(Synapse* synapse,
                               const std::vector<Timestamp>& preSpikes,
                               const std::vector<Timestamp>& postSpikes,
                               TimestepDuration dt) {
    if (!synapse || preSpikes.empty() || postSpikes.empty()) {
        return;
    }
    
    // Calculate STDP contribution
    float totalDelta = 0.0f;
    float tau = 20.0f;  // Standard STDP time constant
    
    for (Timestamp preTime : preSpikes) {
        for (Timestamp postTime : postSpikes) {
            float dt = static_cast<float>(postTime - preTime);
            
            if (dt > 0) {
                // Potentiation
                float delta = pImpl->learningRate * std::exp(-dt / tau);
                totalDelta += delta;
            } else if (dt < 0) {
                // Depression
                float delta = -pImpl->learningRate * std::exp(dt / tau);
                totalDelta += delta;
            }
        }
    }
    
    // Apply reward modulation
    float modulation = 1.0f;
    if (pImpl->predictionError > 0) {
        // Positive prediction error: enhance learning
        modulation = 1.0f + pImpl->predictionError;
    } else if (pImpl->predictionError < 0) {
        // Negative prediction error: suppress learning
        modulation = std::max(0.0f, 1.0f + pImpl->predictionError);
    }
    
    // Apply modulated weight change
    if (std::abs(totalDelta) > 1e-6f) {
        totalDelta *= modulation;
        applyWeightChange(synapse, totalDelta);
    }
}

void RewardModulatedSTDP::applyWeightChange(Synapse* synapse, SynapticWeight delta) {
    if (!synapse) return;
    
    // Apply weight change with bounds
    float newWeight = synapse->getWeight() + delta;
    newWeight = std::clamp(newWeight, -1.0f, 1.0f);
    synapse->setWeight(newWeight);
}

const char* RewardModulatedSTDP::getName() const {
    return "R-STDP";
}

void RewardModulatedSTDP::setLearningRate(float rate) {
    pImpl->learningRate = std::max(0.0f, rate);
}

float RewardModulatedSTDP::getLearningRate() const {
    return pImpl->learningRate;
}

void RewardModulatedSTDP::setPredictionError(float error) {
    pImpl->predictionError = error;
}

float RewardModulatedSTDP::getPredictionError() const {
    return pImpl->predictionError;
}

// TripletSTDP implementations
struct TripletSTDP::Impl {
    float learningRate;
    float timeConstant;
    float stdpWeight;
    
    Impl() : learningRate(0.001f), timeConstant(20.0f), stdpWeight(0.01f) {}
};

TripletSTDP::TripletSTDP() : pImpl(new Impl) {}

TripletSTDP::~TripletSTDP() = default;

void TripletSTDP::update(Synapse* synapse,
                        const std::vector<Timestamp>& preSpikes,
                        const std::vector<Timestamp>& postSpikes,
                        TimestepDuration dt) {
    if (!synapse || preSpikes.empty() || postSpikes.empty()) {
        return;
    }
    
    // Triplet STDP implementation with pre-post-post interactions
    // This is a simplified implementation based on the classic triplet STDP rule
    
    float totalDelta = 0.0f;
    float tau = pImpl->timeConstant;
    float a_plus = pImpl->stdpWeight;   // Potentiation strength
    float a_minus = pImpl->stdpWeight * 0.5f; // Depression strength
    
    // For each post-synaptic spike
    for (Timestamp postTime : postSpikes) {
        // Find all pre-synaptic spikes that occurred within time window
        std::vector<Timestamp> relevantPreSpikes;
        for (Timestamp preTime : preSpikes) {
            if (postTime - preTime <= tau * 3) {  // 3τ window
                relevantPreSpikes.push_back(preTime);
            }
        }
        
        // Calculate triplet contributions
        for (Timestamp preTime : relevantPreSpikes) {
            float dt = static_cast<float>(postTime - preTime);
            
            if (dt > 0) {
                // Pairwise term (classic STDP)
                float pairwiseDelta = a_plus * std::exp(-dt / tau);
                
                // Find previous pre-synaptic spike to calculate triplet term
                auto it = std::find_if(preSpikes.rbegin(), preSpikes.rend(),
                                      [postTime, dt](Timestamp t) { return t < postTime - dt; });
                if (it != preSpikes.rend()) {
                    Timestamp prePreTime = *it;
                    float dt_pre = static_cast<float>(postTime - prePreTime);
                    
                    // Post-post triplet term
                    float tripletDelta = -a_plus * std::exp(-dt_pre / (tau * 2));
                    totalDelta += pairwiseDelta + tripletDelta;
                } else {
                    totalDelta += pairwiseDelta;
                }
            } else if (dt < 0) {
                // Depression term
                float delta = -a_minus * std::exp(dt / tau);
                totalDelta += delta;
            }
        }
    }
    
    // Apply weight change
    if (std::abs(totalDelta) > 1e-6f) {
        totalDelta *= pImpl->learningRate;
        applyWeightChange(synapse, totalDelta);
    }
}

void TripletSTDP::applyWeightChange(Synapse* synapse, SynapticWeight delta) {
    if (!synapse) return;
    
    // Apply weight change with bounds
    float newWeight = synapse->getWeight() + delta;
    newWeight = std::clamp(newWeight, -1.0f, 1.0f);
    synapse->setWeight(newWeight);
}

