// Update optimized brain configuration
void Brain::updateOptimizedBrainConfig(const std::string& key, const std::string& value) {
    if (pImpl->optimizedBrain) {
        NLM_LOG_INFO("Updating optimized brain config: " + key + " = " + value);
        
        // Parse configuration and apply to optimized brain
        if (key == "event_driven") {
            bool enabled = (value == "true" || value == "1" || value == "yes");
            pImpl->optimizedBrain->enableEventDriven(enabled);
        } else if (key == "multithreading") {
            bool enabled = (value == "true" || value == "1" || value == "yes");
            pImpl->optimizedBrain->enableMultithreading(enabled);
        } else if (key == "simd") {
            bool enabled = (value == "true" || value == "1" || value == "yes");
            pImpl->optimizedBrain->enableSIMD(enabled);
        } else if (key == "sparse_connectivity") {
            bool enabled = (value == "true" || value == "1" || value == "yes");
            pImpl->optimizedBrain->enableSparseConnectivity(enabled);
        } else if (key == "thread_count") {
            try {
                size_t threads = std::stoul(value);
                pImpl->optimizedBrain->setThreadCount(threads);
            } catch (...) {
                NLM_LOG_WARN("Invalid thread count in config: " + value);
            }
        }
    }
}

// Get performance statistics from optimized brain
Brain::PerformanceStats Brain::getOptimizedBrainStats() const {
    if (pImpl->optimizedBrain && pImpl->useOptimizedImplementation) {
        return pImpl->optimizedBrain->getPerformanceStats();
    }
    
    // Return default statistics if optimized brain not available
    PerformanceStats stats;
    stats.neuronsPerSecond = 0.0;
    stats.spikesPerSecond = 0.0;
    stats.synapticEventsPerSecond = 0.0;
    stats.realTimeFactor = 1.0;
    stats.activeNeurons = getActiveNeuronCount();
    stats.firingNeurons = getFiringNeuronCount();
    stats.pendingSpikes = getPendingSpikeEventCount();
    stats.pendingDelayedSpikes = 0;
    stats.avgFiringRate = getAverageFiringRate();
    stats.memoryUsageMB = 0.0;
    stats.stepTimeMs = 0.0;
    return stats;
}

// Check if all optimizations are enabled
bool Brain::areAllOptimizationsEnabled() const {
    if (!pImpl->optimizedBrain || !pImpl->useOptimizedImplementation) {
        return false;
    }
    
    OptimizedBrain::PerformanceStats stats = pImpl->optimizedBrain->getPerformanceStats();
    
    // Check if performance meets optimization targets
    bool eventDrivenOk = stats.activeNeurons < stats.avgFiringRate * 1000; // Reasonable activity
    bool multiThreadOk = stats.spikesPerSecond > 0; // Processing spikes
    bool simdOk = stats.synapticEventsPerSecond > 0; // Processing synaptic events
    
    return eventDrivenOk && multiThreadOk && simdOk;
}

