namespace nlm {

void Neuron::stepLIF(Timestamp currentTime, TimestepDuration dt) {
    pImpl->neuronDynamics->stepLIF(currentTime, dt);
}

void Neuron::step(Timestamp currentTime) {
    pImpl->neuronDynamics->stepLIF(currentTime, 0.001); // Default timestep
}

void Neuron::reset() {
    pImpl->neuronStateManagement->reset();
}

void Neuron::initializeRandom(RandomGenerator& rng) {
    pImpl->neuronDynamics->initializeRandom(rng);
}

} // namespace nlm