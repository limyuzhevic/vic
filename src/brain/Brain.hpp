#pragma once

#include "../core/Types/Types.hpp"
#include "NeuralRegion.hpp"
#include "../dynamics/SpikeSystem.hpp"
#include "../plasticity/STDP.hpp"
#include "../plasticity/Hebbian.hpp"
#include "../plasticity/StructuralPlasticity.hpp"
#include <memory>
#include <string>

namespace nlm {

// Brain: The central coordinator of the neural system
// Implements real spiking neural computation with event-driven dynamics
// and integrated memory, prediction, cognition, and neuromodulation systems

class Brain {
public:
    // Create brain with configuration
    // @param config Shared pointer to configuration containing brain parameters
    // @pre config should contain all required brain parameters (neuron_count, etc.)
    explicit Brain(std::shared_ptr<Config> config);
    
    // Destructor - cleans up brain resources
    ~Brain();
    
    // Disable copying, enable moving
    Brain(const Brain&) = delete;
    Brain& operator=(const Brain&) = delete;
    Brain(Brain&&) noexcept;
    Brain& operator=(Brain&&) noexcept;
    
    // Initialize brain with configuration
    // @return true if initialization succeeded, false on failure
    // @pre Should be called after construction before any simulation steps
    bool initialize();
    
    // Main simulation step
    void step(SimulationStep currentStep);
    
    // Simulation time step
    void step(SimulationStep currentStep, Timestamp currentTime);
    
    // Receive sensory input from environment
    // Injects current into sensory neurons based on input pattern
    void receiveSensoryInput(const class SensoryInput& input);
    
    // Inject current directly into a specific neuron
    void injectCurrent(NeuronId neuron, MembranePotential current);
    
    // Inject current into all neurons of a specific type
    void injectCurrentToNeurons(NeuronType type, MembranePotential current);
    
    // Spike system access
    SpikeSystem* getSpikeSystem();
    const SpikeSystem* getSpikeSystem() const;
    
    // Plasticity system access
    STDP* getSTDP();
    Hebbian* getHebbian();
    StructuralPlasticity* getStructuralPlasticity();
    
    // Statistics
    // @return Excitation/Inhibition ratio (E/I balance) between -1.0 and 1.0
    float getExcitationInhibitionRatio() const;
    
    // @return Total number of spikes generated by all neurons
    size_t getTotalSpikeCount() const;
    
    // @return Number of pending spike events scheduled for future execution
    size_t getPendingSpikeEventCount() const;
    
    // Produce motor/action output based on motor neuron activity
    // @return Unique pointer to Action containing selected motor command and parameters
    // @post Creates appropriate motor action based on current neural activity patterns
    std::unique_ptr<class Action> produceAction();
    
    // Apply neuromodulatory signals
    // @param signal Neuromodulator containing dopamine, curiosity, novelty, or prediction error
    // @post Applies neuromodulatory effects to plasticity, firing, and learning
    void applyNeuromodulation(const class Neuromodulator& signal);
    
    // Update plasticity rules (called automatically in step)
    // @post Updates synaptic weights based on STDP, Hebbian, and other plasticity rules
    void updatePlasticity();
    
    // Apply developmental changes (called automatically in step)
    // @post Modifies developmental parameters based on agent age
    void develop();
    
    // Reset brain state
    // @post Resets all neurons, synapses, and internal states to initial values
    void reset();
    
    // Save brain state to file (checkpointing)
    bool save(const std::string& filepath) const;
    
    // Load brain state from file
    bool load(const std::string& filepath);
    
    // Region management
    RegionId addRegion(const std::string& name = "");
    NeuralRegion* getRegion(RegionId id);
    const NeuralRegion* getRegion(RegionId id) const;
    size_t getRegionCount() const;
    std::vector<RegionId> getRegionIds() const;
    
    // Get all regions
    const std::vector<std::unique_ptr<NeuralRegion>>& getRegions() const;
    
    // Save brain state to file (checkpointing)
    // @param filepath Path to save file (binary format)
    // @return true if save succeeded, false on error
    bool save(const std::string& filepath) const;
    
    // Load brain state from file
    // @param filepath Path to load file (binary format)
    // @return true if load succeeded, false on error
    bool load(const std::string& filepath);
    
    // Region management
    // @param name Optional name for the new region (default: empty)
    // @return ID of the newly created region
    RegionId addRegion(const std::string& name = "");
    
    // Get region by ID
    // @param id Region identifier
    // @return Pointer to NeuralRegion, or nullptr if not found
    NeuralRegion* getRegion(RegionId id);
    const NeuralRegion* getRegion(RegionId id) const;
    
    // Get region count
    // @return Number of neural regions in the brain
    size_t getRegionCount() const;
    
    // Get all region IDs
    // @return Vector of all region IDs in the brain
    std::vector<RegionId> getRegionIds() const;
    
    // Get all regions
    // @return Const reference to vector of all neural regions
    const std::vector<std::unique_ptr<NeuralRegion>>& getRegions() const;
    
    // Inter-region connection management
    // @param source Source region ID
    // @param target Target region ID
    // @param weight Connection weight (default: 0.0)
    // @param delay Connection delay in simulation steps (default: 1)
    void addInterRegionConnection(RegionId source, RegionId target, 
                                  float weight = 0.0f, Delay delay = 1);
    
    // Remove inter-region connection
    // @param source Source region ID
    // @param target Target region ID
    void removeInterRegionConnection(RegionId source, RegionId target);
    
    // Global statistics
    // @return Total number of neurons across all regions
    size_t getTotalNeuronCount() const;
    
    // @return Total number of synapses across all regions
    size_t getTotalSynapseCount() const;
    
    // @return Number of neurons currently active
    size_t getActiveNeuronCount() const;
    
    // @return Number of neurons currently firing spikes
    size_t getFiringNeuronCount() const;
    
    // @return Average firing rate across all neurons (Hz)
    float getAverageFiringRate() const;
    
    // ========== MEMORY SYSTEMS ==========
    
    // Working memory - transient active information
    // @return Pointer to working memory system for short-term information storage
    NeuralWorkingMemory* getWorkingMemory();
    
    // Episodic memory - experience storage
    // @return Pointer to episodic memory system for experience recording and replay
    NeuralEpisodicMemory* getEpisodicMemory();
    
    // Associative memory - pattern associations
    // @return Pointer to associative memory system for pattern linking
    NeuralAssociativeMemory* getAssociativeMemory();
    
    // ========== PREDICTION SYSTEM ==========
    
    // Prediction system for sensory prediction and error computation
    PredictionSystem* getPredictionSystem();
    
    // ========== COGNITION SYSTEMS ==========
    
    // Neural planner for action planning
    NeuralPlanner* getPlanner();
    
    // Concept formation for pattern discovery
    ConceptFormation* getConceptFormation();
    
    // Attentional selection for focus
    AttentionalSelection* getAttention();
    
    // ========== DEVELOPMENT SYSTEM ==========
    
    DevelopmentSystem* getDevelopmentSystem();
    DevelopmentalStage getDevelopmentalStage() const;
    void setDevelopmentalStage(DevelopmentalStage stage);
    
    // ========== NEUROMODULATION SYSTEMS ==========
    
    // Dopamine - reward and reinforcement
    Dopamine* getDopamine();
    
    // Curiosity - exploration motivation
    Curiosity* getCuriosity();
    
    // Novelty - novelty detection
    // @return Pointer to novelty detection system
    Novelty* getNovelty();
    
    // Prediction error signal
    // @return Pointer to prediction error system for computing sensory prediction errors
    PredictionError* getPredictionErrorSignal();
    
    // Get current configuration
    // @return Shared pointer to const configuration
    std::shared_ptr<const Config> getConfig() const;
    
    // Get random generator
    // @return Pointer to random number generator used by the brain
    RandomGenerator* getRandomGenerator();
    
    // Logging
    // @post Logs detailed brain status including neuron counts, firing rates, etc.
    void logStatus() const;
    
private:
    // Pimpl idiom implementation details
    // Impl contains all private implementation details to reduce compilation dependencies
    struct Impl;
    Impl* pImpl;
};

} // namespace nlm
