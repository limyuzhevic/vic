void ResultReporter::printConsole(const std::string& title, const std::string& content) {
    std::cout << "=== " << title << " ===" << std::endl;
    std::cout << content << std::endl;
    std::cout << "=== End " << title << " ===" << std::endl;
}

bool ResultReporter::exportJson(const std::string& filename, const std::string& content) {
    std::ofstream file(filename);
    if (!file.is_open()) {
        std::cerr << "Error: Cannot open file for writing: " << filename << std::endl;
        return false;
    }
    
    file << content;
    file.close();
    return true;
}

bool ResultReporter::exportCsv(const std::string& filename, const std::vector<std::string>& headers,
                              const std::vector<std::vector<std::string>>& data) {
    std::ofstream file(filename);
    if (!file.is_open()) {
        std::cerr << "Error: Cannot open file for writing: " << filename << std::endl;
        return false;
    }
    
    // Write headers
    for (size_t i = 0; i < headers.size(); ++i) {
        file << headers[i];
        if (i < headers.size() - 1) file << ",";
    }
    file << "\n";
    
    // Write data rows
    for (const auto& row : data) {
        for (size_t i = 0; i < row.size(); ++i) {
            file << row[i];
            if (i < row.size() - 1) file << ",";
        }
        file << "\n";
    }
    
    file.close();
    return true;
}

bool ResultReporter::exportHtml(const std::string& filename, const std::string& title,
                               const std::string& content) {
    std::ofstream file(filename);
    if (!file.is_open()) {
        std::cerr << "Error: Cannot open file for writing: " << filename << std::endl;
        return false;
    }
    
    file << "<!DOCTYPE html>\n";
    file << "<html>\n";
    file << "<head>\n";
    file << "  <title>" << title << "</title>\n";
    file << "  <style>\n";
    file << "    body { font-family: Arial, sans-serif; margin: 20px; }\n";
    file << "    h1 { color: #333; }\n";
    file << "    .header { background-color: #f0f0f0; padding: 10px; border-radius: 5px; }\n";
    file << "    .content { margin: 20px 0; }\n";
    file << "    .footer { font-size: 0.8em; color: #666; margin-top: 20px; }\n";
    file << "  </style>\n";
    file << "</head>\n";
    file << "<body>\n";
    file << "  <div class=\"header\">\n";
    file << "    <h1>" << title << "</h1>\n";
    file << "    <p>Generated on " << getCurrentTimestamp() << "</p>\n";
    file << "  </div>\n";
    file << "  <div class=\"content\">\n";
    file << "    <pre>" << content << "</pre>\n";
    file << "  </div>\n";
    file << "  <div class=\"footer\">\n";
    file << "    <p>Generated by NLM Result Reporter</p>\n";
    file << "  </div>\n";
    file << "</body>\n";
    file << "</html>";
    
    file.close();
    return true;
}

std::string ResultReporter::generatePerformanceReport(const PerformanceMetrics& metrics) {
    std::ostringstream oss;
    oss << "Performance Metrics Report" << std::endl;
    oss << "===========================" << std::endl;
    oss << std::endl;
    oss << "Timestamp: " << metrics.timestamp << std::endl;
    oss << std::endl;
    oss << "Timing:" << std::endl;
    oss << "  CPU Time: " << formatDuration(metrics.cpuTime) << std::endl;
    oss << "  Simulation Time: " << formatDuration(metrics.simulationTime) << std::endl;
    oss << std::endl;
    oss << "Resource Usage:" << std::endl;
    oss << "  Memory Usage: " << formatNumber(metrics.memoryUsage, " MB") << std::endl;
    oss << std::endl;
    oss << "Performance:" << std::endl;
    oss << "  Spike Rate: " << formatNumber(metrics.spikeRate, " Hz") << std::endl;
    oss << "  Throughput: " << formatNumber(metrics.throughput, " ops/sec") << std::endl;
    oss << "  Total Operations: " << metrics.totalOperations << std::endl;
    
    return oss.str();
}

std::string ResultReporter::generateExperimentReport(const std::string& experimentName,
                                                     const std::vector<std::string>& parameters,
                                                     const std::string& results) {
    std::ostringstream oss;
    oss << experimentName << " Experiment Report" << std::endl;
    oss << std::string(experimentName.length() + 16, '=') << std::endl;
    oss << std::endl;
    oss << "Parameters:" << std::endl;
    for (const auto& param : parameters) {
        oss << "  " << param << std::endl;
    }
    oss << std::endl;
    oss << "Results:" << std::endl;
    oss << results << std::endl;
    
    return oss.str();
}

std::string ResultReporter::generateComparisonReport(const std::vector<std::string>& experimentNames,
                                                     const std::vector<std::string>& resultContents) {
    std::ostringstream oss;
    oss << "Experiment Comparison Report" << std::endl;
    oss << std::string(32, '=') << std::endl;
    oss << std::endl;
    
    for (size_t i = 0; i < experimentNames.size(); ++i) {
        oss << experimentNames[i] << ":" << std::endl;
        oss << resultContents[i] << std::endl;
        if (i < experimentNames.size() - 1) {
            oss << "\n";
        }
    }
    
    return oss.str();
}

void ResultReporter::printSystemInfo() {
    std::cout << "System Information:" << std::endl;
    std::cout << "  Platform: " << (sizeof(void*) == 8 ? "x86_64" : "x86") << std::endl;
    std::cout << "  Architecture: " << (sizeof(void*) * 8) << "-bit" << std::endl;
    std::cout << "  Compiler: " << (defined(__GNUC__) ? "GCC " + std::string(__VERSION__) : 
                            defined(_MSC_VER) ? "MSVC " + std::to_string(_MSC_VER) : "Unknown") << std::endl;
    std::cout << "  C++ Standard: C++" << __cplusplus << std::endl;
    std::cout << "  Memory Model: " << (sizeof(void*) == 8 ? "64-bit" : "32-bit") << std::endl;
}

std::string ResultReporter::getCurrentTimestamp() {
    auto now = std::chrono::system_clock::now();
    auto time = std::chrono::system_clock::to_time_t(now);
    
    std::ostringstream oss;
    oss << std::put_time(std::localtime(&time), "%Y-%m-%d %H:%M:%S");
    
    return oss.str();
}

std::string ResultReporter::formatDuration(double seconds) {
    if (seconds < 1.0) {
        return std::to_string(seconds * 1000) + " ms";
    } else if (seconds < 60.0) {
        return std::to_string(seconds) + " s";
    } else if (seconds < 3600.0) {
        int minutes = static_cast<int>(seconds / 60.0);
        int secs = static_cast<int>(seconds) % 60;
        return std::to_string(minutes) + "m " + std::to_string(secs) + "s";
    } else {
        int hours = static_cast<int>(seconds / 3600.0);
        int minutes = static_cast<int>(seconds / 60.0) % 60;
        return std::to_string(hours) + "h " + std::to_string(minutes) + "m";
    }
}

std::string ResultReporter::formatNumber(double number, const std::string& unit) {
    if (std::abs(number) < 1000.0) {
        return std::to_string(number) + unit;
    } else if (std::abs(number) < 1000000.0) {
        return std::to_string(number / 1000.0) + " K" + unit;
    } else if (std::abs(number) < 1000000000.0) {
        return std::to_string(number / 1000000.0) + " M" + unit;
    } else {
        return std::to_string(number / 1000000000.0) + " G" + unit;
    }
}

