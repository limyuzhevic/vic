void CLIUtils::updateProgress(int current, int total, const std::string& message) {
    double percentage = static_cast<double>(current) / total * 100.0;
    
    std::cout << "\r" << message << " " << current << "/" << total << " (" 
              << std::fixed << std::setprecision(1) << percentage << "%)";
    
    if (current >= total) {
        std::cout << std::endl;
    }
}

std::string CLIUtils::errorToString(CLIErrorType error) {
    switch (error) {
        case CLIErrorType::None: return "None";
        case CLIErrorType::FileNotFound: return "File not found";
        case CLIErrorType::InvalidFormat: return "Invalid file format";
        case CLIErrorType::ValidationError: return "Validation error";
        case CLIErrorType::ConfigurationError: return "Configuration error";
        case CLIErrorType::CommandError: return "Command error";
        case CLIErrorType::RuntimeError: return "Runtime error";
        default: return "Unknown error";
    }
}

std::unordered_map<std::string, std::string> CLIUtils::parseArguments(int argc, char* argv[]) {
    std::unordered_map<std::string, std::string> args;
    
    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        if (arg.substr(0, 2) == "--") {
            size_t equalPos = arg.find('=');
            if (equalPos != std::string::npos) {
                std::string key = arg.substr(0, equalPos);
                std::string value = arg.substr(equalPos + 1);
                args[key] = value;
            } else {
                // Check if next argument is a value
                if (i + 1 < argc && argv[i + 1][0] != '-') {
                    args[arg] = argv[++i];
                }
            }
        }
    }
    
    return args;
}

