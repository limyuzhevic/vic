CLIResult CLIUtils::validateConfig(const std::string& filepath, bool strict) {
    CLIResult result;
    
    // Check if file exists
    if (!std::filesystem::exists(filepath)) {
        result.success = false;
        result.errorType = CLIErrorType::FileNotFound;
        result.errorMessage = "Configuration file not found: " + filepath;
        return result;
    }
    
    // Detect file format
    FileFormat format = detectFileFormat(filepath);
    
    if (format == FileFormat::UNKNOWN) {
        result.success = false;
        result.errorType = CLIErrorType::InvalidFormat;
        result.errorMessage = "Unable to detect file format: " + filepath;
        return result;
    }
    
    // Try to parse as Config
    auto config = std::make_shared<Config>();
    
    bool parseSuccess = false;
    switch (format) {
        case FileFormat::JSON:
            // JSON parsing would go here
            result.validationWarnings.push_back("JSON parsing not yet implemented for validation");
            parseSuccess = false;
            break;
        case FileFormat::YAML:
            // YAML parsing would go here
            result.validationWarnings.push_back("YAML parsing not yet implemented for validation");
            parseSuccess = false;
            break;
        case FileFormat::SIMPLE:
            parseSuccess = config->loadFromFile(filepath);
            break;
        default:
            parseSuccess = false;
            break;
    }
    
    if (!parseSuccess) {
        result.success = false;
        result.errorType = CLIErrorType::InvalidFormat;
        result.errorMessage = "Failed to parse configuration file: " + filepath;
        return result;
    }
    
    // Perform validation if strict mode is enabled
    if (strict) {
        if (!config->validate()) {
            auto errors = config->getValidationErrors();
            auto warnings = config->getValidationWarnings();
            
            for (const auto& error : errors) {
                result.validationErrors.push_back(error.message + ": " + error.suggestion);
            }
            
            for (const auto& warning : warnings) {
                result.validationWarnings.push_back(warning.message);
            }
            
            if (!errors.empty()) {
                result.success = false;
                result.errorType = CLIErrorType::ValidationError;
                result.errorMessage = "Configuration validation failed with " + std::to_string(errors.size()) + " error(s)";
            }
        }
    }
    
    result.output = "Configuration file: " + filepath + "\n";
    result.output += "Format detected: " + std::to_string(static_cast<int>(format)) + "\n";
    result.output += "Validation errors: " + std::to_string(result.validationErrors.size()) + "\n";
    result.output += "Validation warnings: " + std::to_string(result.validationWarnings.size()) + "\n";
    
    return result;
}

CLIResult CLIUtils::displayConfigInfo(const std::string& filepath, const std::string& field) {
    CLIResult result;
    
    auto config = std::make_shared<Config>();
    
    if (!config->loadFromFile(filepath)) {
        result.success = false;
        result.errorType = CLIErrorType::InvalidFormat;
        result.errorMessage = "Failed to load configuration file: " + filepath;
        return result;
    }
    
    std::stringstream ss;
    
    if (field.empty()) {
        // Display all configuration
        ss << "Configuration File: " << filepath << "\n";
        ss << "====================\n\n";
        
        // Get all keys and display them
        auto keys = config->getKeys();
        for (const auto& key : keys) {
            if (config->has(key)) {
                ss << key << " = ";
                
                // Try to get value as different types
                if (config->has<int64_t>(key)) {
                    ss << config->get<int64_t>(key);
                } else if (config->has<double>(key)) {
                    ss << config->get<double>(key);
                } else if (config->has<bool>(key)) {
                    ss << (config->get<bool>(key) ? "true" : "false");
                } else {
                    ss << config->get<std::string>(key);
                }
                ss << "\n";
            }
        }
    } else {
        // Display specific field
        if (config->has(field)) {
            ss << field << " = ";
            if (config->has<int64_t>(field)) {
                ss << config->get<int64_t>(field);
            } else if (config->has<double>(field)) {
                ss << config->get<double>(field);
            } else if (config->has<bool>(field)) {
                ss << (config->get<bool>(field) ? "true" : "false");
            } else {
                ss << config->get<std::string>(field);
            }
        } else {
            result.success = false;
            result.errorMessage = "Field not found in configuration: " + field;
        }
    }
    
    result.output = ss.str();
    return result;
}

