std::vector<std::string> NLMScriptGenerator::getAvailableTemplates() const {
    return {"bash_template", "docker_template", "slurm_template", "k8s_template"};
}

std::string NLMScriptGenerator::generateBashScript(const std::string& templateName,
                                                   const std::map<std::string, std::string>& parameters) const {
    std::stringstream ss;
    
    ss << "#!/bin/bash" << std::endl;
    ss << "# Generated NLM script from template: " << templateName << std::endl;
    ss << "# Generated by NLM Script Generator" << std::endl;
    ss << std::endl;
    ss << "set -e" << std::endl;
    ss << std::endl;
    ss << "echo \"NLM Neural Network Simulator\"" << std::endl;
    ss << std::endl;
    
    // Add parameters
    for (const auto& param : parameters) {
        ss << "# Parameter: " << param.first << " = " << param.second << std::endl;
        ss << "export " << param.first << "=\"" << param.second << "\"" << std::endl;
    }
    
    ss << std::endl;
    ss << "# Run NLM simulation" << std::endl;
    ss << "nlm run basic" << std::endl;
    
    ss << std::endl;
    ss << "echo \"Script completed successfully\"" << std::endl;
    
    return ss.str();
}

std::string NLMScriptGenerator::generateDockerFile(const std::string& templateName,
                                                   const std::map<std::string, std::string>& parameters) const {
    std::stringstream ss;
    
    ss << "FROM ubuntu:20.04" << std::endl;
    ss << "LABEL maintainer=\"NLM Team\"" << std::endl;
    ss << "LABEL description=\"NLM Neural Network Simulator\"" << std::endl;
    ss << std::endl;
    ss << "RUN apt-get update && apt-get install -y g++ make git" << std::endl;
    ss << std::endl;
    ss << "WORKDIR /app" << std::endl;
    ss << "COPY . /app" << std::endl;
    ss << std::endl;
    ss << "RUN make all" << std::endl;
    ss << std::endl;
    ss << "EXPOSE 8080" << std::endl;
    ss << std::endl;
    ss << "CMD [" << std::endl;
    ss << "  \"nlm\"," << std::endl;
    ss << "  \"run\"," << std::endl;
    ss << "  \"basic\"" << std::endl;
    ss << "]" << std::endl;
    
    return ss.str();
}

std::string NLMScriptGenerator::generateSLURMScript(const std::string& templateName,
                                                     const std::map<std::string, std::string>& parameters) const {
    std::stringstream ss;
    
    ss << "#!/bin/bash" << std::endl;
    ss << "#SBATCH --job-name=nlm-simulation" << std::endl;
    ss << "#SBATCH --nodes=1" << std::endl;
    ss << "#SBATCH --ntasks-per-node=1" << std::endl;
    ss << "#SBATCH --cpus-per-task=4" << std::endl;
    ss << "#SBATCH --mem=16G" << std::endl;
    ss << "#SBATCH --time=48:00:00" << std::endl;
    ss << "#SBATCH --output=nlm-%j.out" << std::endl;
    ss << "#SBATCH --error=nlm-%j.err" << std::endl;
    ss << std::endl;
    ss << "module load gcc/8.2.0" << std::endl;
    ss << std::endl;
    ss << "export NLM_HOME=/app" << std::endl;
    ss << "cd /app" << std::endl;
    ss << std::endl;
    
    for (const auto& param : parameters) {
        ss << "export " << param.first << "=\"" << param.second << "\"" << std::endl;
    }
    
    ss << std::endl;
    ss << "echo \"Starting NLM simulation\"" << std::endl;
    ss << "./nlm run basic" << std::endl;
    ss << std::endl;
    ss << "echo \"SLURM job completed successfully\"" << std::endl;
    
    return ss.str();
}

std::string NLMScriptGenerator::generateKubernetesManifest(const std::string& templateName,
                                                          const std::map<std::string, std::string>& parameters) const {
    std::stringstream ss;
    
    ss << "apiVersion: batch/v1" << std::endl;
    ss << "kind: Job" << std::endl;
    ss << "metadata:" << std::endl;
    ss << "  name: nlm-simulation" << std::endl;
    ss << "spec:" << std::endl;
    ss << "  template:" << std::endl;
    ss << "    spec:" << std::endl;
    ss << "      containers:" << std::endl;
    ss << "      - name: nlm" << std::endl;
    ss << "        image: nlm/simulator:latest" << std::endl;
    ss << "        command: [\"nlm\", \"run\", \"basic\"]" << std::endl;
    ss << "        resources:" << std::endl;
    ss << "          requests:" << std::endl;
    ss << "            cpu: \"1\"" << std::endl;
    ss << "            memory: \"1Gi\"" << std::endl;
    ss << "          limits:" << std::endl;
    ss << "            cpu: \"4\"" << std::endl;
    ss << "            memory: \"16Gi\"" << std::endl;
    ss << "      restartPolicy: Never" << std::endl;
    ss << "  backoffLimit: 0" << std::endl;
    
    return ss.str();
}

void NLMScriptGenerator::writeScript(const std::string& content, const std::string& outputFile) const {
    std::ofstream file(outputFile);
    if (!file.is_open()) {
        std::cerr << "Error: Failed to create output file: " << outputFile << std::endl;
        return;
    }
    
    file << content;
    file.close();
    
    // Make shell script executable
    if (outputFile.find(".sh") != std::string::npos) {
        system(("chmod +x " + outputFile).c_str());
    }
}

