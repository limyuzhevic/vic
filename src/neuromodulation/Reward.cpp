#include "Reward.hpp"
#include "../environment/Observation.hpp"
#include "../sensory/SensoryInput.hpp"
#include <string>

namespace nlm {

struct Reward::Impl {
    float currentValue;
    float accumulatedReward;
    std::vector<float> history;
    
    Impl() : currentValue(0.0f), accumulatedReward(0.0f) {}
};

Reward::Reward() : pImpl(new Impl) {}

Reward::~Reward() = default;

float Reward::getValue() const {
    return pImpl->currentValue;
}

void Reward::setValue(float value) {
    pImpl->currentValue = value;
}

void Reward::add(float delta) {
    pImpl->accumulatedReward += delta;
    pImpl->currentValue += delta;
}

void Reward::reset() {
    pImpl->currentValue = 0.0f;
    pImpl->accumulatedReward = 0.0f;
}

float Reward::computeReward(const Observation& observation) const {
    // TODO PHASE 2: Implement real reward computation from observation
    // Phase 2: Compute reward based on sensory input
    // Reward for resource proximity (positive), hazard proximity (negative)
    // and prediction errors based on internal state
    
    const SensoryInput* sensoryInput = observation.getSensoryInput();
    if (!sensoryInput) {
        return 0.0f;
    }
    
    // Check for vision input to detect nearby objects
    if (std::string(sensoryInput->getType()) == "Vision") {
        const std::vector<float>& visionData = sensoryInput->getData();
        
        // Vision data structure: [ray1, ray2, ..., ray16, ray17, ...]
        // For vision, we look for resource or hazard signals in the field of view
        float totalResourceValue = 0.0f;
        float totalHazardValue = 0.0f;
        
        // Process vision data to find nearby objects
        // In SimpleWorld, vision is generated by raycasting
        for (float value : visionData) {
            if (value > 0.5f) {  // Object detected (resource)
                totalResourceValue += value * 10.0f;  // Scale to match resource reward
            } else if (value < -0.5f) {  // Hazard detected  
                totalHazardValue += value * 15.0f;  // Scale to match hazard reward
            }
        }
        
        // Compute net reward based on sensory input
        float reward = totalResourceValue + totalHazardValue;
        
        // Add small cost for movement (penalty for energy expenditure)
        float movementCost = 0.001f;
        reward -= movementCost;
        
        // Normalize to reasonable range
        if (reward > 1.0f) reward = 1.0f;
        if (reward < -1.0f) reward = -1.0f;
        
        return reward;
    }
    
    // For other sensory modalities or if vision unavailable
    // Return small baseline reward to encourage exploration
    return 0.1f;
}

const std::vector<float>& Reward::getHistory() const {
    return pImpl->history;
}

void Reward::clearHistory() {
    pImpl->history.clear();
}

} // namespace nlm
