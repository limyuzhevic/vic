def _build_nlm_bindings():
    """Attempt to build the NLM Python bindings."""
    print("Attempting to build NLM Python bindings...")
    
    try:
        # Get the directory where this file is located
        current_dir = os.path.dirname(os.path.abspath(__file__))
        python_dir = os.path.join(current_dir, 'python')
        
        # Check if there's a build directory
        build_dir = os.path.join(current_dir, 'build')
        
        if os.path.exists(build_dir):
            # Try to build using CMake
            os.chdir(build_dir)
            
            # Run cmake if needed
            if not os.path.exists('Makefile') and not os.path.exists('CMakeCache.txt'):
                subprocess.run(['cmake', '..'], check=True, capture_output=True)
            
            # Build the project
            result = subprocess.run(['make', '-j4'], capture_output=True, text=True)
            
            if result.returncode == 0:
                print("Successfully built NLM Python bindings")
            else:
                print(f"Build failed: {result.stderr}")
                return False
        
        os.chdir(current_dir)
        return True
    except Exception as e:
        print(f"Build failed: {e}")
        return False

