#!/usr/bin/env python3
"""
Motor module for NLM (Neural Learning Machine).

This module provides motor control classes for agent actions and movements,
including action representation, motor commands, and action creation utilities.
"""

from typing import Dict, Any, Optional, List
from dataclasses import dataclass

@dataclass
class MotorCommand:
    """
    Motor command representation.

    This class represents a motor command generated by the agent's
    brain that can be sent to the world to produce actions.
    """

    id: str = ""
    command_type: str = "move"
    parameters: Dict[str, Any] = None
    priority: int = 1
    duration: float = 1.0

    def __post_init__(self) -> None:
        """Initialize default parameters."""
        if self.parameters is None:
            self.parameters = {}

    def get_parameter(self, key: str, default: Any = None) -> Any:
        """
        Get a parameter value.

        Args:
            key: Parameter key
            default: Default value if parameter not found

        Returns:
            Parameter value or default
        """
        return self.parameters.get(key, default)

    def set_parameter(self, key: str, value: Any) -> None:
        """
        Set a parameter value.

        Args:
            key: Parameter key
            value: Parameter value
        """
        self.parameters[key] = value

    def get_action_type(self) -> str:
        """Get the action type."""
        return self.command_type

    def get_duration(self) -> float:
        """Get the action duration."""
        return self.duration

    def get_priority(self) -> int:
        """Get the action priority."""
        return self.priority

    def is_high_priority(self) -> bool:
        """Check if this is a high priority action."""
        return self.priority >= 5

    def __str__(self) -> str:
        """String representation."""
        return f"MotorCommand(id='{self.id}', type='{self.command_type}', priority={self.priority})"

    def __repr__(self) -> str:
        """Detailed string representation."""
        return (f"MotorCommand(id='{self.id}', command_type='{self.command_type}', "
                f"parameters={self.parameters}, priority={self.priority}, "
                f"duration={self.duration})")
class Action:
    """
    Action representation for motor output.

    This class represents an agent's action in the world, including
    movement, interaction, or other types of behavior.
    """

    def __init__(self, action_type: str = "move", params: Optional[Dict[str, Any]] = None):
        """
        Initialize an action.

        Args:
            action_type: Type of action (e.g., "move", "speak", "wait")
            params: Dictionary of action parameters
        """
        self.action_type = action_type
        self.params = params or {}
        self.timestamp = 0.0

    def get_parameter(self, key: str, default: Any = None) -> Any:
        """
        Get an action parameter.

        Args:
            key: Parameter key
            default: Default value if parameter not found

        Returns:
            Parameter value or default
        """
        return self.params.get(key, default)

    def set_parameter(self, key: str, value: Any) -> None:
        """
        Set an action parameter.

        Args:
            key: Parameter key
            value: Parameter value
        """
        self.params[key] = value

    def get_action_type(self) -> str:
        """Get the action type."""
        return self.action_type

    def get_timestamp(self) -> float:
        """Get the action timestamp."""
        return self.timestamp

    def set_timestamp(self, timestamp: float) -> None:
        """
        Set the action timestamp.

        Args:
            timestamp: Action timestamp
        """
        self.timestamp = timestamp

    def get_movement_parameters(self) -> Dict[str, Any]:
        """
        Get movement parameters.

        Returns:
            Movement parameters if this is a movement action
        """
        if self.action_type == "move":
            return {
                'direction': self.get_parameter('direction', 0.0),
                'distance': self.get_parameter('distance', 1.0),
                'speed': self.get_parameter('speed', 1.0),
            }
        return {}

    def get_interaction_parameters(self) -> Dict[str, Any]:
        """
        Get interaction parameters.

        Returns:
            Interaction parameters if this is an interaction action
        """
        if self.action_type == "interact":
            return {
                'target': self.get_parameter('target', ''),
                'action': self.get_parameter('action', 'none'),
                'intensity': self.get_parameter('intensity', 1.0),
            }
        return {}

    def __str__(self) -> str:
        """String representation."""
        return f"Action(type='{self.action_type}', params={self.params})"

    def __repr__(self) -> str:
        """Detailed string representation."""
        return f"Action(action_type='{self.action_type}', params={self.params})"
def create_action(action_type: str = "move", params: Optional[Dict[str, Any]] = None) -> Action:
    """
    Create an action with specified type and parameters.

    Args:
        action_type: Type of action (e.g., "move", "interact", "wait")
        params: Dictionary of action parameters

    Returns:
        New Action instance
    """
    return Action(action_type, params)
def create_movement_action(direction: float = 0.0, distance: float = 1.0, speed: float = 1.0) -> Action:
    """
    Create a movement action.

    Args:
        direction: Movement direction in radians
        distance: Distance to move
        speed: Movement speed

    Returns:
        Movement Action instance
    """
    params = {
        'direction': direction,
        'distance': distance,
        'speed': speed,
    }
    return create_action("move", params)
def create_interaction_action(target: str = "", action: str = "none", intensity: float = 1.0) -> Action:
    """
    Create an interaction action.

    Args:
        target: Target object ID or type
        action: Type of interaction (e.g., "pick", "use", "examine")
        intensity: Interaction intensity (0.0 to 1.0)

    Returns:
        Interaction Action instance
    """
    params = {
        'target': target,
        'action': action,
        'intensity': intensity,
    }
    return create_action("interact", params)
def create_wait_action(duration: float = 1.0) -> Action:
    """
    Create a wait action.

    Args:
        duration: Duration to wait

    Returns:
        Wait Action instance
    """
    return create_action("wait", {'duration': duration})


# Export functions for backward compatibility
__all__ = ['Action', 'MotorCommand', 'create_action', 'create_movement_action',
           'create_interaction_action', 'create_wait_action']