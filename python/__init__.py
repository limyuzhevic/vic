# NLM Enhanced Python Package
# 
# This package provides enhanced Python bindings for the NLM neural simulation framework.
# It includes:
# - Better error handling and user-friendly APIs
# - Comprehensive metrics collection and analysis
# - Environment simulation integration
# - Configuration management tools
# - Command-line interface support
# - Advanced features for power users
# - Examples and tutorials
#
# The package is designed to be both user-friendly for beginners and powerful for advanced users.
#
# Quick start:
# 1. Import the package: from pynlm_enhanced import BrainSimulator, NLMEnvironment, etc.
# 2. Create a brain simulator: brain_sim = BrainSimulator()
# 3. Initialize: brain_sim.initialize()
# 4. Run simulation: brain_sim.run(100)
# 5. Get results: metrics = brain_sim.get_metrics_summary()
#
# For more information, see:
# - README.md: Package overview and installation
# - examples/: Example scripts
# - python/: Core modules
# - python/: Command-line tools
#
# Package structure:
# python/
#   ├── pynlm_enhanced.py        # Enhanced Python bindings
#   ├── nlm_cli.py               # Command-line interface
#   ├── test_enhanced.py          # Test suite
#   └── examples/                # Example scripts
#
# Features:
# ✓ Better error handling with custom exception classes
# ✓ Comprehensive metrics collection and analysis
# ✓ Environment simulation with agent interaction
# ✓ Configuration management
# ✓ Simulation control with custom timesteps
# ✓ Progress callbacks and monitoring
# ✓ Data export (JSON, CSV)
# ✓ Convenience functions for common tasks
# ✓ CLI tools for batch processing
# ✓ Performance benchmarking
# ✓ Comprehensive testing suite
# ✓ Detailed documentation and examples
#
# The package is built on the existing C++ NLM framework but provides a much
# more user-friendly and feature-rich Python interface.
