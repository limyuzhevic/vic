# Mock pynlm module for compatibility
class MockBrain:
    """Mock brain object for Python API compatibility."""
    
    def __init__(self):
        self._initialized = False
        self._total_neuron_count = 0
        self._total_spike_count = 0
        self._firing_neuron_count = 0
        self._average_firing_rate = 0.0
    
    def initialize(self):
        """Initialize the brain."""
        self._initialized = True
        self._total_neuron_count = 500
        self._total_spike_count = 0
        self._firing_neuron_count = 0
        self._average_firing_rate = 2.5
        print("Brain initialized")
    
    def step(self, step_number):
        """Make the brain process one moment in time."""
        # Simulate brain activity
        self._total_spike_count += int(self._average_firing_rate * 0.001)  # spikes per step
        self._firing_neuron_count = int(self._total_neuron_count * self._average_firing_rate / 10)
        print(f"Brain step {step_number}: processed")
    
    def getTotalNeuronCount(self):
        """Return total number of neurons in the brain."""
        return self._total_neuron_count
    
    def getTotalSpikeCount(self):
        """Return total number of spikes generated by the brain."""
        return self._total_spike_count
    
    def getFiringNeuronCount(self):
        """Return number of neurons currently firing."""
        return self._firing_neuron_count
    
    def getAverageFiringRate(self):
        """Return average firing rate of the brain."""
        return self._average_firing_rate


