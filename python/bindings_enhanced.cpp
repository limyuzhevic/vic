// Custom Python exceptions
class NLMException : public std::exception {
public:
    explicit NLMException(const std::string& msg) : message(msg) {}
    const char* what() const noexcept override { return message.c_str(); }
private:
    std::string message;
};

class ConfigurationError : public NLMException {
public:
    explicit ConfigurationError(const std::string& msg) : NLMException(msg) {}
};

class InitializationError : public NLMException {
public:
    explicit InitializationError(const std::string& msg) : NLMException(msg) {}
};

class SimulationError : public NLMException {
public:
    explicit SimulationError(const std::string& msg) : NLMException(msg) {}
};

