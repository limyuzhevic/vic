#include <pybind11/pybind11.h>
#include <pybind11/stl.h>
#include <memory>
#include <string>

#include "../src/motor/Action.hpp"
#include "../src/world/Objects/WorldObject.hpp"
#include "../src/agent/AgentBody.hpp"

namespace py = pybind11;
namespace nlm {

// state_bindings.cpp - Action, WorldObject, AgentBody, ActionResult
// Purpose: Defines Python bindings for action and state representation classes

// Register action and state class bindings to the given module
void register_state(pybind11::module_& m) {

    py::class_<Action>(m, "Action", R"pbdoc(
        Motor action representation for agent behavior in the NLM system.
        
        Action represents a specific behavioral response that the brain generates
        to achieve goals or adapt to the environment. Each action has a type that
        determines the general category of behavior and parameters that provide
        specific values for that action.
        
        Actions are the fundamental units of behavior in the NLM brain. They
        represent what the agent does in the world and are generated by the
        brain based on sensory input and internal states.
        
        Examples:
            >>> # Create simple movement actions
            >>> move_forward = nlm.Action(nlm.ActionType.MoveForward)
            >>> move_left = nlm.Action(nlm.ActionType.MoveLeft)
            
            >>> # Create actions with parameters
            >>> custom_action = nlm.Action(nlm.ActionType.Custom, [0.5, 0.7, 0.9])
            >>> print(custom_action.getName())
            "Custom"
        )pbdoc")
        .def(py::init<>())
        .def(py::init<ActionType>(), py::arg("type"),
             R"pbdoc(
             Initialize Action with just a type.
             
             Args:
                 type: The type of action to create
             
             Examples:
                 >>> action = nlm.Action(nlm.ActionType.MoveForward)
                 >>> action.getType()
                 <ActionType.MoveForward: 0>
             )pbdoc")
        .def(py::init<ActionType, std::vector<float>>(), py::arg("type"), py::arg("parameters"),
             R"pbdoc(
             Initialize Action with type and parameters.
             
             Args:
                 type: The type of action to create
                 parameters: Vector of float parameters for the action
             
             Examples:
                 >>> action = nlm.Action(nlm.ActionType.Custom, [0.5, 0.7, 0.9])
                 >>> params = action.getParameters()
                 >>> len(params) == 3
                 True
             )pbdoc")
        .def("getType", &Action::getType,
             R"pbdoc(
             Get the type of this action.
             
             Returns:
                 ActionType: The type of this action
             
             Examples:
                 >>> action = nlm.Action(nlm.ActionType.TurnRight)
                 >>> action.getType()
                 <ActionType.TurnRight: 4>
             )pbdoc")
        .def("setType", &Action::setType, py::arg("type"),
             R"pbdoc(
             Set the type of this action.
             
             Args:
                 type: The new action type
             
             Examples:
                 >>> action = nlm.Action(nlm.ActionType.MoveForward)
                 >>> action.setType(nlm.ActionType.TurnRight)
                 >>> action.getType()
                 <ActionType.TurnRight: 4>
             )pbdoc")
        .def("getParameters", &Action::getParameters,
             R"pbdoc(
             Get the parameters of this action.
             
             Returns:
                 list[float]: The action parameters as a list of floats
             
             Examples:
                 >>> action = nlm.Action(nlm.ActionType.Custom, [0.5, 0.7, 0.9])
                 >>> params = action.getParameters()
                 >>> params[0] >= 0.0
                 True
             )pbdoc")
        .def("setParameters", &Action::setParameters, py::arg("params"),
             R"pbdoc(
             Set the parameters of this action.
             
             Args:
                 params: New parameters for the action as a list of floats
             
             Examples:
                 >>> action = nlm.Action(nlm.ActionType.Custom, [0.5, 0.7, 0.9])
                 >>> action.setParameters([0.1, 0.2, 0.3])
                 >>> action.getParameters()
                 [0.1, 0.2, 0.3]
             )pbdoc")
        .def("getName", &Action::getName,
             R"pbdoc(
             Get the human-readable name of this action.
             
             Returns:
                 str: Human-readable name of the action type
             
             Examples:
                 >>> action = nlm.Action(nlm.ActionType.MoveForward)
                 >>> action.getName()
                 "MoveForward"
             )pbdoc")
        .def("clone", &Action::clone,
             R"pbdoc(
             Create a copy of this action.
             
             Returns:
                 Action: A new Action object with the same type and parameters
             
             Examples:
                 >>> action = nlm.Action(nlm.ActionType.TurnLeft, [0.5])
                 >>> action_copy = action.clone()
                 >>> action_copy.getType() == action.getType()
                 True
                 >>> action_copy.getParameters() == action.getParameters()
                 True
             )pbdoc");

    py::class_<WorldObject>(m, "WorldObject", R"pbdoc(
        World object representation in the NLM simulation.
        
        WorldObject represents entities that exist in the simulation world. These can be
        resources (valuable items), hazards (dangerous items), walls (boundaries), or
        markers (special points). Each object has position, type, size, and state information
        that determines how the brain should interact with it.
        
        World objects are the fundamental building blocks of the simulation environment
        and provide the context for agent behavior and learning.
        
        Examples:
            >>> # Create a resource object
            >>> resource = nlm.WorldObject(5.0, 5.0, nlm.WorldObjectType.Resource, 10.0)
            >>> resource.type
            <WorldObjectType.Resource: 1>
            >>> resource.value
            10.0
            
            >>> # Create a wall object
            >>> wall = nlm.WorldObject(0.0, 10.0, nlm.WorldObjectType.Wall)
            >>> wall.radius
            0.5
        )pbdoc")
        .def(py::init<>())
        .def(py::init<float, float, WorldObjectType, float, float>(),
             py::arg("x"), py::arg("y"), py::arg("type"), py::arg("value") = 0.0f,
             py::arg("radius") = 0.5f,
             R"pbdoc(
             Initialize WorldObject with position and properties.
             
             Args:
                 x: X-coordinate of the object
                 y: Y-coordinate of the object
                 type: Type of the world object
                 value: Value or size of the object (default: 0.0)
                 radius: Physical radius of the object (default: 0.5)
             
             Examples:
                 >>> resource = nlm.WorldObject(5.0, 5.0, nlm.WorldObjectType.Resource, 10.0)
                 >>> resource.x
                 5.0
                 >>> resource.y
                 5.0
             )pbdoc")
        .def_readwrite("x", &WorldObject::x,
                      R"pbdoc(X-coordinate of the object in the world)pbdoc")
        .def_readwrite("y", &WorldObject::y,
                      R"pbdoc(Y-coordinate of the object in the world)pbdoc")
        .def_readwrite("radius", &WorldObject::radius,
                      R"pbdoc(Physical radius of the object)pbdoc")
        .def_readwrite("type", &WorldObject::type,
                      R"pbdoc(Type of the world object)pbdoc")
        .def_readwrite("value", &WorldObject::value,
                      R"pbdoc(Value or size of the object)pbdoc")
        .def_readwrite("active", &WorldObject::active,
                      R"pbdoc(Whether the object is active in the simulation)pbdoc");

    py::class_<AgentBody>(m, "AgentBody", R"pbdoc(
        Agent body state and physical properties.
        
        AgentBody represents the physical state of the agent in the simulation world.
        It includes position, orientation, velocity, and various physiological properties
        like energy and health. The body state is updated by the world simulation
        based on the agent's actions.
        
        The agent body represents the embodied agent that interacts with the world.
        Its state determines the agent's current condition and capabilities.
        
        Examples:
            >>> body = nlm.AgentBody()
            >>> body.x = 5.0
            >>> body.y = 5.0
            >>> body.orientation = 0.0
            >>> body.energy
            100.0
        )pbdoc")
        .def(py::init<>())
        .def_readwrite("x", &AgentBody::x,
                      R"pbdoc(Current X-position of the agent)pbdoc")
        .def_readwrite("y", &AgentBody::y,
                      R"pbdoc(Current Y-position of the agent)pbdoc")
        .def_readwrite("orientation", &AgentBody::orientation,
                      R"pbdoc(Current orientation/direction of the agent in radians)pbdoc")
        .def_readwrite("velocityX", &AgentBody::velocityX,
                      R"pbdoc(Current X-velocity of the agent)pbdoc")
        .def_readwrite("velocityY", &AgentBody::velocityY,
                      R"pbdoc(Current Y-velocity of the agent)pbdoc")
        .def_readwrite("angularVelocity", &AgentBody::angularVelocity,
                      R"pbdoc(Current angular velocity of the agent)pbdoc")
        .def_readwrite("energy", &AgentBody::energy,
                      R"pbdoc(Current energy level of the agent)pbdoc")
        .def_readwrite("health", &AgentBody::health,
                      R"pbdoc(Current health level of the agent)pbdoc")
        .def_readwrite("age", &AgentBody::age,
                      R"pbdoc(Current age of the agent)pbdoc")
        .def_readwrite("isMoving", &AgentBody::isMoving,
                      R"pbdoc(Whether the agent is currently moving)pbdoc")
        .def_readwrite("isTurning", &AgentBody::isTurning,
                      R"pbdoc(Whether the agent is currently turning)pbdoc")
        .def_readwrite("lastActionTime", &AgentBody::lastActionTime,
                      R"pbdoc(Timestamp of the last action taken)pbdoc")
        .def("reset", &AgentBody::reset,
             R"pbdoc(
             Reset the agent body to its initial state.
             
             This restores all body properties to their default values,
             typically including full energy, zero velocity, and position
             at the origin.
             
             Examples:
                 >>> body = nlm.AgentBody()
                 >>> body.energy = 50.0
                 >>> body.isMoving = True
                 >>> body.reset()
                 >>> body.isMoving
                 False
                 >>> body.energy > 0.0
                 True
             )pbdoc");

    py::class_<ActionResult>(m, "ActionResult", R"pbdoc(
        Result of an agent's action in the world.
        
        ActionResult represents the outcome of an action taken by the agent in
        the simulation world. It includes reward information, success status,
        and a descriptive message about what happened as a result of the action.
        
        Action results are used by the brain's reward systems to learn and adapt
        behavior. The reward signal drives learning and the success status indicates
        whether the action was effective.
        
        Examples:
            >>> result = nlm.ActionResult(10.0, True, "Found food!")
            >>> result.reward
            10.0
            >>> result.success
            True
            >>> result.message
            "Found food!"
        )pbdoc")
        .def(py::init<>())
        .def(py::init<float, bool, std::string>(),
             py::arg("reward"), py::arg("success"), py::arg("message") = "",
             R"pbdoc(
             Initialize ActionResult with outcome information.
             
             Args:
                 reward: Reward value received from the world (positive = good)
                 success: Whether the action was successful
                 message: Descriptive message about the outcome
             
             Examples:
                 >>> result = nlm.ActionResult(5.0, True, "Goal reached")
                 >>> result.reward
                 5.0
                 >>> result.success
                 True
             )pbdoc")
        .def_readwrite("reward", &ActionResult::reward,
                      R"pbdoc(Reward value received from the world)pbdoc")
        .def_readwrite("success", &ActionResult::success,
                      R"pbdoc(Whether the action was successful)pbdoc")
        .def_readwrite("message", &ActionResult::message,
                      R"pbdoc(Descriptive message about the action outcome)pbdoc");
}

} // namespace nlm