    m.def("run_simulation", [](std::shared_ptr<Brain> brain, std::shared_ptr<SimpleWorld> world,
                               const py::dict& config) {
        // Configure brain from Python dict
        if (config.contains("neuron_count")) {
            brain->getConfig()->set("neuron_count", 
                config["neuron_count"].cast<int64_t>(), ConfigSource::Runtime);
        }
        if (config.contains("region_count")) {
            brain->getConfig()->set("region_count",
                config["region_count"].cast<int64_t>(), ConfigSource::Runtime);
        }
        
        // Initialize
        brain->initialize();
        world->configure(100.0f, 100.0f, 11, 11);
        world->setAgentStart(50.0f, 50.0f);
        
        // Run simulation
        for (SimulationStep step = 0; step < 1000; ++step) {
            // Simple forward simulation
            world->update(0.001);
            brain->step(step, step * 0.001);
        }
        
        return py::dict({
            {"total_spikes", brain->getTotalSpikeCount()},
            {"final_action", brain->produceAction()}
        });
    }, py::arg("brain"), py::arg("world"), py::arg("config") = py::dict(),
       "Run a simple simulation with brain and world");
    
