    m.def("runSimulationLoop", [](std::shared_ptr<Brain> brain, std::shared_ptr<SimpleWorld> world, 
                                 std::shared_ptr<AgentBrain> agent, size_t numSteps) {
        for (size_t step = 0; step < numSteps; ++step) {
            if (world) {
                world->update(0.1f);
                auto percept = world->getSensoryPercept();
                if (agent) {
                    agent->processSensoryInput(percept);
                }
            }
            brain->step(step);
            if (agent) {
                auto action = agent->decodeMotorCommand();
                if (world) {
                    world->applyMotorCommand(action, world->getSimulationTime());
                }
            }
        }
    }, py::arg("brain"), py::arg("world"), py::arg("agent"), py::arg("numSteps"), "Run a complete simulation loop");

