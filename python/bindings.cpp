// Utility functions for Python integration
std::string format_neuron_stats(const NeuronId& id, float potential, float rate, FiringState state) {
    std::stringstream ss;
    ss << "Neuron(id=" << id.value << ", V=" << potential << "mV, rate=" << rate 
       << "Hz, state=" << static_cast<int>(state) << ")";
    return ss.str();
}

std::string format_synapse_stats(const SynapseId& id, float weight, SynapseType type) {
    std::stringstream ss;
    ss << "Synapse(id=" << id.value << ", weight=" << weight 
       << ", type=" << static_cast<int>(type) << ")";
    return ss.str();
}

std::string format_brain_stats(const Brain& brain) {
    std::stringstream ss;
    ss << "Brain(neurons=" << brain.getTotalNeuronCount() 
       << ", synapses=" << brain.getTotalSynapseCount()
       << ", firing=" << brain.getFiringNeuronCount()
       << ", rate=" << brain.getAverageFiringRate()
       << ", dev_stage=" << static_cast<int>(brain.getDevelopmentalStage()) << ")";
    return ss.str();
}

