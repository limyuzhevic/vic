// Python exception types for better error handling
class NLMError : public std::runtime_error {
public:
    explicit NLMError(const std::string& msg) : std::runtime_error("NLM Error: " + msg) {}
};

class ConfigError : public NLMError {
public:
    explicit ConfigError(const std::string& msg) : NLMError("Configuration Error: " + msg) {}
};

class SimulationError : public NLMError {
public:
    explicit SimulationError(const std::string& msg) : NLMError("Simulation Error: " + msg) {}
};

// Context manager wrapper for automatic cleanup
class BrainContext {
public:
    std::shared_ptr<Brain> brain;
    bool auto_reset;
    
    explicit BrainContext(std::shared_ptr<Brain> b, bool autoReset = true) 
        : brain(b), auto_reset(autoReset) {
        if (!brain) throw NLMError("Brain cannot be null");
    }
    
    ~BrainContext() {
        if (auto_reset && brain) {
            try {
                brain->reset();
            } catch (...) {
                // Ignore cleanup errors
            }
        }
    }
    
    BrainContext& operator=(const BrainContext&) = delete;
    BrainContext(const BrainContext&) = delete;
};

