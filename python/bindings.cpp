// Minimal, clean bindings - one function per class
template<typename T>
void addClassBinding(py::module_& m, const std::string& name) {
    // Generic class binding
    py::class_<T>(m, name.c_str())
        .def(py::init<>())
        .def("__repr__", &T::toString);
}

