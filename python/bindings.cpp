    // Add action synthesis helper functions
    m.def("selectBestAction", [](const ActionType& type, float score) {
        return Action(type, std::vector<float>{score});
    }, py::arg("type"), py::arg("score"),
       "Create an action with a quality score");

    // Add motor command conversion utilities
    m.def("motorCommandToActionType", [](MotorCommand cmd) {
        // Convert MotorCommand to ActionType for motor system interaction
        switch (cmd) {
            case MotorCommand::MoveForward: return ActionType::MoveForward;
            case MotorCommand::MoveBackward: return ActionType::MoveBackward;
            case MotorCommand::TurnLeft: return ActionType::TurnLeft;
            case MotorCommand::TurnRight: return ActionType::TurnRight;
            case MotorCommand::LookLeft: return ActionType::Look;
            case MotorCommand::LookRight: return ActionType::Look;
            case MotorCommand::Interact: return ActionType::Interact;
            case MotorCommand::Wait: return ActionType::Wait;
            default: return ActionType::Wait;
        }
    }, py::arg("cmd"), "Convert MotorCommand to ActionType");

    // Add world simulation helper functions
    m.def("runSimpleEpisode", [](std::shared_ptr<SimpleWorld> world,
                                std::shared_ptr<Brain> brain,
                                std::shared_ptr<AgentBrain> agent,
                                int steps) {
        for (int step = 0; step < steps; ++step) {
            world->update(0.1);
            const auto& percept = world->getSensoryPercept();
            agent->processSensoryInput(percept);
            brain->step(step, world->getSimulationTime());
            auto action = agent->decodeMotorCommand();
            world->applyMotorCommand(action, world->getSimulationTime());
        }
        return ActionResult{0.0f, true, "Episode completed"};
    }, py::arg("world"), py::arg("brain"), py::arg("agent"), py::arg("steps"),
       "Run a simple simulation episode");

    // Add advanced configuration utilities
    m.def("loadConfigFromJsonString", [](const std::string& jsonStr) {
        auto config = std::make_shared<Config>();
        try {
            auto json = nlohmann::json::parse(jsonStr);
            config->loadFromJson(json);
            return config;
        } catch (const std::exception& e) {
            throw py::value_error(std::string("Invalid JSON: ") + e.what());
        }
    }, py::arg("jsonStr"), "Load configuration from JSON string");

    m.def("exportConfigToJsonString", [](const std::shared_ptr<Config>& config) {
        auto json = config->toJson();
        return json.dump(2);
    }, py::arg("config"), "Export configuration to JSON string");
