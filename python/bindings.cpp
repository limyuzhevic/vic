// Performance monitoring utilities
namespace nlm {
    class PerformanceMonitor {
    public:
        struct StepMetrics {
            Timestamp timestamp;
            double worldUpdateTime;
            double sensoryProcessingTime;
            double brainStepTime;
            double actionDecodingTime;
            double totalStepTime;
            size_t spikesGenerated;
            float curiosityLevel;
            float noveltyLevel;
            float predictionError;
        };
        
        PerformanceMonitor() : totalSteps(0), maxSteps(1000), currentStep(0) {
            steps.reserve(maxSteps);
        }
        
        void startStep() {
            startTime = std::chrono::high_resolution_clock::now();
        }
        
        void endStep(size_t spikes, float curiosity, float novelty, float predictionError) {
            auto endTime = std::chrono::high_resolution_clock::now();
            auto duration = std::chrono::duration_cast<std::chrono::microseconds>(endTime - startTime);
            
            StepMetrics metrics;
            metrics.timestamp = std::chrono::duration_cast<std::chrono::duration<double>>(endTime.time_since_epoch()).count();
            metrics.totalStepTime = duration.count() / 1000000.0; // Convert to seconds
            metrics.spikesGenerated = spikes;
            metrics.curiosityLevel = curiosity;
            metrics.noveltyLevel = novelty;
            metrics.predictionError = predictionError;
            
            steps.push_back(metrics);
            totalSteps++;
            currentStep++;
        }
        
        void setMaxSteps(size_t max) {
            maxSteps = max;
            if (steps.size() > maxSteps) {
                steps.resize(maxSteps);
            }
        }
        
        py::dict getStepMetrics(size_t step) const {
            if (step >= steps.size()) {
                return py::dict();
            }
            
            py::dict metrics;
            const auto& stepData = steps[step];
            metrics["timestamp"] = stepData.timestamp;
            metrics["total_time_us"] = stepData.totalStepTime * 1000000;
            metrics["spikes_generated"] = stepData.spikesGenerated;
            metrics["curiosity_level"] = stepData.curiosityLevel;
            metrics["novelty_level"] = stepData.noveltyLevel;
            metrics["prediction_error"] = stepData.predictionError;
            return metrics;
        }
        
        py::dict getPerformanceReport() const {
            py::dict report;
            
            if (steps.empty()) {
                return report;
            }
            
            double totalTime = 0.0;
            size_t totalSpikes = 0;
            float avgCuriosity = 0.0;
            float avgNovelty = 0.0;
            float avgPredictionError = 0.0;
            
            for (const auto& step : steps) {
                totalTime += step.totalStepTime;
                totalSpikes += step.spikesGenerated;
                avgCuriosity += step.curiosityLevel;
                avgNovelty += step.noveltyLevel;
                avgPredictionError += step.predictionError;
            }
            
            size_t numSteps = steps.size();
            
            report["total_steps"] = numSteps;
            report["total_time_seconds"] = totalTime;
            report["average_step_time_ms"] = (totalTime / numSteps) * 1000;
            report["spikes_per_second"] = totalSpikes / totalTime;
            report["average_curiosity"] = avgCuriosity / numSteps;
            report["average_novelty"] = avgNovelty / numSteps;
            report["average_prediction_error"] = avgPredictionError / numSteps;
            report["steps_per_second"] = numSteps / totalTime;
            
            // Calculate variance
            double curiosityVariance = 0.0, noveltyVariance = 0.0, errorVariance = 0.0;
            for (const auto& step : steps) {
                curiosityVariance += std::pow(step.curiosityLevel - (avgCuriosity / numSteps), 2);
                noveltyVariance += std::pow(step.noveltyLevel - (avgNovelty / numSteps), 2);
                errorVariance += std::pow(step.predictionError - (avgPredictionError / numSteps), 2);
            }
            
            if (numSteps > 1) {
                curiosityVariance /= numSteps;
                noveltyVariance /= numSteps;
                errorVariance /= numSteps;
            }
            
            report["curiosity_variance"] = curiosityVariance;
            report["novelty_variance"] = noveltyVariance;
            report["prediction_error_variance"] = errorVariance;
            
            return report;
        }
        
        void clear() {
            steps.clear();
            totalSteps = 0;
            currentStep = 0;
        }
        
        bool isReady() const {
            return !steps.empty();
        }
        
        size_t getCurrentStep() const {
            return currentStep;
        }
        
        size_t getTotalSteps() const {
            return totalSteps;
        }
        
    private:
        std::vector<StepMetrics> steps;
        size_t maxSteps;
        size_t totalSteps;
        size_t currentStep;
        std::chrono::high_resolution_clock::time_point startTime;
    };
    
    // Function to create a performance monitor
    PerformanceMonitor createPerformanceMonitor() {
        return PerformanceMonitor();
    }
    
    // Function to create a performance monitor with custom max steps
    PerformanceMonitor createPerformanceMonitor(size_t maxSteps) {
        PerformanceMonitor monitor;
        monitor.setMaxSteps(maxSteps);
        return monitor;
    }
}

