    m.def("run_simple_simulation", [](std::shared_ptr<Brain> brain, std::shared_ptr<SimpleWorld> world, 
                                    std::shared_ptr<AgentBrain> agent, size_t steps) {
        if (!brain || !world || !agent) {
            throw PyInitializationError("Brain, world, and agent must all be initialized");
        }
        
        agent->initialize(*world);
        
        for (size_t i = 0; i < steps; ++i) {
            world->update(0.1);
            auto percept = world->getSensoryPercept();
            agent->processSensoryInput(percept);
            brain->step(i);
            auto action = agent->decodeMotorCommand();
            world->applyMotorCommand(action, world->getSimulationTime());
            agent->applyRewardModulation(0.0f, 0.0f); // No reward in simple sim
            agent->updateDevelopment(0.1);
        }
    }, py::arg("brain"), py::arg("world"), py::arg("agent"), py::arg("steps"),
       "Run a simple simulation with brain, world, and agent");
    
