// Custom exception classes for better error handling
class NLMError : public std::runtime_error {
public:
    enum class ErrorType {
        ConfigValidationError,
        BrainInitializationError,
        WorldError,
        AgentError,
        SimulationError,
        IOError,
        MemoryError,
        NotInitializedError,
        InvalidArgumentError,
        ResourceUnavailableError
    };

    NLMError(const std::string& message, ErrorType type = ErrorType::RuntimeError)
        : std::runtime_error("NLM Error: " + message), type_(type) {}

    NLMError(ErrorType type, const std::string& context, const std::string& message)
        : std::runtime_error("NLM " + errorTypeToString(type) + " in " + context + ": " + message),
          type_(type), context_(context) {}

    ErrorType getType() const { return type_; }
    const std::string& getContext() const { return context_; }

    static std::string errorTypeToString(ErrorType type) {
        switch (type) {
            case ErrorType::ConfigValidationError: return "ConfigValidationError";
            case ErrorType::BrainInitializationError: return "BrainInitializationError";
            case ErrorType::WorldError: return "WorldError";
            case ErrorType::AgentError: return "AgentError";
            case ErrorType::SimulationError: return "SimulationError";
            case ErrorType::IOError: return "IOError";
            case ErrorType::MemoryError: return "MemoryError";
            case ErrorType::NotInitializedError: return "NotInitializedError";
            case ErrorType::InvalidArgumentError: return "InvalidArgumentError";
            case ErrorType::ResourceUnavailableError: return "ResourceUnavailableError";
            default: return "RuntimeError";
        }
    }

private:
    ErrorType type_;
    std::string context_;
};

// Register custom exceptions with pybind11
void registerExceptions(py::module_& m) {
    py::register_exception<NLMError>(m, "NLMError", PyExc_RuntimeError);
    
    // Specific error types for easier exception handling
    py::register_exception_translator<NLMError>([](std::exception_ptr p) {
        try {
            if (p) std::rethrow_exception(p);
        } catch (const NLMError& e) {
            throw py::value_error(std::string("NLM Error: ") + e.what());
        }
    });
}

