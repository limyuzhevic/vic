// Helper function for error reporting
template<typename T>
py::object handle_errors(const std::string& operation, const T& result) {
    if (!result) {
        PyErr_SetString(PyExc_RuntimeError, (operation + " failed").c_str());
        return py::none();
    }
    return py::cast(result.value());
}

