    m.def("createEnsemble", [](const std::vector<std::shared_ptr<Brain>>& brains) {
        // Create an ensemble of brains for comparison and averaging
        py::dict ensemble;
        
        for (size_t i = 0; i < brains.size(); ++i) {
            ensemble[std::to_string(i)] = brains[i];
        }
        
        ensemble["size"] = brains.size();
        ensemble["avgNeuronCount"] = 0.0;
        ensemble["avgSynapseCount"] = 0.0;
        ensemble["avgFiringRate"] = 0.0;
        
        if (!brains.empty()) {
            double totalNeurons = 0.0, totalSynapses = 0.0, totalRate = 0.0;
            for (const auto& brain : brains) {
                auto stats = brain->getActivityStats();
                totalNeurons += stats.neuronCount;
                totalSynapses += stats.synapseCount;
                totalRate += stats.avgFiringRate;
            }
            ensemble["avgNeuronCount"] = totalNeurons / brains.size();
            ensemble["avgSynapseCount"] = totalSynapses / brains.size();
            ensemble["avgFiringRate"] = totalRate / brains.size();
        }
        
        return ensemble;
    }, py::arg("brains"), "Create an ensemble of brains for comparison");

