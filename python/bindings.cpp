    // Convenience functions
    m.def("run_agent_simulation", [](std::shared_ptr<Brain> brain, std::shared_ptr<SimpleWorld> world, std::shared_ptr<AgentBrain> agent, int num_steps) {
        brain->initialize();
        world->reset();
        agent->initialize(*world);
        
        for (int step = 0; step < num_steps; ++step) {
            world->update(0.1);
            auto percept = world->getSensoryPercept();
            agent->processSensoryInput(percept);
            brain->step(step);
            auto action = agent->decodeMotorCommand();
            world->applyMotorCommand(action, world->getSimulationTime());
        }
        
        return py::dict(
            "steps_completed", num_steps,
            "final_neurons", brain->getFiringNeuronCount(),
            "total_spikes", brain->getTotalSpikeCount()
        );
    }, py::arg("brain"), py::arg("world"), py::arg("agent"), py::arg("num_steps"),
       "Run a complete agent simulation");

    m.def("create_agent_from_config", [](std::shared_ptr<Config> config, std::shared_ptr<SimpleWorld> world) {
        auto brain = std::make_shared<Brain>(config);
        brain->initialize();
        auto agent = std::make_shared<AgentBrain>(brain);
        agent->initialize(*world);
        return std::make_pair(brain, agent);
    }, py::arg("config"), py::arg("world"),
       "Create agent (brain and agent brain) from config and world");

