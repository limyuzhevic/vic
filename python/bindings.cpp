    m.def("benchmarkBrain", [](std::shared_ptr<Brain> brain, int numSteps) {
        auto startTime = std::chrono::high_resolution_clock::now();
        size_t totalSpikes = 0;
        
        for (int step = 0; step < numSteps; ++step) {
            brain->step(step);
            totalSpikes += brain->getTotalSpikeCount();
        }
        
        auto endTime = std::chrono::high_resolution_clock::now();
        auto duration = std::chrono::duration_cast<std::chrono::milliseconds>(endTime - startTime);
        
        py::dict results;
        results["steps"] = numSteps;
        results["totalSpikes"] = totalSpikes;
        results["executionTimeMs"] = static_cast<double>(duration.count());
        results["spikesPerSecond"] = totalSpikes / std::max<double>(duration.count() / 1000.0, 0.001);
        results["avgSpikesPerStep"] = totalSpikes / std::max<size_t>(numSteps, 1);
        
        return results;
    }, py::arg("brain"), py::arg("numSteps"),
        "Benchmark brain performance and return statistics");

    m.def("validateConfig", [](const std::shared_ptr<Config>& config) {
        py::dict validation;
        validation["valid"] = config->validate();
        validation["warnings"] = config->getValidationWarnings();
        
        if (config->has("neuron_count")) {
            int64_t neuronCount = config->getOr<int64_t>("neuron_count", 1000);
            validation["neuronCount"] = neuronCount;
            validation["neuronCountValid"] = (neuronCount > 0 && neuronCount < 1000000);
        }
        
        if (config->has("connection_probability")) {
            float connProb = config->getOr<float>("connection_probability", 0.1);
            validation["connectionProbability"] = connProb;
            validation["connectionProbabilityValid"] = (connProb >= 0.0 && connProb <= 1.0);
        }
        
        if (config->has("simulation_timestep")) {
            double timestep = config->getOr<double>("simulation_timestep", 0.001);
            validation["timestep"] = timestep;
            validation["timestepValid"] = (timestep > 0.0 && timestep <= 1.0);
        }
        
        return validation;
    }, py::arg("config"), "Validate configuration and return validation results");

    m.def("compareBrains", [](const std::shared_ptr<Brain>& brain1, const std::shared_ptr<Brain>& brain2) {
        py::dict comparison;
        
        auto stats1 = brain1->getActivityStats();
        auto stats2 = brain2->getActivityStats();
        
        comparison["neuronCountMatch"] = (stats1.neuronCount == stats2.neuronCount);
        comparison["synapseCountMatch"] = (stats1.synapseCount == stats2.synapseCount);
        comparison["firingNeuronsMatch"] = (stats1.firingNeurons == stats2.firingNeurons);
        comparison["totalSpikesMatch"] = (stats1.totalSpikes == stats2.totalSpikes);
        
        double rateDiff = std::abs(stats1.avgFiringRate - stats2.avgFiringRate);
        comparison["avgFiringRateDiff"] = rateDiff;
        comparison["avgFiringRateMatch"] = (rateDiff < 1e-6);
        
        double ratioDiff = std::abs(stats1.excitationInhibitionRatio - stats2.excitationInhibitionRatio);
        comparison["eIRatioDiff"] = ratioDiff;
        comparison["eIRatioMatch"] = (ratioDiff < 1e-6);
        
        return comparison;
    }, py::arg("brain1"), py::arg("brain2"),
        "Compare two brains and return comparison results");

