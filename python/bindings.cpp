        config->set("region_count", int64_t(1), ConfigSource::Default);
        
        auto brain = std::make_shared<Brain>(config);
        brain->initialize();
        
        // Inject current to activate neurons
        brain->injectCurrentToNeurons(NeuronType::Internal, 20.0f);
        
        // Run simulation
        for (SimulationStep step = 0; step < num_steps; ++step) {
            brain->step(step, step * 0.001);
        }
        
        return py::dict({
            {"neurons_created", brain->getTotalNeuronCount()},
            {"total_spikes", brain->getTotalSpikeCount()},
            {"final_firing_rate", brain->getAverageFiringRate()}
        });
