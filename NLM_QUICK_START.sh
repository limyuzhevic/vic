#!/usr/bin/env bash
# NLM Quick Start Script
# 
# This script demonstrates the new NLM command-line interface features
# Run this script from the NLM project directory after building

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo -e "${GREEN}╔═══════════════════════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║                   NLM Quick Start Guide                            ║${NC}"
echo -e "${GREEN}╚═══════════════════════════════════════════════════════════════╝${NC}"
echo ""

echo -e "${YELLOW}1. Basic Usage${NC}"
echo "   # Run default neural computation tests"
echo "   ./nlm"
echo ""

echo -e "${YELLOW}2. Get Help${NC}"
echo "   # Display complete help information"
echo "   ./nlm --help"
echo ""

echo -e "${YELLOW}3. Experiment Modes${NC}"
echo "   # Test basic neural connectivity"
echo "   ./nlm --experiment connectivity"
echo ""
echo "   # Test learning and plasticity"
echo "   ./nlm --experiment plasticity --steps 2000"
echo ""
echo "   # Test STDP mechanisms"
echo "   ./nlm --experiment stdp"
echo ""
echo "   # Run integration test"
echo "   ./nlm --experiment integration --enable-neuromodulation"
echo ""

echo -e "${YELLOW}4. Configuration Management${NC}"
echo "   # Use custom configuration"
echo "   ./nlm --config configs/development.cfg --experiment plasticity"
echo ""
echo "   # Set custom parameters"
echo "   ./nlm --experiment plasticity --key=neuron_count --value=800"
echo "   ./nlm --experiment plasticity --key=region_count --value=3"
echo ""
echo "   # List available configs"
echo "   ./nlm --list-configs"
echo ""

echo -e "${YELLOW}5. Model Persistence${NC}"
echo "   # Save brain state after training"
echo "   ./nlm --experiment plasticity --save-checkpoint my_brain.bin"
echo ""
echo "   # Load saved brain state"
echo "   ./nlm --load-checkpoint my_brain.bin --experiment connectivity"
echo ""
echo "   # Combine save and load"
echo "   ./nlm --experiment plasticity --save-checkpoint trained_brain.bin"
echo ""
echo "   # Resume from checkpoint"
echo "   ./nlm --load-checkpoint trained_brain.bin --experiment plasticity"
echo ""

echo -e "${YELLOW}6. Advanced Features${NC}"
echo "   # Enable verbose logging"
echo "   ./nlm --verbose --experiment plasticity"
echo ""
echo "   # Run with development features"
echo "   ./nlm --enable-development --enable-neuromodulation"
echo ""
echo "   # Enable prediction and memory systems"
echo "   ./nlm --enable-prediction --enable-memory --enable-neuromodulation"
echo ""
echo "   # Performance profiling"
echo "   ./nlm --enable-profiling --experiment plasticity --benchmark"
echo ""

echo -e "${YELLOW}7. Output and Results${NC}"
echo "   # Save results to file"
echo "   ./nlm --experiment connectivity --output results.txt"
echo ""
echo "   # Combined output and checkpoint"
echo "   ./nlm --experiment plasticity --save-checkpoint model.bin --output stats.csv"
echo ""

echo -e "${YELLOW}8. Configuration Files${NC}"
echo "   # Built-in configuration files:"
echo "   - configs/default.cfg         (Standard configuration)"
echo "   - configs/development.cfg     (Development/testing)"
echo "   - configs/performance.cfg     (Performance benchmark)"
echo "   - configs/example.cfg         (Custom config template)"
echo ""

echo -e "${YELLOW}9. Troubleshooting${NC}"
echo "   # Check if configuration file exists"
echo "   ./nlm --config my_config.cfg --experiment plasticity"
echo ""
echo "   # Run with verbose mode for debugging"
echo "   ./nlm --verbose --experiment connectivity"
echo ""

echo -e "${GREEN}╔═══════════════════════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║                    Quick Reference Commands                       ║${NC}"
echo -e "${GREEN}╚═══════════════════════════════════════════════════════════════╝${NC}"
echo ""
echo "# Essential commands for beginners:"
echo "   ./nlm                                    # Default tests"
echo "   ./nlm --help                             # Help and documentation"
echo "   ./nlm --experiment connectivity          # Basic connectivity test"
echo ""
echo "# Advanced commands for researchers:"
echo "   ./nlm --experiment integration          # Full integration test"
echo "   ./nlm --enable-prediction --enable-memory # Enable all subsystems"
echo "   ./nlm --save-checkpoint model.bin       # Save trained model"
echo ""
echo "# For more information:"
echo "   Read IMPROVEMENTS_SUMMARY.md for detailed feature list"
echo "   Check configs/ directory for configuration examples"
echo "   Consult HOW_TO_USE.md for Python API usage"
echo ""

echo -e "${YELLOW}=== Quick Start Complete ===${NC}"
echo "You're ready to use NLM with the improved command-line interface!"
echo ""
echo "Need help? Run './nlm --help' for complete documentation."
