        "src/cognition/NeuralPlanner.hpp"
        "src/cognition/ConceptFormation.hpp"
        "src/cognition/AttentionalSelection.hpp"
    )
    
    for file in "${cpp_files[@]}"; do
        if [[ -f "$file" ]]; then
            local doc_file="$GENERATED_DIR/api/${file#src\/}.md"
            mkdir -p "$(dirname "$doc_file")"
            
            # Extract class documentation and public methods
            extract_class_docs "$file" > "$doc_file"
            
            print_info "  Generated: $(basename "$doc_file")"
        else
            print_warning "  File not found: $file"
        fi
    done
    
    print_success "C++ documentation extracted!"
}

# Extract documentation from a single header file
extract_class_docs() {
    local file="$1"
    
    echo "# $(basename "$file" .hpp)" > /dev/stdout
    echo "" >> /dev/stdout
    
    # Extract multi-line comments (/** ... */)
    sed -n '/\*\*.*/,/\*\*\*/p' "$file" | sed '/\*\*\*/d' | sed 's/\*\*\s*//g' | sed 's/\s\*//' >> /dev/stdout
    
    echo "" >> /dev/stdout
    echo "## Public Methods" >> /dev/stdout
    echo "" >> /dev/stdout
    
    # Extract method signatures
    grep -E "(public:|protected:|private:).*?(;|{|->*).*" "$file" | head -50 | sed 's/\s*public:\s*//' | sed 's/\s*protected:\s*//' | sed 's/\s*private:\s*//' | sed '/^$/d' | sed '/^$/d' >> /dev/stdout
}

