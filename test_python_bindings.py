def test_thread_safety():
    """Test thread safety of concurrent operations."""
    print("Testing thread safety...")
    
    if PYBIND11_AVAILABLE:
        # Test ThreadSafeBrain concepts
        class SharedCounter:
            def __init__(self):
                self._counter = 0
                self._lock = threading.Lock()
            
            def increment(self):
                with self._lock:
                    self._counter += 1
            
            def get_count(self):
                with self._lock:
                    return self._counter
        
        counter = SharedCounter()
        
        def worker():
            for _ in range(1000):
                counter.increment()
        
        threads = []
        for _ in range(5):
            t = threading.Thread(target=worker)
            threads.append(t)
            t.start()
        
        for t in threads:
            t.join()
        
        assert counter.get_count() == 5000
    
    print("  PASSED")

