function nlm-config-get() {
    local option=$1
    if [[ -n "${CONFIG_OPTS[$option]}" ]]; then
        echo "Config[$option] = ${CONFIG_OPTS[$option]}"
    else
        echo "Error: Unknown option '$option'"
        echo "Available options:"
        for key in "${!CONFIG_OPTS[@]}"; do
            echo "  $key"
        done
    fi
}

function nlm-config-set() {
    local option=$1
    local value=$2
    
    if [[ -n "${CONFIG_OPTS[$option]}" ]]; then
        CONFIG_OPTS[$option]=$value
        echo "Set config[$option] = $value"
        
        # Apply to running simulation if active
        if [[ -n "$NLM_PID" ]]; then
            echo "Applying config to running simulation..."
            # Implementation depends on how simulation is controlled
        fi
    else
        echo "Error: Unknown option '$option'"
    fi
}

function nlm-config-save() {
    local file=$1
    local temp_file="$(mktemp)"
    
    # Convert associative array to config format
    {
        echo "# NLM Configuration File"
        echo "# Generated by nlm-config-save"
        echo "# $(date)"
        echo ""
        
        for key in "${!CONFIG_OPTS[@]}"; do
            echo "$key = ${CONFIG_OPTS[$key]}"
        done
    } > "$temp_file"
    
    if [[ -n "$file" ]]; then
        mv "$temp_file" "$file"
        echo "Configuration saved to: $file"
    else
        cat "$temp_file"
        rm "$temp_file"
    fi
}

function nlm-simulate() {
