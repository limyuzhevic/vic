        echo "Loading configuration from: $config_file"
        # Parse config file and apply settings
    fi
    
    # Start simulation process
    nlm --simulate $steps &
    NLM_PID=$!
    echo "Simulation started with PID: $NLM_PID"
}

function nlm-stop-sim() {
    if [[ -n "$NLM_PID" ]]; then
        echo "Stopping simulation (PID: $NLM_PID)..."
        kill $NLM_PID
        unset NLM_PID
        echo "Simulation stopped"
    else
        echo "No running simulation found"
    fi
}

